"""Подхват покрытия в подпроцессах (задача T037).

Движок вызывается подпроцессом, а не импортируется, — это техническая
гарантия принципа «оценку не считать заново» (docs/forge/plan.md). Побочный
эффект: построчная метрика родительского процесса его не видит, и двенадцать
файлов тестов, гоняющих `engine/audit.py` и `engine/report.py` через CLI,
для покрытия выглядят как ничего не проверяющие.

Python импортирует этот модуль автоматически при старте любого процесса, у
которого корень проекта в `sys.path`. Если задан `COVERAGE_PROCESS_START`,
подпроцесс сам включает измерение и дописывает свой файл данных рядом с
родительским; без переменной модуль не делает ничего и на обычный прогон не
влияет.
"""

from __future__ import annotations

import os

if os.environ.get("COVERAGE_PROCESS_START"):
    try:
        import coverage
    except ImportError:  # coverage не установлен — это не повод ронять процесс
        pass
    else:
        coverage.process_startup()
