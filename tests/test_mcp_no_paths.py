def test_ни_один_ответ_инструмента_не_называет_абсолютного_пути(батарея: Батарея) -> None:
    """Общее утверждение: ни успешный ответ, ни отказ не показывают агенту путь.

    Путь на диске — это устройство каталогов деплоя и имя пользователя, под
    которым поднят сервер. Ответ инструмента уходит в модель, то есть за
    пределы машины.
    """
    найдено = [
        (о.стенд, о.инструмент, о.набор, найденное.group(0))
        for о in батарея.ответы
        if (найденное := АБСОЛЮТНЫЙ_ПУТЬ.search(о.текст))
    ]

    assert найдено == []


def test_ни_один_ответ_не_называет_каталогов_самого_стенда(батарея: Батарея) -> None:
    """Второй заслон, к регулярному выражению не сводящийся: путей стенда в
    ответе нет ни в каком виде — ни целиком, ни куском."""
    корни = {str(батарея.корень), str(батарея.корень.resolve())}
    найдено = [
        (о.стенд, о.инструмент, о.набор)
        for о in батарея.ответы
        if any(корень in о.текст for корень in корни)
    ]

    assert найдено == []


def test_батарея_и_правда_доводит_инструменты_до_отказов(батарея: Батарея) -> None:
    """Утверждение про пути ничего не стоит, если батарея отвечает одними успехами.

    Здесь проверяется, что она доходит до тех отказов, ради которых заведена
    задача, — и до отказа хранилища на неизвестную версию, до которого годные
    аргументы не добираются.
    """
    склейка = "\n".join(о.текст for о in батарея.ответы)

    assert "на сервере не найден" in склейка, "отказ про ненайденную методику не случился"
    assert "не хватает" in склейка, "отказ про неполную методику не случился"
    assert "лежит не ссылка" in склейка, "отказ про сбитый указатель не случился"
    assert "переставляет этот указатель" in склейка, "отказ публикации не случился"
    assert "в хранилище нет" in склейка, "отказ на неизвестную версию не случился"
    assert "нет в методике версии" in склейка, "отказ на неизвестный пункт не случился"
    assert "Traceback" in склейка, "движок ни разу не упал — трейсбек не проверен"


