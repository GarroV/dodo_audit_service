@dataclass(frozen=True)
class Ответ:
    """Один текст, который увидел бы агент."""

    стенд: str
    инструмент: str
    набор: str
    текст: str


@dataclass(frozen=True)
class Батарея:
    """Прогон целиком: где он жил и что ответил."""

    корень: Path
    ответы: tuple[Ответ, ...]


def _версия(store: Store | None) -> str:
    """Действующая версия хранилища либо заглушка, если хранилище не отвечает."""
    if store is None:
        return ЗАГЛУШКА_ВЕРСИИ
    try:
        return current_version(store)
    except McpError:
        return ЗАГЛУШКА_ВЕРСИИ


def _ломающая(корень: Path) -> Path:
    """Методика, на которой движок падает без общего перехвата.

    Файлы на месте, поэтому хранилище её принимает и доходит до движка, а
    движок спотыкается о ставки вычетов и печатает трейсбек. В трейсбеке —
    путь к его собственным файлам, то есть каталог, куда развёрнут продукт,
    вместе с именем пользователя: это тот же показ диска, что и в отказе,
    только приехавший из подпроцесса.
    """
    сломанная = build_methodology(корень / "ломающая-методика")
    (сломанная / "scoring.json").write_text(json.dumps({"start_pct": "сто"}), encoding="utf-8")
    return сломанная


def _стенды(корень: Path) -> list[tuple[str, Store | None]]:
    """Шесть состояний сервера: закрытое, собранное, промежуточное и три сломанных.

    Сломанные взяты не с потолка — это ровно те, в которых блок называл агенту
    путь: методики нет, методика неполная, на месте указателя лежит не ссылка,
    движок читает не хранилище.
    """
    методика = build_methodology(корень / "методика")

    связанное = корень / "связанное-хранилище"
    current_version(Store(root=связанное, live=методика))  # заводим нулевую версию

    неполная = корень / "неполная-методика"
    неполная.mkdir(parents=True, exist_ok=True)
    (неполная / "checklist.csv").write_text("id,kind\n", encoding="utf-8")

    сбитый = корень / "сбитый-указатель"
    сбитый.mkdir(parents=True, exist_ok=True)
    (сбитый / "current").write_text("не ссылка\n", encoding="utf-8")

    return [
        ("методика закрыта этому доступу", None),
        ("связанное хранилище", Store(root=связанное, live=связанное / "current")),
        ("промежуточное состояние по .env.example", Store(root=корень / "х2", live=методика)),
        ("каталога методики нет", Store(root=корень / "х3", live=корень / "нет-такого")),
        ("методика неполная", Store(root=корень / "х4", live=неполная)),
        ("на месте указателя не ссылка", Store(root=сбитый, live=методика)),
        ("движок падает на этой методике", Store(root=корень / "х5", live=_ломающая(корень))),
    ]


def _тексты(ответ: dict[str, Any] | None) -> list[str]:
    """Всё, что из ответа увидит агент: и текст вызова, и текст отказа протокола."""
    if ответ is None:
        return []
    собранное: list[str] = []
    ошибка = ответ.get("error")
    if isinstance(ошибка, dict):
        собранное.append(str(ошибка.get("message", "")))
    итог = ответ.get("result")
    if isinstance(итог, dict):
        for блок in итог.get("content", []):
            if isinstance(блок, dict):
                собранное.append(str(блок.get("text", "")))
    return собранное


def _вызвать(имя: str, аргументы: dict[str, Any], *, store: Store | None) -> dict[str, Any] | None:
    сообщение = {
        "jsonrpc": "2.0",
        "id": 1,
        "method": "tools/call",
        "params": {"name": имя, "arguments": аргументы},
    }
    return handle(сообщение, tenant=АРЕНДАТОР, checklist=store)


def _собрать(корень: Path) -> Батарея:
    """Прогнать батарею целиком и собрать всё, что она сказала."""
    собранное: list[Ответ] = []
    for имя_стенда, store in _стенды(корень):
        версия = _версия(store)
        for имя_набора, набор in НАБОРЫ.items():
            for spec in TOOLS:
                аргументы = {
                    ключ: (версия if ключ == "version" and значение is None else значение)
                    for ключ, значение in набор[spec.name].items()
                }
                for текст in _тексты(_вызвать(spec.name, аргументы, store=store)):
                    собранное.append(Ответ(имя_стенда, spec.name, имя_набора, текст))
    return Батарея(корень=корень, ответы=tuple(собранное))


