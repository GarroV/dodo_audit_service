def test_отказ_публикации_объясняет_причину_без_путей(tmp_path: Path) -> None:
    """Промежуточное состояние из `.env.example`: `AUDIT_DATA_DIR` смотрит в
    обычный каталог, и публикация обязана объяснить это словами, а не путями.

    Вырезать объяснение нельзя: без него человек видит отказ и не знает, что
    именно поправить в настройках.
    """
    методика = build_methodology(tmp_path / "методика")
    store = Store(root=tmp_path / "хранилище", live=методика)
    версия = current_version(store)

    ответ = _вызвать("publish_checklist_version", {"version": версия}, store=store)
    текст = _тексты(ответ)[0]

    assert ответ is not None and ответ["result"]["isError"] is True
    assert not АБСОЛЮТНЫЙ_ПУТЬ.search(текст)
    assert "AUDIT_DATA_DIR" in текст
    assert "MCP_CHECKLIST_STORE" in текст
    assert "current" in текст


def test_путь_ушёл_в_лог_сервера_а_не_пропал(tmp_path: Path, capsys: Any) -> None:
    """Путь нужен тому, кто держит сервер, — иначе отказ нечем чинить. Он
    печатается в лог процесса: лог остаётся на машине, ответ уходит в модель."""
    методика = build_methodology(tmp_path / "методика")
    store = Store(root=tmp_path / "хранилище", live=методика)
    версия = current_version(store)
    capsys.readouterr()

    _вызвать("publish_checklist_version", {"version": версия}, store=store)

    лог = capsys.readouterr().err
    assert str(методика) in лог
    assert str(store.root) in лог


