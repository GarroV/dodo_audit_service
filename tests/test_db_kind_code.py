"""T178: вид проверки связан КОДОМ на всём пути через базу.

С T152/T177 вид проверки — код (`planned`), а слово подставляется при печати и
по языку печати (`domain.kinds.kind_title`). Для этого блока отсюда следуют
две вещи, и обе тихие.

Первая: код входит в отпечаток содержимого (`compute_fingerprint`), а отпечаток
— это и есть техническая гарантия «повторный слив не создаёт дубль». Значение
в нём поменялось со слова на код, поэтому идемпотентность здесь проверяется
пересчётом СТРОК В ТАБЛИЦЕ, а не совпадением возвращённых идентификаторов:
дубль даёт другой id, и сравнение id с id о числе строк ничего не говорит,
пока их не посчитали.

Вторая: чтение отдаёт код, а не слово. Это правильно и должно таким остаться:
формулировки переводятся и правятся, коды нет. Отсюда обязанность потребителя —
показать вид человеком самому и на языке ТОГО документа, который он печатает.
Здесь это закреплено с обеих сторон: из базы приходит код, и по этому коду
`kind_title` даёт слово на каждом языке отчёта.
"""

from __future__ import annotations

from dataclasses import replace
from pathlib import Path

import pytest
from conftest import requires_db

psycopg = pytest.importorskip("psycopg")

from src.db.fingerprint import compute_fingerprint  # noqa: E402 — после importorskip намеренно
from src.db.push import push_inspection  # noqa: E402
from src.db.queries import get_inspection, list_inspections  # noqa: E402
from src.domain import add_finding, get_state, start_inspection  # noqa: E402
from src.domain import score as domain_score  # noqa: E402
from src.domain.kinds import kind_title  # noqa: E402

pytestmark = requires_db

АРЕНДАТОР = "вид-проверки"

#: Код вида и слово, которым он показывается по-русски. Слово написано здесь
#: буквально, а не получено тем же `kind_title`: сверка функции с самой собой
#: сошлась бы и после того, как таблица переводов опустеет.
КОД = "planned"
СЛОВО_RU = "Плановая"
СЛОВО_EN = "Planned"


def _строки(dsn: str, sql: str, params: tuple[object, ...] = ()) -> list[tuple[object, ...]]:
    with psycopg.connect(dsn) as conn, conn.cursor() as cur:
        cur.execute(sql, params)
        return cur.fetchall()


def _проверка(chat_id: int, *, точка: str = "Белград-1") -> None:
    start_inspection(chat_id, unit=точка, kind=КОД, report_lang="ru", tenant=АРЕНДАТОР)
    add_finding(chat_id, code="CLN05", level="D1", zone="hot_kitchen", text="нагар на печи")


def test_в_колонку_вида_ложится_код_а_не_слово(domain_env: Path, db_env: str) -> None:
    """Первое звено: то, что положил слив, обязано быть кодом.

    Слово в этой колонке не отказ и не поломка — оно просто перестанет
    переводиться на языке отчёта, и партнёр однажды получит письмо со словом на
    чужом языке. Ровно так это и выглядело до T152.
    """
    _проверка(801)

    ident = push_inspection(801)

    (вид,) = _строки(db_env, "select kind from inspections where id = %s", (ident,))
    assert вид == (КОД,), "в колонке вида проверки не код — слово там больше не переводится"
    assert вид != (СЛОВО_RU,)


def test_повторный_слив_находит_ту_же_проверку_а_не_заводит_вторую(
    domain_env: Path, db_env: str
) -> None:
    """Идемпотентность после смены значения в отпечатке (T178).

    Считаются СТРОКИ арендатора, а не совпадение идентификаторов: второй слив,
    заведший дубль, вернул бы другой id, и проверка «id тот же» о числе строк
    не сказала бы ничего. Дубль здесь — это две записи одной проверки в
    истории точки, то есть испорченная динамика, а не отказ.
    """
    _проверка(802)

    первый = push_inspection(802)
    второй = push_inspection(802)

    assert первый == второй, "повторный слив вернул другой идентификатор — это уже дубль"
    (сколько,) = _строки(
        db_env, "select count(*) from inspections where tenant_code = %s", (АРЕНДАТОР,)
    )
    assert сколько == (1,), "повторный слив завёл вторую строку той же проверки"


def test_отпечаток_считается_по_коду_вида_а_не_по_слову(domain_env: Path, db_env: str) -> None:
    """Отпечаток обязан меняться вместе с видом — и брать именно код.

    Проверяется тем, что подмена кода на его же СЛОВО даёт другой отпечаток:
    значит, в отпечаток уходит вид, и уходит он кодом. Если бы функция брала
    слово (или не брала вид вовсе), эти два отпечатка совпали бы, и проверка,
    заведённая заново с другим видом, легла бы поверх прежней.
    """
    _проверка(803)
    состояние = get_state(803)
    assert состояние is not None
    оценка = domain_score(803)

    по_коду = compute_fingerprint(состояние, оценка, tenant_code=АРЕНДАТОР)
    словом = compute_fingerprint(replace(состояние, kind=СЛОВО_RU), оценка, tenant_code=АРЕНДАТОР)

    assert по_коду != словом, (
        "отпечаток не отличает код вида от слова — значит, вид в него не попадает, "
        "и проверка другого вида легла бы поверх этой"
    )
    assert состояние.kind == КОД


def test_чтение_отдаёт_код_и_по_нему_есть_слово_на_каждом_языке(
    domain_env: Path, db_env: str
) -> None:
    """Что читающий получает код — это требование, а не недоделка.

    Слово он подставляет сам и по языку своего документа: письмо по одной и той
    же проверке собирается и по-русски, и по-английски (`mcp.letters`), и
    слово, записанное однажды, было бы верным ровно на одном из них.
    """
    _проверка(804)
    ident = push_inspection(804)

    подробно = get_inspection(ident, tenant=АРЕНДАТОР)
    (строка,) = list_inspections(tenant=АРЕНДАТОР)

    assert подробно is not None
    assert подробно.inspection.kind == КОД, "чтение по идентификатору отдало не код вида"
    assert строка.kind == КОД, "список отдал не код вида"
    assert kind_title(строка.kind, "ru") == СЛОВО_RU
    assert kind_title(строка.kind, "en") == СЛОВО_EN


def test_схема_сама_говорит_что_в_колонке_вида_код(domain_env: Path, db_env: str) -> None:
    """Миграция `0006` объясняет колонку прямо в базе, а не только в репозитории.

    Схему читают не только из кода: её открывает тот, кто заливает историю за
    прошлые годы программно (D035), и тот, кто разбирается в чужой базе. Рядом
    стоит `units.name` с человеческим названием, поэтому `kind text not null`
    без объяснения читается как слово — а слово здесь не отказывает, оно молча
    перестаёт переводиться.
    """
    (пояснение,) = _строки(
        db_env,
        "select col_description(a.attrelid, a.attnum) from pg_attribute a "
        "where a.attrelid = 'inspections'::regclass and a.attname = 'kind'",
    )
    текст = str(пояснение[0] or "")
    assert КОД in текст, "в схеме не сказано, что вид проверки хранится кодом"
    assert "domain.kinds" in текст, "в схеме не сказано, где живёт перечень видов и его переводы"
