"""T095: окружение MCP-сервера — кто спрашивает и чьи проверки ему видны.

Главное свойство блока проверяется именно здесь, а не в инструментах: **код
арендатора берётся из токена, а не из аргумента вызова**. Инструмент, у
которого арендатор пришёл бы параметром, отдал бы историю соседа любому, кто
угадает код партнёра, — а угадывать там нечего, коды короткие и осмысленные.

Поэтому связка «токен → арендатор» живёт в окружении (`.env`), разбирается
один раз на старте и дальше не принимает ничего снаружи.
"""

from __future__ import annotations

import pytest

from src.mcp.config import (
    MCP_TOKENS_VAR,
    MIN_TOKEN_LENGTH,
    Settings,
    load_settings,
    resolve_tenant,
)
from src.mcp.errors import AuthError, McpConfigError

# Выдуманные токены нужной длины: в коде продукта настоящих нет и быть не может.
ТОКЕН_А = "a" * MIN_TOKEN_LENGTH
ТОКЕН_Б = "b" * MIN_TOKEN_LENGTH
АРЕНДАТОР_А = "партнёр-а"
АРЕНДАТОР_Б = "партнёр-б"

ПАРА_А = f"{АРЕНДАТОР_А}={ТОКЕН_А}"
ПАРА_Б = f"{АРЕНДАТОР_Б}={ТОКЕН_Б}"


def _настройки(**env: str) -> Settings:
    return load_settings({MCP_TOKENS_VAR: ПАРА_А, **env})


# --- разбор связки «токен → арендатор» ---------------------------------------


def test_без_токенов_сервер_не_поднимается() -> None:
    """Пустая карта токенов означала бы сервер, который отдаёт всем и всё."""
    with pytest.raises(McpConfigError, match=MCP_TOKENS_VAR):
        load_settings({})


@pytest.mark.parametrize("разделитель", [",", "\n", ", ", " \n "])
def test_несколько_пар_разбираются_запятой_и_переводом_строки(разделитель: str) -> None:
    настройки = load_settings({MCP_TOKENS_VAR: разделитель.join([ПАРА_А, ПАРА_Б])})

    assert настройки.tenant_for(ТОКЕН_А) == АРЕНДАТОР_А
    assert настройки.tenant_for(ТОКЕН_Б) == АРЕНДАТОР_Б


def test_токен_разбирается_целиком_даже_со_знаком_равенства() -> None:
    """Разбор идёт по ПЕРВОМУ `=`: код арендатора простой, а токен произвольный.

    Обрезанный по последнему `=` токен base64 не совпал бы ни с чем, и это
    выглядело бы как «неверный токен», а не как ошибка разбора настроек.
    """
    токен = "AAAA/BBBB+CCCC/DDDD+EEEE=FFFF=="
    настройки = load_settings({MCP_TOKENS_VAR: f"{АРЕНДАТОР_А}={токен}"})

    assert настройки.tenant_for(токен) == АРЕНДАТОР_А


@pytest.mark.parametrize(
    "кривая",
    [
        "простотокен",  # нет `=` вовсе — непонятно, чей это токен
        f"={ТОКЕН_А}",  # пустой арендатор
        f"{АРЕНДАТОР_А}=",  # пустой токен
        f"{АРЕНДАТОР_А}=  ",
    ],
)
def test_кривая_запись_это_отказ_а_не_пропуск(кривая: str) -> None:
    """Пропущенная молча запись — это доступ, который человек считает выданным."""
    with pytest.raises(McpConfigError):
        load_settings({MCP_TOKENS_VAR: кривая})


def test_короткий_токен_это_отказ() -> None:
    """Токен, который набирается с памяти, дверью не является."""
    with pytest.raises(McpConfigError, match="длин"):
        load_settings({MCP_TOKENS_VAR: f"{АРЕНДАТОР_А}=короткий"})


def test_один_токен_на_двух_арендаторов_это_отказ() -> None:
    """Иначе вопрос «чьи проверки отдать» решался бы порядком строк в файле."""
    with pytest.raises(McpConfigError, match="дважды"):
        load_settings({MCP_TOKENS_VAR: f"{АРЕНДАТОР_А}={ТОКЕН_А},{АРЕНДАТОР_Б}={ТОКЕН_А}"})


def test_два_токена_одного_арендатора_разрешены() -> None:
    """Законный случай: два человека одного партнёра, разные личные токены."""
    настройки = load_settings({MCP_TOKENS_VAR: f"{АРЕНДАТОР_А}={ТОКЕН_А},{АРЕНДАТОР_А}={ТОКЕН_Б}"})

    assert настройки.tenant_for(ТОКЕН_А) == АРЕНДАТОР_А
    assert настройки.tenant_for(ТОКЕН_Б) == АРЕНДАТОР_А


# --- заголовок запроса → арендатор -------------------------------------------


@pytest.mark.parametrize("заголовок", [f"Bearer {ТОКЕН_А}", f"bearer {ТОКЕН_А}"])
def test_известный_токен_даёт_своего_арендатора(заголовок: str) -> None:
    """Регистр схемы клиенты пишут по-разному, поэтому сверка без учёта регистра."""
    assert resolve_tenant(_настройки(), заголовок) == АРЕНДАТОР_А


@pytest.mark.parametrize(
    "заголовок",
    [
        None,
        "",
        "   ",
        "Bearer",
        "Bearer   ",
        "Basic " + ТОКЕН_А,
        ТОКЕН_А,  # голый токен без схемы (T116)
    ],
)
def test_запрос_без_внятного_токена_это_отказ(заголовок: str | None) -> None:
    """Голый токен без схемы сервер принимал осознанно и брешью это не было —
    но инструменты, маскирующие секреты в логах, ищут образец `Bearer <токен>`,
    а голое значение заголовка пишут как есть (T116). Годный вид доступа
    остался один, и он же объявлен в `WWW-Authenticate` при отказе."""
    with pytest.raises(AuthError):
        resolve_tenant(_настройки(), заголовок)


def test_чужой_токен_не_даёт_ничего() -> None:
    """Не «арендатор по умолчанию» и не пустая выдача — именно отказ."""
    with pytest.raises(AuthError):
        resolve_tenant(_настройки(), f"Bearer {ТОКЕН_Б}")


def test_отказ_не_повторяет_предъявленный_токен() -> None:
    """Текст отказа уходит в лог и клиенту; токен в нём — это утечка токена."""
    with pytest.raises(AuthError) as отказ:
        resolve_tenant(_настройки(), f"Bearer {ТОКЕН_Б}")

    assert ТОКЕН_Б not in str(отказ.value)


def test_настройки_не_печатают_токены() -> None:
    """`repr` настроек попадает в трейсбек при любой ошибке рядом."""
    представление = repr(_настройки())

    assert ТОКЕН_А not in представление
    assert АРЕНДАТОР_А in представление, "чей это доступ — видеть надо, сам ключ — нет"


# --- адрес, на котором сервер слушает ----------------------------------------


def test_по_умолчанию_сервер_слушает_только_петлю() -> None:
    настройки = _настройки()

    assert настройки.host == "127.0.0.1"
    assert 8260 <= настройки.port <= 8269, "порт по умолчанию — из диапазона рабочей копии"


@pytest.mark.parametrize("адрес", ["0.0.0.0", "::", "192.168.1.10", "example.com"])  # noqa: S104
def test_адрес_вне_петли_это_отказ(адрес: str) -> None:
    """Площадка общая, рядом живут чужие проекты (конституция, безопасность).

    Сервер отдаёт проверки партнёров по личному токену — открытый в сеть порт
    означал бы, что дверь стоит, но на общем коридоре.
    """
    with pytest.raises(McpConfigError, match="петл"):
        _настройки(MCP_HOST=адрес)


@pytest.mark.parametrize("адрес", ["127.0.0.1", "localhost", "::1"])
def test_петля_записана_любым_привычным_способом(адрес: str) -> None:
    assert _настройки(MCP_HOST=адрес).host == адрес


@pytest.mark.parametrize("порт", ["0", "80", "70000", "не число", "-1"])
def test_негодный_порт_это_отказ(порт: str) -> None:
    with pytest.raises(McpConfigError, match="орт"):
        _настройки(MCP_PORT=порт)


@pytest.mark.parametrize("порт", ["8266", " 8269 ", "1024"])
def test_годный_порт_берётся_как_назван(порт: str) -> None:
    """Без этой проверки разбор порта был бы проверен только отказами: правка,
    после которой годный порт молча заменяется значением по умолчанию, прошла
    бы незамеченной."""
    assert _настройки(MCP_PORT=порт).port == int(порт.strip())
