"""T115, T116: вход сервера — кодировка токена, схема заголовка, лог.

Три свойства, каждое из которых сбоит МОЛЧА, и потому проверяется здесь
отдельно от остальной двери (`test_mcp_server.py`):

1. **Сбой сравнения токенов не съедает ответ.** `secrets.compare_digest` не
   умеет строки вне ASCII и бросает `TypeError`. Токен, заданный владельцем
   кириллицей, ронял сравнение на КАЖДОМ запросе, а необработанное исключение
   в обработчике оставляло клиента с пустым ответом: ни кода, ни причины.
   Понять, что происходит, можно было только из лога сервера (issue #94).
2. **Секрет, положенный клиентом в адрес, не уезжает в лог.** Через строку
   запроса авторизация не принимается, но клиент об этом не знает и вполне
   может дописать туда токен (issue #95).
3. **Схема `Bearer` обязательна.** Голый токен без схемы читается частью
   инструментов как обычное значение заголовка и пишется в их логи как есть;
   `Bearer <токен>` они маскируют.

Запросы, где заголовок обязан содержать не-ASCII, идут **сырым сокетом**:
`urllib` кодирует заголовки latin-1 и такой запрос не соберёт вовсе — то есть
через клиентскую библиотеку этот сценарий не выразить.
"""

from __future__ import annotations

import json
import socket
import threading
from collections.abc import Iterator
from http.server import ThreadingHTTPServer
from typing import Any

import pytest

from src.mcp.config import MCP_TOKENS_VAR, MIN_TOKEN_LENGTH, Settings, load_settings, resolve_tenant
from src.mcp.errors import AuthError, McpConfigError
from src.mcp.server import build_server

ТОКЕН = "a" * MIN_TOKEN_LENGTH
АРЕНДАТОР = "партнёр-а"

#: Токен, набранный кириллицей: ровно то, что владелец впишет в `.env`, если
#: придумает его сам, а не сгенерирует.
КИРИЛЛИЧЕСКИЙ_ТОКЕН = "токен-альфа-достаточно-длинный-24"


@pytest.fixture
def адрес() -> Iterator[tuple[str, int]]:
    """Поднятый сервер с одним арендатором. Отдаёт хост и порт."""
    settings = Settings(tokens={ТОКЕН: АРЕНДАТОР}, tenants=(АРЕНДАТОР,), host="127.0.0.1", port=0)
    httpd: ThreadingHTTPServer = build_server(settings)
    поток = threading.Thread(target=httpd.serve_forever, daemon=True)
    поток.start()
    try:
        yield ("127.0.0.1", int(httpd.server_address[1]))
    finally:
        httpd.shutdown()
        httpd.server_close()
        поток.join(timeout=5)


def _сырой_запрос(адрес: tuple[str, int], запрос: bytes) -> str:
    """Готовые байты запроса в сокет; ответ целиком строкой.

    Пустая строка в ответе — это и есть тот самый молчаливый сбой: соединение
    закрыто без единого байта.
    """
    хост, порт = адрес
    with socket.create_connection((хост, порт), timeout=10) as сокет:
        сокет.sendall(запрос)
        куски = []
        while True:
            кусок = сокет.recv(4096)
            if not кусок:
                break
            куски.append(кусок)
    return b"".join(куски).decode("utf-8", "replace")


def _запрос_с_заголовком(адрес: tuple[str, int], авторизация: bytes, *, путь: str = "/") -> str:
    тело = b'{"jsonrpc": "2.0", "id": 1, "method": "ping"}'
    return _сырой_запрос(
        адрес,
        b"POST " + путь.encode() + b" HTTP/1.1\r\nHost: 127.0.0.1\r\n"
        b"Authorization: " + авторизация + b"\r\n"
        b"Content-Type: application/json\r\n"
        b"Content-Length: " + str(len(тело)).encode() + b"\r\n\r\n" + тело,
    )


# --- T115: токен вне ASCII ---------------------------------------------------


def test_кириллический_токен_в_настройках_это_отказ_на_старте() -> None:
    """Такой токен нельзя ни отправить, ни сверить — сервер обязан сказать это
    человеку на старте, а не отвечать пустотой на каждый запрос."""
    with pytest.raises(McpConfigError, match="ASCII"):
        load_settings({MCP_TOKENS_VAR: f"{АРЕНДАТОР}={КИРИЛЛИЧЕСКИЙ_ТОКЕН}"})


def test_отказ_на_кириллический_токен_не_печатает_сам_токен() -> None:
    """Отказ настроек уходит в лог: токен в его тексте — это утечка токена."""
    with pytest.raises(McpConfigError) as отказ:
        load_settings({MCP_TOKENS_VAR: f"{АРЕНДАТОР}={КИРИЛЛИЧЕСКИЙ_ТОКЕН}"})

    assert КИРИЛЛИЧЕСКИЙ_ТОКЕН not in str(отказ.value)
    assert АРЕНДАТОР in str(отказ.value), "чей токен негоден — человек видеть должен"


def test_сверка_не_падает_на_предъявленном_токене_вне_ascii() -> None:
    """Сравнение идёт байтами: строковое `compare_digest` здесь бросает
    `TypeError`, и падение прилетает выше как пустой ответ, а не как отказ."""
    настройки = Settings(tokens={ТОКЕН: АРЕНДАТОР}, tenants=(АРЕНДАТОР,), host="127.0.0.1", port=0)

    assert настройки.tenant_for(КИРИЛЛИЧЕСКИЙ_ТОКЕН) is None
    with pytest.raises(AuthError):
        resolve_tenant(настройки, f"Bearer {КИРИЛЛИЧЕСКИЙ_ТОКЕН}")


def test_токен_вне_ascii_в_заголовке_даёт_отказ_а_не_пустой_ответ(
    адрес: tuple[str, int],
) -> None:
    """Живой запрос теми же байтами, что послал бы `curl`.

    Пустой ответ — худший исход: клиент не знает ни кода, ни причины, а
    владелец видит «сервер перестал отвечать» без единой подсказки.
    """
    ответ = _запрос_с_заголовком(адрес, "Bearer ".encode() + КИРИЛЛИЧЕСКИЙ_ТОКЕН.encode())

    assert ответ, "сервер закрыл соединение молча — ровно тот сбой, ради которого задача"
    assert " 401 " in ответ.splitlines()[0]
    assert КИРИЛЛИЧЕСКИЙ_ТОКЕН not in ответ, "отказ не повторяет предъявленный токен"


def test_необработанный_отказ_обработчика_даёт_код_а_не_пустой_ответ(
    адрес: tuple[str, int], monkeypatch: pytest.MonkeyPatch
) -> None:
    """Любое исключение ниже авторизации обязано стать внятным кодом.

    Проверяется общий заслон, а не конкретный дефект: тот же пустой ответ даст
    любая будущая ошибка в разборе сообщения, и увидеть её будет так же нечем.
    """
    import src.mcp.server as сервер_модуль

    def падение(*_: Any, **__: Any) -> dict[str, Any]:
        raise RuntimeError("строка-подключения-из-драйвера-базы")

    monkeypatch.setattr(сервер_модуль, "handle", падение)

    ответ = _запрос_с_заголовком(адрес, f"Bearer {ТОКЕН}".encode())

    assert ответ, "необработанное исключение оставило клиента без ответа"
    assert " 500 " in ответ.splitlines()[0]
    assert "строка-подключения-из-драйвера-базы" not in ответ, "наружу уходит тип, а не текст"
    assert "Traceback" not in ответ
    тело = json.loads(ответ.split("\r\n\r\n", 1)[1])
    assert "RuntimeError" in тело["error"], "тип отказа назвать надо: иначе чинить нечего"


# --- T116: строка запроса в логе ---------------------------------------------


def test_строка_запроса_не_попадает_в_лог(
    адрес: tuple[str, int], capfd: pytest.CaptureFixture[str]
) -> None:
    """Авторизация через адрес не принимается, но клиент об этом не знает.

    Положенный им в адрес секрет сегодня никуда не открывает дверь — и всё
    равно оседает в логе навсегда.
    """
    секрет = "подсмотренный-секрет-из-адреса"

    _запрос_с_заголовком(адрес, f"Bearer {ТОКЕН}".encode(), путь=f"/?token={секрет}")

    напечатано = capfd.readouterr().err
    assert напечатано.strip(), "лог запроса не должен исчезать целиком"
    assert секрет not in напечатано
    assert "token=" not in напечатано


# --- T116: схема Bearer обязательна ------------------------------------------


def test_голый_токен_без_схемы_это_отказ() -> None:
    """Инструменты маскируют в логах именно `Bearer <токен>`; голый токен они
    записывают как обычное значение заголовка, то есть как есть."""
    настройки = Settings(tokens={ТОКЕН: АРЕНДАТОР}, tenants=(АРЕНДАТОР,), host="127.0.0.1", port=0)

    with pytest.raises(AuthError, match="Bearer"):
        resolve_tenant(настройки, ТОКЕН)


def test_голый_токен_не_пускают_и_по_настоящему_http(адрес: tuple[str, int]) -> None:
    ответ = _запрос_с_заголовком(адрес, ТОКЕН.encode())

    assert " 401 " in ответ.splitlines()[0]


def test_отказ_называет_ожидаемый_вид_заголовка(адрес: tuple[str, int]) -> None:
    """Отказ обязан быть починяемым: человек, забывший схему, должен увидеть
    какую — иначе 401 неотличим от «токен не тот»."""
    ответ = _запрос_с_заголовком(адрес, ТОКЕН.encode())

    assert "Bearer" in ответ
    assert ТОКЕН not in ответ, "ожидаемый вид заголовка — не повод повторить предъявленное"
