"""Методика управляющей компании не цитируется в репозитории (T146, #138).

Репозиторий публичный (D073), а `data/` и `examples/` намеренно вне git: это
материалы управляющей компании и реальные проверки партнёров. Через код и
документы фрагменты методики просачиваются обратно — за одни сутки этот канал
затыкали трижды, и **каждый раз находилось новое**:

* сначала — цитаты в двух тестах;
* потом — что счёт занижен вчетверо: порог длины отсекал ровно ту строку,
  которая утекла целиком;
* потом — что пороги классов не попадали в поиск вообще, потому что
  сверялась только первая колонка таблицы подсказок, а они лежат в остальных.

Три ручных прохода — три разных ответа. Дело не во внимательности: проверки
не было как проверки, и канал протекал заново на первом же тесте, написанном
по боевым данным.

**Иглы строятся из методики на ходу.** Замороженный список строк сделал бы
утечкой сам этот файл — ровно то, что он ловит.

Тест требует боевую методику: это единственное место, где её читать правильно.
"""

from __future__ import annotations

import csv
import re
import subprocess
from collections.abc import Iterator
from pathlib import Path

import pytest
from conftest import DATA, requires_data

#: Класс стоит в методике и в начале строки, и в конце — одного правила мало.
_КЛАСС = re.compile(r"^\s*\((?:D[123])(?:,\s*D[123])*\)\s*|\s*\((?:D[123])(?:,\s*D[123])*\)\s*$")

#: Короче этого фрагмент ловит служебный шум, а не цитату. Порогов ДВА, и это
#: не придирка: единый порог в 12 знаков пропускал название зоны длиной 11
#: знаков — оно короче порога, но это полноценная цитата. Ровно та ошибка,
#: которую этот файл и заведён
#: ловить: порог собственного изготовления отсекает находку, и «ничего не
#: найдено» выглядит как чистота.
#:
#: Названия зон конкретны сами по себе, им хватает пяти знаков. Формулировкам
#: вопросов и ячейкам таблицы порог нужен выше: там короткий фрагмент — это
#: служебный обрывок вроде «см.» или «нет».
МИН_ДЛИНА = 12
МИН_ДЛИНА_ЗОНЫ = 5

#: Что цитатой НЕ считается, с причиной на каждую строку. Список короткий
#: намеренно: без него тест утонет в шуме и его заглушат целиком.
#:
#: * `Поломка` — заголовок колонки таблицы подсказок, от него зависит разбор
#:   в продукте (`recognize.cues`), убрать нельзя, не сломав быстрый путь;
#: * `Вид проверки` / `Inspection type` — собственная надпись мастера бота,
#:   совпадающая с формулировкой поля методики. Совпадение, а не копия;
#: * `# Критерии нарушений по вопросам` — заголовок файла критериев, который
#:   оснастка пишет для своего синтетического набора.
ИСКЛЮЧЕНИЯ = frozenset(
    {
        "Поломка",
        "Вид проверки",
        "Inspection type",
        "# Критерии нарушений по вопросам",
        # То же без решётки: нормализация снимает markdown-разметку, и
        # заголовок доходит сюда уже очищенным. Его пишет сам движок при
        # выгрузке критериев, то есть это имя формата, а не содержание.
        "Критерии нарушений по вопросам",
        # `Freezer` — название зоны длиной 7 знаков и одновременно обычное
        # английское слово. Первый же тест, упомянувший морозильник
        # по-английски, дал бы ложную находку, а ложная находка — самый
        # быстрый путь к тому, что тест заглушат целиком.
        "Freezer",
    }
)

#: Коды пунктов и зон цитатой не являются: это идентификаторы, которыми
#: продукт связывает сущности по жёсткому правилу проекта, и они были в
#: репозитории всегда. Ловим текст, а не коды — в том числе ячейку из
#: нескольких кодов через запятую: она тоже перечень идентификаторов.
_КОД = re.compile(r"^[A-Z]{2,4}\d{2}(?:\s*,\s*[A-Z]{2,4}\d{2})*$")


def _норма(s: str) -> str:
    return _КЛАСС.sub("", (s or "").strip()).rstrip(".").strip()


def _иглы(data: Path) -> set[str]:
    """Всё, что не должно встречаться в репозитории, — прямо из методики."""
    иглы: set[str] = set()

    with (data / "checklist.csv").open(encoding="utf-8") as f:
        for row in csv.DictReader(f):
            for ключ in ("question_ru", "question_en"):
                иглы.add(_норма(row.get(ключ) or ""))

    зоны: set[str] = set()
    with (data / "zones.csv").open(encoding="utf-8") as f:
        for row in csv.DictReader(f):
            for ключ in ("name_ru", "name_en"):
                зоны.add(_норма(row.get(ключ) or ""))

    # Критерии — самое чувствительное, что есть в методике: дословные правила
    # «что считать каким классом» плюс ссылки на внутренние стандарты. Формулировку
    # вопроса можно угадать по смыслу, критерий — нет, это и есть ноу-хау
    # управляющей компании. До 04.09.2026 их тут не было вовсе: иглы строились
    # по вопросам, зонам и подсказкам, и строка критериев проходила насквозь.
    for строка in (data / "criteria.md").read_text(encoding="utf-8").splitlines():
        текст = _норма(строка.lstrip("#*-| ").strip())
        if len(текст) >= МИН_ДЛИНА:
            иглы.add(текст)

    # ВСЕ ячейки таблицы подсказок, а не первая: пороги классов живут в
    # остальных колонках, и именно поэтому их не находили два прохода подряд.
    for line in (data / "photo-cues.md").read_text(encoding="utf-8").splitlines():
        if line.startswith("|") and line.count("|") >= 3:
            for ячейка in line.split("|"):
                иглы.add(_норма(ячейка))

    годные = {и for и in иглы if len(и) >= МИН_ДЛИНА}
    годные |= {з for з in зоны if len(з) >= МИН_ДЛИНА_ЗОНЫ}
    return {и for и in годные if и not in ИСКЛЮЧЕНИЯ and not _КОД.match(и)}


#: Что выведено за скобки — и это НЕ «markdown», а именно документы. Разница
#: не словесная: `tests/methodology/*.md` — не дока, а данные, которыми идёт
#: весь набор, то есть первое место, куда следующий человек скопирует боевую
#: формулировку «чтобы было похоже на настоящее». Пока фильтр стоял по
#: расширению, фикстура не проверялась вовсе.
#:
#: Документы вне проверки по решению владельца о видимости репозитория (D073):
#: там названия зон стоят по построению, и красить ими сборку бессмысленно.
ВНЕ_ПРОВЕРКИ = ("docs/", "progress.md", "tasks.md", "CHANGELOG.md")


def _вне_проверки(относительный: Path) -> bool:
    имя = относительный.as_posix()
    return any(имя.startswith(x) for x in ВНЕ_ПРОВЕРКИ)


def _файлы_под_git(корень: Path) -> Iterator[Path]:
    вывод = subprocess.run(
        ["git", "ls-files"],  # noqa: S607 — git из PATH
        cwd=корень,
        capture_output=True,
        text=True,
        check=True,
    ).stdout
    for имя in вывод.split():
        путь = корень / имя
        if путь.is_file():
            yield путь


@requires_data
def test_методика_не_цитируется_в_коде_и_тестах() -> None:
    """Код и тесты не содержат формулировок методики — только идентификаторы.

    Документы вынесены за скобки отдельным тестом ниже: там названия зон стоят
    по построению, и это вопрос видимости репозитория, а не дефект.
    """
    корень = Path(__file__).resolve().parents[1]
    иглы = _иглы(DATA)
    assert иглы, "иглы не собрались — тест перестал что-либо проверять"

    находки: list[str] = []
    for путь in _файлы_под_git(корень):
        if _вне_проверки(путь.relative_to(корень)):
            continue
        try:
            текст = путь.read_text(encoding="utf-8")
        except (UnicodeDecodeError, OSError):
            continue
        for игла in иглы:
            if игла in текст:
                находки.append(f"{путь.relative_to(корень)}: «{игла[:40]}»")

    assert not находки, (
        "методика управляющей компании процитирована в репозитории "
        f"({len(находки)} шт.), а он публичный:\n  " + "\n  ".join(sorted(находки))
    )


@requires_data
def test_демо_набор_не_повторяет_боевую_методику() -> None:
    """Демо обещает боевых данных не касаться — проверяем, что так и есть.

    Демо-набор лежит В git, боевая методика намеренно вне его, поэтому любое
    дословное совпадение здесь — утечка того же рода, что чинили в тестах.
    """
    корень = Path(__file__).resolve().parents[1]
    demo = корень / "demo" / "data"
    if not demo.is_dir():
        pytest.skip("демо-набора нет в этой копии")

    иглы = _иглы(DATA)
    находки: list[str] = []
    for путь in sorted(demo.iterdir()):
        if not путь.is_file():
            continue
        try:
            текст = путь.read_text(encoding="utf-8")
        except (UnicodeDecodeError, OSError):
            continue
        for игла in иглы:
            if игла in текст:
                находки.append(f"{путь.relative_to(корень)}: «{игла[:40]}»")

    assert not находки, "демо-набор повторяет боевую методику дословно:\n  " + "\n  ".join(
        sorted(находки)
    )
