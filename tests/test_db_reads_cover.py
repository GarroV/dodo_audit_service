"""T176: шапка письма — аудитор, город, партнёр и контакт — доезжает до чтения.

Слив записывает эти четыре поля в `inspections` с самого T091, но слой чтения
их не выбирал и `InspectionRow` их не отдавал. Наружу это выходило не отказом,
а испорченным документом: письмо, пересобранное по записанной проверке
(`src/mcp/letters.py`), подписывалось прочерком вместо имени аудитора, и
движок при этом выходил с нулевым кодом.

Поэтому проверяется не «колонка есть в запросе», а то, что записанное сливом
значение возвращается ИМЕННО ТЕМ ЖЕ — и что снятие колонки из запроса видно.
Рядом с каждым «поле пришло» стоит сверка со значением, заданным при заведении
проверки: поле, заполненное пустой строкой, выглядело бы «прочитанным» и
подписывало бы письмо ровно тем же прочерком.
"""

from __future__ import annotations

from pathlib import Path

import pytest
from conftest import requires_db

psycopg = pytest.importorskip("psycopg")

from src.db.push import push_inspection  # noqa: E402 — после importorskip намеренно
from src.db.queries import get_inspection, list_inspections  # noqa: E402
from src.domain import add_finding, start_inspection  # noqa: E402

pytestmark = requires_db

АРЕНДАТОР = "шапка"

#: Шапка проверки так, как её задаёт мастер бота. Значения разные и непустые:
#: одинаковые не отличили бы перепутанные местами колонки, а пустые — снятую
#: колонку от честно незаполненного поля.
ШАПКА = {
    "auditor": "Василий Гарро",
    "city": "Белград",
    "partner": "ООО «Партнёр Балканы»",
    "contact": "Марко Марković, +381 60 000-00-00",
}


def _проверка(
    chat_id: int, *, точка: str = "Белград-1", шапка: dict[str, str] | None = None
) -> str:
    """Завершённая проверка с заполненной шапкой — через контракт домена."""
    поля = ШАПКА if шапка is None else шапка
    start_inspection(
        chat_id,
        unit=точка,
        kind="planned",
        report_lang="ru",
        tenant=АРЕНДАТОР,
        auditor=поля["auditor"],
        city=поля["city"],
        partner=поля["partner"],
        contact=поля["contact"],
    )
    add_finding(chat_id, code="CLN05", level="D1", zone="hot_kitchen", text="нагар на печи")
    return push_inspection(chat_id)


def test_чтение_по_идентификатору_отдаёт_шапку_письма(domain_env: Path, db_env: str) -> None:
    """Главная проверка задачи: по этому пути письмо и пересобирается.

    `src/mcp/letters.py` берёт поля из прочитанной записи по имени
    (`getattr(detail.inspection, поле, "")`), поэтому непрочитанное поле не
    падает, а превращается в прочерк в подписи письма партнёру.
    """
    ident = _проверка(701)

    прочитано = get_inspection(ident, tenant=АРЕНДАТОР)

    assert прочитано is not None, "проверка не прочиталась — дальше сверять нечего"
    строка = прочитано.inspection
    assert строка.auditor == ШАПКА["auditor"], (
        "чтение не вернуло аудитора — именно этим прочерком подписывалось письмо"
    )
    assert строка.city == ШАПКА["city"]
    assert строка.partner == ШАПКА["partner"]
    assert строка.contact == ШАПКА["contact"]


def test_список_проверок_отдаёт_шапку_письма(domain_env: Path, db_env: str) -> None:
    """Тот же список, что читает MCP: шапка обязана быть и в нём.

    Письмо собирается по `get_inspection`, но список — это первое, что видит
    спрашивающий, и «аудитор: пусто» там читается как «аудитора не записали».
    """
    _проверка(702)

    строки = list_inspections(tenant=АРЕНДАТОР)

    assert len(строки) == 1, "проверка не попала в список — дальше сверять нечего"
    строка = строки[0]
    assert строка.auditor == ШАПКА["auditor"]
    assert строка.city == ШАПКА["city"]
    assert строка.partner == ШАПКА["partner"]
    assert строка.contact == ШАПКА["contact"]


def test_выборка_по_точке_отдаёт_шапку_письма(domain_env: Path, db_env: str) -> None:
    """Третий запрос слоя чтения. Свой текст — значит, своя возможность его забыть.

    У списка два текста запроса (с точкой и без), и колонку легко добавить в
    один из них: тогда шапка есть, пока не назвали точку, и пропадает ровно у
    того, кто спрашивает про конкретную пиццерию.
    """
    _проверка(703, точка="Ниш-1")

    строки = list_inspections(tenant=АРЕНДАТОР, unit="Ниш-1")

    assert len(строки) == 1, "проверка не нашлась по точке — дальше сверять нечего"
    строка = строки[0]
    assert строка.auditor == ШАПКА["auditor"]
    assert строка.city == ШАПКА["city"]
    assert строка.partner == ШАПКА["partner"]
    assert строка.contact == ШАПКА["contact"]


def test_незаполненная_шапка_остаётся_пустой_а_не_ломает_чтение(
    domain_env: Path, db_env: str
) -> None:
    """Пустая шапка законна: мастер бота даёт эти поля пропустить.

    Колонки объявлены `not null default ''`, поэтому «поле не заполнено» и
    «поля нет» обязаны выглядеть одинаково — пустой строкой, а не `None`,
    который у потребителя превратился бы в слово «None» в подписи письма.
    """
    ident = _проверка(704, шапка=dict.fromkeys(ШАПКА, ""))

    прочитано = get_inspection(ident, tenant=АРЕНДАТОР)

    assert прочитано is not None
    строка = прочитано.inspection
    assert (строка.auditor, строка.city, строка.partner, строка.contact) == ("", "", "", "")
