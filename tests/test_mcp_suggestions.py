def test_хвост_фраз_обрезан_и_назван_числом() -> None:
    """Один промах может стоять за сотней разных фраз, и вывалить их все значило
    бы утопить ответ. Обрезка названа числом здесь же, а не общим `truncated`:
    тот говорит про непрочитанные проверки, и подмена сказала бы неправду."""
    находки = [
        находка(n=i, code="CLN07", слова=f"фраза {i:02d}") for i in range(1, PHRASES_PER_MISS + 3)
    ]

    услышано = собрать(*находки)["code_misses"][0]["heard"]

    assert len(услышано["phrases"]) == PHRASES_PER_MISS
    assert услышано["other_phrases"] == 2
    assert "not listed" in услышано["note"]


