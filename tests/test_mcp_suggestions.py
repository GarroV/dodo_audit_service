# --- фраза, которую произнёс аудитор (T194) -----------------------------------


def test_промах_называет_фразу_аудитора_а_не_только_строку_карты() -> None:
    """Требование владельца было про ФРАЗУ: «если пользователь добавит что-то в
    духе "ГРЯЗЬ НА ПОЛКЕ В ГОРЯЧЕМ ЦЕХЕ, ЭТО ЧИСТОТА" то мы дополняем наш список
    терминов». Строка карты при этом никуда не девается: управляющей компании
    надо понять, какую строку править, аудитору — увидеть, что он сказал."""
    итог = собрать(находка(code="CLN07", слова="ГРЯЗЬ НА ПОЛКЕ В ГОРЯЧЕМ ЦЕХЕ, ЭТО ЧИСТОТА"))

    промах = итог["code_misses"][0]
    assert промах["heard"]["phrases"] == [
        {"phrase": "ГРЯЗЬ НА ПОЛКЕ В ГОРЯЧЕМ ЦЕХЕ, ЭТО ЧИСТОТА", "count": 1}
    ]
    assert [строка["phrase"] for строка in промах["cue_rows"]] == ["Пол в разводах, лужа на полу"]


