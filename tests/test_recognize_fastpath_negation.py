"""T195 (#160): быстрый путь не записывает то, что аудитор отрицает.

Защита от отрицания была только там, где выбирается колонка («грязь» против
«поломки»). Строку карты она не проверяла вовсе — совпадение шло по основам
слов, а частицу основа не видит. На боевой методике по-русски это выглядело так
(строка карты здесь не приводится — методика управляющей компании в публичный
репозиторий не цитируется, см. `tests/test_methodology_leak.py`):

    «<строка карты про нарушение>»       → пункт этой строки
    «<та же строка, но с частицей НЕ>»   → ТОТ ЖЕ пункт

Цена ошибки здесь выше, чем у неверного кандидата для модели: быстрый путь
показывает пункт кнопкой и без подтверждения (D064) — запись уходит в отчёт
партнёру, и аудитор увидит её, только если перечитает список перед сборкой.

**Чего эти тесты требуют, кроме отказа.** Слишком строгое правило обнулило бы
быстрый путь незаметно: доля срабатываний упала бы до нуля, а выглядело бы как
«стало безопаснее». Поэтому половина файла — сторожа против перестраховки:
отрицание в другой части фразы («жалоб нет, ...»), отрицание не того слова
(«печь не сломана» — это про поломку, а не про печь) и строка карты, которая
сама сформулирована через отрицание, обязаны работать как работали.

Методика здесь синтетическая (T141). Там, где нужна строка-высказывание с
глаголом, а не строка-объект («Урна в зале»), тест дописывает свою в КОПИЮ
карты: боевая карта лежит вне git и одна на все рабочие копии (D002), а её
формулировки в репозиторий не попадают.
"""

from __future__ import annotations

from pathlib import Path

import pytest

from src.recognize.cues import CUES_FILE
from src.recognize.fastpath import NO_COLUMN, NO_CUE, fast_path

# --- строка-объект: «Урна в зале» → CLN13 ----------------------------------


