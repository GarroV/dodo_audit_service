# --- сторожа против перестраховки ------------------------------------------


def test_отрицание_в_другой_части_фразы_не_снимает_срабатывание(domain_env: Path) -> None:
    """«Жалоб нет, в зале урна переполнена» — отрицание про жалобы, а не про урну.

    Правило «слово рядом с отрицанием не считается» без оглядки на знаки
    препинания снимает здесь срабатывание: «нет» и «урна» стоят рядом через
    запятую. Замер на боевой карте: так теряются 30 строк из 32 — быстрый путь
    обнуляется молча. Поэтому отрицание за знаком препинания не действует.
    """
    итог = fast_path("жалоб нет, в зале урна переполнена", "dining")

    assert итог.item is not None, итог.reason
    assert итог.item.code == "CLN13"


def test_отрицание_после_находки_не_снимает_срабатывание(domain_env: Path) -> None:
    """«… , остальное без замечаний» — хвост про остальное, находка остаётся."""
    итог = fast_path("в зале урна переполнена, остальное без замечаний", "dining")

    assert итог.item is not None, итог.reason
    assert итог.item.code == "CLN13"


def test_отрицание_действует_вперёд_а_не_назад(domain_env: Path) -> None:
    """«Печь не сломана» отрицает поломку, а не печь.

    Частица «не» по-русски относится к тому, что стоит ПОСЛЕ неё. Правило,
    снимающее слово и слева, и справа, отбросило бы саму «печь» — строка карты
    перестала бы находиться, и вместо честного «по словам не видно, грязь это
    или поломка» аудитор получил бы «ни одна строка карты не произнесена».
    Причина отказа — то, что видно в замере, и подменять её нельзя.
    """
    assert fast_path("печь не сломана", "hot_kitchen").reason == NO_COLUMN


def test_строка_карты_с_отрицанием_требует_отрицания_и_в_словах(
    карта_с_высказыванием: Path,
) -> None:
    """«Короб БЕЗ пломбы» — строка карты, сформулированная через отсутствие.

    Правило сверяет отрицание с двух сторон: слово, отрицаемое в строке карты,
    обязано быть отрицаемым и в словах аудитора. Иначе «короб с пломбой»
    покрывал бы строку «короб без пломбы», то есть ровно наоборот, — и правило,
    заведённое против записи отрицания, само стало бы его записывать.
    """
    сказано = fast_path("на складе, короб без пломбы", "fridge")
    отрицание_снято = fast_path("на складе, короб с пломбой", "fridge")

    assert сказано.item is not None, сказано.reason
    assert сказано.item.code == "PRD11"
    assert отрицание_снято.reason == NO_CUE, "без отрицания строка про отсутствие не произнесена"


# --- T197 (#160): одно и то же слово сказано и отрицаемо разом --------------


def test_слово_сказанное_и_отрицаемое_разом_не_покрывает_строку(domain_env: Path) -> None:
    """Остаток отрицания, названный замером T195: 8 случаев из 412.

    Разбор считает основы слов НАБОРАМИ, и одна основа, встреченная во фразе
    дважды, попадала сразу в оба набора: одно вхождение отрицаемо, второе
    сказано утвердительно. Утвердительное побеждало — строка карты считалась
    покрытой, и быстрый путь показывал пункт.

    Так это выглядит на точке: урны в зале нет, а переполнена она в подсобке.
    Обе половины фразы правда, вместе они означают «в зале нарушения нет», а
    записывался ровно противоположный пункт — про зал. Подтверждения такая
    запись не требует (D064) и уходит в отчёт партнёру.

    Верный ответ здесь — отказ, то есть обычный вызов модели: фраза
    противоречива по словам, а быстрый путь на то и быстрый, что берётся
    только за бесспорное.
    """
    итог = fast_path("в зале урны нет, а в подсобке урна переполнена", "dining")

    assert итог.item is None, f"записан пункт {итог.item and итог.item.code} про зал"
    assert итог.reason == NO_CUE


def test_повтор_слова_без_отрицания_срабатывание_не_снимает(domain_env: Path) -> None:
    """Сторож против перестраховки: повтор слова сам по себе ничего не значит.

    Правило обязано смотреть на противоречие («сказано и отрицаемо»), а не на
    повтор. Спутай эти две вещи — и обычная речь, где слово называется дважды,
    перестала бы срабатывать вовсе.
    """
    итог = fast_path("в зале урна переполнена, вторая урна рядом такая же", "dining")

    assert итог.item is not None, итог.reason
    assert итог.item.code == "CLN13"


def test_противоречие_снимает_и_строку_сформулированную_через_отсутствие(
    карта_с_высказыванием: Path,
) -> None:
    """То же правило со стороны строки карты про отсутствие — и оно тоже отказ.

    «Короб без пломбы» требует отрицания и в словах (T195). Сказать при этом
    про пломбу утвердительно во второй раз — то же противоречие, и разрешать
    его за человека быстрый путь не должен ни в ту сторону, ни в другую:
    правило симметрично, потому что и разбор комментария, и разбор строки
    карты — один и тот же разбор.
    """
    итог = fast_path("на складе, короб без пломбы, пломба валяется рядом", "fridge")

    assert итог.item is None, f"записан пункт {итог.item and итог.item.code} на противоречии"
    assert итог.reason == NO_CUE
