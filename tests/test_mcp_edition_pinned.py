"""T236: каталог издания опознаётся ОТПЕЧАТКОМ, и ответ на этот вопрос один.

До задачи вопрос «где каталог издания X» имел в продукте два разных ответа.
Полка снимков домена (`domain.edition`, T169) сверяла отпечаток: годным
считался каталог, чьё содержимое и есть это издание. Хранилище версий MCP
(`mcp.letters.pinned`) довольствовалось ИМЕНЕМ каталога.

Для письма это было наполовину скомпенсировано: движок пересчитывает оценку
(`letters._verify`), и подмена методики выдала бы другую букву. У карточки
проверки (`mcp.info_part`) компенсации нет вовсе — она берёт каталог у того же
`pinned` и читает из него подписи полей, ничего не считая. Каталог с правильным
именем и чужим содержимым подписал бы ответы аудитора формулировками другой
методики молча.

Здесь проверяется закрытие: сверка есть, ответ один на обоих потребителей, и
он тот же самый, что у полки домена.
"""

from __future__ import annotations

import shutil
from pathlib import Path

import pytest
from mcp_checklist_harness import build_edition, build_methodology

from src.domain.config import DATA_FILES, Settings
from src.domain.edition import shelf, snapshot
from src.domain.version import edition_of
from src.mcp import letters
from src.mcp.checklist import VERSIONS_DIR
from src.mcp.errors import ToolError

#: Пункт, дописываемый в чек-лист, чтобы у двух изданий отличалось содержимое.
#: Формулировки выдуманы: боевая методика лежит вне git (D002).
ПУНКТ_СНИМКА = "INF07,info,Итоги,Wrap-up,Срок из снимка,Deadline from snapshot,D1,*,10\n"
ПУНКТ_ПОДМЕНЫ = "INF07,info,Итоги,Wrap-up,Срок из подмены,Deadline from swap,D1,*,10\n"


def _дописать(каталог: Path, строка: str) -> None:
    with (каталог / "checklist.csv").open("a", encoding="utf-8") as файл:
        файл.write(строка)


def _издание(каталог: Path, строка: str, *, day: str) -> str:
    """Издание со своим содержимым: набор оснастки плюс одна своя строка."""
    build_edition(каталог, day=day)
    _дописать(каталог, строка)
    издание = edition_of(каталог, DATA_FILES)
    assert издание is not None
    return издание


# --- имя каталога доказательством не является ---------------------------------


def test_каталог_с_правильным_именем_и_чужим_содержимым_в_дело_не_идёт(tmp_path: Path) -> None:
    """Тот самый дефект: имя совпадает, содержимое чужое.

    Каталог кладёт не только этот блок — рядом полка бота, ручная копия,
    восстановление из резервной копии. Поэтому «каталог с таким именем есть»
    и «это то самое издание» — разные утверждения, и второе стоит одного
    чтения файлов.
    """
    настоящее = _издание(tmp_path / "настоящее", ПУНКТ_СНИМКА, day="2026-09-04")

    подмена = tmp_path / "store" / VERSIONS_DIR / настоящее
    build_edition(подмена, day="2026-09-04")
    _дописать(подмена, ПУНКТ_ПОДМЕНЫ)
    assert подмена.is_dir(), "каталог под именем издания обязан существовать"
    assert edition_of(подмена, DATA_FILES) != настоящее, "подмена обязана быть НЕ этим изданием"

    assert letters.pinned(настоящее, letters.Papers(live=None, store=tmp_path / "store")) is None


def test_снимок_того_же_издания_берётся_как_и_прежде(tmp_path: Path) -> None:
    """Встречное утверждение: сверка не отвергает годный снимок.

    Без него тест выше был бы зелен и на коде, который не берёт вообще ничего,
    — а это отняло бы у карточки подписи, а у письма письмо.
    """
    издание = _издание(tmp_path / "живая", ПУНКТ_СНИМКА, day="2026-09-04")
    снимок = tmp_path / "store" / VERSIONS_DIR / издание
    shutil.copytree(tmp_path / "живая", снимок)

    найдено = letters.pinned(издание, letters.Papers(live=None, store=tmp_path / "store"))

    assert найдено is not None
    каталог, откуда = найдено
    assert каталог == снимок
    assert откуда == letters.FROM_SNAPSHOT


