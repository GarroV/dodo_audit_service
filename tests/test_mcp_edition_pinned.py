def test_полка_домена_и_хранилище_MCP_отвечают_одинаково(tmp_path: Path) -> None:
    """Сведение, ради которого задача и заведена.

    Один и тот же каталог, один и тот же вопрос — и два разных потребителя,
    которые до T236 отвечали на него по-разному. Расходились они молча: у
    полки была сверка, у хранилища не было, и заметить это можно было только
    по подписи чужой методики под ответом аудитора.
    """
    издание = _издание(tmp_path / "живая", ПУНКТ_СНИМКА, day="2026-09-04")
    состояние = tmp_path / "state"
    настройки = Settings(
        data_dir=tmp_path / "живая",
        state_dir=состояние,
        audit_script=tmp_path / "audit.py",
    )
    полка = shelf(настройки) / издание
    shutil.copytree(tmp_path / "живая", полка)

    # Годный снимок опознают оба.
    assert snapshot(настройки, издание) == полка
    бумаги = letters.Papers(live=None, store=None, shelf=shelf(настройки))
    assert letters.pinned(издание, бумаги) == (полка, letters.FROM_SHELF)

    # Подменённый — тоже оба, и одинаково.
    _дописать(полка, ПУНКТ_ПОДМЕНЫ)
    assert snapshot(настройки, издание) is None
    assert letters.pinned(издание, бумаги) is None


def test_полка_бота_даёт_издание_которого_в_хранилище_MCP_нет(tmp_path: Path) -> None:
    """Вторая половина сведения: полка знает то, чего хранилище не знает.

    Хранилище версий наполняет правка методики через агента, полку — каждый
    выезд на точку. Проверка, начатая до переиздания, помечена изданием,
    которого в хранилище не появится никогда, — и письмо по ней собиралось бы
    отказом «снимка нет», хотя снимок лежит на соседней полке.

    Брать его безопасно ровно потому, что сверка отпечатка уже есть: до неё
    это было бы расширением дефекта, а не его закрытием.
    """
    издание = _издание(tmp_path / "выезд", ПУНКТ_СНИМКА, day="2026-09-04")
    состояние = tmp_path / "state"
    полка = состояние / "methodology" / издание
    shutil.copytree(tmp_path / "выезд", полка)

    # Хранилище MCP заведено и пусто, боевая методика — другое издание.
    (tmp_path / "store" / VERSIONS_DIR).mkdir(parents=True)
    build_methodology(tmp_path / "боевая")
    бумаги = letters.Papers(
        live=tmp_path / "боевая",
        store=tmp_path / "store",
        shelf=состояние / "methodology",
    )

    найдено = letters.pinned(издание, бумаги)

    assert найдено is not None
    assert найдено == (полка, letters.FROM_SHELF)


def test_полка_читается_из_окружения_а_не_подставляется_вызовом(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    """Инструменты получают от точки входа только код арендатора.

    Каталоги методики `sources()` берёт из окружения — так же, как берёт своё
    окружение блок `db`. Полка обязана приезжать оттуда же, иначе у неё
    появился бы второй способ быть названной, и назвать её смог бы вызывающий.
    """
    monkeypatch.setenv("STATE_DIR", str(tmp_path / "state"))
    monkeypatch.delenv("MCP_CHECKLIST_STORE", raising=False)
    monkeypatch.delenv("AUDIT_DATA_DIR", raising=False)

    бумаги = letters.sources()

    assert бумаги.shelf == tmp_path / "state" / "methodology"

    monkeypatch.delenv("STATE_DIR", raising=False)
    assert letters.sources().shelf is None, "полки без STATE_DIR быть не может"


def test_имя_издания_с_побегом_не_читает_каталог_за_полкой(tmp_path: Path) -> None:
    """Сверка отпечатка сторожа имени не заменяет: они про разное.

    Отпечаток отвечает, ТО ЛИ ЭТО содержимое; сторож имени — куда мы вообще
    пошли смотреть. За `..` кладётся настоящая работающая методика, иначе тест
    был бы зелёным по неверной причине — побег упирался бы во второй сторож
    «такого каталога нет».

    Побег теперь ОТКАЗ, а не `None` (T243). Молчаливое `None` означало для
    обоих потребителей «издания на машине нет»: испорченный идентификатор был
    неотличим от потерянного снимка, и человека посылали искать то, чего никто
    не терял.
    """
    чужое = _издание(tmp_path / "sneaky", ПУНКТ_ПОДМЕНЫ, day="2026-09-04")
    (tmp_path / "state" / "methodology").mkdir(parents=True)
    бумаги = letters.Papers(live=None, store=None, shelf=tmp_path / "state" / "methodology")

    with pytest.raises(ToolError):
        letters.pinned("../../sneaky", бумаги)
    with pytest.raises(ToolError):
        letters.pinned(f"../../{чужое}", бумаги)


def test_подменённый_каталог_называется_в_логе_а_не_в_ответе(
    tmp_path: Path, capsys: pytest.CaptureFixture[str]
) -> None:
    """Сверка закрывает дефект и не имеет права спрятать его причину.

    До сверки недоразложенный снимок доходил до чтения `checklist.csv` и
    оставлял в логе путь к себе — по нему человек и чинил хранилище. Сверка
    отвергает такой каталог раньше, поэтому след обязан остаться здесь: иначе
    у того, у кого на полке лежит каталог с правильным именем и чужим
    содержимым, нет ни одного способа узнать, какой именно.

    Путь при этом остаётся в логе процесса и в ответ не уходит (T120) — сам
    ответ проверяет `tests/test_mcp_no_paths.py`.
    """
    издание = _издание(tmp_path / "настоящее", ПУНКТ_СНИМКА, day="2026-09-04")
    подмена = tmp_path / "store" / VERSIONS_DIR / издание
    build_edition(подмена, day="2026-09-04")
    _дописать(подмена, ПУНКТ_ПОДМЕНЫ)
    capsys.readouterr()

    assert letters.pinned(издание, letters.Papers(live=None, store=tmp_path / "store")) is None

    сказано = capsys.readouterr().err
    assert str(подмена) in сказано, "подменённый каталог не назван нигде"


def test_переизданная_боевая_методика_лога_не_плодит(
    tmp_path: Path, capsys: pytest.CaptureFixture[str]
) -> None:
    """Встречное утверждение: лог о подмене — не лог о каждом чтении.

    Боевую методику переиздают, а письма собирают по прежним изданиям — это
    обычный ход дела, а не подмена. Жалоба на него утопила бы настоящую
    подмену в шуме, и лог перестал бы читать кто-либо.
    """
    издание = _издание(tmp_path / "живая", ПУНКТ_СНИМКА, day="2026-09-04")
    _дописать(tmp_path / "живая", ПУНКТ_ПОДМЕНЫ)
    capsys.readouterr()

    assert letters.pinned(издание, letters.Papers(live=tmp_path / "живая", store=None)) is None

    assert capsys.readouterr().err == ""


def test_самозванец_назван_в_логе_даже_когда_выручила_соседняя_полка(
    tmp_path: Path, capsys: pytest.CaptureFixture[str]
) -> None:
    """Удачный ответ не отменяет того, что хранилище сломано.

    Самое неприятное расположение: в хранилище версий лежит каталог с
    правильным именем и чужим содержимым, а издание проверки при этом честно
    лежит на полке бота. Ответ выходит верным, и потому дефект был бы виден
    ровно ничем: сломанное хранилище продолжало бы стоять, пока в один день
    полка не окажется убрана.
    """
    издание = _издание(tmp_path / "выезд", ПУНКТ_СНИМКА, day="2026-09-04")
    полка = tmp_path / "state" / "methodology" / издание
    shutil.copytree(tmp_path / "выезд", полка)

    самозванец = tmp_path / "store" / VERSIONS_DIR / издание
    build_edition(самозванец, day="2026-09-04")
    _дописать(самозванец, ПУНКТ_ПОДМЕНЫ)
    capsys.readouterr()

    бумаги = letters.Papers(
        live=None, store=tmp_path / "store", shelf=tmp_path / "state" / "methodology"
    )

    найдено = letters.pinned(издание, бумаги)

    assert найдено == (полка, letters.FROM_SHELF), "ответ обязан остаться верным"
    assert str(самозванец) in capsys.readouterr().err, (
        "самозванец за спиной удачного ответа остался незамеченным"
    )
