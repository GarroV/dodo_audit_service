"""T114: период отбирается в базе, а не после чтения страницы.

Почему это не косметика. Историю проверок за три года зальют одним заходом
программно (D035) — значит, `pushed_at` у всех записей окажется одной датой.
После этого «первая страница по дате слива» и «проверки за период» перестают
быть связаны вовсе: отбор поверх прочитанной страницы начнёт систематически
терять проверки, и заметить это будет нечем — ответ выглядит нормальным
списком, просто не тем.

Поэтому здесь проверяются две вещи, обе на данных вида D035 (одна дата слива
на всю историю): период отбирает база, а «свежие впереди» считается по дате
ОБХОДА точки, а не по дате попадания в базу.
"""

from __future__ import annotations

from datetime import date, timedelta
from pathlib import Path

import pytest
from conftest import requires_db

psycopg = pytest.importorskip("psycopg")

from src.db.errors import DbError  # noqa: E402 — после importorskip намеренно
from src.db.push import push_inspection  # noqa: E402
from src.db.queries import _LIST_ALL_SQL, MAX_LIMIT, list_inspections  # noqa: E402
from src.domain import add_finding, start_inspection  # noqa: E402

pytestmark = requires_db

АРЕНДАТОР_А = "партнёр-а"
АРЕНДАТОР_Б = "партнёр-б"

#: Начало залитой истории. Дальше даты идут подряд по дню на проверку.
НАЧАЛО = date(2023, 1, 1)


def _проверка(chat_id: int, *, арендатор: str, дата: str, точка: str = "Белград-1") -> str:
    """Завершённая проверка нужного арендатора через официальный контракт домена."""
    start_inspection(
        chat_id, unit=точка, kind="Плановая", report_lang="ru", tenant=арендатор, date=дата
    )
    add_finding(chat_id, code="CLN05", level="D1", zone="hot_kitchen", text="нагар на печи")
    return push_inspection(chat_id)


# --- залитая история (D035) --------------------------------------------------

#: Сколько точек у арендатора в залитой истории. Не одна намеренно: у сети
#: сотни пиццерий, и на одной точке планировщик выбирает не тот план, что на
#: настоящих данных, — проверка плана на такой заливке ничего не проверяет.
ТОЧЕК = 40

_ТОЧКИ_SQL = """
insert into units (tenant_code, name, name_normalized)
select %(tenant)s, 'Точка ' || g, 'точка ' || g
from generate_series(1, %(точек)s) g
"""

# Одна дата слива на всю историю — это и есть D035: заливка идёт одним заходом,
# и `pushed_at` перестаёт различать проверки. Дата обхода при этом у каждой
# своя, по дню на строку.
_ИСТОРИЯ_SQL = """
with точки as (
    select id, row_number() over (order by name_normalized) - 1 as ном
    from units where tenant_code = %(tenant)s
)
insert into inspections (
    tenant_code, unit_id, chat_id, kind, inspection_date, report_lang,
    ui_lang, speech_lang, checklist_version, pct, grade, source_fingerprint,
    pushed_at
)
select
    %(tenant)s, т.id, 1, 'Плановая', %(начало)s::date + g, 'ru',
    'ru', 'ru', 'v1', 97.5, 'A', %(tenant)s || '-' || g,
    %(слив)s::timestamptz
from generate_series(0, %(сколько)s - 1) g
join точки т on т.ном = g %% %(точек)s
"""


def _залить_историю(dsn: str, *, арендатор: str, сколько: int) -> None:
    """История за годы, слитая одним заходом: даты обхода разные, дата слива одна.

    Заливка идёт под привилегированной ролью: `analyze` требует владения
    таблицей, а без свежей статистики планировщик строит план по выдуманным
    оценкам и проверять его бессмысленно.
    """
    with psycopg.connect(dsn) as conn, conn.cursor() as cur:
        cur.execute(
            "insert into tenants (code) values (%(tenant)s) on conflict (code) do nothing",
            {"tenant": арендатор},
        )
        cur.execute(_ТОЧКИ_SQL, {"tenant": арендатор, "точек": ТОЧЕК})
        cur.execute(
            _ИСТОРИЯ_SQL,
            {
                "tenant": арендатор,
                "начало": НАЧАЛО,
                "сколько": сколько,
                "точек": ТОЧЕК,
                "слив": "2026-09-03 12:00:00+00",
            },
        )
        cur.execute("analyze inspections")
        cur.execute("analyze units")
        conn.commit()


def test_период_отбирается_в_базе_а_не_поверх_прочитанной_страницы(
    pg_dsn: str, db_env: str
) -> None:
    """Проверки нужного периода лежат ЗА пределом чтения по дате слива.

    Окно взято намеренно в хвосте истории: эти проверки — с 1128-й по 1155-ю
    по порядку заливки, то есть дальше потолка чтения (`MAX_LIMIT` = 1000).
    Отбор периода поверх прочитанной страницы вернул бы здесь пустоту и
    сказал бы «за этот период проверок нет» — на настоящей истории это тот же
    ответ, что и правда, и отличить их нечем.
    """
    _залить_историю(pg_dsn, арендатор=АРЕНДАТОР_А, сколько=1200)
    окно_с, окно_по = date(2026, 2, 1), date(2026, 2, 28)
    assert (окно_с - НАЧАЛО).days > MAX_LIMIT, "окно должно лежать за потолком чтения"

    строки = list_inspections(tenant=АРЕНДАТОР_А, date_from=окно_с, date_to=окно_по)

    даты = [строка.inspection_date for строка in строки]
    assert len(даты) == 28, f"за февраль 2026 прочитано {len(даты)} проверок вместо 28"
    assert min(даты) == окно_с and max(даты) == окно_по
    assert all(окно_с <= д <= окно_по for д in даты)


def test_свежими_считаются_проверки_по_дате_обхода_а_не_по_дате_слива(
    pg_dsn: str, db_env: str
) -> None:
    """После заливки истории `pushed_at` одинаков у всех — сортировать по нему
    значит отдавать случайные строки под видом последних проверок."""
    _залить_историю(pg_dsn, арендатор=АРЕНДАТОР_А, сколько=1200)
    последняя = НАЧАЛО + timedelta(days=1199)

    строки = list_inspections(tenant=АРЕНДАТОР_А, limit=3)

    assert [строка.inspection_date for строка in строки] == [
        последняя,
        последняя - timedelta(days=1),
        последняя - timedelta(days=2),
    ]


def test_период_не_выпускает_за_арендатора(pg_dsn: str, db_env: str) -> None:
    """Фильтр по датам не заменяет фильтр по арендатору и не отменяет его."""
    _залить_историю(pg_dsn, арендатор=АРЕНДАТОР_А, сколько=40)
    _залить_историю(pg_dsn, арендатор=АРЕНДАТОР_Б, сколько=40)

    строки = list_inspections(
        tenant=АРЕНДАТОР_А, date_from=НАЧАЛО, date_to=НАЧАЛО + timedelta(days=39)
    )

    assert {строка.tenant_code for строка in строки} == {АРЕНДАТОР_А}
    assert len(строки) == 40


