def test_период_идёт_по_индексу_а_не_полным_проходом(pg_dsn: str) -> None:
    """План строит настоящий планировщик на настоящем объёме, а не догадка.

    Разбирается тот же текст запроса, который выполняет код: план,
    закреплённый по переписанной от руки копии, обещает не то, что происходит.
    """
    _залить_историю(pg_dsn, арендатор=АРЕНДАТОР_А, сколько=8000)
    _залить_историю(pg_dsn, арендатор=АРЕНДАТОР_Б, сколько=2000)

    with psycopg.connect(pg_dsn) as conn, conn.cursor() as cur:
        cur.execute(
            "explain " + _LIST_ALL_SQL,
            {
                "tenant": АРЕНДАТОР_А,
                "limit": 100,
                "date_from": НАЧАЛО + timedelta(days=5000),
                "date_to": НАЧАЛО + timedelta(days=5030),
            },
        )
        план = "\n".join(строка[0] for строка in cur.fetchall())

    assert "Seq Scan on inspections" not in план, (
        f"выборка за период читает таблицу проверок целиком:\n{план}"
    )
    assert "inspections_tenant_date_idx" in план, (
        f"выборка за период не пользуется индексом по арендатору и дате проверки:\n{план}"
    )
