"""T166: замер ложных срабатываний признака «это <процесс>» меряет то, что обещает.

Урок T125 стоил задачи: замер быстрого пути год считал долю по зоне из
эталонной записи и выдавал за боевое число то, чего у бота нет. Здесь та же
опасность в другом месте — корпус. Признак живёт в **сырых словах аудитора**;
всё остальное (формулировки записей, вопросы методики, критерии) — речь другого
рода, и если замер молча сложит их в одно число, получится доля ложных
срабатываний на выборке, где ложным срабатыванием быть нечему.

Поэтому проверяется не «сколько получилось», а устройство: корпуса считаются
раздельно, сырые слова читаются те самые, что завёл T183, а пустой корпус
сырых слов виден как пустой, а не как ноль ложных срабатываний.
"""

from __future__ import annotations

import json
from pathlib import Path

from src.domain import add_finding, start_inspection
from src.domain.config import check_environment
from src.domain.engine import state_file
from tools.process_hint_measure import corpora, measure, render, spoken_words

CHAT = 794_000_166

#: Пример владельца из D077 на синтетическом имени процесса.
СКАЗАНО = "ГРЯЗЬ НА ПОЛКЕ В ГОРЯЧЕМ ЦЕХЕ, ЭТО ПОРЯДОК"


def _проверка_со_словами(слова: str) -> None:
    start_inspection(
        CHAT,
        unit="Замер признака",
        kind="planned",
        report_lang="ru",
        date="2026-09-05",
        auditor="Тест",
    )
    add_finding(CHAT, "CLN05", "D1", "hot_kitchen", "Нагар на подине печи", words=слова)


def test_сырые_слова_читаются_те_самые_что_завёл_T183(domain_env: Path) -> None:
    """Замер обязан брать слова оттуда же, где их хранит продукт.

    Своя копия правил чтения разошлась бы с продуктом молча, и замер снова мерил
    бы не то — ровно та ошибка, которую разбирала T125.
    """
    _проверка_со_словами(СКАЗАНО)
    assert state_file(CHAT, check_environment()).is_file()

    assert spoken_words(domain_env) == (СКАЗАНО,)


def test_признак_на_сырых_словах_виден_отдельно_от_остальных_корпусов(
    domain_env: Path, tmp_path: Path
) -> None:
    """Корпуса не складываются в одно число: у них разная природа."""
    _проверка_со_словами(СКАЗАНО)

    итоги = [measure(c) for c in corpora(tmp_path)]

    слова, записи = итоги[0], итоги[1]
    assert len(слова.corpus.texts) == 1
    assert len(слова.fired) == 1, "признак не сработал на фразе, ради которой заведён"
    assert слова.fired[0][0] == "Порядок"
    assert записи.corpus.texts == (), "боевых проверок в этом прогоне нет"
    assert {и.corpus.title for и in итоги}.__len__() == len(итоги), "корпуса не различимы по имени"


def test_пустой_корпус_сырых_слов_виден_как_пустой(domain_env: Path, tmp_path: Path) -> None:
    """Ноль текстов и ноль ложных срабатываний — разные утверждения.

    Пока слов не накоплено, доля ложных срабатываний не посчитана ни по чему, и
    отчёт обязан говорить это словами, а не показывать успокоительный ноль.
    """
    отчёт = render([measure(c) for c in corpora(tmp_path)])

    assert "Пусто: мерить нечего" in отчёт


def test_имя_процесса_без_связки_считается_но_не_срабатывает(
    domain_env: Path, tmp_path: Path
) -> None:
    """Потолок признака и сам признак — два разных столбца.

    Без этого различения нельзя сказать, что именно делает признак пригодным:
    имя процесса встречается в обычной речи о нарушениях, связка — почти нет.
    """
    _проверка_со_словами("Нужно навести порядок на складе")

    слова = measure(next(iter(corpora(tmp_path))))

    assert слова.named == 1, "имя процесса в тексте есть"
    assert слова.linked == 0
    assert слова.fired == (), "без связки это обычный комментарий, а не указание"


def test_испорченный_файл_состояния_не_роняет_замер(domain_env: Path, tmp_path: Path) -> None:
    """Одна битая папка чата — не повод не померить остальные.

    Замер идёт по всему каталогу состояния, а туда пишет живой бот: недописанный
    файл после падения процесса там возможен, и падать на нём замеру незачем.
    """
    _проверка_со_словами(СКАЗАНО)
    битая = domain_env / "chat-000"
    битая.mkdir()
    (битая / "inspection.json").write_text("{не json", encoding="utf-8")
    пустая = domain_env / "chat-001"
    пустая.mkdir()
    (пустая / "inspection.json").write_text(json.dumps({}), encoding="utf-8")

    assert spoken_words(domain_env) == (СКАЗАНО,)
