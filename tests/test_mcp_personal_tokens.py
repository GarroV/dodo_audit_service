"""T253: сторона MCP сверяет ЛИЧНЫЙ токен, выпущенный ботом (решение D098).

До этой задачи у сервера была одна дверь — карта «арендатор=токен» из `.env`.
Токен в ней принадлежит СТОРОНЕ, открывает всю её историю проверок и
отзывается правкой файла с перезапуском, то есть у всех сразу. Теперь рядом
появилась вторая: токены, выпущенные ботом на конкретного человека, хранимые
отпечатком и отзываемые поимённо (`src/db/mcp_access.py`).

Проверяется здесь ровно стык, а не хранилище: механика выпуска и отзыва живёт
в `tests/test_db_mcp_access.py`, разговор с человеком — в
`tests/test_bot_mcp_setup.py`. Сюда вынесено то, что не видно ни оттуда, ни
оттуда:

* личный токен опознаётся и приносит СВОЕГО арендатора;
* **карта из `.env` продолжает работать** — на момент перехода это
  единственный живой доступ, и отключать его тем же движением, которым
  вводится новый, значило бы устроить перерыв в работе ради опрятности;
* отозванный личный токен не опознаётся;
* личный токен НЕ получает права снимать проверки: оно остаётся за
  `MCP_RETRACTION_TOKENS`, где его называют руками;
* отказ базы не выдаётся за незнакомый токен молча — причина уходит в журнал.
"""

from __future__ import annotations

import logging

import pytest
from conftest import requires_db

from src.mcp.config import (
    MCP_RETRACTION_TOKENS_VAR,
    MCP_TOKENS_VAR,
    MIN_TOKEN_LENGTH,
    Settings,
    load_settings,
    resolve_access,
)
from src.mcp.errors import AuthError

#: Выдуманный токен стороны нужной длины: настоящих в коде продукта нет.
ТОКЕН_СТОРОНЫ = "s" * MIN_TOKEN_LENGTH
АРЕНДАТОР_СТОРОНЫ = "партнёр-из-файла"

#: Человек, на которого бот выпускает личный токен, и его арендатор. Арендатор
#: намеренно ДРУГОЙ: если бы личный токен приносил арендатора из карты `.env`,
#: разница была бы не видна, и подмена прошла бы незамеченной.
ЧЕЛОВЕК = 777001
АРЕНДАТОР_ЧЕЛОВЕКА = "управляющая-компания"


def _настройки(**env: str) -> Settings:
    return load_settings({MCP_TOKENS_VAR: f"{АРЕНДАТОР_СТОРОНЫ}={ТОКЕН_СТОРОНЫ}", **env})


def _выпустить(кому: int = ЧЕЛОВЕК, арендатор: str = АРЕНДАТОР_ЧЕЛОВЕКА) -> str:
    """Привести человека в круг и выпустить ему токен — как это делает бот."""
    from src.db.mcp_access import add_admin, issue_token

    add_admin(кому, by=None)
    return issue_token(кому, tenant=арендатор).value


# --- вторая дверь ------------------------------------------------------------


@requires_db
def test_личный_токен_опознаётся_и_приносит_своего_арендатора(db_env: str) -> None:
    """Суть стыка: сервер узнаёт токен, которого нет ни в одной строке `.env`.

    Арендатор при этом берётся из записи о токене, а не из карты файла, —
    поэтому он здесь заведомо другой, чем у стороны.
    """
    личный = _выпустить()

    доступ = resolve_access(_настройки(), f"Bearer {личный}")

    assert доступ.tenant == АРЕНДАТОР_ЧЕЛОВЕКА


@requires_db
def test_карта_из_файла_продолжает_работать(db_env: str) -> None:
    """Прежний доступ не отключён появлением нового.

    На момент перехода токены из `.env` — единственный живой доступ к серверу.
    Отключить их тем же движением, которым вводятся личные, означало бы
    устроить перерыв в работе ради опрятности.
    """
    доступ = resolve_access(_настройки(), f"Bearer {ТОКЕН_СТОРОНЫ}")

    assert доступ.tenant == АРЕНДАТОР_СТОРОНЫ


@requires_db
def test_отозванный_личный_токен_не_опознаётся(db_env: str) -> None:
    """Отзыв обязан действовать на самой двери, а не только в боте.

    Бот у сервера не спрашивается вовсе: он выпускает, сервер сверяет. Если бы
    отзыв жил только в боте, отозванный токен продолжал бы открывать историю
    проверок — то есть отзыв не отзывал бы ничего.
    """
    from src.db.mcp_access import revoke_access

    личный = _выпустить()
    revoke_access(ЧЕЛОВЕК, by=ЧЕЛОВЕК)

    with pytest.raises(AuthError):
        resolve_access(_настройки(), f"Bearer {личный}")


@requires_db
def test_повторный_выпуск_закрывает_прежний_токен_и_на_сервере(db_env: str) -> None:
    """«Показан один раз» проверяется там, где токен предъявляют.

    В боте видно, что строка пришла новая; что СТАРАЯ перестала открывать
    историю проверок — видно только здесь.
    """
    первый = _выпустить()
    второй = _выпустить()

    assert resolve_access(_настройки(), f"Bearer {второй}").tenant == АРЕНДАТОР_ЧЕЛОВЕКА
    with pytest.raises(AuthError):
        resolve_access(_настройки(), f"Bearer {первый}")


@requires_db
def test_незнакомый_токен_по_прежнему_отказ(db_env: str) -> None:
    """Вторая дверь не должна открывать то, чего не открывала первая.

    Отказ при этом не называет ни предъявленный токен, ни живых арендаторов:
    перечислять по нему партнёров не должен никто.
    """
    with pytest.raises(AuthError) as отказ:
        resolve_access(_настройки(), "Bearer " + "z" * MIN_TOKEN_LENGTH)

    assert АРЕНДАТОР_СТОРОНЫ not in str(отказ.value)
    assert АРЕНДАТОР_ЧЕЛОВЕКА not in str(отказ.value)


# --- чего личный токен НЕ даёт ------------------------------------------------


@requires_db
def test_личный_токен_не_получает_права_снимать_проверки(db_env: str) -> None:
    """Снятие проверки необратимо для партнёра: документ у него на руках.

    Раздавать такое право вместе с обычным доступом, выпускаемым в чате, —
    отдельное решение, которого никто не принимал. Право остаётся там, где его
    называют руками (`MCP_RETRACTION_TOKENS`), и здесь проверяется, что личный
    токен его не подобрал по дороге.
    """
    личный = _выпустить()
    настройки = _настройки(**{MCP_RETRACTION_TOKENS_VAR: ТОКЕН_СТОРОНЫ})

    assert resolve_access(настройки, f"Bearer {личный}").may_retract is False
    assert resolve_access(настройки, f"Bearer {ТОКЕН_СТОРОНЫ}").may_retract is True


@requires_db
def test_личный_токен_требует_схемы_Bearer_как_и_все(db_env: str) -> None:
    """Второй дверью не заводится второй вид годного заголовка.

    Голый токен без схемы сервер не принимает (T116): инструменты маскируют в
    логах именно образец `Bearer <токен>`. Появление личных токенов не повод
    сделать для них исключение — исключение как раз и было бы тем видом
    доступа, который нигде не описан.
    """
    личный = _выпустить()

    with pytest.raises(AuthError, match="Bearer"):
        resolve_access(_настройки(), личный)


# --- отказ базы не выдаётся за незнакомый токен -------------------------------


def test_недоступная_база_не_выдаётся_за_незнакомый_токен_молча(
    monkeypatch: pytest.MonkeyPatch, caplog: pytest.LogCaptureFixture
) -> None:
    """Тихий `None` объяснил бы человеку его же беду неверными словами.

    Владелец личного токена получил бы «токен не опознан» и пошёл бы искать
    свой токен, пока настоящая причина — недоступный список доступа. Клиенту
    по-прежнему достаётся общий отказ (перечислять по нему устройство сервера
    не должен никто), но причина обязана уйти в журнал, и уйти заметно.

    База здесь недоступна по-настоящему: `DATABASE_URL` снят автоматической
    фикстурой `_база_не_видна_сама_собой`, то есть сверка личных токенов
    падает на чтении окружения — ровно так же, как упала бы на отказе связи.
    """
    caplog.set_level(logging.WARNING)

    with pytest.raises(AuthError):
        resolve_access(_настройки(), "Bearer " + "q" * MIN_TOKEN_LENGTH)

    assert caplog.records, "про несостоявшуюся сверку личных токенов не сказано ничего"
    assert any(запись.levelno >= logging.WARNING for запись in caplog.records), (
        "о недоступном списке доступа сказано тише предупреждения"
    )
