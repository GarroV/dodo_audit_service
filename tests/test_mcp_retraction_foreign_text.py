"""T211: заслон от чужого текста в ответе опирается на `__cause__` — и это сверяется.

`src/mcp/retraction._retract` различает два вида отказа блока `db` по
происхождению текста: `RetractionError` с `__cause__` — это обёрнутый чужой
отказ, и в его тексте стоит сообщение драйвера (у psycopg там адрес, порт и имя
базы), а без `__cause__` — отказ, написанный блоком `db` целиком, и он уезжает
человеку дословно.

Правило держится ровно до тех пор, пока в `src/db/retract.py` соблюдается
обратное: если чужой текст в сообщение подставлен, исключение обёрнуто через
`raise ... from`. Сегодня так и есть, но это соглашение между двумя блоками,
и живёт оно в разных файлах. Автор, который завтра напишет
`raise RetractionError(f"... {exc}")` без `from exc`, откроет чужому тексту
дорогу в ответ агенту — и ни один тест поведения этого не заметит, потому что
для такого отказа нужен сломанный драйвер.

Поэтому соглашение проверяется разбором исходника: заслон построен на нём, и
проверять его должен тот, кто на него опирается.
"""

from __future__ import annotations

import ast
from pathlib import Path

СНЯТИЕ = Path(__file__).resolve().parent.parent / "src" / "db" / "retract.py"


def _имена(узел: ast.AST) -> set[str]:
    """Все имена, упомянутые в поддереве."""
    return {вложенный.id for вложенный in ast.walk(узел) if isinstance(вложенный, ast.Name)}


def test_чужой_текст_в_отказе_снятия_всегда_обёрнут_через_from() -> None:
    """Подставил в сообщение перехваченное исключение — обязан назвать его причиной.

    Проверяется не «есть ли `from` вообще», а совпадение двух вещей: имя
    перехваченного исключения упомянуто в аргументах `raise`, и у этого же
    `raise` назван `from`. Ровно по этому совпадению инструмент и решает,
    можно ли показать текст человеку.
    """
    дерево = ast.parse(СНЯТИЕ.read_text(encoding="utf-8"), filename=str(СНЯТИЕ))

    нарушения: list[str] = []
    for узел in ast.walk(дерево):
        if not isinstance(узел, ast.ExceptHandler) or узел.name is None:
            continue
        поймано = узел.name
        for внутри in ast.walk(узел):
            if not isinstance(внутри, ast.Raise) or внутри.exc is None:
                continue
            if поймано not in _имена(внутри.exc):
                continue
            if внутри.cause is None:
                нарушения.append(f"строка {внутри.lineno}: «{поймано}» в тексте, но без from")

    assert not нарушения, (
        "в src/db/retract.py текст перехваченного отказа подставлен в сообщение, "
        "а исключение не обёрнуто через `from` — инструмент MCP считает такой отказ "
        "написанным блоком db и покажет его агенту целиком, вместе с адресом и именем "
        "базы (T120). Нарушения: " + "; ".join(нарушения)
    )


def test_разбор_и_правда_видит_нарушение() -> None:
    """Встречное утверждение: без него проверка выше зелена на любом файле.

    Разбор исходника легко написать так, что он не находит ничего никогда, —
    и выглядит это точно так же, как соблюдённое соглашение.
    """
    образец = ast.parse(
        "try:\n    ...\nexcept ValueError as exc:\n    raise RetractionError(f'беда: {exc}')\n"
    )

    найдено = [
        внутри.lineno
        for узел in ast.walk(образец)
        if isinstance(узел, ast.ExceptHandler) and узел.name is not None
        for внутри in ast.walk(узел)
        if isinstance(внутри, ast.Raise)
        and внутри.exc is not None
        and узел.name in _имена(внутри.exc)
        and внутри.cause is None
    ]

    assert найдено == [4]
