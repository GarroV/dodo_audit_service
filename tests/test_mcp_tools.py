"""T095: инструменты чтения MCP на настоящей базе.

Проверяется не «инструмент что-то вернул», а четыре свойства, ради которых
блок и делался осторожно:

1. **Чужого арендатора не видно ни через один инструмент.** Арендатор приходит
   из токена (`src/mcp/config.py`), в аргументы вызова не входит вовсе — и
   снятый фильтр обязан валить эти тесты, а не оставаться незамеченным до
   первого партнёра.
2. **Оценка не считается заново.** Проценты, буквы и разбивка приходят из базы
   ровно такими, какими их положил движок; инструмент не выводит из них новых
   чисел.
3. **Пусто — это ответ, а не молчание.** У каждой пустой выдачи есть
   написанное словами состояние.
4. **Предел есть у каждой выдачи**, и когда чтение в него упёрлось, ответ
   говорит об этом сам.
"""

