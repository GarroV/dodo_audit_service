def test_процент_и_буква_приходят_из_базы_как_их_положил_движок(
    domain_env: Path, db_env: str
) -> None:
    """Сверка идёт с оценкой движка, а не с ожидаемым числом в тесте.

    Собственная арифметика, случайно совпавшая с движком на этих данных, эту
    проверку не пройдёт: сравниваются те же значения, что вернул `score`.
    """
    _проверка(209, арендатор=АРЕНДАТОР_А, находок=3)
    оценка = score(209)

    строка = list_inspections(tenant=АРЕНДАТОР_А)["inspections"][0]

    assert строка["pct"] == pytest.approx(оценка.pct)
    assert строка["grade"] == оценка.grade


def test_сводка_не_выводит_новых_чисел_об_оценке(domain_env: Path, db_env: str) -> None:
    """В сводке нет ни среднего процента, ни буквы сети.

    Среднее по проверкам — число, которого не записывал никто; появившись в
    ответе инструмента, оно немедленно начинает цитироваться как «оценка
    сети». Распределение записанных букв и записанные крайние значения несут
    тот же сигнал, ничего не выдумывая.
    """
    _проверка(210, арендатор=АРЕНДАТОР_А, точка="Белград-1", находок=1)
    _проверка(211, арендатор=АРЕНДАТОР_А, точка="Ниш-1", находок=5)

    сводка = network_summary(tenant=АРЕНДАТОР_А)

    записанные = {строка.pct for строка in db_list_inspections(tenant=АРЕНДАТОР_А)}
    assert сводка["best"]["pct"] in записанные
    assert сводка["worst"]["pct"] in записанные
    записанные_буквы = {строка.grade for строка in db_list_inspections(tenant=АРЕНДАТОР_А)}
    assert set(сводка["grades"]) <= записанные_буквы
    выдуманные = {"average", "avg", "mean", "average_pct", "grade", "network_grade", "trend"}
    assert not выдуманные & set(сводка), f"в сводке появилось выведенное число: {сводка.keys()}"


