    деталь = get_inspection(tenant=АРЕНДАТОР_А, id=id_а)
    находки = findings_by_unit(tenant=АРЕНДАТОР_А, unit="Белград-1")

    выдуманные = {"average", "avg", "mean", "trend", "repeats", "repeated", "total_pct"}
    assert not выдуманные & set(деталь), (
        f"в деталях проверки появилось выведенное число: {деталь.keys()}"
    )
    assert not выдуманные & set(находки), f"в находках появилось выведенное число: {находки.keys()}"
