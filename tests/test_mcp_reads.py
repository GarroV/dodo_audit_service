"""Инструменты чтения `get_inspection` и `findings_by_unit` на настоящей базе.

Слой чтения блока `db` эти два запроса уже умеет (T114); здесь проверяется
именно прокладка блока `mcp` поверх него — те же четыре свойства, что и у
трёх прежних инструментов (`tests/test_mcp_tools.py`), плюс то, что появилось
только с деталями проверки и находками:

1. **Чужого арендатора не видно.** Ни настоящий чужой идентификатор проверки,
   ни чужая точка не должны отвечать данными — снятый фильтр по арендатору на
   пути к слою чтения обязан валить эти тесты.
2. **Оценка не считается заново.** `pct`, `grade`, `deductions`, `counts` и
   набор зон в `by_zone` приходят из движка ровно такими, какими он их
   положил при завершении проверки.
3. **Пусто — это ответ, а не молчание и не отказ.** Несуществующий
   идентификатор и чужая проверка отвечают одинаково: `found: False` и
   словами — это не `ToolError`.
4. **Личные идентификаторы и выведенные числа наружу не уезжают.** `chat_id`
   не появляется ни в одном ответе; ни среднего, ни счёта повторов, ни доли
   инструменты не считают за спрашивающего.
5. **`text`/`comment` не теряют различие `None` и пустой строки.** «Перевода
   нет вовсе» и «аудитор ничего не написал» — разные состояния находки.
"""

from __future__ import annotations

import json
import uuid
from pathlib import Path

import pytest
from conftest import requires_db

pytest.importorskip("psycopg")

from src.db.push import push_inspection
from src.db.queries import MAX_LIMIT
from src.domain import add_finding, score, start_inspection
from src.mcp.errors import ToolError
from src.mcp.tools import findings_by_unit, get_inspection

pytestmark = requires_db

АРЕНДАТОР_А = "партнёр-а"
АРЕНДАТОР_Б = "партнёр-б"

#: Один пункт в одной зоне движок принимает один раз, поэтому несколько
#: находок разводятся по зонам, а не повторяют одну и ту же запись.
ЗОНЫ = ("hot_kitchen", "cold_kitchen", "dough", "dishwashing", "staff")


def _проверка(
    chat_id: int,
    *,
    арендатор: str,
    точка: str = "Белград-1",
    дата: str = "2026-08-15",
    находок: int = 1,
) -> str:
    """Завершённая проверка нужного арендатора через официальный контракт домена."""
    start_inspection(
        chat_id, unit=точка, kind="planned", report_lang="ru", tenant=арендатор, date=дата
    )
    for номер in range(находок):
        add_finding(chat_id, code="CLN05", level="D1", zone=ЗОНЫ[номер], text="нагар на печи")
    return push_inspection(chat_id)


# --- изоляция арендаторов ----------------------------------------------------


def test_чужую_проверку_по_настоящему_идентификатору_не_видно(
    domain_env: Path, db_env: str
) -> None:
    """Главная проверка файла: снятый фильтр по арендатору обязан её валить.

    Идентификатор настоящий и существующий — просто принадлежит другому
    арендатору. Ответ обязан быть тем же самым «не найдено», что и на
    случайный UUID: иначе перебор идентификаторов подтвердил бы существование
    чужого документа.
    """
    id_б = _проверка(401, арендатор=АРЕНДАТОР_Б, точка="Ниш-1")

    ответ = get_inspection(tenant=АРЕНДАТОР_А, id=id_б)

    assert ответ["found"] is False
    assert "no inspection found" in ответ["status"].lower()
    assert ответ["inspection"] is None
    assert ответ["findings"] == []


def test_находки_чужой_точки_не_видны(domain_env: Path, db_env: str) -> None:
    """Точка есть у соседа — её находки под чужим арендатором не читаются."""
    _проверка(402, арендатор=АРЕНДАТОР_Б, точка="Ниш-1")

    ответ = findings_by_unit(tenant=АРЕНДАТОР_А, unit="Ниш-1")

    assert ответ["count"] == 0
    assert ответ["findings"] == []
    assert "no findings" in ответ["status"].lower()


def test_одноимённая_точка_двух_арендаторов_не_склеивается(domain_env: Path, db_env: str) -> None:
    """«Белград-1» есть и у управляющей компании, и у партнёра."""
    id_а = _проверка(403, арендатор=АРЕНДАТОР_А, точка="Белград-1")
    _проверка(404, арендатор=АРЕНДАТОР_Б, точка="Белград-1")

    ответ = findings_by_unit(tenant=АРЕНДАТОР_А, unit="Белград-1")

    assert ответ["count"] == 1
    assert {находка["inspection_id"] for находка in ответ["findings"]} == {id_а}


# --- оценка не считается заново ----------------------------------------------


def test_числа_get_inspection_приходят_из_движка_как_их_положил_движок(
    domain_env: Path, db_env: str
) -> None:
    """Сверка идёт с оценкой движка, а не с ожидаемым числом в тесте.

    Собственная арифметика, случайно совпавшая с движком на этих данных, эту
    проверку не пройдёт: сравниваются те же значения, что вернул `score`.
    """
    chat_id = 405
    id_а = _проверка(chat_id, арендатор=АРЕНДАТОР_А, находок=3)
    оценка = score(chat_id)

    ответ = get_inspection(tenant=АРЕНДАТОР_А, id=id_а)

    assert ответ["inspection"]["pct"] == pytest.approx(оценка.pct)
    assert ответ["inspection"]["grade"] == оценка.grade
    assert ответ["deductions"] == pytest.approx(оценка.deductions)
    assert ответ["counts"] == оценка.counts
    assert set(ответ["by_zone"]) == set(оценка.by_zone)


# --- находки проверки читаются целиком ----------------------------------------


def test_находки_проверки_читаются_целиком(domain_env: Path, db_env: str) -> None:
    """Три записанные находки приходят все три, с кодами, уровнями, зонами, по
    порядку `n` — и с различимыми `text`/`comment`.

    `comment` в `_проверка` не заполняется — это и есть «аудитор ничего не
    написал», отличное от «перевода нет»: наружу обязан уйти `None`, а не
    пустая строка, которую подмена спутала бы со вторым состоянием.
    """
    id_а = _проверка(406, арендатор=АРЕНДАТОР_А, находок=3)

    ответ = get_inspection(tenant=АРЕНДАТОР_А, id=id_а)
    находки = ответ["findings"]

    assert len(находки) == 3
    assert [находка["n"] for находка in находки] == sorted(находка["n"] for находка in находки)
    assert {находка["zone"] for находка in находки} == set(ЗОНЫ[:3])
    assert all(находка["code"] == "CLN05" for находка in находки)
    assert all(находка["level"] == "D1" for находка in находки)
    assert all(находка["text"] == "нагар на печи" for находка in находки)
    assert all(находка["comment"] is None for находка in находки)


# --- личные идентификаторы наружу не уезжают ---------------------------------


def test_chat_id_наружу_не_уезжает_ни_из_одного_ответа(domain_env: Path, db_env: str) -> None:
    """`chat_id` — это чат аудитора в телеграме, агенту партнёра он не нужен.

    Проверка идёт по сериализованному ответу целиком, а не по перечню
    ожидаемых ключей: так же ловится и `chat_id`, случайно попавший внутрь
    вложенного `inspection` или одной из находок.
    """
    chat_id = 917253
    id_а = _проверка(chat_id, арендатор=АРЕНДАТОР_А, находок=2)

    деталь = json.dumps(get_inspection(tenant=АРЕНДАТОР_А, id=id_а))
    находки = json.dumps(findings_by_unit(tenant=АРЕНДАТОР_А, unit="Белград-1"))

    assert "chat_id" not in деталь
    assert str(chat_id) not in деталь
    assert "chat_id" not in находки
    assert str(chat_id) not in находки


# --- пусто — это ответ, а не отказ --------------------------------------------


def test_несуществующий_идентификатор_это_не_найдено_а_не_отказ(
    domain_env: Path, db_env: str
) -> None:
    ответ = get_inspection(tenant=АРЕНДАТОР_А, id=str(uuid.uuid4()))

    assert ответ["found"] is False
    assert "no inspection found" in ответ["status"].lower()
    assert ответ["inspection"] is None
    assert ответ["deductions"] is None
    assert ответ["counts"] is None
    assert ответ["by_zone"] is None
    assert ответ["findings"] == []


# --- аргументы проверяются, а не подгоняются ---------------------------------


@pytest.mark.parametrize("кривой", ["не-uuid", ""])
def test_кривой_идентификатор_проверки_это_отказ(кривой: str) -> None:
    """Кривой идентификатор — ошибка вызывающего, а не «проверки нет».

    Слитые в одно «не найдено», опечатка в идентификаторе выглядела бы
    законным ответом вместо сигнала, что спросили не то.
    """
    with pytest.raises(ToolError, match="UUID"):
        get_inspection(tenant=АРЕНДАТОР_А, id=кривой)


