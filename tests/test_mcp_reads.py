# --- предел ---------------------------------------------------------------


def test_findings_by_unit_предел_виден_в_ответе(domain_env: Path, db_env: str) -> None:
    """Предел применяет слой чтения — и ответ обязан сказать, что показал не
    всё, что нашёл."""
    _проверка(407, арендатор=АРЕНДАТОР_А, точка="Белград-1", находок=3)

    ответ = findings_by_unit(tenant=АРЕНДАТОР_А, unit="Белград-1", limit=2)

    assert ответ["count"] == 2
    assert ответ["truncated"] is True
    assert "limit" in ответ["status"].lower()


def test_findings_by_unit_свежие_проверки_впереди(domain_env: Path, db_env: str) -> None:
    """Находки точки идут начиная с более свежей по дате обхода проверки."""
    старая = _проверка(408, арендатор=АРЕНДАТОР_А, точка="Белград-1", дата="2026-06-01")
    свежая = _проверка(409, арендатор=АРЕНДАТОР_А, точка="Белград-1", дата="2026-07-01")

    ответ = findings_by_unit(tenant=АРЕНДАТОР_А, unit="Белград-1")

    идентификаторы_проверок = [находка["inspection_id"] for находка in ответ["findings"]]
    assert идентификаторы_проверок[0] == свежая
    assert идентификаторы_проверок[-1] == старая


# --- выведенных чисел не появляется -------------------------------------------


def test_ответы_не_выводят_новых_чисел(domain_env: Path, db_env: str) -> None:
    """Ни в деталях проверки, ни в находках точки нет посчитанного за
    спрашивающего: ни среднего, ни счёта повторов, ни доли."""
    id_а = _проверка(410, арендатор=АРЕНДАТОР_А, находок=2)

    деталь = get_inspection(tenant=АРЕНДАТОР_А, id=id_а)
    находки = findings_by_unit(tenant=АРЕНДАТОР_А, unit="Белград-1")

    выдуманные = {"average", "avg", "mean", "trend", "repeats", "repeated", "total_pct"}
    assert not выдуманные & set(деталь), (
        f"в деталях проверки появилось выведенное число: {деталь.keys()}"
    )
    assert not выдуманные & set(находки), f"в находках появилось выведенное число: {находки.keys()}"
