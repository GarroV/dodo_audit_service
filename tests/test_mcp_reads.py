pytestmark = requires_db

АРЕНДАТОР_А = "партнёр-а"
АРЕНДАТОР_Б = "партнёр-б"

#: Один пункт в одной зоне движок принимает один раз, поэтому несколько
#: находок разводятся по зонам, а не повторяют одну и ту же запись.
ЗОНЫ = ("hot_kitchen", "cold_kitchen", "dough", "dishwashing", "staff")


def _проверка(
    chat_id: int,
    *,
    арендатор: str,
    точка: str = "Белград-1",
    дата: str = "2026-08-15",
    находок: int = 1,
    язык_отчёта: str = "ru",
    инфо: tuple[tuple[str, str], ...] = (),
) -> str:
    """Завершённая проверка нужного арендатора через официальный контракт домена.

    Информационная часть записывается тем же путём, что у аудитора в конце
    обхода (`domain.set_info`), и в том порядке, в каком названа: порядок
    записи — это порядок разделов документа партнёру, и подменять его здесь
    сборкой строки в базе значило бы проверять не тот путь.
    """
    start_inspection(
        chat_id, unit=точка, kind="planned", report_lang=язык_отчёта, tenant=арендатор, date=дата
    )
    for номер in range(находок):
        add_finding(chat_id, code="CLN05", level="D1", zone=ЗОНЫ[номер], text="нагар на печи")
    for код, ответ in инфо:
        set_info(chat_id, код, ответ)
    return push_inspection(chat_id)


