"""T217 (#150): подписи в ручном перечне — ширина ряда, а не половина.

Ручной перечень — последняя линия обороны: модель не помогла или её нет вовсе,
и аудитор выбирает пункт руками. Кнопки в нём стоят по одной в ряд, а подпись
резалась по общему пределу продукта в 34 знака — числу, выведенному под кнопку
в ПОЛОВИНУ ряда. Из этих 34 знаков восемь забирал код пункта.

Чем это стоило на боевой методике: обрезанными показывались 94 % пунктов при
медианной длине формулировки в 64 знака. Выбирать приходилось по обрубку — на
точке, одной рукой, когда модель уже не помогла.

Правка возвращает место шириной ряда, а не снятием кода, и это измерено, а не
на глаз: после обрезки до 60 знаков одиннадцать пунктов боевой методики из 123
совпадают подписью буква в букву. Без кода аудитор выбирал бы из двух кнопок,
неразличимых на экране, — а код к тому же единственное, чем пункт связан с
методикой и отчётом.

**Формулировки боевой методики здесь не пишутся** (`tests/test_methodology_leak.py`):
что нужно от неё по существу — читается из неё же на ходу, остальное сочинено.
"""

from __future__ import annotations

from pathlib import Path

from aiogram.types import InlineKeyboardMarkup
from conftest import requires_data

from src.bot.keyboards import (
    BUTTON_TITLE_LIMIT,
    MANUAL_CODE_SEPARATOR,
    ROW_TITLE_LIMIT,
    manual_keyboard,
)
from src.bot.texts import UI_LANGS
from src.domain import list_items

КОД = "CLN05"
ПРЕФИКС = f"{КОД}{MANUAL_CODE_SEPARATOR}"

#: Сколько знаков остаётся формулировке: ряд минус код с разделителем.
ПОД_ФОРМУЛИРОВКУ = ROW_TITLE_LIMIT - len(ПРЕФИКС)


def _подписи(markup: InlineKeyboardMarkup) -> list[list[str]]:
    return [[button.text for button in row] for row in markup.inline_keyboard]


def _страница(*пункты: tuple[str, str]) -> InlineKeyboardMarkup:
    """Одна страница перечня из готовых пар «код, формулировка»."""
    return manual_keyboard([(n, code, title) for n, (code, title) in enumerate(пункты)], 0, 1, "ru")


def test_пункт_перечня_стоит_в_ряду_один() -> None:
    """Ширина ряда — это половина ряда дважды, и держится она тем, что кнопка одна."""
    ряды = _подписи(_страница(("CLN05", "первый"), ("CLN06", "второй"), ("PRD06", "третий")))

    пункты = ряды[:3]
    assert all(len(ряд) == 1 for ряд in пункты), f"пункты стоят не по одному в ряд: {пункты}"


def test_под_формулировку_отведён_ряд_за_вычетом_кода() -> None:
    """Не половина ряда: 34 знака под формулировку — это предел кнопки в два столбца.

    Проверяется на заведомо длинной выдуманной формулировке: важно, до чего её
    режут, а не что она значит.
    """
    (ряд, *_) = _страница((КОД, "очень длинная формулировка пункта " * 10)).inline_keyboard
    (кнопка,) = ряд

    assert кнопка.text.startswith(ПРЕФИКС), f"код с кнопки пропал: {кнопка.text}"
    assert len(кнопка.text) == ROW_TITLE_LIMIT, (
        f"подпись обрезана не по ширине ряда: {len(кнопка.text)} вместо {ROW_TITLE_LIMIT}"
    )
    assert len(кнопка.text) - len(ПРЕФИКС) > BUTTON_TITLE_LIMIT, (
        "формулировке отведено не больше, чем было, — место не вернулось"
    )


def test_предел_остался_и_виден_многоточием() -> None:
    """Сторож против «починки» снятием предела: ряд не бесконечный."""
    (ряд, *_) = _страница((КОД, "очень длинная формулировка пункта " * 10)).inline_keyboard
    (кнопка,) = ряд

    assert кнопка.text.endswith("…")


def test_формулировка_по_ширине_ряда_показана_целиком() -> None:
    """Ровно то, ради чего задача: то, что влезает в ряд, не обрезается."""
    формулировка = "ф" * ПОД_ФОРМУЛИРОВКУ

    (ряд, *_) = _страница((КОД, формулировка)).inline_keyboard
    (кнопка,) = ряд

    assert кнопка.text == ПРЕФИКС + формулировка


def test_код_на_кнопке_различает_совпавшие_обрубки() -> None:
    """Сторож против «починки» снятием кода: обрубки совпадают, кнопки — нет.

    Одиннадцать пар таких пунктов есть в боевой методике; здесь тот же случай
    выдуманными формулировками, чтобы сторож работал и без неё.
    """
    общее = "одинаковое начало формулировки " * 4

    ряды = _подписи(_страница(("CLN05", общее + "первый хвост"), ("CLN06", общее + "второй хвост")))

    первая, вторая = ряды[0][0], ряды[1][0]
    assert первая != вторая, "две кнопки перечня неразличимы на экране"


@requires_data
def test_на_боевой_методике_целиком_показана_треть_пунктов(live_data_env: Path) -> None:
    """Сторож к возврату половинного предела — фактом на самой методике.

    Боевая методика нужна по существу: дефект найден на ней, а в синтетической
    формулировки короткие и при любом пределе влезают. Числа: при 34 знаках
    целиком показывался каждый двадцатый пункт, при ширине ряда — почти
    половина. Порог взят с запасом вниз (треть), чтобы правка методики
    управляющей компанией не красила сборку без причины.

    Оба языка интерфейса: длины у них разные, и правка, проверенная только
    по-русски, могла бы не сработать для англоязычного аудитора.
    """
    пункты = [item for item in list_items() if item.kind == "violation"]
    assert пункты, "в боевой методике не нашлось ни одного пункта-нарушения"

    for lang in UI_LANGS:
        markup = _страница(*[(item.code, item.question(lang)) for item in пункты])
        # Хвост клавиатуры — «Не записывать», к пунктам он не относится.
        подписи = [row[0].text for row in markup.inline_keyboard[: len(пункты)]]
        целиком = [text for text in подписи if not text.endswith("…")]

        assert len(целиком) * 3 >= len(пункты), (
            f"на языке {lang} целиком показано {len(целиком)} пунктов из {len(пункты)} — "
            "предел подписи вернулся к половине ряда"
        )
