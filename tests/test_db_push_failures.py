"""Пути отказа слива в базу — те, что не покрывал ни один тест.

Найдено при приёмке спасённой работы блока engine-fix 03.09: движок стал
отказывать на нечитаемой дате проверки, и блок `db` получил собственную
проверку даты. Проверка появилась, а теста на неё не было — то есть на
следующей приёмке она уже считалась бы работающей просто потому, что строки
есть в коде.

Оба пути ведут к отказу слива, и оба молчаливыми быть не могут: проверка,
не доехавшая в базу, теряется целиком, и узнают об этом на отчёте.
"""

from __future__ import annotations

import pytest

# `psycopg` — зависимость блока `db`, а не всего проекта: без этой строки сбор
# этого файла падает целиком в окружении, где её ещё не поставили.
pytest.importorskip("psycopg")

from src.db.errors import PushError
from src.db.push import _parse_date, _require_row


def test_нечитаемая_дата_отменяет_слив() -> None:
    """Дата не в ISO — отказ с номером чата, а не проверка с пустой датой."""
    with pytest.raises(PushError) as exc:
        _parse_date("21.08.2026", chat_id=42)
    assert "42" in str(exc.value), "в отказе нет номера чата — непонятно, какую проверку чинить"
    assert "ГГГГ-ММ-ДД" in str(exc.value), "в отказе не назван нужный формат"


def test_читаемая_дата_проходит() -> None:
    assert _parse_date("2026-08-21", chat_id=42).isoformat() == "2026-08-21"


def test_пустой_ответ_после_insert_не_проглатывается() -> None:
    """`fetchone()` без строки — нарушенная транзакция, а не повод вернуть None.

    Тихий `None` здесь разошёлся бы по коду дальше и всплыл в другом месте,
    где причину уже не восстановить.
    """

    class ПустойКурсор:
        def fetchone(self) -> None:
            return None

    with pytest.raises(PushError) as exc:
        _require_row(ПустойКурсор())
    assert "целостность транзакции" in str(exc.value)
