"""Тесты каталога инструментов MCP (T111): что видно агенту и что за этим стоит.

Каталог — декларация поверх `src.mcp.tools`: имя, текст для агента, схема
аргументов, ссылка на обработчик. Главный риск здесь не в тексте описаний, а
в расхождении схемы и кода — новый параметр обработчика без записи в схеме
агент не увидит и не сможет назвать, а снятый параметр со следом в схеме
агент попробует передать напрасно. Второй риск — размытая граница арендатора:
схема, объявившая `tenant`, позволила бы агенту назвать код соседа (T110).

Каталог сам не импортирует `src.db`, и этим тестам база не нужна вовсе —
фикстуры `db_env`/`domain_env` здесь не подключаются намеренно.
"""

from __future__ import annotations

import inspect

from src.mcp.catalogue import TOOLS, as_list, find

ИМЕНА_ИНСТРУМЕНТОВ = {
    "list_inspections",
    "unit_history",
    "network_summary",
    "get_inspection",
    "findings_by_unit",
}


def test_каталог_содержит_ровно_пять_инструментов_с_ожидаемыми_именами() -> None:
    """Лишний инструмент в каталоге — не описанный обработчик, снятый —
    инструмент, к которому агент внезапно теряет доступ."""
    assert len(TOOLS) == 5
    assert {spec.name for spec in TOOLS} == ИМЕНА_ИНСТРУМЕНТОВ


def test_ни_одна_схема_не_объявляет_tenant() -> None:
    """`tenant` в схеме означал бы, что агент может назвать код соседа и
    прочитать его историю проверок — арендатор приходит только из личного
    токена запроса, не из аргумента вызова (T110)."""
    for spec in TOOLS:
        свойства = spec.input_schema["properties"]
        assert "tenant" not in свойства, spec.name


def test_каждая_схема_запрещает_лишние_свойства() -> None:
    """Без `additionalProperties: false` лишний или опечатанный аргумент
    прошёл бы молча вместо явного отказа."""
    for spec in TOOLS:
        assert spec.input_schema["additionalProperties"] is False, spec.name


def test_свойства_схемы_совпадают_с_сигнатурой_обработчика() -> None:
    """Главный тест файла: ловит расхождение схемы и кода при любой будущей
    правке обработчика в `src/mcp/tools.py`, до которой каталог не достали
    руками."""
    for spec in TOOLS:
        параметры_обработчика = set(inspect.signature(spec.handler).parameters) - {"tenant"}
        параметры_схемы = set(spec.input_schema["properties"])
        assert параметры_схемы == параметры_обработчика, spec.name


def test_required_согласован_со_схемой_и_с_сигнатурой_обработчика() -> None:
    """Обязательность в схеме и обязательность в коде обязаны совпадать:
    иначе агент либо не назовёт то, чего обработчик требует без запасного
    значения, либо схема требует то, что уже необязательно."""
    for spec in TOOLS:
        параметры_обработчика = inspect.signature(spec.handler).parameters
        свойства = set(spec.input_schema["properties"])
        обязательные = set(spec.input_schema["required"])
        assert обязательные <= свойства, spec.name
        for имя_параметра in свойства:
            без_умолчания = параметры_обработчика[имя_параметра].default is inspect.Parameter.empty
            assert без_умолчания == (имя_параметра in обязательные), (spec.name, имя_параметра)


def test_find_находит_каждый_инструмент_по_имени() -> None:
    for имя in ИМЕНА_ИНСТРУМЕНТОВ:
        найденный = find(имя)
        assert найденный is not None
        assert найденный.name == имя


def test_find_на_незнакомое_имя_отдаёт_none() -> None:
    """Опечатка в имени инструмента — это отказ, а не спецификация первого
    попавшегося инструмента из каталога."""
    assert find("несуществующий_инструмент") is None


def test_as_list_отдаёт_ровно_три_нужных_ключа_на_запись() -> None:
    """Протокол MCP `tools/list` ждёт camelCase `inputSchema` — лишний ключ
    или `input_schema` вместо него не разберёт клиент на другой стороне."""
    перечень = as_list()
    assert len(перечень) == 5
    for запись in перечень:
        assert set(запись) == {"name", "description", "inputSchema"}


def test_as_list_передаёт_то_же_имя_и_ту_же_схему_что_и_toolspec() -> None:
    """`as_list()` — витрина `TOOLS`, а не отдельный источник истины: если
    значения разошлись, MCP-клиент увидит не ту схему, по которой на самом
    деле вызывается обработчик."""
    по_имени = {запись["name"]: запись for запись in as_list()}
    for spec in TOOLS:
        запись = по_имени[spec.name]
        assert запись["description"] == spec.description
        assert запись["inputSchema"] == spec.input_schema


def test_описание_каждого_инструмента_непустое_и_не_короче_40_знаков() -> None:
    """Заглушка вместо описания — инструмент, который агент применит не по
    назначению: описание для него единственный источник о том, что делает
    вызов."""
    for spec in TOOLS:
        assert len(spec.description) >= 40, spec.name
