"""Тесты каталога инструментов MCP (T111, T098): что видно агенту и что за этим стоит.

Каталог — декларация поверх `src.mcp.tools` (инструменты проверок) и
`src.mcp.checklist_tools` (инструменты методики): имя, текст для агента,
схема аргументов, ссылка на обработчик, вид (`kind`). Главный риск здесь не в
тексте описаний, а в расхождении схемы и кода — новый параметр обработчика
без записи в схеме агент не увидит и не сможет назвать, а снятый параметр со
следом в схеме агент попробует передать напрасно. Второй риск — размытая
граница арендатора и хранилища: схема, объявившая `tenant` или `store`,
позволила бы агенту назвать код соседа или путь к чужому хранилищу методики
(T110). Третий риск — перепутанный `kind` или обработчик не из того модуля:
`kind` решает, пускать ли вызов вообще, и молча съехавший вид открыл бы
правку методики инструменту, которого никто на это не проверял; обработчик
из не того модуля вызывает не то, что объявлено агенту.

Каталог сам не импортирует `src.db`, и этим тестам база не нужна вовсе —
фикстуры `db_env`/`domain_env` здесь не подключаются намеренно.
"""

from __future__ import annotations

import inspect

from src.mcp import checklist_tools
from src.mcp import tools as tools_module
from src.mcp.catalogue import KIND_CHECKLIST, KIND_INSPECTIONS, TOOLS, as_list, find

ИМЕНА_ИНСТРУМЕНТОВ_ПРОВЕРОК = {
    "list_inspections",
    "unit_history",
    "network_summary",
    "get_inspection",
    "findings_by_unit",
    "inspection_letter",
}

ИМЕНА_ИНСТРУМЕНТОВ_МЕТОДИКИ = {
    "checklist_versions",
    "checklist_items",
    "checklist_item",
    "add_checklist_item",
    "edit_checklist_item",
    "remove_checklist_item",
    "restore_checklist_item",
    "add_zone",
    "remove_zone",
    "publish_checklist_version",
    "photo_cues",
    "add_photo_cue",
    "edit_photo_cue",
    "remove_photo_cue",
    "photo_cue_suggestions",
}

ИМЕНА_ИНСТРУМЕНТОВ = ИМЕНА_ИНСТРУМЕНТОВ_ПРОВЕРОК | ИМЕНА_ИНСТРУМЕНТОВ_МЕТОДИКИ

#: Кто ходит в базу проверок. Инструменты проверок — все, и с ними один
#: инструмент методики: предложения для управляющей компании собираются из
#: записанных находок (T165). Перечислено списком намеренно: по виду
#: инструмента это не выводится, а снятый флаг выключил бы заслон «пусто ≠
#: читать неоткуда» молча — перебор в `tests/test_mcp_no_history.py` просто
#: перестал бы этот инструмент видеть, не покраснев.
ИМЕНА_ЧИТАЮЩИХ_ИСТОРИЮ = ИМЕНА_ИНСТРУМЕНТОВ_ПРОВЕРОК | {"photo_cue_suggestions"}


def test_каталог_содержит_ровно_двадцать_один_инструмент_с_ожидаемыми_именами() -> None:
    """Лишний инструмент в каталоге — не описанный обработчик, снятый —
    инструмент, к которому агент внезапно теряет доступ."""
    assert len(TOOLS) == 21
    assert {spec.name for spec in TOOLS} == ИМЕНА_ИНСТРУМЕНТОВ


def test_ни_одна_схема_не_объявляет_tenant() -> None:
    """`tenant` в схеме означал бы, что агент может назвать код соседа и
    прочитать его историю проверок — арендатор приходит только из личного
    токена запроса, не из аргумента вызова (T110)."""
    for spec in TOOLS:
        свойства = spec.input_schema["properties"]
        assert "tenant" not in свойства, spec.name


def test_ни_одна_схема_не_объявляет_store() -> None:
    """`store` в схеме означал бы, что агент называет путь к хранилищу версий
    методики сам — хранилище подставляет точка входа сервера, а не аргумент
    вызова, точно так же, как арендатор приходит не из аргумента, а из
    токена."""
    for spec in TOOLS:
        свойства = spec.input_schema["properties"]
        assert "store" not in свойства, spec.name


def test_каждая_схема_запрещает_лишние_свойства() -> None:
    """Без `additionalProperties: false` лишний или опечатанный аргумент
    прошёл бы молча вместо явного отказа."""
    for spec in TOOLS:
        assert spec.input_schema["additionalProperties"] is False, spec.name


def test_свойства_схемы_совпадают_с_сигнатурой_обработчика() -> None:
    """Главный тест файла: ловит расхождение схемы и кода при любой будущей
    правке обработчика в `src/mcp/tools.py` или `src/mcp/checklist_tools.py`,
    до которой каталог не достали руками. `tenant` и `store` вычитаются из
    сигнатуры: их подставляет точка входа, а не собеседник, поэтому в схеме
    им взяться неоткуда."""
    for spec in TOOLS:
        параметры_обработчика = set(inspect.signature(spec.handler).parameters) - {
            "tenant",
            "store",
        }
        параметры_схемы = set(spec.input_schema["properties"])
        assert параметры_схемы == параметры_обработчика, spec.name


def test_required_согласован_со_схемой_и_с_сигнатурой_обработчика() -> None:
    """Обязательность в схеме и обязательность в коде обязаны совпадать:
    иначе агент либо не назовёт то, чего обработчик требует без запасного
    значения, либо схема требует то, что уже необязательно."""
    for spec in TOOLS:
        параметры_обработчика = inspect.signature(spec.handler).parameters
        свойства = set(spec.input_schema["properties"])
        обязательные = set(spec.input_schema["required"])
        assert обязательные <= свойства, spec.name
        for имя_параметра in свойства:
            без_умолчания = параметры_обработчика[имя_параметра].default is inspect.Parameter.empty
            assert без_умолчания == (имя_параметра in обязательные), (spec.name, имя_параметра)


def test_вид_инструмента_соответствует_его_группе() -> None:
    """`kind` решает, пускать ли вызов вообще (доступ к методике — отдельная
    настройка `MCP_CHECKLIST_TENANTS`): инструмент методики с перепутанным на
    `KIND_INSPECTIONS` видом открыл бы правку методики любому, у кого есть
    обычный токен, а инструмент проверок с `KIND_CHECKLIST` — наоборот, стал
    бы недоступен тем, кому доступны только проверки."""
    for spec in TOOLS:
        if spec.name in ИМЕНА_ИНСТРУМЕНТОВ_МЕТОДИКИ:
            assert spec.kind == KIND_CHECKLIST, spec.name
        else:
            assert spec.kind == KIND_INSPECTIONS, spec.name


def test_флаг_истории_стоит_ровно_у_тех_кто_читает_проверки() -> None:
    """Снятый флаг не роняет перебор в `tests/test_mcp_no_history.py` — тот
    просто перестаёт видеть инструмент. Поэтому список назван здесь: заслон,
    который можно выключить и не увидеть красного, заслоном не является."""
    assert {spec.name for spec in TOOLS if spec.history} == ИМЕНА_ЧИТАЮЩИХ_ИСТОРИЮ


def test_каждый_инструмент_проверок_объявляет_что_ходит_в_базу() -> None:
    """Флаг `history` включает инструмент в перебор «пусто ≠ читать неоткуда»
    (`tests/test_mcp_no_history.py`). Забытый у нового инструмента, он выключил
    бы этот заслон молча: на стенде с намеренно не поднятой базой инструмент
    ответил бы пустой выдачей, а агент пересказал бы её человеку как факт."""
    for spec in TOOLS:
        if spec.kind == KIND_INSPECTIONS:
            assert spec.history is True, spec.name


def test_обработчик_взят_из_правильного_модуля() -> None:
    """Инструмент, объявленный как чтение методики, но вызывающий что-то из
    `src.mcp.tools` (или наоборот), — это каталог, который врёт о том, что на
    самом деле выполнится: агент увидел одно описание, а вызвался чужой
    обработчик."""
    for spec in TOOLS:
        if spec.name in ИМЕНА_ИНСТРУМЕНТОВ_МЕТОДИКИ:
            assert spec.handler.__module__ == checklist_tools.__name__, spec.name
        else:
            assert spec.handler.__module__ == tools_module.__name__, spec.name


def test_find_находит_каждый_инструмент_по_имени() -> None:
    for имя in ИМЕНА_ИНСТРУМЕНТОВ:
        найденный = find(имя)
        assert найденный is not None
        assert найденный.name == имя


def test_find_на_незнакомое_имя_отдаёт_none() -> None:
    """Опечатка в имени инструмента — это отказ, а не спецификация первого
    попавшегося инструмента из каталога."""
    assert find("несуществующий_инструмент") is None


def test_as_list_отдаёт_ровно_три_нужных_ключа_на_запись() -> None:
    """Протокол MCP `tools/list` ждёт camelCase `inputSchema` — лишний ключ
    или `input_schema` вместо него не разберёт клиент на другой стороне."""
    перечень = as_list()
    assert len(перечень) == 21
    for запись in перечень:
        assert set(запись) == {"name", "description", "inputSchema"}


def test_as_list_передаёт_то_же_имя_и_ту_же_схему_что_и_toolspec() -> None:
    """`as_list()` — витрина `TOOLS`, а не отдельный источник истины: если
    значения разошлись, MCP-клиент увидит не ту схему, по которой на самом
    деле вызывается обработчик."""
    по_имени = {запись["name"]: запись for запись in as_list()}
    for spec in TOOLS:
        запись = по_имени[spec.name]
        assert запись["description"] == spec.description
        assert запись["inputSchema"] == spec.input_schema


def test_описание_каждого_инструмента_непустое_и_не_короче_40_знаков() -> None:
    """Заглушка вместо описания — инструмент, который агент применит не по
    назначению: описание для него единственный источник о том, что делает
    вызов."""
    for spec in TOOLS:
        assert len(spec.description) >= 40, spec.name


def test_описание_предложений_обещает_фразу_аудитора_а_не_её_отсутствие() -> None:
    """T194. Описание — единственное, из чего агент знает, о чём спрашивать
    инструмент. Пока оно говорило «сырых слов в истории нет», агент не стал бы
    и спрашивать про фразу — а она с T185 записана и в ответе есть."""
    спецификация = find("photo_cue_suggestions")
    assert спецификация is not None
    описание = спецификация.description

    assert "not stored" not in описание
    assert "phrase" in описание
