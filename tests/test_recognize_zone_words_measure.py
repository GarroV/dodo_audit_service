"""T242 (#198): зона, названная не в именительном падеже, и замер этого.

Имя зоны лежит в методике в именительном падеже, а на точке место называют
предложным: «на тепловом участке», «в раздевалке». Разбор
слов (`src/bot/zones.py`) сводит имя и слова аудитора к основам, и до T242
стеммер разводил «участок» с «участке» по разным ключам — беглая гласная стоит
не на конце слова, а внутри основы, и отсечкой окончаний не снималась.

Цена дефекта — не пропуск строки карты, а зона: неузнанную зону молча
подставляла память о ПРОШЛОЙ записи (D048), и вычет уезжал в чужую зону отчёта
партнёру, а бот при этом писал «записал по вашим словам».

Здесь проверяются обе половины задачи: продуктовое поведение (зона узнаётся) и
сам замер `tools/zone_words_measure.py`, которым это число снимается. Замер идёт
по СИНТЕТИЧЕСКОЙ методике (`tests/methodology`, фикстура `domain_env`): боевая
лежит вне git (D002), её правит управляющая компания, и имён с беглой гласной в
ней сегодня нет вовсе — то есть на ней этот тест ничего бы не сторожил.
"""

from __future__ import annotations

from pathlib import Path

import pytest

from src.bot.zones import zone_from_words
from src.recognize.config import NO_CHAT
from tools import zone_words_measure as zwm

#: Зоны синтетической методики, чьё имя несёт беглую гласную («…участок»).
#: Именно они и не узнавались: три из них не имеют обиходного названия и
#: потерялись целиком, у четвёртой (`dough`) запись спасал «мучной цех».
УЧАСТКИ = (
    ("на тепловом участке грязный пол", "hot_kitchen"),
    ("в холодном участке открытый продукт", "cold_kitchen"),
    ("мусор в углу, на мучном участке", "dough"),
    ("налёт на посудном участке", "dishwashing"),
)


@pytest.mark.parametrize(("слова", "зона"), УЧАСТКИ)
def test_зона_узнаётся_названной_в_предложном_падеже(
    domain_env: Path, слова: str, зона: str
) -> None:
    """Главное требование задачи: так на точке и говорят."""
    assert zone_from_words(слова, chat_id=NO_CHAT) == зона


@pytest.mark.parametrize(("слова", "зона"), УЧАСТКИ)
def test_именительный_падеж_узнаваться_не_перестал(domain_env: Path, слова: str, зона: str) -> None:
    """Сторож против размена: падеж добавился, а не заменил именительный."""
    имя = слова.replace("тепловом участке", "тепловой участок")
    имя = имя.replace("холодном участке", "холодный участок")
    имя = имя.replace("мучном участке", "мучной участок")
    имя = имя.replace("посудном участке", "посудный участок")
    assert zone_from_words(имя, chat_id=NO_CHAT) == зона


def test_замер_не_находит_ни_одной_неузнанной_зоны(domain_env: Path) -> None:
    """Продуктовое число замера: на синтетической методике было 12 из 16 имён."""
    outcomes = zwm.measure(zwm.forms(chat_id=NO_CHAT), chat_id=NO_CHAT)

    плохие = [o for o in outcomes if o.verdict != "узнана"]
    assert not плохие, [(o.form.zone, o.form.spoken, o.verdict) for o in плохие]
    assert not [o for o in outcomes if o.form.drifted]


def test_замер_называет_слово_с_уехавшей_основой_а_не_только_итог() -> None:
    """Причина обязана быть в отчёте: по одному итогу чинить нечего.

    Форма собрана руками, а не методикой: проверяется сам механизм показа, и
    он обязан работать на любом слове, а не только на том, которое сегодня
    уезжает.
    """
    форма = zwm.Form(
        zone="dining",
        lang="ru",
        origin=zwm.FROM_METHODOLOGY,
        nominative="Стол зала",
        spoken="столбе зале",
        case=zwm.PREPOSITIONAL,
    )

    assert форма.drifted == ("стол → столбе",)


def test_замер_называет_чужую_зону_и_выходит_единицей(
    domain_env: Path, monkeypatch: pytest.MonkeyPatch, capsys: pytest.CaptureFixture[str]
) -> None:
    """Неверно узнанная зона опаснее неузнанной: она уводит запись молча.

    Правило то же, что в `tools/fastpath_measure.py`, и код возврата у него
    значит то же самое.
    """
    monkeypatch.setattr(zwm, "zone_from_words", lambda _note, *, chat_id: "freezer")

    rc = zwm.main([])

    out = capsys.readouterr().out
    assert rc == 1
    assert "НЕВЕРНО" in out


def test_прогон_по_методике_без_чужих_зон_выходит_нулём(
    domain_env: Path, capsys: pytest.CaptureFixture[str]
) -> None:
    """Зелёный прогон — регрессионный якорь задачи."""
    rc = zwm.main([])

    out = capsys.readouterr().out
    assert rc == 0
    assert "НЕВЕРНО" in out, "колонка чужих зон исчезла из отчёта — считать нечем"
    assert "участок → участке" in out, "правило беглой гласной перестало применяться"


def test_язык_без_падежей_не_пропускается_молча(domain_env: Path) -> None:
    """Английский падежей не имеет — и это объявлено, а не выражено пропуском.

    Молчаливый пропуск означал бы «этот язык не меряется», и узнать это было бы
    неоткуда: замер выглядел бы полным, не будучи им.
    """
    built = zwm.forms(chat_id=NO_CHAT)

    английские = [f for f in built if f.lang == "en"]
    assert английские, "английское плечо исчезло из замера"
    assert {f.case for f in английские} == {zwm.NO_CASES}
    assert zwm.CASES["en"] == ()


def test_служебное_слово_падеж_не_трогает() -> None:
    """«Незначимо» решает сам продукт: слово без основы остаётся как есть.

    Иначе предлог внутри имени зоны превращался бы в несуществующее слово, и
    замер мерил бы собственную поломку. Имя ниже выдумано: у зон обеих методик
    в репозитории предлога внутри имени нет, а у боевой — есть, и цитировать её
    сюда нельзя (репозиторий публичный, D073).
    """
    (_case, правило) = zwm.CASES["ru"][0]

    assert zwm.inflect("Полка для тары", правило) == "полке для таре"
    assert zwm.inflect("Тепловой участок", правило) == "тепловом участке"


def test_без_переменной_state_dir_внятный_отказ_а_не_трассировка(
    domain_env: Path, monkeypatch: pytest.MonkeyPatch, capsys: pytest.CaptureFixture[str]
) -> None:
    """Тот же уговор, что у соседних замеров (T224, T239): код 2 и одна строка."""
    monkeypatch.delenv("STATE_DIR")

    rc = zwm.main([])

    out = capsys.readouterr().out
    assert rc == 2
    assert "Замерять не по чему" in out
    assert "STATE_DIR" in out
    assert "Traceback" not in out
