"""T106: битая дата проверки не даёт молча отчёт без сроков устранения.

`compute()` считал срок устранения в `try/except Exception: pass`. Дата в шапке
не читается — `due` остаётся `None` по каждому нарушению, и молча. Дальше
`report.py` подставляет вместо пропавшего срока «немедленно», а в письме срок
плана действий превращается в `___`. Партнёр получает предписание, где обычная
D1 требует немедленного устранения, — и понять, что движок сбился на дате,
неоткуда.

«Сроки устранения напечатаны в PDF» — объявленный пункт готовности MVP
(`docs/forge/spec.md`). Беззвучный сбой снимает его так, что на приёмке всё
выглядит зелёным. Поэтому здесь проверяются два наблюдаемых факта: битая дата
роняет расчёт с внятной причиной, а на живой дате в отчёт попадает настоящий
срок, а не «немедленно».
"""

from __future__ import annotations

import json
from collections.abc import Callable
from pathlib import Path

import pytest
from conftest import Run


def подменить_дату(workdir: Path, значение: object) -> None:
    """Записать в шапку начатой проверки дату, которую `init` не пропустил бы.

    Такое состояние появляется не из воздуха: файл проверки правится руками, а
    проверки, начатые до появления валидации шапки (T014), лежат на диске как
    есть.
    """
    path = workdir / "inspection.json"
    st = json.loads(path.read_text(encoding="utf-8"))
    if значение is None:
        st["meta"].pop("date", None)
    else:
        st["meta"]["date"] = значение
    path.write_text(json.dumps(st, ensure_ascii=False), encoding="utf-8")


@pytest.fixture
def с_нарушением(started: Callable[..., Run], workdir: Path) -> Path:
    """Начатая проверка с одной D1 — на ней у отчёта обязан быть срок."""
    r = started("add", "--qid", "CLN05", "--level", "D1", "--zone", "hot_kitchen")
    assert r.code == 0, r.text
    return workdir


def test_нечитаемая_дата_роняет_расчёт(started: Callable[..., Run], с_нарушением: Path) -> None:
    подменить_дату(с_нарушением, "21.08.2026")

    r = started("score")

    assert r.code != 0, "оценка посчитана на дате, от которой не считается ни один срок"
    assert "21.08.2026" in r.text, f"в отказе нет встреченного значения: {r.text!r}"


def test_отказ_называет_формат_и_файл(started: Callable[..., Run], с_нарушением: Path) -> None:
    """Человеку надо знать, что править и где: файлов проверки по одному на чат."""
    подменить_дату(с_нарушением, "завтра")

    r = started("score")

    assert "ГГГГ-ММ-ДД" in r.text, f"в отказе нет нужного формата даты: {r.text!r}"
    assert str(с_нарушением / "inspection.json") in r.text, (
        f"в отказе нет пути к файлу проверки: {r.text!r}"
    )


def test_шапка_без_даты_роняет_расчёт(started: Callable[..., Run], с_нарушением: Path) -> None:
    """Пропавший ключ — тот же сбой, что и мусор в нём: считать сроки не от чего."""
    подменить_дату(с_нарушением, None)

    r = started("score")

    assert r.code != 0, "оценка посчитана на проверке без даты"


def test_отчёт_партнёру_не_собирается_на_битой_дате(
    started: Callable[..., Run], report: Callable[..., Run], с_нарушением: Path
) -> None:
    """PDF и письмо уходят наружу — они обязаны спотыкаться о ту же проверку."""
    подменить_дату(с_нарушением, "2026-13-45")

    assert report("letter").code != 0, "письмо собрано на проверке с нечитаемой датой"
    assert report("html", "--out", str(с_нарушением / "o.html")).code != 0, (
        "отчёт собран на проверке с нечитаемой датой"
    )


def test_на_живой_дате_в_отчёте_настоящий_срок(
    started: Callable[..., Run], report: Callable[..., Run], с_нарушением: Path
) -> None:
    """Ровно то, что терялось молча: у D1 в отчёте дата, а не «немедленно»."""
    out = с_нарушением / "o.html"

    r = report("html", "--out", str(out))

    assert r.code == 0, r.text
    html = out.read_text(encoding="utf-8")
    assert "Устранить до: " in html, f"в отчёте нет строки срока: {html[:400]!r}"
    срок = html.split("Устранить до: ")[1][:10]
    assert срок[:2].isdigit() and "." in срок, f"вместо срока напечатано {срок!r}"


def test_в_письме_срок_плана_а_не_прочерк(
    started: Callable[..., Run], report: Callable[..., Run], с_нарушением: Path
) -> None:
    """Заглушка `___` в письме партнёру — тот же беззвучный сбой на той же дате.

    Срок плана действий печатается только в письме с планом, а оно выбирается по
    наличию D2/D3 (T016). Поэтому нужен пункт, которому D2 вообще разрешён:
    `CLN05` из фикстуры допускает только D1, и молча взятое им письмо оказалось
    коротким — тест зеленел, ничего не проверяя. Поймано порчей.
    """
    r = started("add", "--qid", "TEH22", "--level", "D2", "--zone", "dining")
    assert r.code == 0, r.text

    r = report("letter")

    assert r.code == 0, r.text
    assert "___" not in r.out, f"вместо срока плана действий в письме прочерк: {r.out!r}"
