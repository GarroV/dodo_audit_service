"""T185: сырые слова аудитора доезжают до базы и читаются обратно.

Бот с T183 хранит рядом с записью весь материал, каким он пришёл, — подпись к
кадру, отдельное сообщение, расшифровку голоса (`domain.models.Finding.words`).
В базе места под них не было, и слив их терял: тот же случай, что был с
предложением модели (T164) и с источником записи (D044) — колонки заводятся,
как только домен начинает отдавать значение.

Зачем это нужно целиком, а не «до колонки». На этих словах стоит инструмент,
собирающий предложения для управляющей компании (T165, `mcp.suggestions`):
сегодня он называет СТРОКУ КАРТЫ СЛОВ, которая привела к неверному пункту, а
владелец просил фразу, которую произнёс аудитор. Пока слов в базе нет,
инструмент отвечает половиной — и говорит об этом прямо в своём описании.

Два свойства, которые здесь важнее самой колонки:

1. **Слова — показание о моменте.** Записанные один раз, они не меняются: ни
   правкой записи, ни дописыванием. Переписанные, они стирали бы сигнал ровно
   тогда, когда он появляется, — потому что переписывают их как раз после
   того, как заметили промах. Домен это соблюдает у себя (`remember_words`
   зовётся только при фиксации), база — политикой `findings_frozen_with_...`
   из `0004`, и это проверяется под ролью приложения, а не под той, что
   создавала базу: суперпользователь обходит RLS всегда.
2. **В отпечаток проверки слова НЕ входят** — как и предложение модели.
   Отпечаток это содержимое документа, ушедшего партнёру, а сказанное на точке
   партнёру не предназначено вовсе (`domain.models.Finding.words`). Попади оно
   в отпечаток — проверка, слитая до этой задачи и слитая после, дала бы две
   строки в истории одной точки, то есть ровно то, от чего отпечаток и стоит.
"""

from __future__ import annotations

from dataclasses import replace
from pathlib import Path
from typing import Any

import pytest
from conftest import requires_db

psycopg = pytest.importorskip("psycopg")

from src.db.fingerprint import compute_fingerprint  # noqa: E402 — после importorskip намеренно
from src.db.push import push_inspection  # noqa: E402
from src.db.queries import findings_by_unit, get_inspection  # noqa: E402
from src.domain import add_finding, get_state, start_inspection  # noqa: E402
from src.domain import score as domain_score  # noqa: E402

pytestmark = requires_db

АРЕНДАТОР = "слова"
ТОЧКА = "Белград-1"

#: Речь аудитора не совпадает ни с языком интерфейса, ни с языком отчёта — это
#: три разных поля (конституция). Слова записаны на языке РЕЧИ, и читаются они
#: вместе с ним: `FindingRow.lang` говорит, на каком языке отдана строка,
#: вместо того чтобы выдавать её за единственную.
ЯЗЫК_РЕЧИ = "sr"

#: Сырые слова и текст записи — разные вещи, и это не случайность выборки.
#: Партнёру уходит формулировка по правилам фиксации, а сказанное на точке ему
#: не предназначено. Значения тут нарочно непохожие: совпади они, тест не
#: заметил бы, что в колонку легла формулировка вместо речи.
СЛОВА = "тут на полке в горячем цеху жир какой-то, это же чистота вроде"
ТЕКСТ = "Загрязнение полки в горячем цехе"


def _строки(dsn: str, sql: str, params: tuple[Any, ...] = ()) -> list[tuple[Any, ...]]:
    with psycopg.connect(dsn) as conn, conn.cursor() as cur:
        cur.execute(sql, params)
        return cur.fetchall()


def _проверка(chat_id: int, *, words: str = СЛОВА) -> str:
    """Настоящая завершённая проверка с одной записью — и слить её.

    Ничего не подменяется: слова идут тем же путём, каким их кладёт бот
    (`add_finding(..., words=...)`, `src/bot/routers/record.py`). Подмена
    состояния проверяла бы фантазию этого файла о домене, а не слив.
    """
    start_inspection(
        chat_id,
        unit=ТОЧКА,
        kind="planned",
        report_lang="ru",
        speech_lang=ЯЗЫК_РЕЧИ,
        tenant=АРЕНДАТОР,
    )
    add_finding(
        chat_id,
        code="CLN05",
        level="D1",
        zone="hot_kitchen",
        text=ТЕКСТ,
        source="comment",
        words=words,
    )
    return push_inspection(chat_id)


def test_сырые_слова_ложатся_рядом_с_записью(domain_env: Path, db_env: str) -> None:
    """Главная проверка задачи: материал, из которого выросла запись, перестал теряться.

    Проверяется прямым запросом мимо кода продукта: чтение своего же слива
    подтвердило бы только то, что слив и чтение договорились между собой.

    Отдельно — что в колонку легла РЕЧЬ, а не формулировка записи: перепутанные
    местами, они выглядели бы работающей выборкой, в которой управляющая
    компания правит карту слов по нашему же тексту, а не по сказанному.
    """
    ident = _проверка(1851)

    (запись,) = _строки(
        db_env,
        "select f.words, "
        "(select t.text from translations t where t.entity_type = 'finding' "
        " and t.entity_id = f.id and t.field = 'text' and t.lang = %s) "
        "from findings f where f.inspection_id = %s",
        (ЯЗЫК_РЕЧИ, ident),
    )

    assert запись[0] == СЛОВА, "сырые слова аудитора не доехали до базы"
    assert запись[1] == ТЕКСТ, "формулировка записи потерялась"
    assert запись[0] != запись[1], "в колонку слов легла формулировка, а не речь"


def test_чтение_по_идентификатору_отдаёт_слова_и_язык_речи(domain_env: Path, db_env: str) -> None:
    """Слова без языка — половина показания: их читают, чтобы разобрать сказанное.

    Язык здесь не совпадает ни с языком отчёта, ни с языком интерфейса
    намеренно: привяжись слова к языку отчёта — сербская речь уехала бы в
    выборку помеченной русской, и заметить это было бы нечем.
    """
    ident = _проверка(1852)

    подробно = get_inspection(ident, tenant=АРЕНДАТОР)

    assert подробно is not None
    (находка,) = подробно.findings
    assert находка.words == СЛОВА, "чтение по идентификатору не отдаёт слов аудитора"
    assert находка.lang == ЯЗЫК_РЕЧИ, "слова отданы не с тем языком, на котором сказаны"


def test_находки_точки_тоже_несут_слова(domain_env: Path, db_env: str) -> None:
    """Второй запрос слоя чтения — свой текст, своя возможность его забыть.

    Именно этим путём пойдёт инструмент предложений для управляющей компании
    (T165): «что у этой точки модель называет не так и какими словами это
    описал человек».
    """
    _проверка(1853)

    (находка,) = findings_by_unit(tenant=АРЕНДАТОР, unit=ТОЧКА)

    assert находка.words == СЛОВА, "находки точки отданы без слов аудитора"


def test_запись_без_слов_не_выглядит_речью(domain_env: Path, db_env: str) -> None:
    """Слов не было вовсе — в базе `NULL`, а наружу пустая строка.

    Так выглядит разбор голого кадра и любая запись, начатая до T183. Разные
    виды пустоты здесь не нужны: «слова не записаны» не бывает двух видов, а
    отличить «слов не было» от «запись старая» можно источником записи — так
    же, как это делает домен.
    """
    ident = _проверка(1854, words="")

    (запись,) = _строки(db_env, "select words from findings where inspection_id = %s", (ident,))
    assert запись[0] is None, "отсутствие слов записано в базу чем-то, что похоже на речь"

    подробно = get_inspection(ident, tenant=АРЕНДАТОР)
    assert подробно is not None
    assert подробно.findings[0].words == "", "пустота отдана не пустой строкой"


def test_молчание_не_речь(domain_env: Path, db_env: str) -> None:
    """Одни пробелы — это не сказанное, и в базе им делать нечего.

    Пробельная строка в колонке выглядела бы записанным показанием: в выборке
    для управляющей компании она стала бы «фразой аудитора», у которой не
    прочитать ни слова, и отличить её от настоящей потери было бы нечем.
    """
    ident = _проверка(1855, words="   \n\t ")

    (запись,) = _строки(db_env, "select words from findings where inspection_id = %s", (ident,))

    assert запись[0] is None, "пробелы легли в базу как речь аудитора"


def test_слова_записываются_дословно(domain_env: Path, db_env: str) -> None:
    """Показание не правится по дороге — ни отступом, ни переводом строки.

    Обрезка краёв выглядит безобидной ровно до того момента, когда по этим
    словам сверяют, что именно сказал человек: расшифровка голоса приходит
    несколькими строками, и склеенная в одну она перестаёт быть тем, что
    произнесли. Пустой её при этом считает `strip` — но считает, а не делает.
    """
    сказанное = "  жир на полке,\n  ну то есть это чистота  "
    ident = _проверка(1856, words=сказанное)

    (запись,) = _строки(db_env, "select words from findings where inspection_id = %s", (ident,))

    assert запись[0] == сказанное, "слова аудитора подправлены по дороге в базу"


def test_слова_не_меняют_отпечаток_проверки(domain_env: Path) -> None:
    """Отпечаток — содержимое документа, а сказанное на точке в документ не входит.

    Попади слова в отпечаток, одна и та же проверка, слитая до этой задачи и
    слитая после, получила бы два разных отпечатка — то есть две строки в
    истории точки вместо одной. Ровно то, от чего отпечаток и стоит, и та же
    причина, по которой в него не входит предложение модели (T164).
    """
    start_inspection(
        1857,
        unit=ТОЧКА,
        kind="planned",
        report_lang="ru",
        speech_lang=ЯЗЫК_РЕЧИ,
        tenant=АРЕНДАТОР,
    )
    add_finding(
        1857,
        code="CLN05",
        level="D1",
        zone="hot_kitchen",
        text=ТЕКСТ,
        source="comment",
        words=СЛОВА,
    )
    состояние = get_state(1857)
    assert состояние is not None
    # Без этой строки тест был бы зелёным и в том случае, когда домен слов не
    # отдаёт вовсе: сравнивались бы два одинаковых «ничего».
    assert состояние.findings[0].words == СЛОВА, "домен не отдал слов — сравнивать нечего"
    оценка = domain_score(1857)

    со_словами = compute_fingerprint(состояние, оценка, tenant_code=АРЕНДАТОР)
    без_слов = compute_fingerprint(
        replace(состояние, findings=[replace(f, words="") for f in состояние.findings]),
        оценка,
        tenant_code=АРЕНДАТОР,
    )

    assert со_словами == без_слов, "слова аудитора попали в отпечаток — повторный слив даст дубль"


def test_записанные_слова_нельзя_переписать(domain_env: Path, db_env: str) -> None:
    """Показание о моменте не правится задним числом — его держит схема, а не код.

    Правят такое ровно тогда, когда промах уже заметили, то есть стирают сигнал
    в тот момент, когда он появился. Заслон — политика `0004`: запись
    запечатанной проверки заморожена целиком, и слова замерзают вместе с ней.
    Второго заслона под них не заводится: снять один и увидеть красное можно,
    а из двух неизвестно, какой держит.

    Отказ RLS МОЛЧАЛИВЫЙ — строка просто не видна для записи, `UPDATE`
    отчитывается «затронуто 0 строк» и не падает. Поэтому проверяется и число
    строк, и само значение: «не упало» здесь не значит ничего.
    """
    ident = _проверка(1858)

    with psycopg.connect(db_env) as conn, conn.cursor() as cur:
        cur.execute(
            "update findings set words = %s where inspection_id = %s",
            ("я такого не говорил", ident),
        )
        затронуто = cur.rowcount
        conn.commit()

    assert затронуто == 0, "слова записанной проверки удалось переписать"
    (запись,) = _строки(db_env, "select words from findings where inspection_id = %s", (ident,))
    assert запись[0] == СЛОВА, "показание аудитора изменилось задним числом"
