"""T143 (вторая половина): слова колонок «Грязь» и «Поломка» правит УК, а не код.

Быстрый путь различает грязь и поломку одного объекта по словам комментария:
карта пишет «Печь | CLN05 | TEH05» и сама объясняет, что грязь — это `CLN*`, а
поломка — `TEH*`. До этой задачи сами слова («нагар», «трещина») жили двумя
кортежами в `src/recognize/fastpath.py`, то есть **в коде**. Последствие видно на
формулировках самой управляющей компании: «затирки», «потёртости», «затёртости»,
«налипшее» не попадают ни в один из кортежей, и на таком комментарии колонка не
выбирается вовсе — отказ «по словам не видно, грязь это или поломка». Пополнить
словарь может только выпуск кода, а карту (D066) ведёт УК.

Поэтому карта получает свой раздел со словами колонок, а код — встроенный
минимум. Отношения между ними ровно два, и оба проверяются здесь:

* карта **дополняет**, а не заменяет: владелец про этот механизм сказал
  «дополняем наш список терминов» (D077), и раздел, забытый в новой версии
  карты, не должен молча отключать различение грязи и поломки;
* раздела нет — работает встроенный минимум, и это не отказ (D068): карта
  ускоряет разбор, а не является условием работы продукта.
"""

from __future__ import annotations

from pathlib import Path

import pytest

from src.recognize.cues import column_words, load_cues
from src.recognize.fastpath import NO_COLUMN, fast_path

#: Раздел карты со словами колонок — ровно в той форме, в какой его ведёт УК.
РАЗДЕЛ = """
## Слова, которыми аудитор называет колонку

| Колонка | Слова аудитора |
|---|---|
| Грязь | затирки, потёртости, затёртости, налипшее |
| Поломка | заедает, люфт |
"""


def _карта_с_разделом(data_copy: Path, monkeypatch: pytest.MonkeyPatch, раздел: str) -> None:
    карта = data_copy / "photo-cues.md"
    карта.write_text(карта.read_text(encoding="utf-8") + раздел, encoding="utf-8")
    monkeypatch.setenv("AUDIT_DATA_DIR", str(data_copy))


def test_слова_колонки_берутся_из_карты(
    domain_env: Path, data_copy: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    """То, ради чего задача: слово УК различает колонку без правки кода.

    «Затирки» и «потёртости» — формулировки боевых проверок, и во встроенном
    словаре их нет намеренно: выдумывать за управляющую компанию, какими словами
    говорят аудиторы, нельзя.
    """
    assert fast_path("Печь в затирках", "hot_kitchen").reason == NO_COLUMN
    _карта_с_разделом(data_copy, monkeypatch, РАЗДЕЛ)

    итог = fast_path("Печь в затирках", "hot_kitchen")

    assert итог.item is not None, итог.reason
    assert итог.item.code == "CLN05", "слово карты выбрало колонку «Грязь»"


def test_слова_карты_дополняют_встроенный_словарь(
    domain_env: Path, data_copy: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    """Раздел в карте не отменяет того, что работало без него.

    Иначе карта, где УК перечислила три своих слова, молча отключила бы «нагар»
    и «трещину», а заметно это стало бы на точке.
    """
    _карта_с_разделом(data_copy, monkeypatch, РАЗДЕЛ)

    грязь = fast_path("Печь в нагаре", "hot_kitchen")
    поломка = fast_path("печь сломана", "hot_kitchen")

    assert грязь.item is not None and грязь.item.code == "CLN05"
    assert поломка.item is not None and поломка.item.code == "TEH05"


def test_без_раздела_остаётся_встроенный_минимум(domain_env: Path) -> None:
    """D068: карта — ускоритель, её неполнота не отказ.

    В синтетической карте раздела нет, и это законное состояние: встроенные
    слова продолжают различать колонки, а незнакомое слово даёт обычный отказ.
    """
    assert not column_words(), "у синтетической карты раздела слов быть не должно"

    assert fast_path("Печь в нагаре", "hot_kitchen").item is not None
    assert fast_path("Печь в затирках", "hot_kitchen").reason == NO_COLUMN


def test_слово_в_двух_колонках_оставляет_отказ(
    domain_env: Path, data_copy: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    """Одно слово в обеих колонках — это неоднозначность, а не жребий.

    УК ведёт карту руками и может вписать слово дважды. Выбирать «первую
    подходящую» колонку в таком случае значило бы решать за человека монеткой.
    """
    _карта_с_разделом(
        data_copy,
        monkeypatch,
        "\n## Слова, которыми аудитор называет колонку\n\n"
        "| Колонка | Слова аудитора |\n|---|---|\n"
        "| Грязь | подтекает |\n| Поломка | подтекает |\n",
    )

    assert fast_path("Печь подтекает", "hot_kitchen").reason == NO_COLUMN


def test_раздел_слов_не_становится_строкой_карты(
    domain_env: Path, data_copy: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    """Слова колонок — не подсказки «что видно на кадре».

    Раздел пропускается целиком тем же приёмом, что и пороги классов: иначе
    строка «Грязь | затирки…» однажды окажется подсказкой с кодом внутри.
    """
    было = len(load_cues())
    _карта_с_разделом(data_copy, monkeypatch, РАЗДЕЛ)

    assert len(load_cues()) == было


def test_шапка_таблицы_словом_колонки_не_считается(
    domain_env: Path, data_copy: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    """Читаются строки после разделителя, как в любой таблице этого документа."""
    _карта_с_разделом(data_copy, monkeypatch, РАЗДЕЛ)

    прочитано = column_words()

    assert set(прочитано) == {"грязь", "поломка"}, "в словарь попала шапка таблицы"
    assert "затирк" in прочитано["грязь"], "слова карты приводятся к тем же основам"
