"""T140 (#111): кнопки зон — по одной в ряд, подпись целиком.

Зон десять, они стояли по две в ряд, а подпись резалась по 34 знака — общему
пределу кнопок продукта, выбранному под половину ряда. На боевой методике так
получался нечитаемый хвост: самое длинное название зоны длиннее предела, и
аудитор видел его обрубленным на середине слова.

Дело не в аккуратности. Зону аудитор называет кнопкой на самой точке — одной
рукой, в шуме, между делом (D047: обычно зона берётся из слов, кнопки нужны
там, где слов не хватило). Обрубленная подпись здесь означает не «некрасиво», а
«выбрал не ту зону», а зона входит в запись и в разбивку оценки по зонам.

Порядок зон эти тесты намеренно не трогают: он станет маршрутным, когда придут
данные управляющей компании (T133), и закреплять сегодняшний методический
порядок значило бы завтра его же и ломать. Проверяется другое — что клавиатура
не переставляет то, что ей дали.

**Названия зон в этом файле не пишутся.** Методика управляющей компании в
публичный репозиторий не цитируется (`tests/test_methodology_leak.py`), поэтому
боевые подписи читаются из самой методики на ходу, а синтетические примеры
сочинены здесь же.
"""

from __future__ import annotations

from pathlib import Path

from aiogram.types import InlineKeyboardMarkup
from conftest import requires_data

from src.bot.keyboards import ZONE_TITLE_LIMIT, zones_keyboard
from src.bot.texts import UI_LANGS
from src.domain import list_zones

ПРЕФИКС = "rec:zone:"


def _ряды(markup: InlineKeyboardMarkup) -> list[list[str]]:
    return [[button.text for button in row] for row in markup.inline_keyboard]


def test_зона_в_ряду_одна() -> None:
    """Ряд из двух кнопок делит ширину пополам — и подпись вместе с ней.

    Десять зон это десять рядов, а не пять: свиток на телефоне лишний, но
    выбирать зону аудитор будет один раз за запись, а читать подпись — каждый
    раз.
    """
    зоны = [(f"z{n}", f"Зона номер {n}") for n in range(1, 11)]

    ряды = _ряды(zones_keyboard(ПРЕФИКС, зоны))

    assert len(ряды) == 10
    assert all(len(ряд) == 1 for ряд in ряды), f"зоны стоят не по одной в ряд: {ряды}"


def test_порядок_зон_клавиатура_не_меняет() -> None:
    """Сторож к T133: порядок задаёт вызывающий, клавиатура его только показывает."""
    зоны = [("z3", "Третья"), ("z1", "Первая"), ("z2", "Вторая")]

    markup = zones_keyboard(ПРЕФИКС, зоны)

    assert [b.callback_data for row in markup.inline_keyboard for b in row] == [
        f"{ПРЕФИКС}z3",
        f"{ПРЕФИКС}z1",
        f"{ПРЕФИКС}z2",
    ]


def test_предел_подписи_остался_и_виден_многоточием() -> None:
    """Сторож против «починки» снятием предела: ряд не бесконечный.

    Задача просила поднять предел, а не убрать его: подпись, которая не влезает,
    обязана быть видна обрезанной, а не разъезжаться на пол-экрана. Проверяется
    на заведомо длинной выдуманной подписи, а не на боевой.
    """
    (ряд,) = zones_keyboard(ПРЕФИКС, [("z1", "очень длинное название зоны " * 10)]).inline_keyboard
    (кнопка,) = ряд

    assert len(кнопка.text) == ZONE_TITLE_LIMIT
    assert кнопка.text.endswith("…")


@requires_data
def test_ни_одна_зона_боевой_методики_не_режется(live_data_env: Path) -> None:
    """Тот самый хвост — и то, что его больше нет ни у одной зоны, ни на одном языке.

    Боевая методика нужна здесь по существу: дефект нашёлся именно на ней, а в
    синтетической методике длинных названий нет и не будет — их пишет
    управляющая компания.

    Проверяются оба языка интерфейса: предел общий, а длина названия у языков
    разная, и правка, вылеченная только по-русски, оставила бы хвост
    англоязычному аудитору.
    """
    зоны = list_zones()
    assert зоны, "в боевой методике не нашлось ни одной зоны — проверять нечего"

    for lang in UI_LANGS:
        подписи = [(zone.title(lang), zone.code) for zone in зоны]
        markup = zones_keyboard(ПРЕФИКС, [(code, title) for title, code in подписи])
        показано = [button.text for row in markup.inline_keyboard for button in row]

        assert показано == [title for title, _ in подписи], (
            f"подписи зон на языке {lang} показаны не целиком: "
            f"{[t for t in показано if t.endswith('…')]}"
        )
