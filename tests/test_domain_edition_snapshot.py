def test_запись_после_переиздания_идёт_в_издание_проверки(методика: Path) -> None:
    """Дефект T169 целиком: запись, сделанная после переиздания, не мешает изданий.

    До починки движок принимал по действующей методике пункт, которого в
    издании проверки нет вовсе, — и проверка оказывалась собранной из двух
    изданий, ни одно из которых не знает всех её записей.
    """
    код, зоны, класс = начать(методика)
    заведённый = снять_пункт(методика, код)

    add_finding(CHAT, код, класс, зоны[1], "запись после переиздания")

    записи = [f.code for f in get_state(CHAT).findings]  # type: ignore[union-attr]
    assert записи == [код, код], "запись после переиздания легла не в издание проверки"
    коды_издания = {i.code for i in list_items(chat_id=CHAT)}
    assert записи[0] in коды_издания, "проверка держит запись по пункту не из своего издания"
    assert заведённый not in коды_издания, "пункт нового издания предложен идущей проверке"


def утроить_ставку(data_dir: Path, класс: str) -> None:
    """Переиздание, меняющее цифру: ставка вычета этого класса втрое."""
    файл = data_dir / "scoring.json"
    ставки = json.loads(файл.read_text(encoding="utf-8"))
    ставки["penalty"][класс] = float(ставки["penalty"][класс]) * 3
    файл.write_text(json.dumps(ставки, ensure_ascii=False), encoding="utf-8")


def test_письмо_партнёру_собрано_по_изданию_проверки(методика: Path) -> None:
    """Сборщик отчёта считает оценку ЗАНОВО, поэтому издание нужно и ему.

    Иначе партнёр получит документ с одним процентом, а база — с другим, и
    расхождение объяснить будет нечем.
    """
    _, _, класс = начать(методика)
    было = build_letter(CHAT)

    утроить_ставку(методика, класс)

    assert build_letter(CHAT) == было, "письмо собралось по действующей методике"


def test_в_отчёте_стоит_формулировка_пункта_из_издания_проверки(методика: Path) -> None:
    """Цена смеси изданий — испорченный отчёт партнёру, поэтому проверяется отчёт.

    Запись по снятому переизданием пункту движок не отвергает: он печатает её с
    ПУСТОЙ формулировкой процесса и сроком «немедленно» вместо настоящего
    (`compute` берёт `cl.get(qid, {})`). Формулировка читается из методики на
    ходу — в исходниках её нет (T146, D073).
    """
    код, _, _ = начать(методика)
    процесс = get_item(код, chat_id=CHAT).process("ru")
    assert процесс, "в синтетической методике у пункта нет процесса — тест ничего не стережёт"

    снять_пункт(методика, код)

    разметка = run_report(["html"], chat_id=CHAT, settings=окружение_отчёта(CHAT))
    assert процесс in разметка, "в отчёте партнёру у записи пропала формулировка пункта"


def test_подсчёт_не_двигается_переизданием_ставок(методика: Path) -> None:
    """Ставки нового издания на идущую проверку не действуют.

    Самая дорогая часть смеси: процент и буква уезжают в базу и в отчёт
    партнёру, а отличить их от честных потом нечем.
    """
    _, _, класс = начать(методика)
    было = score(CHAT).pct

    ставки_файл = методика / "scoring.json"
    ставки = json.loads(ставки_файл.read_text(encoding="utf-8"))
    ставки["penalty"][класс] = float(ставки["penalty"][класс]) * 4
    ставки_файл.write_text(json.dumps(ставки, ensure_ascii=False), encoding="utf-8")

    assert score(CHAT).pct == было, "проверка посчиталась по ставкам нового издания"


