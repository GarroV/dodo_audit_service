def штрафной_пункт(data_dir: Path) -> tuple[str, list[str], str]:
    """Пункт с двумя зонами и штрафным классом — всё вычитано из методики."""
    ставки = json.loads((data_dir / "scoring.json").read_text(encoding="utf-8"))
    штрафные = {
        уровень for уровень, ставка in (ставки.get("penalty") or {}).items() if float(ставка) > 0
    }
    for пункт in list_items():
        зоны = [z for z in пункт.zones if z != "*"]
        классы = [c for c in пункт.levels if c in штрафные]
        if len(зоны) > 1 and классы:
            return пункт.code, зоны, классы[-1]
    raise AssertionError("в методике не нашлось пункта с двумя зонами и штрафным классом")


def дописать_критерий(data_dir: Path) -> None:
    """Переиздание, меняющее только отпечаток: приписка в критериях."""
    критерии = data_dir / "criteria.md"
    критерии.write_text(
        критерии.read_text(encoding="utf-8") + "\n<!-- издание теста -->\n", encoding="utf-8"
    )


def снять_пункт(data_dir: Path, код: str) -> str:
    """Переиздание, снимающее пункт и заводящее вместо него другой.

    Возвращает код заведённого пункта. Именно такое переиздание и портит отчёт:
    запись по снятому пункту печатается партнёру без формулировки и со сроком
    «немедленно».
    """
    путь = data_dir / "checklist.csv"
    with путь.open(encoding="utf-8-sig", newline="") as f:
        строки = list(csv.DictReader(f))
    колонки = list(строки[0].keys())
    заменяемый = next(с for с in строки if с["id"] == код)
    новый = dict(заменяемый)
    новый["id"] = "ZZZ99"
    with путь.open("w", encoding="utf-8", newline="") as f:
        писарь = csv.DictWriter(f, fieldnames=колонки)
        писарь.writeheader()
        писарь.writerows([с for с in строки if с["id"] != код] + [новый])
    return "ZZZ99"


def начать(методика: Path, chat_id: int = CHAT) -> tuple[str, list[str], str]:
    """Начатая проверка с одной штрафной записью. Возвращает пункт, зоны, класс."""
    start_inspection(chat_id, unit="Тестовая", kind="planned", report_lang="ru")
    код, зоны, класс = штрафной_пункт(методика)
    add_finding(chat_id, код, класс, зоны[0], "формулировка теста")
    return код, зоны, класс


def отметка(chat_id: int = CHAT) -> str:
    состояние = get_state(chat_id)
    assert состояние is not None
    return состояние.checklist_version


