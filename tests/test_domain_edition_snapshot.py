"""T169: проверка идёт по тому изданию методики, при котором её начали.

Задача T148 закрыла половину: считать по методике, отличной от записанной в
проверке, стало нельзя. Осталась вторая половина, и блок T148 назвал её сам —
**сверка стоит на подсчёте, а не на записи**. Записи, сделанные ПОСЛЕ
переиздания, ею не ловятся: проверка спокойно набирает их по новому изданию,
оставаясь помеченной прежним, и узнаётся это в конце выезда.

Дефект воспроизводится и стоит дорого. Переиздание, снявшее пункт, оставляет в
проверке запись по пункту, которого в действующей методике больше нет: движок
такую запись не отвергает, а печатает партнёру с ПУСТОЙ формулировкой и сроком
«немедленно» вместо настоящего (`compute` берёт `cl.get(qid, {})`, откуда
`days` выходит нулём). То есть цена смеси изданий — не отказ, а тихо испорченный
отчёт партнёру.

Отказ на записи ставить нельзя: аудитор стоит на точке, починить методику
оттуда он не может, а выезд не переигрывается. Поэтому издание проверки
снимается снимком на старте и дальше не меняется само: запись, правка, подсчёт
и отчёт идут по нему. Переиздание методики для идущей проверки перестаёт быть
событием, а следующая проверка начинается уже на новом издании.

Формулировок методики здесь нет (T146, D073): пункты, зоны и классы вычитаны из
данных на ходу, а «переиздание» делается припиской в критерии.
"""

