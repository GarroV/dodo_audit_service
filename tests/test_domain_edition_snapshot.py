def test_издание_с_путём_в_имени_не_кладётся_за_полку(
    data_copy: Path, tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    """Имя издания задаёт управляющая компания файлом, и путём оно быть не может.

    Иначе снимок методики уехал бы копией в произвольный каталог рядом с
    состоянием — продукт писал бы туда, куда его никто не просил. Слеш стоит в
    СЕРЕДИНЕ имени намеренно: ведущие точки `version.compose` срезает, и путь
    вышел бы абсолютным, а в корень диска запись не проходит и без охраны —
    тест был бы зелен по чужой причине.
    """
    (data_copy / "checklist_version.txt").write_text(
        "имя/../../беглец 2026-09-04\n", encoding="utf-8"
    )
    monkeypatch.setenv("AUDIT_DATA_DIR", str(data_copy))
    monkeypatch.setenv("STATE_DIR", str(tmp_path / "state"))
    monkeypatch.chdir(tmp_path)

    start_inspection(CHAT, unit="Тестовая", kind="planned", report_lang="ru")

    состояние = check_environment().state_dir
    полка = edition.shelf(check_environment())
    assert "/" in отметка(), "издание перестало быть тем, что записала УК"
    assert sorted(p.name for p in состояние.iterdir()) == [f"chat_{CHAT}"], (
        "рядом с проверками появился каталог, которого никто не просил"
    )
    assert not полка.exists(), (
        "полка снимков заведена на издании, которое в имя каталога не годится"
    )


