def test_движок_зовётся_с_каталогом_издания_проверки(методика: Path) -> None:
    """Проверяется наблюдаемо: движок, запущенный по этому каталогу, даёт тот же процент."""
    начать(методика)
    дописать_критерий(методика)
    настройки = settings_for(CHAT)

    ответ = subprocess.run(  # noqa: S603 — команда собрана здесь, оболочки нет
        [sys.executable, str(настройки.audit_script), "score", "--json"],
        cwd=str(Path(настройки.state_dir) / f"chat_{CHAT}"),
        env={
            "PATH": "/usr/bin:/bin",
            "INSPECTION_FILE": str(Path(настройки.state_dir) / f"chat_{CHAT}" / "inspection.json"),
            "CHECKLIST_DIR": str(настройки.data_dir),
        },
        capture_output=True,
        text=True,
        check=True,
    )

    assert float(json.loads(ответ.stdout)["pct"]) == score(CHAT).pct
    assert настройки.data_dir != check_environment().data_dir, "каталог издания не подставлен"
