"""T200 (#163): письмо по записанной проверке несёт срок, названный аудитором.

Срок плана действий называет аудитор — это одно из семи полей информационной
части, и бот печатает в письме его ответ. Пересборка письма по записанной
проверке (T171) отдавала движку пустой блок `info`, движок падал на запасной
расчёт (дата обхода плюс `plan_due_days`), и партнёр получал от управляющей
компании другой срок, чем от аудитора. Обе бумаги при этом подписаны системой
как верные, а ответ инструмента утверждал, что оценка сверена, и перечислял
невосстановленными только город, партнёра и контакт — срока в перечне не было.

Файл отдельный от `test_mcp_letters.py` намеренно: тот про пересборку и про
запрет пересчёта задним числом, этот — про информационную часть, которая
приезжает в письмо из базы. Правка идёт в чужом для задачи блоке (`src/mcp`)
потому, что иначе письмо собрать нельзя: слой чтения без этого отдаёт поля, а
сборщик их не передаёт — потеря остаётся ровно там же, где была.
"""

from __future__ import annotations

import json
from datetime import date
from pathlib import Path

import pytest
from mcp_checklist_harness import build_methodology

from src.db.models import FindingRow, InfoRow, InspectionDetail, InspectionRow
from src.mcp import letters

ВЕРСИЯ = "harness-2026-09-05-abcdef012345"

#: Пункт методики про срок плана действий. Движок ищет поле НЕ по коду, а по
#: формулировке вопроса (`engine/report.py: plan_due_date` — «план\\w* действий»),
#: поэтому в оснастке он обязан быть настоящим пунктом методики, а не выдумкой
#: этого файла.
СРОК_ПУНКТ = (
    "INF07,info,Информация,Information,Срок составления плана действий,"
    "Deadline for the action plan,,,1\n"
)

#: Дата, которую назвал аудитор.
СРОК = "30.09.2026"

#: Дата, которую подставит движок, если ответа аудитора нет: дата обхода
#: (19.08.2026) плюс `plan_due_days` = 10 из оснастки. Именно она уезжала
#: партнёру вместо ответа аудитора, и именно её тут быть не должно.
ЗАПАСНОЙ_СРОК = "29.08.2026"

#: Нарушение в проверке — класса D2, и это не случайность выборки. Письмо с
#: планом действий движок собирает только там, где есть D2 или D3: при чистой
#: проверке плана не ждут вовсе, и срока в письме нет ни в каком виде
#: (`engine/report.py: LETTER_CLEAN`). На проверке из одних D1 этот файл
#: проверял бы отсутствие строки, которой там не бывает.
КЛАСС = "D2"
ПРОЦЕНТ = 98.0
БУКВА = "C"


def _строка() -> InspectionRow:
    """Шапка записанной проверки — заполненная целиком.

    Пустые поля шапки сами по себе делают письмо неготовым к отправке, и на
    них тест про срок был бы зелёным по неверной причине.
    """
    return InspectionRow(
        id="11111111-1111-1111-1111-111111111111",
        tenant_code="укашка",
        unit_name="Белград-1",
        chat_id=744230399,
        kind="planned",
        inspection_date=date(2026, 8, 19),
        report_lang="ru",
        checklist_version=ВЕРСИЯ,
        pct=ПРОЦЕНТ,
        grade=БУКВА,
        findings_count=1,
        pushed_at="2026-08-19T18:00:00+02:00",
        auditor="Петров",
        city="Белград",
        partner="ООО Партнёр",
        contact="partner@example.test",
    )


def _проверка(*, info: tuple[InfoRow, ...]) -> InspectionDetail:
    находка = FindingRow(
        id="22222222-2222-2222-2222-222222222222",
        inspection_id="11111111-1111-1111-1111-111111111111",
        unit_name="Белград-1",
        inspection_date=date(2026, 8, 19),
        n=1,
        code="CLN01",
        level=КЛАСС,
        zone="fridge",
        zone_unusual=False,
        source="comment",
        lang="ru",
        text="Пол в холодильнике в разводах",
        comment="",
    )
    return InspectionDetail(
        inspection=_строка(),
        deductions=2.0,
        counts={КЛАСС: 1},
        by_zone={},
        findings=(находка,),
        info=info,
    )


@pytest.fixture
def хранилище(tmp_path: Path) -> letters.Papers:
    """Снимок ровно той версии, которой помечена проверка, — с пунктом про срок."""
    for каталог in (tmp_path / "store" / "versions" / ВЕРСИЯ, tmp_path / "live"):
        build_methodology(каталог)
        with (каталог / "checklist.csv").open("a", encoding="utf-8") as файл:
            файл.write(СРОК_ПУНКТ)
    return letters.Papers(live=tmp_path / "live", store=tmp_path / "store")


def test_письмо_несёт_срок_названный_аудитором(хранилище: letters.Papers) -> None:
    """Главное в задаче: партнёру уходит дата аудитора, а не расчёт движка.

    Проверяются обе стороны сразу. Один только поиск «30.09.2026» был бы
    зелёным и в письме, где стоят обе даты; отсутствие запасной — в письме, где
    срока нет вовсе.
    """
    проверка = _проверка(info=(InfoRow(code="INF07", text=СРОК),))

    ответ = letters.build(проверка, lang=None, papers=хранилище)

    письмо = ответ["letter"]
    assert isinstance(письмо, str)
    assert СРОК in письмо, "срок, названный аудитором, в письмо не попал"
    assert ЗАПАСНОЙ_СРОК not in письмо, (
        "письмо несёт запасной расчёт движка вместо ответа аудитора — партнёр "
        "получит от управляющей компании другой срок, чем от аудитора"
    )


def test_записанная_часть_снимает_срок_с_перечня_невосстановленного(
    хранилище: letters.Papers,
) -> None:
    """Ответ аудитора восстановлен — жаловаться не на что, письмо готово к отправке."""
    проверка = _проверка(info=(InfoRow(code="INF07", text=СРОК),))

    ответ = letters.build(проверка, lang=None, papers=хранилище)

    assert ответ["not_restored"] == [], "восстановленное письмо названо неполным"
    assert ответ["ready_to_send"] is True


def test_без_записанной_части_срок_назван_невосстановленным(хранилище: letters.Papers) -> None:
    """Молчание тут опаснее прочерка: подставленная дата выглядит настоящей.

    У пустой шапки хотя бы видно пустое место — движок подписывает письмо
    прочерком. Срок же подставляется расчётом, читается как ответ аудитора и
    ничем себя не выдаёт, поэтому инструмент обязан назвать его вслух, а не
    отдавать письмо со словами «оценка сверена».
    """
    ответ = letters.build(_проверка(info=()), lang=None, papers=хранилище)

    assert letters.PLAN_DUE_FIELD in ответ["not_restored"], (  # type: ignore[operator]
        "срок плана действий не попал в перечень невосстановленного"
    )
    assert ответ["ready_to_send"] is False, "письмо с подставленным сроком названо готовым"
    состояние = ответ["status"]
    assert isinstance(состояние, str)
    assert "action plan" in состояние, "в ответе не сказано, что именно не восстановлено"


def test_порядок_полей_доезжает_до_движка_записанным(хранилище: letters.Papers) -> None:
    """Движок печатает поля в том порядке, в каком их получил.

    Порядок разделов документа партнёру задаётся здесь: пересобранный отчёт с
    переставленными разделами — другая бумага под прежней датой.
    """
    поля = (
        InfoRow(code="INF07", text=СРОК),
        InfoRow(code="INF01", text="смена собрана"),
    )

    состояние = letters.state_json(_проверка(info=поля), lang="ru")

    прочитано = list(json.loads(состояние)["info"])
    assert прочитано == ["INF07", "INF01"], "порядок информационной части потерян по дороге"
