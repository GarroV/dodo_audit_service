"""T155: заметки бота пишутся под блокировкой, иначе кадры теряются молча.

Файл проверки (`inspection.json`) блокировкой защищён — и движком, и блоком
`domain` (`domain/state.py`, `state_lock`). Заметки бота (`bot.json`), лежащие
в той же папке, защищены не были, а пишутся они тем же приёмом «прочитать,
дополнить, положить обратно»: два писателя внахлёст читают одну и ту же основу,
и тот, кто положил вторым, стирает чужое дополнение.

Цена — ровно та, ради которой заведена T068: три процесса по сорок кадров дали
44 записанных из 120. Семьдесят шесть кадров пропали молча, то есть проверка
не показала аудитору в конце те кадры, которые он присылал.

Модуль оправдывался тем, что «двух писателей здесь не бывает»: обновления бота
идут строго последовательно (`handle_as_tasks=False`). Это допущение, а не
гарантия — его снимают перекрытие при перезапуске и вторая копия сервиса, а
файл проверки рядом от того же самого случая защищён.

Проверяется тремя способами, и все три нужны:

* потеря дополнения при перекрытии — на двух потоках с явным окном между
  чтением и записью (`внахлёст`), потому что без окна перекрытия не случается
  и дефект не воспроизводится;
* что взята НАСТОЯЩАЯ файловая блокировка, а не внутрипроцессный замок, —
  захватом того же файла отдельным дескриптором;
* что кадры не теряются у нескольких настоящих процессов — тем самым опытом,
  которым дефект нашли.
"""

from __future__ import annotations

import fcntl
import os
import threading
import time
from pathlib import Path

import pytest

from src.bot import sidecar
from src.bot.sidecar import NOTES_FILE_NAME, SeenFrame, notes_path, read, remember_frames

CHAT = 8462

#: Окно между чтением и записью. Без него перекрытия не бывает: внутри записи
#: нет ожидания, и две задачи не переплетаются (потому дефект и не ловился).
ОКНО_СЕК = 0.3


def кадр(message_id: int, file_id: str) -> SeenFrame:
    return SeenFrame(message_id=message_id, file_id=file_id)


def _путь_замка(chat_id: int) -> Path:
    """Тот же уговор, что у файла проверки: замок зовётся `<файл>.lock`.

    Опознаётся блокировка по имени файла, а не по коду (см. `domain/state.py`),
    поэтому имя проверяется тестом наравне с поведением.
    """
    return notes_path(chat_id).with_name(NOTES_FILE_NAME + ".lock")


def test_перекрытие_двух_писателей_не_теряет_кадров(
    domain_env: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    """Главное утверждение файла: дополнение второго писателя не пропадает.

    Окно открывается на первом чтении: пока первый писатель держит прочитанную
    основу, второй успевает прочитать ту же самую. Под блокировкой второй
    столько же времени ждёт входа и читает уже дополненную.
    """
    настоящий_read = sidecar.read
    окно_открыто = threading.Event()

    def медленное_чтение(chat_id: int) -> sidecar.Notes:
        заметки = настоящий_read(chat_id)
        if not окно_открыто.is_set():
            окно_открыто.set()
            time.sleep(ОКНО_СЕК)
        return заметки

    monkeypatch.setattr(sidecar, "read", медленное_чтение)

    первый = threading.Thread(target=remember_frames, args=(CHAT, [кадр(1, "ПЕРВЫЙ")]))
    первый.start()
    assert окно_открыто.wait(timeout=5), "первый писатель не дошёл до чтения"
    второй = threading.Thread(target=remember_frames, args=(CHAT, [кадр(2, "ВТОРОЙ")]))
    второй.start()
    первый.join(timeout=30)
    второй.join(timeout=30)

    monkeypatch.setattr(sidecar, "read", настоящий_read)
    записаны = {к.file_id for к in read(CHAT).frames}
    assert записаны == {"ПЕРВЫЙ", "ВТОРОЙ"}, (
        "кадр второго писателя стёрт основой, которую первый прочитал до него — "
        "ровно та молчаливая потеря, против которой заведена T068"
    )


def test_запись_берёт_настоящую_файловую_блокировку(domain_env: Path) -> None:
    """Внутрипроцессный замок такую проверку бы прошёл, а дефект бы остался:
    писателей разносит перезапуск и вторая копия сервиса, то есть разные
    процессы. Захват идёт отдельным дескриптором того же файла — для `flock`
    это другой держатель, как и другой процесс.
    """
    remember_frames(CHAT, [кадр(1, "ЗАРАНЕЕ")])
    замок = _путь_замка(CHAT)
    assert замок.is_file(), f"замок {замок.name} не заведён — запись идёт без блокировки"

    записал = threading.Event()

    def писать() -> None:
        remember_frames(CHAT, [кадр(2, "ПОД_ЗАМКОМ")])
        записал.set()

    with замок.open("a+") as чужой:
        fcntl.flock(чужой.fileno(), fcntl.LOCK_EX)
        поток = threading.Thread(target=писать, daemon=True)
        поток.start()
        успел = записал.wait(timeout=1.0)
        fcntl.flock(чужой.fileno(), fcntl.LOCK_UN)

    поток.join(timeout=30)
    assert not успел, "запись прошла, пока файл заметок был занят другим держателем"
    assert записал.is_set(), "запись не возобновилась после освобождения замка"
    assert {к.file_id for к in read(CHAT).frames} == {"ЗАРАНЕЕ", "ПОД_ЗАМКОМ"}


def test_кадры_из_нескольких_процессов_не_теряются(domain_env: Path) -> None:
    """Тот самый опыт, которым дефект нашли: несколько процессов, каждый пишет
    свою пачку кадров. Считается итог — ни один кадр не имеет права пропасть.

    Процессы разводятся `os.fork`, а не запуском интерпретатора: на занятой
    машине новый интерпретатор может не стартовать вовсе (T189), и тест ловил
    бы беду машины вместо дефекта заметок. `fork` копию уже поднятого
    интерпретатора не поднимает заново.
    """
    ПИСАТЕЛЕЙ, КАДРОВ = 3, 20
    дети = []
    for писатель in range(ПИСАТЕЛЕЙ):
        pid = os.fork()
        if pid == 0:
            код = 0
            try:
                for номер in range(КАДРОВ):
                    remember_frames(CHAT, [кадр(писатель * 100 + номер, f"П{писатель}-{номер}")])
            except BaseException:
                код = 1
            finally:
                os._exit(код)
        дети.append(pid)

    for pid in дети:
        _, статус = os.waitpid(pid, 0)
        assert os.waitstatus_to_exitcode(статус) == 0, "писатель не смог записать свою пачку"

    записаны = {к.file_id for к in read(CHAT).frames}
    ожидались = {f"П{п}-{н}" for п in range(ПИСАТЕЛЕЙ) for н in range(КАДРОВ)}
    assert записаны == ожидались, (
        f"записано {len(записаны)} кадров из {len(ожидались)}: "
        f"потерялись молча {sorted(ожидались - записаны)[:5]}…"
    )


def test_очистка_заметок_тоже_ждёт_замка(domain_env: Path) -> None:
    """`reset` снимает файл целиком, и в обход замка это не безобиднее записи:
    писатель, уже прочитавший старую основу, положил бы её обратно — и кадры
    прошлой проверки воскресли бы в новой, начатой вместо неё.
    """
    remember_frames(CHAT, [кадр(1, "ПРОШЛАЯ_ПРОВЕРКА")])
    очистил = threading.Event()

    def чистить() -> None:
        sidecar.reset(CHAT)
        очистил.set()

    with _путь_замка(CHAT).open("a+") as чужой:
        fcntl.flock(чужой.fileno(), fcntl.LOCK_EX)
        поток = threading.Thread(target=чистить, daemon=True)
        поток.start()
        успел = очистил.wait(timeout=1.0)
        fcntl.flock(чужой.fileno(), fcntl.LOCK_UN)

    поток.join(timeout=30)
    assert not успел, "заметки снесены, пока файл был занят другим держателем"
    assert очистил.is_set(), "очистка не возобновилась после освобождения замка"
    assert read(CHAT).frames == ()
