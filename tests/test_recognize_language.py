def test_раздел_слов_колонок_не_становится_подсказками(английская_копия: Path) -> None:
    """Строка словаря колонок с кодом внутри — готовое неверное срабатывание.

    Управляющая компания ведёт словарь словами, но однажды напишет в нём и код
    («scuffs, see also DEM04»). Если раздел не выведен из подсказок, такая
    строка становится подсказкой с фразой «Dirt» — и тогда ЛЮБОЙ комментарий про
    грязь в зале показывает аудитору готовый пункт, который он подтвердит
    нажатием. Поэтому из подсказок выводятся ОБА служебных раздела, а не один.
    """
    _дописать(
        английская_копия,
        "\n## Words the auditor uses for a column\n\n| Column | Auditor words |\n|---|---|\n"
        "| Dirt | scuffs, see also DEM04 |\n",
    )

    фразы = [c.phrase for c in load_cues(английская_копия, chat_id=NO_CHAT)]
    итог = fast_path("Dirt on the menu board", "dining", lang="en", chat_id=NO_CHAT)

    assert "Dirt" not in фразы, "строка словаря колонок стала подсказкой карты"
    assert итог.item is None, f"словарь колонок показал пункт {итог.item}"


def test_неизвестный_заголовок_остаётся_подсказками(английская_копия: Path) -> None:
    """Сторож от перестраховки: пропускается не любой раздел, а два названных.

    Иначе «умное» узнавание разделов молча съело бы обычные подсказки карты.
    """
    _дописать(английская_копия, ДВЕ_КОЛОНКИ)

    фразы = [c.phrase for c in load_cues(английская_копия, chat_id=NO_CHAT)]

