def test_артикль_не_считается_значимым_словом() -> None:
    """То, из-за чего строки демо-карты пришлось писать без артикля.

    Совпадение строки карты идёт по вхождению её основ в основы комментария,
    поэтому артикль В СТРОКЕ КАРТЫ требовал того же артикля от аудитора: карта
    «crumbs left on the table» не совпадала с «crumbs left on a table».
    """
    assert stems("crumbs left on the table") == stems("crumbs left on table")
    assert "the" not in stems("the entrance door glass")


def test_английские_формы_слова_сводятся_к_одной_основе() -> None:
    """Аудитор говорит во множественном числе, карта — в единственном."""
    assert stems("crumbs") == stems("crumb")
    assert stems("boxes") == stems("box")
    assert stems("stains") == stems("stained")
    assert stems("cracks") == stems("cracked")


def test_русские_формы_слова_сводятся_к_одной_основе() -> None:
    """Сторож русского пути: сложение языков не должно его тронуть."""
    assert stems("печи") == stems("печь")
    assert stems("нагара") == stems("нагар")
    assert stems("трещины") == stems("трещина")


def test_русские_стоп_слова_остались_стоп_словами() -> None:
    """Тот же сторож с другой стороны: список русских слов не поредел."""
    assert stems("это и то, что видно рядом") == set()


