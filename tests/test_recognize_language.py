"""T192 (#157): правила разбора слов аудитора — данные, а не константы в коде.

Правило проекта записано в его же `CLAUDE.md`: «Язык — параметр, никогда не
константа». Разбор слов аудитора нарушал его в трёх местах сразу, и все три
видны только тогда, когда проверку ведут по-английски:

* заголовки разделов карты кадров узнавались по русским названиям, поэтому в
  английской карте раздел порогов классов не находился вовсе — а он уходит в
  промпт, и без него класс за аудитора выбирает модель наугад;
* разбор слова на основу и список стоп-слов были русскими: артикль `the`
  считался значимой основой и требовался от аудитора дословно, а `crumbs` и
  `crumb` были разными словами;
* словарь колонок знал только заголовки «Грязь» и «Поломка» и только русские
  слова, поэтому в английской карте колонка не выбиралась никогда.

**Почему проверять надо именно так.** Цена ошибки здесь несимметрична: быстрый
путь показывает готовый пункт кнопкой, и аудитор подтверждает его нажатием.
Пропуск стоит вызова модели, неверное срабатывание — записи в отчёте партнёру.
Поэтому английские тесты ниже проверяют обе стороны: и что срабатывание есть
там, где слова однозначны, и что отрицание его снимает.

**Английская методика в этом наборе одна — демо-набор** (`demo/data`): он лежит
в git, написан по-английски целиком и боевой методики не касается (за этим
следит `tests/test_methodology_leak.py`). Боевых английских проверок нет, и
поэтому доля срабатываний на английском не меряется ничем — здесь проверяется
поведение правил, а не их точность на живых данных.
"""

