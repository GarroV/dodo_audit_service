def test_правила_объявлены_для_обоих_языков_продукта() -> None:
    """Продукт двуязычен с первой версии — значит, правил тоже двое."""
    assert set(RULES) >= set(ЯЗЫКИ_ПРОДУКТА), (
        f"правила разбора объявлены не для всех языков продукта: {sorted(RULES)}"
    )
    for код in ЯЗЫКИ_ПРОДУКТА:
        правила = RULES[код]
        assert правила.stopwords, f"у языка {код} нет стоп-слов"
        assert правила.suffixes, f"у языка {код} нет окончаний"
        assert правила.negations, f"у языка {код} нет частиц отрицания"
        assert правила.column_words, f"у языка {код} нет встроенного словаря колонок"
        assert set(правила.sections) == {THRESHOLDS, COLUMN_WORDS}, (
            f"у языка {код} названы не все разделы карты: {sorted(правила.sections)}"
        )


def test_третий_язык_добавляется_словарём_а_не_кодом(tmp_path: Path) -> None:
    """Главное требование задачи: язык — данные.

    Третий язык обязан заработать от одной записи в файле правил. Проверяется
    это выдуманным языком: настоящий сербский здесь был бы обещанием, а не
    проверкой, — важно, что код не знает списка языков вовсе.
    """
    файл = tmp_path / "language_rules.json"
    файл.write_text(
        json.dumps(
            {
                "xx": {
                    "about": "выдуманный язык оснастки",
                    "stopwords": ["qux"],
                    "suffixes": ["zzz"],
                    "negations": {"nix": "forward"},
                    "connectives": ["ovo"],
                    "column_words": {"prljavo": ["blato"]},
                    "sections": {
                        "thresholds": "## Pragovi",
                        "column_words": "## Reci",
                    },
                }
            },
            ensure_ascii=False,
        ),
        encoding="utf-8",
    )

    правила = load_rules(файл)

    assert set(правила) == {"xx"}
    assert "qux" in stopwords(правила)
    assert "zzz" in suffixes(правила)
    assert negations(правила)["nix"] == "forward"
    assert builtin_column_words(правила)["prljavo"] == ("blato",)
    assert section_headings(THRESHOLDS, правила) == ("## Pragovi",)
    assert section_headings(COLUMN_WORDS, правила) == ("## Reci",)


def test_окончания_идут_от_длинных_к_коротким() -> None:
    """Порядок — часть правила: короткое окончание не должно съедать длинное.

    Отсечка идёт по первому совпавшему окончанию, поэтому «-ами» обязано
    проверяться раньше «-и». Сложение языков этот порядок обязано сохранять.
    """
    длины = [len(s) for s in suffixes()]

    assert длины == sorted(длины, reverse=True), f"окончания перемешаны: {suffixes()}"


def test_сломанные_правила_это_отказ_с_именем_языка(tmp_path: Path) -> None:
    """Правила читаются на границе, и молчаливого отката тут быть не должно.

    Пропущенное поле означает язык, который разбирается наполовину: слова
    режутся, а колонка не выбирается никогда. Такое обязано падать при старте,
    а не через месяц на точке.
    """
    файл = tmp_path / "language_rules.json"
    файл.write_text(json.dumps({"xx": {"about": "без всего"}}), encoding="utf-8")

    with pytest.raises(RecognizeConfigError) as отказ:
        load_rules(файл)

    assert "xx" in str(отказ.value), "в отказе не назван язык, из-за которого он случился"
    assert "stopwords" in str(отказ.value), "в отказе не названо недостающее поле"


def test_стоп_слова_языков_не_пересекаются() -> None:
    """Служебное слово одного языка не должно быть значимым словом другого.

    Правила языков складываются, а не выбираются по параметру (почему — в
    `src/recognize/language.py`). Пересечение здесь означало бы, что слово
    молча теряет вес в чужом языке, поэтому это ловится тестом, а не
    договорённостью.
    """
    for первый in RULES:
        for второй in RULES:
            if первый >= второй:
                continue
            общие = RULES[первый].stopwords & RULES[второй].stopwords
            assert not общие, f"стоп-слова {первый} и {второй} пересекаются: {sorted(общие)}"


def test_словарь_колонок_разбирается_тем_же_стеммером() -> None:
    """Слово словаря обязано сводиться к той же основе, что слово комментария.

    Иначе словарь молча не совпадает ни с чем, и быстрый путь тихо не работает
    на целом языке. Проверка идёт по всем объявленным языкам: третий язык
    добавляют словарём, и промах в нём должен быть виден здесь.
    """
    for код, правила in RULES.items():
        for колонка, слова in правила.column_words.items():
            for слово in слова:
                assert stems(слово), f"{код}/{колонка}: слово «{слово}» стеммер отбрасывает целиком"


def test_словари_колонок_одного_языка_не_пересекаются() -> None:
    """Слово в двух колонках сразу делает выбор колонки случайным."""
    for код, правила in RULES.items():
        основы = {
            колонка: {s for w in слова for s in stems(w)}
            for колонка, слова in правила.column_words.items()
        }
        for первая in основы:
            for вторая in основы:
                if первая >= вторая:
                    continue
                общие = основы[первая] & основы[вторая]
                assert not общие, f"{код}: «{первая}» и «{вторая}» делят основы {sorted(общие)}"


