"""Прямая речь владельца в коде публичного репозитория не прибавляется (T223, #178).

Решение D073 запрещает дословные цитаты владельца в новых документах и задачах
трекера. На комментарии в коде правило распространили не сразу, и к 05.09.2026
таких мест накопилось два с лишним десятка; большая часть уже опубликована, и
затирать её бессмысленно — история правок GitHub публична, это записано в самом
D073.

Поэтому проверка сторожит не ноль, а **потолок**: закрывает приток. Комментарий
обязан объяснять решение, а не пересказывать разговор, — «решение владельца,
D0NN» несёт читателю кода ровно то же, а сама формулировка живёт в
`docs/forge/decisions.md`.

Убрали цитату — опустите потолок тем же коммитом: иначе освободившееся место
молча займёт следующая.
"""

from __future__ import annotations

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

#: Сколько прямой речи в коде на 05.09.2026. Только вниз.
ПОТОЛОК = 25

#: Ввод прямой речи: «дословно», «словами владельца», «владелец: …» — и следом
#: открывающая кавычка. Кавычка обязательна: без неё пересказ решения, который
#: как раз и нужен, считался бы нарушением.
ПРЯМАЯ_РЕЧЬ = re.compile(
    r"(?:дословно|словами владельца|владелец[^.\n]{0,20}[:,]\s*)[^\n]*«", re.IGNORECASE
)

КАТАЛОГИ = ("src", "tests", "engine", "tools")

#: Сам детектор описывает, что ищет, и потому попадает под собственное правило.
СЕБЯ = Path(__file__).name


def _места() -> dict[str, int]:
    найдено: dict[str, int] = {}
    for каталог in КАТАЛОГИ:
        for путь in (ROOT / каталог).rglob("*.py"):
            if путь.name == СЕБЯ:
                continue
            сколько = len(ПРЯМАЯ_РЕЧЬ.findall(путь.read_text(encoding="utf-8")))
            if сколько:
                найдено[str(путь.relative_to(ROOT))] = сколько
    return найдено


def test_прямой_речи_владельца_в_коде_не_прибавляется() -> None:
    места = _места()
    всего = sum(места.values())
    assert всего <= ПОТОЛОК, (
        f"прямой речи владельца в коде стало {всего} вместо {ПОТОЛОК}, а репозиторий публичный "
        f"(D073): ссылайтесь на номер решения вместо цитаты. Где: "
        f"{sorted(места.items(), key=lambda п: -п[1])[:5]}"
    )


def test_потолок_не_завышен() -> None:
    """Убрали цитату — опустите потолок, иначе место молча займёт следующая."""
    всего = sum(_места().values())
    assert всего == ПОТОЛОК, (
        f"прямой речи стало меньше ({всего} против потолка {ПОТОЛОК}) — "
        f"опустите ПОТОЛОК до {всего} тем же коммитом"
    )
