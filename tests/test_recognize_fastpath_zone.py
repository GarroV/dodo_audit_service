"""T143 (задача #114): названная зона участвует в решении об однозначности.

До этой задачи зона проверялась **последней** — уже для единственного кода,
пережившего все остальные условия. Из-за порядка карта не могла держать один
объект с разными пунктами по зонам: строка «Пол | CLN03, CLN12» отвергалась как
«слова указывают на несколько пунктов» ещё до того, как выяснялось, что в
названной зоне из них применим ровно один.

Что здесь проверяется — и, что важнее, чего здесь проверяться НЕ должно.

**Зона разводит коды ВНУТРИ покрытой строки.** Это и есть задача: строка карты
называет объект, зона говорит, о каком пункте про этот объект речь.

**Покрытые строки по зоне не отбрасываются.** Соблазн — выкинуть строку,
которая в названной зоне никуда не ведёт, и ответить по оставшейся. Замер это
запрещает: на боевых записях (карта-черновик T118, зона как её берёт бот)
отбрасывание строк даёт 8 срабатываний из 17 против 7, и восьмое — **неверное**
(belgrade-2: эталон `CLN03` в зоне `dining`, быстрый путь показал бы `CLN12`).
Сигнал «слова и место не сходятся» обязан оставаться громким отказом, а не
превращаться в тихую подстановку.

**Зона разводит только то, что действительно разводится зоной.** Коды с
пересекающимися перечнями зон — это выбор, предложенный самой картой («PRD09,
PRD11»), и зона его не решает: в другой зоне тот же комментарий дал бы другой
ответ, а карта имела в виду два разных вопроса, а не два места. Разводятся
только коды с **непересекающимися** зонами: тогда строка не предлагает выбор, а
перечисляет варианты одного объекта по местам.
"""

from __future__ import annotations

from pathlib import Path

import pytest

from src.domain import get_item, list_items
from src.recognize.config import NO_CHAT
from src.recognize.fastpath import (
    NOT_OFFERED,
    SEVERAL_ITEMS,
    WRONG_ZONE,
    fast_path,
)

#: Заголовок и шапка таблицы, которой тест дописывает свои строки в карту.
#: Раздел свой, чтобы не зависеть от того, что стоит в соседних разделах карты.
ШАПКА = "\n## Проверка зоны\n\n| Что на кадре | Пункты |\n|---|---|\n"


def _карта_со_строками(data_copy: Path, monkeypatch: pytest.MonkeyPatch, *строки: str) -> None:
    """Дописать в копию синтетической карты свои строки и переключить методику."""
    карта = data_copy / "photo-cues.md"
    карта.write_text(
        карта.read_text(encoding="utf-8") + ШАПКА + "".join(f"| {s} |\n" for s in строки),
        encoding="utf-8",
    )
    monkeypatch.setenv("AUDIT_DATA_DIR", str(data_copy))


# --- зона разводит коды внутри строки ---------------------------------------


def test_зона_выбирает_пункт_внутри_строки_карты(
    domain_env: Path, data_copy: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    """Один объект, два пункта по зонам — выбирает названная зона, а не догадка.

    `CLN01` заведён для производственных участков, `CLN12` — для гостевого зала;
    перечни зон не пересекаются. Значит строка карты не предлагает выбор: она
    перечисляет, как один и тот же объект называется в методике по местам.
    """
    assert not set(get_item("CLN01").zones) & set(get_item("CLN12").zones), (
        "тест бессмыслен, если зоны пунктов пересекаются"
    )
    _карта_со_строками(domain_env_dc := data_copy, monkeypatch, "Половое покрытие | CLN01, CLN12")
    assert domain_env_dc.is_dir()

    кухня = fast_path("Половое покрытие в грязи", "hot_kitchen", chat_id=NO_CHAT)
    зал = fast_path("Половое покрытие в грязи", "dining", chat_id=NO_CHAT)

    assert кухня.item is not None, кухня.reason
    assert кухня.item.code == "CLN01"
    assert зал.item is not None, зал.reason
    assert зал.item.code == "CLN12", "в зале тот же объект — другой пункт методики"


def test_ни_один_код_строки_не_подходит_зоне_остаётся_отказом(
    domain_env: Path, data_copy: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    """Строка произнесена целиком, но в названной зоне не ведёт никуда.

    Это по-прежнему отказ, и причина у него своя: расхождение слов и места —
    работа для модели.
    """
    _карта_со_строками(data_copy, monkeypatch, "Половое покрытие | CLN01, CLN12")

    итог = fast_path("Половое покрытие в грязи", "facade", chat_id=NO_CHAT)

    assert итог.item is None
    assert итог.reason == WRONG_ZONE


# --- покрытые строки по зоне не отбрасываются -------------------------------


def test_вторая_строка_вне_зоны_не_отбрасывается_молча(domain_env: Path) -> None:
    """Комментарий про два объекта, один из которых в названной зоне не бывает.

    Соблазн — выкинуть вторую строку и ответить по первой. Так делать нельзя:
    на боевых записях это даёт неверное срабатывание (см. докстроку модуля), а
    здесь превратило бы комментарий про два нарушения (правило 11) в один
    уверенный пункт. Отказ — единственный честный ответ.
    """
    assert "CLN13" not in {i.code for i in list_items(zone="hot_kitchen")}

    итог = fast_path("Печь в нагаре, урна в зале переполнена", "hot_kitchen", chat_id=NO_CHAT)

    assert итог.item is None, "быстрый путь ответил по одной строке из двух"
    assert итог.reason == WRONG_ZONE


# --- зона не решает то, что зоной не решается -------------------------------


def test_коды_с_пересекающимися_зонами_зоной_не_разводятся(
    domain_env: Path, data_copy: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    """«CLN03, CLN06» — выбор карты, а не перечень по местам.

    Перечни зон у пунктов пересекаются: в производственных зонах применимы оба,
    и там строка честно неоднозначна. Значит и в зоне, где применим один, она
    остаётся выбором самой карты: иначе один и тот же комментарий в разных
    местах отвечал бы то однозначно, то нет, и понять почему было бы нечем.
    """
    общие = set(get_item("CLN03").zones) & set(get_item("CLN06").zones)
    assert общие, "тест бессмыслен, если зоны пунктов не пересекаются"
    assert "CLN03" not in {i.code for i in list_items(zone="dining")}
    assert "CLN06" in {i.code for i in list_items(zone="dining")}
    _карта_со_строками(data_copy, monkeypatch, "Перегородка участка | CLN03, CLN06")

    итог = fast_path("Перегородка участка в грязи", "dining", chat_id=NO_CHAT)

    assert итог.item is None
    assert итог.reason == SEVERAL_ITEMS


def test_служебный_пункт_отсекается_до_зоны(
    domain_env: Path, data_copy: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    """Причина отказа не должна подменяться зональной.

    Порядок виден только на служебном пункте **со своими зонами**: у сводных
    строк сегодняшней методики перечня зон нет, и методика считает их
    применимыми везде, поэтому на них любой порядок даёт один и тот же ответ.
    Такой пункт заводится здесь же, на копии: отсутствие подобной строки
    сегодня не гарантирует, что её не впишут завтра, а причина отказа —
    единственное, из чего видно, какое правило сработало.
    """
    чек_лист = data_copy / "checklist.csv"
    чек_лист.write_text(
        chr(10).join(
            [
                чек_лист.read_text(encoding="utf-8").rstrip(chr(10)),
                "INF12,info,Замеры,Measurements,Справочная строка: порядок условий,"
                "Reference line: order of conditions,,hot_kitchen,1",
                "",
            ]
        ),
        encoding="utf-8",
    )
    _карта_со_строками(data_copy, monkeypatch, "Служебная строка карты | INF12")
    assert get_item("INF12").kind != "violation"
    assert "INF12" not in {i.code for i in list_items(zone="dining")}

    итог = fast_path("служебная строка карты", "dining", chat_id=NO_CHAT)

    assert итог.item is None
    assert итог.reason == NOT_OFFERED, "зональный отказ подменил правило 8"
