"""T142 (задача #113): различающее слово не должно слабеть от роста карты.

Подсказка карты срабатывает при двух совпавших словах **или одном
различающем**. «Различающее» до этой задачи означало «стем встречается не более
чем в трёх СТРОКАХ карты» — порог абсолютный, поэтому от подробной карты
обычные слова теряли силу молча: ничего не падает, просто нужного кода нет
среди кандидатов, а модель на неполном перечне не отказывается, а уверенно
предлагает похожий пункт (`docs/forge/research/recognize-probe.md`).

Задача просила считать порог долей карты. Замер показал, что доля — не тот
знаменатель, и заменять надо не число, а **величину**: слово слабеет не от
длины карты, а от собственной многозначности. Пять строк про печь и её узлы —
это один объект, расписанный подробнее, и все они ведут в одну и ту же пару
пунктов; слово «печь» после такого расписывания не стало хуже указывать. А слово «продукт»
плохо указывает и на короткой карте, потому что ведёт в десяток разных пунктов.

Поэтому различающим считается слово, которое ведёт не более чем к
`DISTINCTIVE_CODES_AT_MOST` **различным кодам** — сколько бы строк его ни
содержало. Величина не зависит от размера карты вовсе, и требование задачи
(«слово, различающее при 75 строках, обязано остаться различающим при 500»)
выполняется не подбором коэффициента, а тем, что размер в правило не входит.

Карта здесь собирается прямо в тесте: `match_cues` берёт строки параметром, а
проверяется само правило, а не содержимое чьей-либо методики.
"""

from __future__ import annotations

import pytest

from src.recognize.cues import DISTINCTIVE_CODES_AT_MOST, Cue, match_cues

ПЕЧЬ = ("CLN05", "TEH05")


#: Строки-наполнитель: карта вокруг проверяемого слова. Слова в них свои, чтобы
#: наполнитель ни на что не влиял, кроме размера карты.
def наполнитель(сколько: int) -> list[Cue]:
    return [
        Cue(phrase=f"Объект номер {n:04d}", codes=(f"XXX{n % 90:02d}",)) for n in range(сколько)
    ]


@pytest.mark.parametrize("строк", [1, 5, 40, 200])
def test_слово_остаётся_различающим_как_бы_подробно_ни_расписали_объект(строк: int) -> None:
    """Один объект, расписанный на N строк с теми же пунктами, слово не портит.

    Ровно этот случай сломал карту при первом её пополнении (#113): семь слов
    перешли абсолютный порог и перестали поднимать свои пункты, в том числе
    «печь» — `match_cues("печи не мыли")` вернул только пункт про мойку.
    """
    карта = [Cue(phrase=f"Печь: узел {n}", codes=ПЕЧЬ) for n in range(строк)]
    карта.append(Cue(phrase="Печь", codes=ПЕЧЬ))

    поднято = match_cues("печи не мыли", tuple(карта + наполнитель(300)))

    assert "CLN05" in поднято, "слово одного объекта потеряло силу от подробной карты"


def test_слово_ведущее_ко_многим_пунктам_не_различающее() -> None:
    """«Продукт» есть в десятке строк и сам по себе не значит ничего.

    Две строки — по абсолютному счёту строк это «редкое» слово, и раньше оно
    поднимало бы всё, куда ведёт. Считать надо не строки: одно слово выносит в
    голову перечня восемь разных пунктов, и головы перечня после этого нет.
    """
    много = ("PRD01", "PRD03", "PRD04", "PRD07", "FSB03", "FSB04", "FSB05", "FSB06")
    assert len(много) > DISTINCTIVE_CODES_AT_MOST
    карта = (
        Cue(phrase="Продукт на раздаче", codes=много[:4]),
        Cue(phrase="Продукт в холодильнике", codes=много[4:]),
    )

    assert match_cues("продукт испорчен", карта) == ()


def test_слово_ведущее_к_немногим_пунктам_различающее() -> None:
    """Граница проверяется с обеих сторон: иначе тест выше проходит на пустышке."""
    немного = ("PRD01", "PRD03")
    карта = (
        Cue(phrase="Заказ на выдаче", codes=немного),
        Cue(phrase="Заказ в приложении", codes=немного),
    )

    assert match_cues("заказ выдан", карта) == немного


def test_два_совпавших_слова_поднимают_строку_и_без_различающего() -> None:
    """Второе условие подсказки не тронуто: два слова работают всегда.

    Слово может вести куда угодно — если совпало два, строка названа, а не
    задета, и порог различающего слова к делу не относится.
    """
    много = ("PRD01", "PRD03", "PRD04", "PRD07", "FSB03", "FSB04", "FSB05", "FSB06")
    карта = (
        Cue(phrase="Продукт на раздаче", codes=много[:4]),
        Cue(phrase="Продукт в холодильнике", codes=много[4:]),
    )

    assert match_cues("продукт на раздаче лежит открытым", карта)[0] == "PRD01"


def test_счёт_идёт_по_различным_кодам_а_не_по_их_повторам() -> None:
    """Один и тот же код в двадцати строках — это один код, а не двадцать.

    Иначе правило вернулось бы к счёту строк окольным путём: карта, где объект
    расписан подробно, снова наказывала бы своё главное слово.
    """
    карта = tuple(Cue(phrase=f"Витрина: полка {n}", codes=("CLN13",)) for n in range(20))

    assert match_cues("витрина в крошках", карта) == ("CLN13",)
