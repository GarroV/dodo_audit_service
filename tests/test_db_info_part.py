def test_кадр_поля_ложится_рядом_с_ним_и_уезжает_в_хранилище(domain_env: Path, db_env: str) -> None:
    """Кадр информационного поля — такое же доказательство, как кадр записи.

    Движок печатает его в отчёте под текстом своего поля (T179), а
    `telegram_file_id` живёт ровно столько, сколько живёт бот с этим токеном.
    Не слитый, он стал бы потерянным доказательством — ровно тем, ради чего
    заводилась выгрузка кадров (T094). Поэтому кадр поля идёт в ту же таблицу
    `photos` и той же выгрузкой: своей записи (`finding_id`) у него нет.
    """
    положено: dict[str, bytes] = {}

    class Склад:
        def put(self, key: str, data: bytes, *, content_type: str) -> str:
            положено[key] = data
            return f"s3://корзина/{key}"

    ident = _проверка(2005, кадры=("tg-info-001",))

    (кадр,) = _строки(
        db_env,
        "select p.telegram_file_id, p.finding_id, i.code "
        "from photos p join inspection_info i on i.id = p.info_id "
        "where p.inspection_id = %s",
        (ident,),
    )
    assert кадр[0] == "tg-info-001", "кадр информационного поля не доехал до базы"
    assert кадр[1] is None, "кадр поля привязан к записи, которой у него нет"
    assert кадр[2] == "INF07", "кадр привязан не к тому полю"

    выгружено = upload_photos(ident, fetch=lambda _: b"\xff\xd8 frame", storage=Склад())

    assert выгружено == 1, "выгрузка не увидела кадра информационного поля"
    assert положено, "кадр поля не уехал в хранилище"


def test_информационная_часть_входит_в_отпечаток(domain_env: Path) -> None:
    """Разный срок партнёру — разные документы, а значит разные отпечатки.

    Отпечаток — содержимое документа, ушедшего партнёру. Сырые слова аудитора и
    предложение модели в него не входят именно потому, что в документе их нет;
    информационная часть в документе ЕСТЬ — приложением отчёта и сроком в
    письме. Не войди она в отпечаток, две проверки с разными требованиями к
    партнёру считались бы одной строкой истории точки, и вторая не легла бы в
    базу вовсе.
    """
    start_inspection(2006, unit=ТОЧКА, kind="planned", report_lang="ru", tenant=АРЕНДАТОР)
    add_finding(2006, code="CLN05", level="D1", zone="hot_kitchen", text="нагар на печи")
    set_info(2006, "INF07", СРОК)
    состояние = get_state(2006)
    assert состояние is not None
    # Без этой строки тест был бы зелёным и там, где домен информационной части
    # не отдаёт вовсе: сравнивались бы два одинаковых «ничего».
    assert состояние.info["INF07"].text == СРОК, "домен не отдал поля — сравнивать нечего"
    оценка = domain_score(2006)

    с_ответом = compute_fingerprint(состояние, оценка, tenant_code=АРЕНДАТОР)
    другой_срок = compute_fingerprint(
        replace(состояние, info={"INF07": replace(состояние.info["INF07"], text="15.09.2026")}),
        оценка,
        tenant_code=АРЕНДАТОР,
    )

    assert с_ответом != другой_срок, (
        "срок плана действий не влияет на отпечаток: два разных требования к "
        "партнёру считались бы одной проверкой"
    )


def test_прежний_рецепт_объявлен_и_отличается_от_текущего(domain_env: Path) -> None:
    """Сторож смысла: без объявленного прежнего рецепта совместимость не проверить.

    Красный на неисправленном коде — там информационная часть в отпечаток не
    входит вовсе, и «прежний» рецепт равен текущему.

    Рецепты названы не числом и не порядком, а тем, чем они друг от друга
    отличаются, — иначе тест был бы зелёным на любых двух отпечатках. Рецепт до
    T200 не различает проверки ни по информационной части, ни по источнику
    записи; рецепт до T193 информационной части тоже не знает, но источник в
    него входит. Оба свойства проверяются пересчётом на изменённом состоянии, а
    не знанием о том, как считается хеш.
    """
    start_inspection(2007, unit=ТОЧКА, kind="planned", report_lang="ru", tenant=АРЕНДАТОР)
    add_finding(2007, code="CLN05", level="D1", zone="hot_kitchen", text="нагар на печи")
    set_info(2007, "INF07", СРОК)
    состояние = get_state(2007)
    assert состояние is not None
    оценка = domain_score(2007)

    def прежние(проверка: Inspection) -> tuple[str, ...]:
        return previous_fingerprints(проверка, оценка, tenant_code=АРЕНДАТОР)

    текущий = compute_fingerprint(состояние, оценка, tenant_code=АРЕНДАТОР)
    без_полей = replace(состояние, info={})
    по_кадру = replace(
        состояние, findings=[replace(f, source=SOURCE_PHOTO) for f in состояние.findings]
    )

    assert текущий not in прежние(состояние), "информационная часть в отпечаток не вошла"
    assert прежние(состояние) == прежние(без_полей), (
        "прежний рецепт знает об информационной части — такого рецепта не было в употреблении"
    )
    assert прежние(состояние)[0] == прежние(по_кадру)[0], (
        "рецепта до T200 (без информационной части и без источника записи) среди прежних нет: "
        "проверки, слитые вчера, перестанут находиться и лягут в историю точки второй строкой"
    )
    assert прежние(состояние)[1] != прежние(по_кадру)[1], (
        "рецепта до T193 (с источником записи) среди прежних нет — он унесён вместе со сменой "
        "рецепта, хотя строки того рецепта у площадки никто не отменял"
    )


def test_слитое_прежним_рецептом_не_задваивается(
    domain_env: Path, db_env: str, monkeypatch: pytest.MonkeyPatch
) -> None:
    """Проверка, лежащая под прежним отпечатком, находится — вторая строка не пишется.

    Слив прежним кодом воспроизводится подменой рецепта в самом сливе: это
    ровно то, что делал вчерашний продукт, и другого способа получить такую
    строку у теста нет — рукописный INSERT проверял бы форму запроса, а не
    поведение слива.
    """
    start_inspection(2008, unit=ТОЧКА, kind="planned", report_lang="ru", tenant=АРЕНДАТОР)
    add_finding(2008, code="CLN05", level="D1", zone="hot_kitchen", text="нагар на печи")
    set_info(2008, "INF07", СРОК)
    состояние = get_state(2008)
    assert состояние is not None
    оценка = domain_score(2008)
    прежний = previous_fingerprints(состояние, оценка, tenant_code=АРЕНДАТОР)[0]

    monkeypatch.setattr("src.db.push.compute_fingerprint", lambda *a, **k: прежний)
    первый = push_inspection(2008)
    monkeypatch.setattr("src.db.push.compute_fingerprint", compute_fingerprint)

    второй = push_inspection(2008)

    assert второй == первый, "слив не узнал проверку, лежащую под прежним отпечатком"
    (сколько,) = _строки(db_env, "select count(*) from inspections", ())
    assert сколько[0] == 1, (
        "смена рецепта отпечатка задвоила уже слитую проверку — разделить эти "
        "две строки обратно нельзя, запечатанная не удаляется"
    )


def test_повторный_слив_не_задваивает_полей(domain_env: Path, db_env: str) -> None:
    """Второй вызов на той же проверке не пишет информационную часть заново."""
