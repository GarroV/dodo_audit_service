def test_записанное_поле_нельзя_переписать(domain_env: Path, db_env: str) -> None:
    """Срок, названный партнёру, не правится задним числом — держит схема, а не код.

    Это часть документа, который уже ушёл и стал основанием для требований к
    партнёру: переписанный срок означал бы другую бумагу под прежней датой.
    Заслон тот же, что у находок, — политика запечатанной проверки из `0004`.

    Отказ RLS МОЛЧАЛИВЫЙ: строка просто не видна для записи, `UPDATE` честно
    отчитывается «затронуто 0 строк» и не падает. Поэтому проверяется и число
    строк, и само значение — «не упало» здесь не значит ничего.
    """
    ident = _проверка(2010)

    with psycopg.connect(db_env) as conn, conn.cursor() as cur:
        cur.execute(
            "update inspection_info set text = %s where inspection_id = %s and code = %s",
            ("15.09.2026", ident, "INF07"),
        )
        затронуто = cur.rowcount
        cur.execute("delete from inspection_info where inspection_id = %s", (ident,))
        удалено = cur.rowcount
        conn.commit()

    assert затронуто == 0, "срок плана действий в записанной проверке удалось переписать"
    assert удалено == 0, "информационную часть записанной проверки удалось удалить"
    (поле,) = _строки(
        db_env,
        "select text from inspection_info where inspection_id = %s and code = %s",
        (ident, "INF07"),
    )
    assert поле[0] == СРОК, "срок изменился задним числом"
