"""T200 (#163): информационная часть проверки доезжает до базы и читается обратно.

Семь полей, которые аудитор заполняет в конце обхода (сильные стороны, зоны
роста, отзыв о тестовом заказе, две даты, два ответа «да/нет»), до этой задачи
не сливались вовсе: ни таблицы, ни колонки. Проверка ложилась в базу без них, и
письмо, пересобранное по записанной проверке, брать их было неоткуда.

**Чем это кончалось для партнёра.** Срок плана действий называет аудитор — это
одно из семи полей. Бот печатает в письме его ответ; MCP, пересобирая письмо по
записанной проверке, ответа не видел и подставлял запасной расчёт движка (дата
обхода плюс `plan_due_days`). В прогоне сверки бот говорил «Просим до
30.09.2026», MCP — «Просим до 15.09.2026». Партнёр получал от управляющей
компании другой срок, чем от аудитора, и обе бумаги подписаны системой как
верные.

Что здесь проверяется, кроме самого факта записи:

1. **Ответ доезжает дословно.** Срок читает человек, и «30.09.2026» с точностью
   до символа — это и есть содержание требования к партнёру.
2. **Порядок полей — записанный, а не алфавитный по коду.** Движок печатает
   поля в том порядке, в каком их записали (`engine/report.py`), и порядок
   разделов документа не имеет права меняться при пересборке.
3. **Информационная часть входит в отпечаток проверки** — в отличие от сырых
   слов аудитора (T185) и предложения модели (T164). Отпечаток это содержимое
   документа, ушедшего партнёру, а информационная часть в документ ПОПАДАЕТ:
   печатается приложением отчёта и читается письмом. Две проверки, у которых
   партнёру названы разные сроки, — разные документы.
4. **Смена рецепта отпечатка не задваивает уже слитое** (механизм T193): строка,
   лежащая в базе под прежним отпечатком, обязана найтись, а не лечь второй в
   историю точки — разделить их обратно нечем, миграция `0004` запрещает
   запечатанную проверку и править, и удалять.
5. **Записанное поле замораживается вместе с проверкой.** Это часть документа
   партнёру, и правка задним числом означала бы другой срок под прежней датой.
"""

