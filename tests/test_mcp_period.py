"""T119: период отбирает база, а не инструмент поверх прочитанной страницы.

До этой задачи блок читал страницу «по потолку чтения» и отсеивал период уже
у себя, в памяти. Пока проверок меньше потолка, разницы не видно — и ровно
поэтому дефект дожил до сюда. Разница появляется, когда проверок больше, чем
читается за раз: страница набирается по САМЫМ СВЕЖИМ проверкам, а спрашивают
про период, который в неё не попал. Ответ при этом выглядит обычным: «за этот
период проверок нет», хотя они есть.

Тесты держат оба свойства:

1. **Границы периода доезжают до слоя чтения** — то есть отбор идёт в SQL.
   Снятый аргумент валит этот файл, а не всплывает у первого партнёра с
   историей за три года (D035).
2. **Проверка за периодом видна и тогда, когда она не попала в первую
   страницу.** Потолок чтения подменяется на единицу — это дешёвый способ
   получить «проверок больше, чем читается за раз», не заливая тысячу строк.
"""

from __future__ import annotations

from datetime import date
from pathlib import Path
from typing import Any

import pytest
from conftest import requires_data, requires_db

pytest.importorskip("psycopg")

import src.db.queries as queries
from src.db.push import push_inspection
from src.domain import add_finding, start_inspection
from src.mcp.tools import list_inspections, network_summary, unit_history

АРЕНДАТОР = "партнёр-а"


def _проверка(chat_id: int, *, точка: str = "Белград-1", дата: str) -> str:
    start_inspection(
        chat_id, unit=точка, kind="Плановая", report_lang="ru", tenant=АРЕНДАТОР, date=дата
    )
    add_finding(chat_id, code="CLN05", level="D1", zone="hot_kitchen", text="нагар на печи")
    return push_inspection(chat_id)


# --- границы доезжают до базы ------------------------------------------------


@pytest.fixture
def записанные_вызовы(monkeypatch: pytest.MonkeyPatch) -> list[dict[str, Any]]:
    """Подменённый слой чтения, запоминающий, с чем его позвали.

    Подменяется именно `src.db.queries.list_inspections`: инструменты тянут его
    лениво, внутри функции, поэтому подмена в модуле доходит до вызова.
    """
    вызовы: list[dict[str, Any]] = []

    def запись(**kwargs: Any) -> list[Any]:
        вызовы.append(kwargs)
        return []

    monkeypatch.setattr(queries, "list_inspections", запись)
    return вызовы


def test_период_списка_уходит_в_слой_чтения_а_не_отбирается_здесь(
    записанные_вызовы: list[dict[str, Any]],
) -> None:
    """Границы приходят в базу разобранными датами, а не остаются здесь."""
    list_inspections(tenant=АРЕНДАТОР, date_from="2026-08-01", date_to="2026-08-31")

    assert len(записанные_вызовы) == 1
    вызов = записанные_вызовы[0]
    assert вызов["date_from"] == date(2026, 8, 1)
    assert вызов["date_to"] == date(2026, 8, 31)


def test_период_сводки_уходит_в_слой_чтения_а_не_отбирается_здесь(
    записанные_вызовы: list[dict[str, Any]],
) -> None:
    """Сводка считалась по потолочной странице — то есть по случайной выборке."""
    network_summary(tenant=АРЕНДАТОР, date_from="2026-08-01", date_to="2026-08-31")

    assert len(записанные_вызовы) == 1
    вызов = записанные_вызовы[0]
    assert вызов["date_from"] == date(2026, 8, 1)
    assert вызов["date_to"] == date(2026, 8, 31)


def test_история_точки_читается_одним_запросом_с_названием_точки(
    записанные_вызовы: list[dict[str, Any]],
) -> None:
    """История точки фильтруется базой, а не перебором прочитанного."""
    unit_history(tenant=АРЕНДАТОР, unit="Белград-1")

    assert len(записанные_вызовы) == 1
    assert записанные_вызовы[0]["unit"] == "Белград-1"


# --- проверка за периодом видна и за пределом первой страницы ----------------


@requires_data
@requires_db
def test_старая_проверка_видна_даже_когда_свежих_больше_чем_читается_за_раз(
    domain_env: Path, db_env: str, monkeypatch: pytest.MonkeyPatch
) -> None:
    """Ключевой тест задачи: отбор ПОСЛЕ чтения терял бы эту проверку молча.

    Потолок чтения подменён на одну строку — это то же самое, что тысяча
    свежих проверок перед искомой, только без тысячи проверок. Отбор поверх
    прочитанной страницы вернул бы здесь пустоту: первая (и единственная
    прочитанная) строка — самая свежая, а она не в периоде.
    """
    старая = _проверка(401, точка="Белград-1", дата="2024-05-05")
    _проверка(402, точка="Ниш-1", дата="2026-08-20")
    _проверка(403, точка="Ниш-2", дата="2026-08-21")
    monkeypatch.setattr(queries, "DEFAULT_LIMIT", 1)

    ответ = list_inspections(tenant=АРЕНДАТОР, date_from="2024-01-01", date_to="2024-12-31")

    assert [строка["id"] for строка in ответ["inspections"]] == [старая]
    assert "no inspections" not in ответ["status"].lower()


@requires_data
@requires_db
def test_сводка_за_период_не_считается_по_свежей_странице(
    domain_env: Path, db_env: str, monkeypatch: pytest.MonkeyPatch
) -> None:
    """Сводка за 2024 год не должна зависеть от того, сколько проверок в 2026."""
    _проверка(404, точка="Белград-1", дата="2024-05-05")
    _проверка(405, точка="Ниш-1", дата="2026-08-20")
    _проверка(406, точка="Ниш-2", дата="2026-08-21")
    monkeypatch.setattr(queries, "MAX_LIMIT", 1)

    сводка = network_summary(tenant=АРЕНДАТОР, date_from="2024-01-01", date_to="2024-12-31")

    assert сводка["inspections"] == 1
    assert [точка["unit"] for точка in сводка["by_unit"]] == ["Белград-1"]
    assert сводка["best"]["inspection_date"] == "2024-05-05"


# --- «первая строка точки — её последняя проверка» ---------------------------


@requires_data
@requires_db
def test_последняя_проверка_точки_в_сводке_это_самая_свежая_по_дате_обхода(
    domain_env: Path, db_env: str
) -> None:
    """Свод по точкам берёт первую встреченную строку как последнюю проверку.

    Это верно ровно потому, что выдача упорядочена по дате ОБХОДА: до T114
    порядок шёл по дате слива, и у залитой одним заходом истории (D035)
    «последней» оказывалась случайная проверка.
    """
    _проверка(407, точка="Белград-1", дата="2024-05-05")
    свежая = _проверка(408, точка="Белград-1", дата="2026-08-20")

    сводка = network_summary(tenant=АРЕНДАТОР)

    точка = сводка["by_unit"][0]
    assert точка["inspections"] == 2
    assert точка["latest"]["id"] == свежая
    assert точка["latest"]["inspection_date"] == "2026-08-20"
