def test_быстрый_путь_идёт_по_карте_издания_проверки(методика: Path) -> None:
    """Главное следствие D063: пункт без вызова модели предлагается по СВОЕЙ карте.

    Быстрый путь показывает готовый пункт, а с D064 подтверждение для текста
    снято — значит, запись уходит в отчёт партнёру по той карте, которую здесь
    и выбирают. Прочитанная из действующего каталога, она даёт запись по
    правилам, которых в издании проверки нет.
    """
    начать()
    снять_строку_карты(методика, СТРОКА_КАРТЫ)

    свой = fast_path(СЛОВА, ЗОНА_КАРТЫ, chat_id=CHAT_ID)
    действующий = fast_path(СЛОВА, ЗОНА_КАРТЫ, chat_id=NO_CHAT)

    assert свой.item is not None, f"быстрый путь пошёл по действующей карте: {свой.reason}"
    assert свой.item.code == ПУНКТ_КАРТЫ
    assert действующий.item is None and действующий.reason == NO_CUE


