"""T226 (#181): разбор идёт по изданию ТОЙ проверки, а не по действующему каталогу.

Задача T169 научила домен читать издание конкретной проверки: снимок берётся на
старте, и запись, правка, подсчёт и отчёт идут по нему. T225 провёл то же самое
до бота. Разбор оставался последним местом, где справочники и карта слов
читались из каталога, который лежит в `AUDIT_DATA_DIR` СЕЙЧАС, — то есть
публикация методики посреди выезда (D049) переставляла их под живой проверкой.

Цена не косметическая, и она разная в двух местах:

* **Перечень для модели и ручные кнопки.** Аудитору предлагается пункт или
  класс, которых в его издании нет, — движок запись не примет, и на точке это
  выглядит поломкой на ровном месте. Обратный случай тише и хуже: снятый
  переизданием пункт исчезает из перечня, и модель уверенно предлагает соседний
  (`docs/forge/research/recognize-probe.md`).
* **Карта слов.** Она входит в отпечаток издания с 04.09.2026 (D063/D064) — и
  не для порядка: по ней быстрый путь показывает готовый пункт, а такая запись
  становится находкой в отчёте партнёру без отдельного подтверждения. Карта,
  прочитанная из действующего каталога, означает запись по правилам, которых в
  издании проверки нет.

Проверяется опытом, а не чтением кода: в каждом тесте проверка заводится,
методика под ней переиздаётся правкой той же копии, и дальше спрашивается
разбор. Тем же приёмом живёт `tests/test_bot_edition_pinned.py`.

Формулировок методики здесь нет (D073): методика синтетическая (T141), а
«переиздание» — правка её копии выдуманными строками.
"""

