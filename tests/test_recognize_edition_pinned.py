#: Чат проверки. Число, а не `NO_CHAT`: разница между ними и есть предмет теста.
CHAT_ID = 4242

#: Название зоны, которого в методике заведомо нет: им переиздание подменяет старое.
НОВОЕ_ИМЯ = "Зона нового издания"

#: Класс, которого у пункта не было: им переиздание подменяет прежний набор.
ЧУЖОЙ_КЛАСС = "D3"

#: Строка карты слов, покрываемая словами `СЛОВА` целиком, и её пункт с зоной.
#: Взяты из синтетической карты, а не выдуманы: покрытие строки целиком —
#: условие быстрого пути, и придуманная строка его бы не выполнила.
СТРОКА_КАРТЫ = "Мебель участка"
СЛОВА = "Мебель участка: крошки на столах"
ПУНКТ_КАРТЫ = "CLN06"
ЗОНА_КАРТЫ = "dining"


@pytest.fixture
def методика(data_copy: Path, tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> Path:
    """Своя копия методики: тест её переиздаёт, общий каталог не трогает."""
    monkeypatch.setenv("AUDIT_DATA_DIR", str(data_copy))
    monkeypatch.setenv("STATE_DIR", str(tmp_path / "state"))
    monkeypatch.chdir(tmp_path)
    return data_copy


def начать() -> None:
    """Завести проверку: на старте с методики снимается снимок издания (T169)."""
    domain.start_inspection(CHAT_ID, "Тестовая", "planned", "ru")


def _строки(путь: Path) -> tuple[list[dict[str, str]], list[str]]:
    with путь.open(encoding="utf-8-sig", newline="") as f:
        строки = list(csv.DictReader(f))
    return строки, list(строки[0].keys())


def _записать(путь: Path, строки: list[dict[str, str]], колонки: list[str]) -> None:
    with путь.open("w", encoding="utf-8", newline="") as f:
        писарь = csv.DictWriter(f, fieldnames=колонки)
        писарь.writeheader()
        писарь.writerows(строки)


def пункт_с_классами(chat_id: int | None) -> tuple[str, str, list[str]]:
    """Пункт с зоной и хотя бы двумя классами, ни один из которых не `ЧУЖОЙ_КЛАСС`."""
    for пункт in domain.list_items(chat_id=chat_id):
        зоны = [z for z in пункт.zones if z != "*"]
        if зоны and len(пункт.levels) >= 2 and ЧУЖОЙ_КЛАСС not in пункт.levels:
            return пункт.code, зоны[0], list(пункт.levels)
    raise AssertionError("в методике не нашлось пункта с зоной и двумя классами")


def переиздать_зону(data_dir: Path, код: str) -> str:
    """Переиздание, переименовавшее зону на всех языках. Возвращает прежнее имя."""
    путь = data_dir / "zones.csv"
    строки, колонки = _строки(путь)
    зона = next(с for с in строки if с["code"] == код)
    прежнее = зона["name_ru"]
    for колонка in колонки:
        if колонка.startswith("name_"):
            зона[колонка] = f"{НОВОЕ_ИМЯ} {колонка}"
    _записать(путь, строки, колонки)
    return прежнее


def переиздать_классы(data_dir: Path, код: str) -> None:
    """Переиздание, оставившее пункту единственный и другой класс."""
    путь = data_dir / "checklist.csv"
    строки, колонки = _строки(путь)
    next(с for с in строки if с["id"] == код)["levels"] = ЧУЖОЙ_КЛАСС
    _записать(путь, строки, колонки)


def снять_пункт(data_dir: Path, код: str) -> None:
    """Переиздание, снявшее пункт вовсе."""
    путь = data_dir / "checklist.csv"
    строки, колонки = _строки(путь)
    _записать(путь, [с for с in строки if с["id"] != код], колонки)


def снять_строку_карты(data_dir: Path, фраза: str) -> None:
    """Переиздание, убравшее строку из карты слов (D063: карта — часть издания)."""
    путь = data_dir / CUES_FILE
    строки = путь.read_text(encoding="utf-8").splitlines(keepends=True)
    осталось = [с for с in строки if not с.lstrip().startswith(f"| {фраза} |")]
    assert len(осталось) < len(строки), f"строки «{фраза}» в карте не было — сценарий теста не тот"
    путь.write_text("".join(осталось), encoding="utf-8")


def дописать_слова_колонок(data_dir: Path, заголовок: str, слово: str) -> None:
    """Переиздание, добавившее в карту раздел слов колонок (T143, D077).

    Заголовок раздела берётся из правил языка, а не пишется здесь строкой: он
    объявлен в `language_rules.json` (T192), и своя копия разошлась бы с ним
    молча — раздел перестал бы читаться, а тест это назвал бы «издание держит».
    """
    путь = data_dir / CUES_FILE
    путь.write_text(
        путь.read_text(encoding="utf-8")
        + f"\n{COLUMN_WORDS_HEADINGS[0]}\n\n| Колонка | Слова |\n|---|---|\n"
        + f"| {заголовок} | {слово} |\n",
        encoding="utf-8",
    )


