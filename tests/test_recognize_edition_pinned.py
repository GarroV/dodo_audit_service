# --- Разбор целиком: то, что реально уходит в модель --------------------------


def test_запрос_к_модели_собран_по_изданию_проверки(
    методика: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    """Сквозной случай: `classify` зовут так, как зовёт бот, и смотрят на запрос.

    Модель подменяется на уровне `classify.ask_model` — сети здесь нет. Проверяется
    ровно то, что до неё доехало: перечисление схемы, текст пунктов и названия
    зон обязаны быть из издания проверки, а не из переизданного каталога.
    """
    начать()
    код, зона, _ = пункт_с_классами(CHAT_ID)
    вопрос = domain.get_item(код, chat_id=CHAT_ID).question("ru")
    прежнее_имя_зоны = переиздать_зону(методика, зона)
    снять_пункт(методика, код)

    записано: dict[str, Any] = {}

    def подменённая(**kwargs: Any) -> ModelAnswer:
        записано.update(kwargs)
        return ModelAnswer(payload={"records": [], "question": ""}, usage={})

    monkeypatch.setattr(classify_module, "ask_model", подменённая)

    classify("крошки на столах", zone_hint=зона, chat_id=CHAT_ID)

    picks = записано["schema"]["properties"]["records"]["items"]["properties"]["item"]["enum"]
    assert any(p.startswith(f"{код}:") for p in picks), (
        "в перечисление схемы ушла действующая методика: снятый пункт исчез"
    )
    assert вопрос in записано["question"], "текст пункта взят из действующей методики"
    assert прежнее_имя_зоны in записано["question"], "названия зон взяты из действующей методики"
    assert НОВОЕ_ИМЯ not in записано["question"], "в запрос попало переиздание"


def test_проверки_нет_читается_действующая_методика(методика: Path) -> None:
    """`NO_CHAT` — законный ответ «проверки нет», а не забытый параметр.

    Так справочники читают замеры по выгрузкам `examples/` и команды методики:
    живой проверки там не существует вовсе, и действующий каталог — правильный
    ответ. Ради этой разницы у `chat_id` и нет умолчания.
    """
    код, зона, _ = пункт_с_классами(NO_CHAT)

    assert код in shortlist("", зона, chat_id=NO_CHAT).codes
    снять_пункт(методика, код)
    assert код not in shortlist("", зона, chat_id=NO_CHAT).codes
