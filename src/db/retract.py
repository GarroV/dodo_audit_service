"""T210, T233: снятие сданной проверки из истории.

Неверный отчёт не правится — заводится новый, а старый снимается (D086), и
снимается ПОМЕТКОЙ, а не удалением строки (D089). Строка истории остаётся:
видно, что проверка была и почему её больше нет, — а по пустому месту не видно
ничего. Пометка к тому же обратима, удалённая строка нет.

**Причина снятия обязательна.** Не потому, что так аккуратнее, а потому что
снятая проверка — это документ, отозванный у партнёра: без причины отзыв
неотличим от подчистки истории. Обязательность держат ограничения схемы
(`inspections_retraction_has_reason`), здесь же она проверяется первой, чтобы
отказ назвал, чего не хватает, а не пришёл текстом нарушенного ограничения.

**Снимает администратор, а не приложение.** Право видеть и снимать живёт в
базе: с миграции `0010` есть вторая роль, `dodo_audit_admin`, и обычной роли
приложения снятая проверка не видна вовсе. Поэтому здесь своё подключение
(`DATABASE_RETRACTION_URL`), а не то, которым ходит бот: разграничение обязано
держаться политикой, а не тем, что этот модуль никто не позовёт из бота.

**Кадры снятой проверки убираются из хранилища** (D089). Объекты уезжают, а
строки кадров остаются с отметкой `purged_at` — по той же причине, по какой
остаётся строка проверки. Уборка идёт по одному кадру за раз и своей
транзакцией: обрыв на середине не откатывает уже убранное, а повторный вызов
доделывает остаток.
"""

from __future__ import annotations

import re
from dataclasses import dataclass
from typing import Any

import psycopg

from .config import load_retraction_settings
from .errors import RetractionError, StorageError
from .queries import _require_inspection_id, _require_tenant
from .storage import PhotoStorage, S3PhotoStorage

#: Ссылка на объект в хранилище так, как её записала выгрузка (`storage.put`).
#: Разбирается, а не собирается заново из идентификаторов: убирать надо ровно
#: тот объект, что записан, — пересчитанный по сегодняшнему правилу ключ молча
#: разошёлся бы с кадром, положенным по вчерашнему, и «убрано» стало бы ложью.
_STORAGE_URI = re.compile(r"^s3://(?P<bucket>[^/]+)/(?P<key>.+)$")

_SELECT_INSPECTION_SQL = """
select status, retracted_at, retraction_reason
from inspections
where id = %(id)s and tenant_code = %(tenant)s
"""

#: Кто сослался на эту проверку как на исходную. Предел стоит не ради
#: скорости, а ради текста отказа: перечислять сотню идентификаторов человеку
#: незачем, а факт «ссылаются» от одной строки не меняется.
_SELECT_REFERRING_SQL = """
select id from inspections where repeat_of_id = %(id)s order by inspection_date, id limit 5
"""

#: Снятие. Условия в `where` не украшение: снять можно только запечатанную и
#: только ещё не снятую проверку, и число затронутых строк ниже проверяется, а
#: не считается заведомо единицей (конституция: у операции с наблюдаемым
#: результатом проверяется результат, а не отсутствие исключения).
_RETRACT_SQL = """
update inspections
set retracted_at = now(), retraction_reason = %(reason)s
where id = %(id)s and status = 'finalized' and retracted_at is null
"""

_SELECT_RETRACTED_AT_SQL = "select retracted_at from inspections where id = %s"

#: Кадры, которые ещё лежат в хранилище. Невыгруженный кадр (`storage_path is
#: null`) сюда не попадает: убирать нечего, и отметка «убран» на нём была бы
#: неправдой.
_SELECT_STORED_PHOTOS_SQL = """
select id, storage_path
from photos
where inspection_id = %s and storage_path is not null and purged_at is null
order by created_at, id
"""

_MARK_PURGED_SQL = "update photos set purged_at = now() where id = %s"


@dataclass(frozen=True)
class Retraction:
    """Чем закончилось снятие проверки.

    `reason` — причина, ЗАПИСАННАЯ в истории, а не переданная вызовом. Разница
    видна на повторе: у снятой проверки причина уже записана, и второй вызов
    её не переписывает — иначе снятие превратилось бы в способ править
    основание задним числом.
    """

    inspection_id: str
    reason: str
    retracted_at: str
    #: Сколько кадров убрано из хранилища ЭТИМ вызовом. Ноль означает и «кадров
    #: не было», и «их убрал предыдущий вызов»: оба исхода одинаково хороши,
    #: и различать их нечем — отметка `purged_at` у кадра одна.
    photos_purged: int


def _require_reason(reason: str) -> str:
    """Непустая причина снятия — или явный отказ (D089).

    Пустая причина не пройдёт и ограничение схемы, но тогда вызывающий увидел
    бы имя нарушенного `check`, а не то, чего не хватает. Обрезаются только
    внешние пробелы: причину пишет человек, и «  правил ошибку  » — та же
    причина, а строка из одних пробелов — не причина вовсе.
    """
    записанное = (reason or "").strip()
    if not записанное:
        raise RetractionError(
            "Не названа причина снятия проверки. Причина — обязательное поле (D089): "
            "снятая проверка остаётся в истории пометкой, и без причины эта пометка "
            "неотличима от подчистки истории"
        )
    return записанное


def _refuse_if_referenced(cur: psycopg.Cursor[Any], inspection_id: str) -> None:
    """Проверку, на которую уже сослались как на исходную, снимать нельзя.

    Связь повторной проверки с исходной (`inspections.repeat_of_id`) заложена
    схемой с самого начала. Сняв исходную, мы оставили бы повторную ссылаться
    на документ, которого в истории больше нет: у неё пропало бы основание, и
    заметить это было бы негде — внешний ключ цел, потому что строка на месте.

    Отказ, а не тихое снятие с обрывом связи: снять всё равно можно, но сперва
    разобравшись с тем, что сослалось, — и решает это человек, а не эта
    функция.
    """
    cur.execute(_SELECT_REFERRING_SQL, {"id": inspection_id})
    ссылающиеся = [str(строка[0]) for строка in cur.fetchall()]
    if ссылающиеся:
        raise RetractionError(
            f"Проверку {inspection_id} снять нельзя: на неё уже сослались как на "
            f"исходную — {', '.join(ссылающиеся)}. Снятая проверка осталась бы в "
            f"истории, но перестала бы быть видна, и у сославшейся пропало бы "
            f"основание. Сперва разобраться со ссылающимися"
        )


def _mark_retracted(
    conn: psycopg.Connection[Any], inspection_id: str, *, tenant: str, reason: str
) -> tuple[str, str]:
    """Поставить пометку и вернуть записанную причину и время снятия.

    Повторяемо: у уже снятой проверки пометка не переписывается — возвращается
    записанная. Повторный вызов нужен не для красоты: снятие и уборка кадров
    идут разными транзакциями, и после обрыва между ними доделать уборку можно
    только тем же вызовом.
    """
    with conn.cursor() as cur:
        cur.execute(_SELECT_INSPECTION_SQL, {"id": inspection_id, "tenant": tenant})
        строка = cur.fetchone()
        if строка is None:
            # «Нет такой проверки» и «есть, но не у этого арендатора» — один и
            # тот же ответ намеренно, как и в чтении: второе подтверждало бы
            # существование чужого документа тому, кто перебирает
            # идентификаторы.
            raise RetractionError(
                f"Проверки {inspection_id} у арендатора {tenant} нет — снимать нечего"
            )
        статус, снята, причина = строка
        if снята is not None:
            return str(причина), снята.isoformat()
        if статус != "finalized":
            raise RetractionError(
                f"Проверка {inspection_id} не запечатана (статус «{статус}») — снимать "
                f"можно только сданную проверку"
            )

        _refuse_if_referenced(cur, inspection_id)

        cur.execute(_RETRACT_SQL, {"id": inspection_id, "reason": reason})
        if cur.rowcount != 1:
            # Ноль строк тут — это не «уже снята» (это разобрано выше), а либо
            # гонка, либо отказ политики: построчный запрет молчалив, он не
            # падает, а просто не видит строки для записи.
            raise RetractionError(
                f"Проверку {inspection_id} снять не удалось: обновлено строк — "
                f"{cur.rowcount}, ожидалась одна. Так выглядит и отказ построчной "
                f"политики: подключение обязано идти под ролью администратора "
                f"истории, иначе снятая строка для записи просто не видна"
            )
        cur.execute(_SELECT_RETRACTED_AT_SQL, (inspection_id,))
        отметка = cur.fetchone()
        if отметка is None or отметка[0] is None:
            raise RetractionError(
                f"Проверка {inspection_id} помечена снятой, но отметка времени не "
                f"прочиталась — целостность транзакции нарушена"
            )
    conn.commit()
    return reason, отметка[0].isoformat()


def _object_key(storage_path: str, *, photo_id: str) -> str:
    """Ключ объекта из записанной ссылки. Не разобралась — отказ, а не догадка.

    Убирать по догадке нельзя в обе стороны: пересчитанный ключ либо не найдёт
    ничего (и «убрано» окажется ложью), либо найдёт чужой объект. Поэтому
    ссылка, не похожая на то, что пишет выгрузка, останавливает уборку и
    называет кадр.
    """
    разбор = _STORAGE_URI.match(storage_path)
    if разбор is None:
        raise RetractionError(
            f"Ссылка кадра {photo_id} записана не в том виде, в каком её пишет "
            f"выгрузка («{storage_path}» вместо «s3://корзина/ключ»). Убирать по "
            f"догадке нельзя: пересчитанный ключ либо не найдёт ничего, либо "
            f"найдёт чужой объект"
        )
    return разбор.group("key")


def _purge_photos(
    conn: psycopg.Connection[Any], inspection_id: str, *, storage: PhotoStorage | None
) -> int:
    """Убрать кадры снятой проверки из хранилища. Вернуть, сколько убрано этим вызовом.

    По одному кадру за раз и своей транзакцией — тем же приёмом и по той же
    причине, что выгрузка (`upload_photos`): обрыв на середине не откатывает
    уже убранное, а повторный вызов доделывает остаток.

    Доступ к хранилищу спрашивается ТОЛЬКО когда есть что убирать. Иначе
    снятие проверки без кадров — а на стенде без хранилища это каждая
    проверка — упиралось бы в незаполненные `S3_*` и не состоялось бы вовсе,
    хотя убирать нечего и хранилище к делу не относится.
    """
    with conn.cursor() as cur:
        cur.execute(_SELECT_STORED_PHOTOS_SQL, (inspection_id,))
        кадры = cur.fetchall()
    if not кадры:
        return 0
    склад = storage if storage is not None else _default_storage()

    убрано = 0
    for photo_id, storage_path in кадры:
        ключ = _object_key(str(storage_path), photo_id=str(photo_id))
        try:
            склад.delete(ключ)
        except StorageError as exc:
            # Наружу у снятия один тип отказа. Ловится именно `StorageError`, а
            # не `Exception`: широкий перехват подменял бы собой и ошибку в
            # коде — настоящая поломка выглядела бы отказом хранилища и молча
            # уходила в «повторим позже».
            raise RetractionError(
                f"Хранилище не убрало кадр проверки {inspection_id} "
                f"({type(exc).__name__}): {exc} Пометка снятия уже записана, убранные "
                f"до отказа кадры остались убранными — повторный вызов доделает остаток"
            ) from exc
        with conn.cursor() as cur:
            cur.execute(_MARK_PURGED_SQL, (photo_id,))
            if cur.rowcount != 1:
                raise RetractionError(
                    f"Кадр {photo_id} убран из хранилища, но отметка об этом в базу не "
                    f"легла: обновлено строк — {cur.rowcount}, ожидалась одна. Без "
                    f"отметки повторный вызов пошёл бы убирать его снова"
                )
        conn.commit()
        убрано += 1
    return убрано


def retract_inspection(
    inspection_id: str,
    *,
    tenant: str,
    reason: str,
    storage: PhotoStorage | None = None,
) -> Retraction:
    """Снять сданную проверку из истории и убрать её кадры из хранилища.

    Снятие — пометка, а не удаление (D089): строка остаётся в истории вместе с
    причиной, но обычной роли не видна. Видит её только администратор истории,
    и он же её ставит — подключение берётся из `DATABASE_RETRACTION_URL`, а не
    из `DATABASE_URL`, потому что право видеть снятое живёт в базе, а не здесь.

    Повторяемо: второй вызов на уже снятой проверке не переписывает ни причину,
    ни время снятия и доделывает уборку кадров, если её оборвало.

    Отказывает — `RetractionError` — когда причина не названа (обязательное
    поле, D089), проверки у этого арендатора нет, она не запечатана или на неё
    уже сослались как на исходную.

    `storage` подменяется только проверками; в работе драйвер собирается из
    окружения (`S3_*`), как и у выгрузки.
    """
    ident = _require_inspection_id(inspection_id)
    tenant_code = _require_tenant(tenant)
    записанная_причина = _require_reason(reason)
    settings = load_retraction_settings()

    try:
        with psycopg.connect(settings.dsn) as conn:
            причина, снята = _mark_retracted(
                conn, ident, tenant=tenant_code, reason=записанная_причина
            )
            # Уборка идёт ПОСЛЕ пометки намеренно: снятие не должно упираться
            # в хранилище. Пометка — то, ради чего вызов сделан; уборка кадров
            # доделывается повторным вызовом, а неснятая проверка так и
            # осталась бы в истории партнёра.
            убрано = _purge_photos(conn, ident, storage=storage)
    except RetractionError:
        raise
    except psycopg.Error as exc:
        raise RetractionError(
            f"Снятие проверки {ident} не удалось ({type(exc).__name__}): {exc} "
            f"Пометка ставится одной транзакцией — наполовину снятой проверка не "
            f"остаётся, повторить можно тем же вызовом"
        ) from exc

    return Retraction(inspection_id=ident, reason=причина, retracted_at=снята, photos_purged=убрано)


def _default_storage() -> PhotoStorage:
    """Драйвер хранилища из окружения. Отдельной функцией — ради подмены в проверках."""
    from .config import load_storage_settings

    return S3PhotoStorage(load_storage_settings())
