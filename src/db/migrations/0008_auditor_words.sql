-- 0008_auditor_words.sql
--
-- T185: сырые слова аудитора сохраняются рядом с записью.
--
-- Бот с T183 держит весь материал, каким он пришёл, — подпись к кадру,
-- отдельное сообщение, расшифровку голоса (`domain.models.Finding.words`).
-- Места под него в базе не было, и слив его терял целиком. Тот же случай, что
-- был с `findings.source` (0001) и с предложением модели (0007): колонка
-- заводится ровно тогда, когда домен начинает отдавать значение.
--
-- ЗАЧЕМ ЭТО НУЖНО. На словах стоит инструмент предложений для управляющей
-- компании (T165, `mcp.suggestions`). Сегодня он называет СТРОКУ КАРТЫ СЛОВ,
-- которая привела к неверному пункту, — а владелец просил фразу, которую
-- произнёс аудитор. Без слов инструмент отвечает половиной и говорит об этом
-- прямо в своём описании: «the auditor's raw words are not stored yet».
-- Предложение модели (0007) и итоговая запись у нас есть, сказанного человеком
-- не было нигде — а промах виден только в этой тройке целиком.
--
-- ПОЧЕМУ КОЛОНКА, А НЕ СТРОКА В `translations`. Формулировка и комментарий
-- находки лежат в `translations`, потому что это ФОРМУЛИРОВКИ: их переводят,
-- и добавление языка не должно требовать миграции (D025). Слова аудитора —
-- не формулировка, а показание о моменте: у них ровно один язык — тот, на
-- котором говорили, — и переводить их нельзя, иначе от сигнала о промахе не
-- останется ничего. Положенные в `translations`, они получили бы вместе с
-- местом и повадки соседей: `push_inspection` пишет туда
-- `on conflict do update set text = excluded.text`, то есть речь стала бы
-- перезаписываемой. Язык при этом никуда не девается — он у проверки
-- (`inspections.speech_lang`), и слой чтения отдаёт его полем `lang` рядом со
-- словами.
--
-- ПОЧЕМУ БЕЗ ВТОРОГО ЗАСЛОНА НА ПРАВКУ. Показание пишется один раз и не
-- меняется: правят его ровно тогда, когда промах уже заметили, то есть стирают
-- сигнал в момент его появления. Держит это политика `findings_frozen_with_
-- inspection` из 0004 — запись запечатанной проверки заморожена целиком, и
-- слова замерзают вместе с ней. Свой триггер поверх неё был бы вторым запретом
-- на том же месте: снять один и увидеть красное можно, а из двух неизвестно,
-- какой держит (тот же довод, что в 0004 про права и политику).
--
-- В ОТПЕЧАТОК ПРОВЕРКИ СЛОВА НЕ ВХОДЯТ — как и предложение модели, и по той же
-- причине: отпечаток это содержимое документа, ушедшего партнёру, а сказанное
-- на точке партнёру не предназначено вовсе. Попади слова в отпечаток, проверка,
-- слитая до этой задачи и слитая после, дала бы две строки в истории одной
-- точки. Закреплено тестом, а не обещанием.
--
-- Раннер оборачивает файл в одну транзакцию сам — begin/commit здесь не нужны.

alter table findings add column words text;

comment on column findings.words is
    'Сырые слова аудитора, из которых выросла эта запись: подпись к кадру, '
    'отдельное сообщение, расшифровка голоса — ровно так, как пришли (T183). '
    'Язык — язык речи проверки (inspections.speech_lang), своего у колонки нет. '
    'Текстом записи слова не становятся намеренно: партнёру уходит формулировка '
    'по правилам фиксации, а сказанное на точке ему не предназначено. '
    'NULL — слов не было вовсе (разбор голого кадра) либо запись начата до '
    'T183; отличает эти случаи findings.source. Пишутся один раз и не меняются: '
    'правка запечатанной проверки запрещена политикой из 0004 (T185).';

-- Индекса под выборку промахов здесь нет — по той же причине, что и в 0007:
-- её потребитель (T165) сегодня не знает, каким вопросом пойдёт, а индекс под
-- воображаемый запрос стоит записи на каждом сливе и ничего не ускоряет.
