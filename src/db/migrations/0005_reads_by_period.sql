-- 0005_reads_by_period.sql
--
-- T114: чтение научилось отбирать период и читать находки, и схеме от этого
-- нужны другие индексы, чем от чтения «последних N по дате слива» (0003).
--
-- ПОЧЕМУ ВЕДУЩИМ ПОРЯДКОМ СТАЛА ДАТА ОБХОДА, А НЕ ДАТА СЛИВА. Историю проверок
-- за три года зальют одним заходом программно (D035) — значит, `pushed_at` у
-- всей истории окажется одной датой. После этого «последние сто по дате слива»
-- перестаёт что-либо значить: строки с одинаковым `pushed_at` возвращаются в
-- том порядке, в каком их достанет исполнитель, и ответ «вот последние
-- проверки точки» становится случайной выборкой, ничем себя не выдающей.
-- Спрашивают же всегда про дату ОБХОДА точки: «что было летом», «покажи
-- последние проверки». Поэтому и порядок, и отбор периода идут по
-- `inspection_date`, а `pushed_at` остаётся вторым ключом — на нём разъезжаются
-- проверки одного дня.
--
-- Раннер оборачивает файл в одну транзакцию сам — begin/commit здесь не нужны.

create index inspections_tenant_date_idx
    on inspections (tenant_code, inspection_date desc, pushed_at desc);

comment on index inspections_tenant_date_idx is
    'Проверки одного арендатора за период и в порядке дат обхода, без '
    'сортировки всей таблицы. Ведущая колонка — арендатор: разделение '
    'арендаторов держится схемой (0002), а скорость чтения — этим индексом.';

-- Отдельный индекс под «историю одной точки» — самый частый вопрос к базе
-- (`list_inspections(unit=...)`, `findings_by_unit`). Без него отбор по точке
-- идёт поверх всей истории арендатора: у сети из сотен пиццерий это
-- девяносто девять процентов прочитанного впустую на каждый вопрос.
create index inspections_tenant_unit_date_idx
    on inspections (tenant_code, unit_id, inspection_date desc, pushed_at desc);

comment on index inspections_tenant_unit_date_idx is
    'История одной точки: арендатор, точка, дата обхода. Под него же попадает '
    'чтение находок точки — оно идёт через те же проверки.';

-- Индекс 0003 после этого не обслуживает ни одного запроса: по `pushed_at`
-- больше никто не сортирует и не отбирает (проверено поиском по src/ —
-- единственным потребителем был `list_inspections`). Индекс, которым не
-- пользуются, не бесплатен: он стоит записи на каждом сливе и места на диске.
-- Понадобится вопрос «что залили последним» — вернётся отдельной строкой.
drop index inspections_tenant_pushed_at_idx;
