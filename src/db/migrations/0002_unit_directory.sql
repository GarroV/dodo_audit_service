-- 0002_unit_directory.sql
--
-- T092: справочник точек и карта синонимов. Задача после MVP (D051): в первой
-- версии название пиццерии вводится текстом, и это здесь не меняется. Меняется
-- то, ЧЕМ введённая строка становится: раньше «БГ2» и «Белград 2» заводили две
-- несвязанные точки с двумя историями, теперь синоним приводит к той же точке
-- по её идентификатору.
--
-- Формулировки переводятся и правятся, коды — нет (конституция, принцип 5):
-- поэтому связь идёт через `units.id`, а строка живёт отдельной таблицей
-- синонимов и на связь не влияет.
--
-- Раннер оборачивает файл в одну транзакцию сам — begin/commit здесь не нужны.

alter table units add column code text;

comment on column units.code is
    'Код точки во внешнем источнике управляющей компании, если он есть. '
    'Форма заложена заранее (конституция, принцип 6): без него повторная '
    'загрузка справочника не смогла бы опознать уже заведённые точки иначе '
    'как по названию — то есть ровно по тому, от чего задача и уходит. '
    'NULL для точек, заведённых по факту первой проверки: у них источника нет.';

-- NULL-коды друг другу не мешают: в Postgres NULL в уникальном индексе по
-- умолчанию считаются различными, поэтому точек без кода может быть сколько
-- угодно, а заданный код в пределах арендатора остаётся один.
create unique index units_code_idx on units (tenant_code, code);

-- Составной ключ нужен, чтобы на точку можно было сослаться ВМЕСТЕ с
-- арендатором. Без него ссылка на `units (id)` разрешает строку одного
-- арендатора, указывающую на точку другого, — и разделение арендатора
-- держалось бы только на дисциплине запросов в коде.
alter table units add constraint units_tenant_id_key unique (tenant_code, id);

create table unit_aliases (
    tenant_code text not null,
    alias_normalized text not null,
    unit_id uuid not null,
    alias text not null,
    created_at timestamptz not null default now(),
    primary key (tenant_code, alias_normalized),
    -- Ссылка составная намеренно: синоним арендатора A физически не может
    -- указывать на точку арендатора B. Иначе `resolve_unit(name, tenant="A")`
    -- отдавал бы чужую точку — тихая утечка между арендаторами через карту
    -- синонимов, которую в коде не видно вовсе.
    -- Отдельная ссылка на tenants здесь не нужна: арендатор проверен этой же
    -- ссылкой через саму точку.
    foreign key (tenant_code, unit_id) references units (tenant_code, id) on delete cascade
);

comment on table unit_aliases is
    'Карта синонимов названия точки: «БГ2» → та же точка, что «Белград 2». '
    'Ключ — нормализованное написание (обрезка, схлопнутые пробелы, нижний '
    'регистр), то же правило, что у units.name_normalized: иначе «бг2» и «БГ 2» '
    'считались бы разными синонимами и карта перестала бы работать ровно там, '
    'где она нужна — на быстром вводе с телефона.';
comment on column unit_aliases.alias is
    'Как синоним написан человеком. Для показа в списке; связь идёт по unit_id.';

create index unit_aliases_unit_idx on unit_aliases (unit_id);

-- Та же дыра была и в самой проверке: `inspections.unit_id` ссылался на точку
-- без арендатора, то есть проверка арендатора A могла указывать на точку
-- арендатора B. Живого дефекта из этого не выросло только потому, что слив
-- всегда подставляет один и тот же арендатор в оба поля — но это соглашение в
-- коде, а не свойство схемы. Теперь свойство схемы.
alter table inspections
    add constraint inspections_unit_same_tenant
    foreign key (tenant_code, unit_id) references units (tenant_code, id);

-- Прежняя односоставная ссылка после этого лишняя: она проверяет строго меньше
-- и стоит лишнего похода в индекс на каждой записи.
alter table inspections drop constraint inspections_unit_id_fkey;
