-- потребитель — задача T165 блока mcp, и какой именно вопрос она задаст
-- (порог уверенности? одна точка? весь арендатор за период?), сегодня не
-- известно. Индекс под воображаемый запрос стоит записи на каждом сливе и
-- ничего не ускоряет.
