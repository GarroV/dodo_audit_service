-- 0007_model_suggestion.sql
--
-- T164 (D077): предложение модели сохраняется рядом с итоговой записью.
--
-- Владелец, дословно: «при несостыковках, или если пользователь добавит что-то
-- в духе "ГРЯЗЬ НА ПОЛКЕ В ГОРЯЧЕМ ЦЕХЕ, ЭТО ЧИСТОТА" то мы долполняем наш
-- список терминов». Пополняет список человек — управляющая компания;
-- автоматическое пополнение D077 запрещает прямо, потому что быстрый путь
-- показывает пункт без подтверждения (D064) и неверное слово уехало бы в отчёт
-- партнёру без чьего-либо ведома. Но пополнять нечего, пока промах не сохранён,
-- а сегодня предложение модели не живёт нигде: ни код, ни уверенность, ни то,
-- что аудитор поменял. Эта миграция даёт ему место.
--
-- ПОЧЕМУ КОЛОНКИ РЯДОМ, А НЕ ОТДЕЛЬНАЯ ТАБЛИЦА. Предложение относится ровно к
-- одной записи и живёт ровно столько же: отдельная таблица дала бы связь один
-- к одному, вторую страницу чтения и вторую возможность разъехаться с
-- запечатанной проверкой (0004). Форма повторяет `findings.source`, заложенный
-- в 0001 за задачу до появления значения: домен предложение пока не отдаёт.
--
-- ПОЧЕМУ НЕ ХРАНИТСЯ «ЧТО АУДИТОР ИЗМЕНИЛ». Это сравнение предложенной тройки
-- с итоговой, и обе лежат в этой же строке. Записанное третьей копией, оно
-- разъехалось бы с парой, из которой считается, — и разъехалось бы молча,
-- потому что проверять его было бы не с чем.
--
-- NULL И 'NONE' — РАЗНОЕ. NULL означает «модель не предлагала ничего»: запись
-- заведена вручную или до T164. 'NONE' — код, которым модель говорит «ничего
-- из перечня не подходит» (`recognize.models.NONE_CODE`), то есть её ответ, а
-- не отсутствие ответа. Слитые в одно, они утопили бы друг друга в выборке для
-- управляющей компании: ручных записей на порядок больше.
--
-- Раннер оборачивает файл в одну транзакцию сам — begin/commit здесь не нужны.

alter table findings
    add column suggested_code text,
    add column suggested_level text,
    add column suggested_zone text,
    add column suggested_confidence numeric(4, 3);

comment on column findings.suggested_code is
    'Пункт методики, который предложила модель. NULL — модель не предлагала '
    'ничего (ручная запись или запись до T164); NONE — модель ответила, что '
    'ничего из перечня не подходит. Что аудитор поправил, видно сравнением с '
    'колонкой code — отдельно это не хранится (D077, T164).';
comment on column findings.suggested_level is
    'Класс нарушения, который предложила модель. Сравнивается с level.';
comment on column findings.suggested_zone is
    'Зона, которую предложила модель. Сравнивается с zone. UNKNOWN — модель '
    'ответила, что из слов аудитора места не видно (recognize.models).';
comment on column findings.suggested_confidence is
    'Уверенность модели в своём предложении, доля от 0 до 1. Порог отбора '
    'предложений для управляющей компании ставится по ней, поэтому чужая '
    'шкала (проценты вместо доли) обесценила бы выборку целиком — отсюда '
    'ограничение диапазона в самой схеме.';

-- Ограничение на ДИАПАЗОН, а не на перечень значений. Диапазон — свойство
-- самой величины и живёт здесь по праву; перечень пунктов и зон живёт в
-- методике, и его копия в схеме отказывала бы на сливе, то есть на точке.
alter table findings
    add constraint findings_suggested_confidence_is_a_share
    check (suggested_confidence is null or suggested_confidence between 0 and 1);

