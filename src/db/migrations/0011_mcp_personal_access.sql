-- 0011_mcp_personal_access.sql
--
-- T253, решения D098 и D099: доступ к MCP выпускается ЧЕЛОВЕКУ, а не стороне.
--
-- ЧТО БЫЛО. Токен заводился руками в `.env` записью «арендатор=токен»
-- (`src/mcp/config.py`), принадлежал СТОРОНЕ и открывал всю её историю
-- проверок. Связи «этот человек — этот токен» не существовало нигде, поэтому
-- бот честно не печатал токен вовсе (T209): напечатанный был бы выдан наугад.
-- Отзыв же был правкой файла и перезапуском сервера, то есть отъёмом доступа
-- сразу у всех, кто им пользовался.
--
-- ЧТО ПОЯВЛЯЕТСЯ. Две таблицы: круг людей, которым настройка вообще доступна,
-- и выпущенные токены. Обе устроены ПОМЕТКОЙ, а не удалением строки, — тем же
-- приёмом и по той же причине, что снятие проверки в `0010`: вопрос «у кого
-- сейчас доступ» без следа не проверить, а «кто его выдал и кто отнял» по
-- пустому месту не восстановить вовсе.
--
-- ГЛАВНОЕ СВОЙСТВО: ЗНАЧЕНИЯ ТОКЕНА ЗДЕСЬ НЕТ. Хранится отпечаток, и это не
-- договорённость в коде, а ограничение схемы: колонка принимает только 64
-- знака шестнадцатеричной записи, то есть SHA-256. Сырой токен
-- (`secrets.token_urlsafe(32)` — 43 знака, среди них `-` и `_`) в неё не
-- запишется физически, и попытка сохранить значение вместо отпечатка упадёт
-- отказом на первой же записи, а не проживёт до чужого взгляда в базу.
--
-- Раннер оборачивает файл в одну транзакцию сам — begin/commit здесь не нужны.

-- --- круг: кому настройка доступна и кто кого в него привёл ------------------
--
-- Круг маленький и плоский намеренно (решение владельца об объёме): у всех в
-- нём одинаковые возможности — выпустить себе токен, привести следующего,
-- отозвать доступ поимённо. Системы прав здесь нет и не заводится: роль,
-- уровень, набор разрешений — это отдельная задача, а не то, что тихо
-- появляется вместе с первой таблицей.
--
-- `telegram_id` первичным ключом, а не суррогат: человек здесь и есть ключ,
-- дважды один и тот же в круг не приводится. Повторный привод — это снятие
-- пометки отзыва на существующей строке, и `on conflict` ниже по коду
-- (`src/db/mcp_access.py`) опирается именно на этот ключ.

create table mcp_admins (
    telegram_id bigint primary key,
    -- Кто привёл. NULL ровно у одного человека — у основателя круга, он
    -- приходит из настройки стенда (`BOT_MCP_OWNER_ID`), а не из чужой руки.
    -- Поэтому не `not null`: «никто не приводил» — законное состояние, и
    -- подставить сюда его же идентификатор значило бы записать в след, что
    -- он привёл себя сам, — а это неправда, его назвали настройкой.
    added_by bigint,
    added_at timestamptz not null default now(),
    -- Отзыв — пометка, как и снятие проверки в `0010`. Строка остаётся: по
    -- ней видно, что доступ был, кто его дал и кто отнял.
    revoked_at timestamptz,
    revoked_by bigint
);

-- Обе половины отзыва называются вместе: «отозвано неизвестно кем» — это
-- ровно тот след, ради которого таблица и заведена, и он не должен
-- получаться сам собой из наполовину заполненной строки.
alter table mcp_admins add constraint mcp_admins_revocation_is_named
    check ((revoked_at is null) = (revoked_by is null));

comment on table mcp_admins is
    'Круг людей, которым доступна настройка подключения к MCP (T253, D099). '
    'Основатель круга приходит из настройки стенда, остальных приводят друг '
    'друга — у всех в круге возможности одинаковые. Отозванный не удаляется, '
    'а помечается: иначе «кто кого привёл и кто отнял» не восстановить.';
comment on column mcp_admins.added_by is
    'Кто привёл этого человека в круг. NULL только у основателя: его назвала '
    'настройка стенда, а не чужая рука.';
comment on column mcp_admins.revoked_at is
    'Когда доступ отозван. NULL — человек в круге. Отзыв снимает и круг, и '
    'живые токены разом: иначе отозванный просто выпустил бы себе новый.';

-- --- токены: отпечаток, а не значение ---------------------------------------

create table mcp_tokens (
    id uuid primary key default gen_random_uuid(),
    -- Чей токен. Внешнего ключа на `mcp_admins` нет намеренно: выпущенный
    -- токен переживает выход человека из круга как ЗАПИСЬ (кому и когда
    -- выдавали), а действовать перестаёт по своей пометке отзыва. Каскад
    -- отсюда стёр бы ровно тот след, ради которого всё и заводится.
    telegram_id bigint not null,
    -- Чью историю открывает. Тот же вопрос, на который отвечает запись
    -- «арендатор=токен» в `.env`, — и отвечает на него по-прежнему
    -- развёртывание (`BOT_MCP_TENANT`), а не человек в чате.
    tenant_code text not null references tenants (code),
    -- ОТПЕЧАТОК, а не токен. Проверка формы — заслон, а не украшение:
    -- шестнадцатеричные 64 знака даёт только SHA-256, и сырой токен сюда не
    -- пройдёт. Ошибка «записали значение» становится отказом записи вместо
    -- секрета, лежащего в базе в открытую.
    fingerprint text not null unique
        check (fingerprint ~ '^[0-9a-f]{64}$'),
    issued_at timestamptz not null default now(),
    revoked_at timestamptz,
    revoked_by bigint
);

alter table mcp_tokens add constraint mcp_tokens_revocation_is_named
    check ((revoked_at is null) = (revoked_by is null));

-- У человека живым может быть РОВНО ОДИН токен, и держит это схема, а не
-- порядок вызовов в коде. Повторный выпуск обязан убивать прежний (иначе
-- «показан один раз» превращается в «накопили десяток и не знаем, чей какой»),
-- а забытый в коде отзыв прежнего — это ровно та ошибка, которую индекс
-- превращает в отказ вместо тихо накопившихся живых токенов.
create unique index mcp_tokens_one_live_per_person_idx
    on mcp_tokens (telegram_id) where revoked_at is null;

-- Отдельного индекса под сверку предъявленного токена здесь НЕТ намеренно,
-- хотя сервер MCP спрашивает её на каждый запрос. Уникальность `fingerprint`
-- выше уже дала индекс, и запрос «отпечаток = X и не отозван» разрешается им
-- в одно обращение: отпечаток уникален глобально, то есть строка находится
-- ровно одна, а `revoked_at is null` проверяется на ней же. Частичный индекс
-- по тому же столбцу не сократил бы ни одного обращения — он лишь добавил бы
-- работы каждой записи и второй индекс на одну колонку, над которым следующий
-- читатель ломал бы голову, чем они отличаются.

comment on table mcp_tokens is
    'Личные токены доступа к MCP (T253, D098). Хранится ОТПЕЧАТОК SHA-256, '
    'значение не хранится нигде и показывается человеку один раз при выпуске. '
    'Отозванная строка остаётся: кому и когда выдавали — часть следа.';
comment on column mcp_tokens.fingerprint is
    'SHA-256 токена шестнадцатеричной записью. Форма проверяется ограничением: '
    'сырой токен (43 знака, есть - и _) в колонку не запишется, поэтому '
    '«сохранили значение вместо отпечатка» — отказ записи, а не тихая утечка.';
comment on column mcp_tokens.tenant_code is
    'Чью историю проверок открывает токен. Приходит из настройки стенда, а не '
    'из разговора: арендатор, названный тем, кто просит доступ, — это не '
    'граница арендаторов, а её отсутствие.';

-- --- права и политики --------------------------------------------------------
--
-- Продукт ходит в базу под `dodo_audit_app` — под ней и бот (выпускает,
-- приводит, отзывает), и сервер MCP (сверяет отпечаток). Права те же, что у
-- остальных рабочих таблиц из `0004`, кроме DELETE: удалять здесь нечего —
-- обе таблицы живут пометками, и выданный на удаление грант противоречил бы
-- самой причине, по которой они так устроены.

grant select, insert on mcp_admins to dodo_audit_app;
grant select, insert on mcp_tokens to dodo_audit_app;

-- А ПРАВИТЬ МОЖНО РОВНО ПЕРЕЧИСЛЕННЫЕ КОЛОНКИ, и это здесь главный заслон.
-- Тот же приём и та же причина, что у администратора истории в `0010`:
-- политика такого сказать не умеет вовсе — `with check` видит только новую
-- строку и не видит старой, поэтому «менять разрешено лишь пометку отзыва» в
-- ней не выражается. Привилегия на КОЛОНКИ выражает это дословно и
-- проверяется одним взглядом в `\dp`.
--
-- Что этим закрыто по существу: подмена `fingerprint` у живой строки — это
-- выдача доступа под чужим именем, причём след остался бы нетронутым. Права
-- на эту колонку нет ни у кого, поэтому такая правка невозможна, а не
-- «не предусмотрена кодом». Ровно так же защищены владелец токена, арендатор
-- и время выпуска.
grant update (revoked_at, revoked_by) on mcp_tokens to dodo_audit_app;

-- У круга правится больше: возвращение отозванного — это снятие пометки на
-- существующей строке (`telegram_id` первичный ключ, второй строки на того же
-- человека не бывает), и вместе с ней обновляется, кто и когда привёл. А вот
-- сам `telegram_id` не правится: смена его на живой строке означала бы, что
-- приведённым в круг оказался не тот, кого назвали, — и запись о приводе
-- досталась бы другому человеку.
grant update (added_by, added_at, revoked_at, revoked_by) on mcp_admins to dodo_audit_app;

-- `force` — по той же причине, что в `0004`: владелец таблицы иначе не
-- подчиняется собственным политикам, и как только владельцем станет обычная
-- роль, только `force` удержит её от правки чужой строки. Разрешающая
-- политика на роль приложения нужна отдельно: с включённым RLS и без единой
-- политики не проходит ничего, включая обычный выпуск.

alter table mcp_admins enable row level security;
alter table mcp_admins force row level security;
create policy mcp_admins_app_access on mcp_admins
    for all to dodo_audit_app using (true) with check (true);

alter table mcp_tokens enable row level security;
alter table mcp_tokens force row level security;
create policy mcp_tokens_app_access on mcp_tokens
    for all to dodo_audit_app using (true) with check (true);

-- Отзыв токена односторонен — так же, как печать проверки и её снятие в
-- `0010`. Сужающая политика (`as restrictive`, без `to <роль>` — по тем же
-- двум причинам, что там же: разрешающие политики объединяются через ИЛИ, а
-- запрет обязан действовать и на роль, о которой мы сегодня не подумали)
-- пропускает ровно один переход: живая строка → отозванная.
--
-- `using (revoked_at is null)` не пускает правку уже отозванной строки, то
-- есть воскресить токен нечем; `with check (revoked_at is not null)` не даёт
-- правке оставить строку живой. Ограничение `mcp_admins_revocation_is_named`
-- выше добирает второе поле: отозвать, не назвавшись, нельзя.
--
-- Подмену отпечатка, владельца, арендатора и времени выпуска эта политика не
-- обсуждает вовсе — их закрывает привилегия на колонки выше. Разделение
-- намеренное: политика говорит про ПЕРЕХОД, привилегия — про ПОЛЯ, и каждая
-- вещь сказана одним способом в одном месте.
create policy mcp_tokens_are_revoked_not_rewritten on mcp_tokens
    as restrictive for update
    using (revoked_at is null)
    with check (revoked_at is not null);
