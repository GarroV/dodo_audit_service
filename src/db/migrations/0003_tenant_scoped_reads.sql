-- 0003_tenant_scoped_reads.sql
--
-- T110: чтение проверок стало обязательно арендаторским (`list_inspections`
-- больше не отдаёт чужие проверки и не отдаёт всё разом). Схеме от этого нужна
-- одна вещь — индекс, по которому «последние N проверок арендатора» берутся
-- готовым порядком, а не полным проходом с сортировкой всей таблицы ради
-- первой сотни строк. Иначе предел выдачи экономит трафик и не экономит базу,
-- а читать через этот слой будет MCP-сервер (T095), то есть часто.
--
-- Порядок колонок в индексе — тот же, что в запросе: сперва равенство по
-- арендатору, потом убывающее время слива. `desc` здесь не украшение: с
-- возрастающим индексом планировщику пришлось бы читать его задом наперёд или
-- досортировывать, и на `limit` это перестало бы быть бесплатным.
--
-- Раннер оборачивает файл в одну транзакцию сам — begin/commit здесь не нужны.

create index inspections_tenant_pushed_at_idx
    on inspections (tenant_code, pushed_at desc);

comment on index inspections_tenant_pushed_at_idx is
    'Последние проверки одного арендатора без сортировки всей таблицы. '
    'Ведущая колонка — арендатор: разделение арендаторов держится схемой '
    '(миграция 0002), а скорость чтения — этим индексом.';

-- Прежний индекс по одному `tenant_code` после этого лишний: составной
-- начинается с той же колонки и обслуживает всё, что обслуживал он, а лишний
-- индекс стоит записи на каждом сливе и места на диске.
drop index inspections_tenant_idx;
