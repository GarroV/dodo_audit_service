-- 0009_inspection_info.sql
--
-- T200 (#163): информационная часть проверки получает место в базе.
--
-- Семь полей, которые аудитор заполняет в конце обхода (сильные стороны, зоны
-- роста, отзыв о тестовом заказе, дата созвона, срок плана действий и два
-- ответа «да/нет»), не сливались вовсе: ни таблицы, ни колонки. Домен отдаёт
-- их с T158 (`Inspection.info`), движок печатает приложением отчёта с T159 и
-- носит при них кадры с T179 — а слив терял всё это молча.
--
-- ЧЕМ ЭТО КОНЧАЛОСЬ ДЛЯ ПАРТНЁРА. Срок плана действий называет аудитор — это
-- одно из семи полей, и бот печатает в письме именно его ответ
-- (`engine/report.py: plan_due_date`). MCP, пересобирая письмо по записанной
-- проверке, ответа не видел и подставлял запасной расчёт движка: дата обхода
-- плюс `plan_due_days`. В прогоне сверки бот говорил «Просим до 30.09.2026»,
-- MCP — «Просим до 15.09.2026». Партнёр получал от управляющей компании другой
-- срок, чем от аудитора, и обе бумаги подписаны системой как верные.
--
-- ПОЧЕМУ ОТДЕЛЬНАЯ ТАБЛИЦА, А НЕ КОЛОНКИ В `inspections`. Состав
-- информационной части задаёт управляющая компания своим чек-листом, а не наш
-- код (`src/bot/info.py`): нет пункта в методике — нет и вопроса аудитору.
-- Колонка на поле означала бы миграцию на каждую правку чужой методики, то
-- есть перенос её состава в схему. Строка на поле связывает запись КОДОМ
-- пункта — тем же способом, каким связаны все сущности продукта.
--
-- ПОЧЕМУ НЕ `translations`. Формулировка и комментарий находки лежат там,
-- потому что это формулировки: их переводят, и добавление языка не должно
-- требовать миграции (D025). Ответ аудитора не переводит никто — движок
-- печатает его как записан на любом языке отчёта, а письмо читает им срок.
-- Хуже того, языка у информационной части нет ОДНОГО: свободный текст записан
-- на языке речи аудитора, «да/нет» — на языке отчёта (`bot/routers/info.py`:
-- «строку читает партнёр»), а дата не на языке вовсе. Строка в `translations`
-- потребовала бы выбрать один язык на все три и подписать им заведомо чужое, а
-- чтение по языку письма молча теряло бы срок ровно там, где письмо собирают
-- на другом языке, — то есть повторило бы дефект, ради которого эта миграция и
-- заведена. Повадки соседей тоже не подходят: слив пишет в `translations`
-- `on conflict do update set text = excluded.text`, то есть ответ стал бы
-- перезаписываемым.
--
-- ПОЧЕМУ ЕСТЬ `position`. Движок печатает поля в том порядке, в каком их
-- записали, и это порядок разделов документа партнёру. Сегодня он совпал бы с
-- порядком кодов, но совпадение — не правило: порядок вопросов задаёт бот
-- (`src/bot/info.py: FIELDS`), а состав — чужая методика. Чтение «order by
-- code» переставило бы разделы отчёта при первой же правке порядка, и заметить
-- это можно было бы только сличением двух бумаг.
--
-- В ОТПЕЧАТОК ПРОВЕРКИ ИНФОРМАЦИОННАЯ ЧАСТЬ ВХОДИТ — в отличие от сырых слов
-- аудитора (T185) и предложения модели (T164). Правило там одно и то же:
-- отпечаток это содержимое документа, ушедшего партнёру. Слова и предложение в
-- документе не печатаются, а информационная часть печатается приложением
-- отчёта и читается письмом; две проверки с разными сроками — два разных
-- требования к партнёру, и слитые под одним отпечатком они стали бы одной
-- строкой, а вторая не легла бы в базу вовсе. Рецепт отпечатка при этом
-- сменился, и прежний остаётся объявленным (`src/db/fingerprint.py`,
-- механизм T193): проверка, уже лежащая в базе, обязана найтись, а не лечь
-- второй строкой в историю точки.
--
-- Раннер оборачивает файл в одну транзакцию сам — begin/commit здесь не нужны.

create table inspection_info (
    id uuid primary key default gen_random_uuid(),
    inspection_id uuid not null references inspections (id) on delete cascade,
    position integer not null,
    code text not null,
    text text not null,
    created_at timestamptz not null default now(),
    unique (inspection_id, code),
    unique (inspection_id, position),
    constraint inspection_info_answer_is_not_empty check (btrim(text) <> '')
);

comment on table inspection_info is
    'Информационная часть проверки: ответы аудитора на пункты методики вида '
    'INF* (T200). Не находки и не замеры — на оценку не влияют вовсе, но '
    'печатаются партнёру приложением отчёта, и один из них (срок плана '
    'действий) читает письмо. Строка на поле, а не колонка: состав задаёт '
    'чек-лист управляющей компании, и колонка означала бы миграцию на каждую '
    'его правку.';
comment on column inspection_info.code is
    'Код пункта методики (INF01, INF07, …). Сущности связаны кодами, а не '
    'формулировками: формулировки переводятся и правятся, коды нет.';
comment on column inspection_info.text is
    'Ответ аудитора ДОСЛОВНО, как он попал в проверку: свободный текст на '
    'языке речи, «Да»/«Нет» на языке отчёта, дата в виде ДД.ММ.ГГГГ. Не '
    'переводится никем — движок печатает его как записан на любом языке '
    'отчёта, поэтому в translations ему не место. Пустым не бывает: '
    'пропущенное поле по решению D070 не записывается вовсе и не печатается, '
    'а пустая строка выглядела бы ответом, которого не было.';
comment on column inspection_info.position is
    'Место поля в записанном порядке. Порядок печати в отчёте — записанный, а '
    'не алфавитный по коду: его задаёт бот, а состав части — чужая методика.';

create index inspection_info_inspection_idx on inspection_info (inspection_id);

-- --- кадры информационного поля ----------------------------------------------
--
-- Поле бывает с кадром (T179): движок печатает снимок под текстом своего поля,
-- и это такое же доказательство, как кадр записи. Хранить его негде было —
-- `photos.finding_id` обязателен, а записи у поля нет.
--
-- ПОЧЕМУ ТА ЖЕ ТАБЛИЦА, А НЕ СВОЯ. Кадр ценен не строкой в базе, а тем, что
-- уезжает в хранилище: `telegram_file_id` живёт ровно столько, сколько живёт
-- бот с этим токеном (T094). Выгрузка берёт кадры проверки по
-- `photos.inspection_id` — в этой таблице кадр поля выгружается ею без единой
-- правки, в своей же таблице он остался бы мёртвой ссылкой ровно до тех пор,
-- пока кто-нибудь не вспомнит про вторую выгрузку.
--
-- Владелец у кадра ровно один и он обязателен: `check` ниже не даёт ни кадра
-- без владельца (он не напечатался бы нигде и висел бы в хранилище), ни кадра
-- сразу у записи и у поля (он напечатался бы партнёру дважды).

alter table photos alter column finding_id drop not null;

alter table photos add column info_id uuid references inspection_info (id) on delete cascade;

alter table photos add constraint photos_belong_to_one_owner
    check ((finding_id is not null) <> (info_id is not null));

comment on column photos.finding_id is
    'Запись, к которой приложен кадр. NULL — кадр приложен не к записи, а к '
    'информационному полю (info_id): ровно один из двух владельцев заполнен.';
comment on column photos.info_id is
    'Информационное поле, к которому приложен кадр (T179, T200). Выгрузка в '
    'хранилище идёт общая: она берёт кадры по inspection_id и про владельца '
    'не спрашивает.';

create index photos_info_idx on photos (info_id);

-- --- права и политики --------------------------------------------------------
--
-- Таблица заведена ПОСЛЕ миграции `0004`, поэтому ни прав роли приложения, ни
-- построчных политик на ней нет — их не бывает по умолчанию, а не «наверное,
-- унаследуются». Без этого блока слив под ролью приложения отказал бы на
-- первой же вставке, а запечатанная проверка осталась бы с правимой
-- информационной частью: заморозка держится политикой на КАЖДОЙ таблице
-- документа, а не на одной шапке.
--
-- Полный набор прав выдан намеренно, как и находкам: решает политика. Два
-- запрета друг поверх друга нельзя снять по одному и увидеть красное, то есть
-- проверить, что заслон работает, стало бы нечем.

grant select, insert, update, delete on inspection_info to dodo_audit_app;

alter table inspection_info enable row level security;
alter table inspection_info force row level security;

create policy inspection_info_app_access on inspection_info
    for all to dodo_audit_app using (true) with check (true);

-- Сужающие политики — `as restrictive` и БЕЗ `to <роль>`, по тем же двум
-- причинам, что в `0004`: разрешающие политики объединяются через ИЛИ (и
-- «сужающая» разрешающая не сужает ничего), а запрет обязан действовать и на
-- того, кто придёт к базе потом — клиент партнёра, будущий веб.
--
-- `with check (true)` у правки задан явно: без него PostgreSQL применил бы
-- выражение `using` и к новой строке, и запечатать черновик стало бы нельзя.
-- Заслон стоит на СТАРОЙ строке — тронуть запечатанное нельзя, а слив кладёт
-- информационную часть, пока проверка ещё `draft`.

create policy inspection_info_frozen_with_inspection on inspection_info
    as restrictive for update
    using (not exists (
        select 1 from inspections i
        where i.id = inspection_info.inspection_id and i.status = 'finalized'))
    with check (true);

create policy inspection_info_undeletable_with_inspection on inspection_info
    as restrictive for delete
    using (not exists (
        select 1 from inspections i
        where i.id = inspection_info.inspection_id and i.status = 'finalized'));

create policy inspection_info_not_added_to_finalized on inspection_info
    as restrictive for insert
    with check (not exists (
        select 1 from inspections i
        where i.id = inspection_info.inspection_id and i.status = 'finalized'));
