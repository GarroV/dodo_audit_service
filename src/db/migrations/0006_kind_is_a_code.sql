-- 0006_kind_is_a_code.sql
--
-- T178: колонка `inspections.kind` хранит КОД вида проверки, а не слово, — и
-- до этой миграции схема об этом молчала. Молчание здесь не мелочь: рядом
-- стоит `units.name`, где лежит человеческое название, и `kind text not null`
-- читается точно так же. Читающий схему (или заливающий историю за прошлые
-- годы программно, D035) кладёт туда «Плановая» и не получает ни отказа, ни
-- предупреждения — слово просто перестаёт переводиться, и партнёр однажды
-- получает письмо со словом на чужом языке. Ровно этим кончалось хранение
-- вида словом до T152.
--
-- ПОЧЕМУ НЕ ОГРАНИЧЕНИЕ, А КОММЕНТАРИЙ. Перечень видов живёт в предметной
-- области (`src/domain/kinds.py`) и там же переводится. Список кодов,
-- переписанный в `check (kind in (...))`, стал бы второй копией перечня: новый
-- вид пришлось бы заводить в двух местах, и забытая половина отказала бы уже
-- на сливе — то есть на точке, где чинить нечем. Сущности связываются кодами
-- (D025), а держать перечень кодов — работа того блока, чей это перечень.
--
-- Данные миграция не трогает: значения в колонке уже коды (`domain` кладёт
-- туда `Inspection.kind` с T152). Это правка документации схемы, и накат её
-- обратим снятием комментария.
--
-- Раннер оборачивает файл в одну транзакцию сам — begin/commit здесь не нужны.

comment on column inspections.kind is
    'Вид проверки КОДОМ (planned/repeat/unscheduled), а не словом: перечень и '
    'его переводы живут в domain.kinds, слово подставляется при печати и по '
    'языку печатаемого документа (T152, T177). Формулировки переводятся и '
    'правятся, коды нет (D025) — поэтому слово в этой колонке молча ломает '
    'перевод, а не отказывает.';
