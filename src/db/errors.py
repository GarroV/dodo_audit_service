"""Отказы блока `db`.

Один базовый класс, чтобы вызывающий (бот, T093/T068) мог перехватить любой
отказ этого блока одним `except DbError` и не уронить проверку на точке:
падение базы задерживает аналитику, но не сам обход (D027, DoD блока).
"""

from __future__ import annotations


class DbError(Exception):
    """Базовый отказ блока `db`."""


class ConfigError(DbError):
    """Окружение непригодно: не задан `DATABASE_URL` или база недоступна на старте."""


class PushError(DbError):
    """Слив завершённой проверки не удался: нет состояния, оценки или базы нет на связи.

    Текст отказа безопасен для лога: путей вне проверки и содержимого записей
    в нём нет (конституция, раздел «Правила безопасности»).
    """


class VersionMismatchError(PushError):
    """Проверку считают не по той методике, которой она помечена (T148, T178).

    Наследник `PushError`, а не сосед: слив действительно не состоялся, и
    вызывающий, который ловит блок целиком (`except DbError`), не должен
    падать от того, что у отказа появился более точный тип. Но разбирать этот
    случай ему придётся отдельно — база здесь в полном порядке, и сообщение
    «историю сохранить не удалось» отправило бы человека чинить не то.

    Обе версии лежат полями, а не только в тексте: текст пишется человеку и
    правится, а ветка кода, которая его показывает, обязана выбираться типом и
    заполняться значениями, а не разбором строки.
    """

    def __init__(self, message: str, *, recorded: str, current: str) -> None:
        super().__init__(message)
        self.recorded = recorded
        self.current = current


class StorageError(DbError):
    """Хранилище кадров не приняло или не отдало объект.

    Заведён отдельным типом, чтобы драйвер хранилища переводил свои исключения
    (у boto3 они свои, у следующего поставщика будут другие) на границе самого
    драйвера. Иначе перевод пришлось бы делать в месте вызова широким
    `except Exception`, а он заодно подменял бы собой ошибки в коде
    вызывающего — и настоящая поломка выглядела бы отказом хранилища.
    """


class RetractionError(DbError):
    """Проверку не сняли из истории (T210, T233).

    Отдельный тип, а не `PushError`: слив и снятие отказывают по разным
    причинам и чинятся по-разному, а вызывающему, который ловит блок целиком
    (`except DbError`), от появления более точного типа ничего не делается.

    Текст отказа безопасен для лога: ни строки подключения, ни содержимого
    записей в нём нет (конституция, раздел «Правила безопасности»).
    """
