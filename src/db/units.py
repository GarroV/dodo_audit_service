"""Нормализация названия точки для сопоставления повторного ввода.

MVP не заводит справочник пиццерий (D051): название приходит текстом. Чтобы
историю точки через полгода можно было связать по идентификатору, а не по
совпавшей строке, точка получает свой `id` при первом появлении и дальше
опознаётся по нормализованному имени. Карта синонимов («БГ2» → «Белград 2») —
отдельная задача T092, после MVP; здесь только точное совпадение после
схлопывания пробелов и регистра, ничего умнее.
"""

from __future__ import annotations

import re

_WHITESPACE = re.compile(r"\s+")


def normalize_unit_name(name: str) -> str:
    """Ключ сопоставления: обрезанные края, схлопнутые пробелы, нижний регистр.

    `casefold`, а не `lower`: на кириллице разницы нет, но правило одно на все
    будущие языки сети, а не «пока сойдёт lower для русского».
    """
    return _WHITESPACE.sub(" ", name.strip()).casefold()
