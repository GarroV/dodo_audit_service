def rules_text() -> str:
    """Правила фиксации сплошным куском — так они уходят в запрос."""
    return "\n".join(f"{n}. {title}. {body}" for n, title, body in RECORDING_RULES)


def instructions(thresholds: str) -> str:
    """Постоянная часть запроса: роль, правила фиксации, пороги классов."""
    return (
        "Ты помощник аудитора выездной проверки пиццерии. По комментарию аудитора "
        "и, если он приложен, по кадру ты предлагаешь записи проверки: пункт "
        "методики, класс нарушения, зону и формулировку. Решение принимает аудитор, "
        "ты только предлагаешь.\n\n"
        "ПРАВИЛА ФИКСАЦИИ — обязательны, каждое появилось из разбора боевой ошибки:\n"
        f"{rules_text()}\n\n"
        "ПОРОГИ КЛАССОВ там, где класс выбирается:\n"
        f"{thresholds}\n\n"
        "Формулировку пиши на языке, на котором задан перечень пунктов. Пиши только "
        "то, что видно в кадре или сказано аудитором."
    )


def _zone_lines(zones: Sequence[Zone], lang: str) -> str:
    return "\n".join(f"- {z.code} — {z.title(lang)}" for z in zones)


def _pick_lines(picks: Sequence[str], lang: str) -> str:
    """Перечень допустимых значений `item` с текстом пункта из методики.

    Строка на каждое значение, а не на каждый код: у пункта с выбором класса
    модель должна видеть все варианты ровно так, как они записаны в схеме.
    """
    lines: list[str] = []
    for pick in picks:
        code, _, level = pick.partition(PICK_SEP)
        if not level:
            continue
        lines.append(f"- {pick} — {get_item(code).question(lang)}")
    return "\n".join(lines)


def _photo_line(*, with_photo: bool, has_note: bool) -> str:
    """Инструкция про кадр — разная в трёх случаях, а не одна на всех.

    Комментарий пуст и кадр есть — это самостоятельный разбор по кнопке
    «Разобрать» (D043, D046, T064): комментария нет вовсе, догадка по кадру —
    единственное, что есть. Тон другой: не «уточни слова аудитора», а «найди
    сам». Требование к формулировке — по D043: пунктами, коротко, без воды,
    чтобы аудитор успел подтвердить и пойти дальше, а не читать абзац.
    """
    if not with_photo:
        return "Кадра нет — опирайся только на слова аудитора."
    if not has_note:
        return (
            "Комментария нет: аудитор нажал «Разобрать» на голый кадр. Посмотри сам, "
            "найди то, что стоит зафиксировать, и предложи это отдельными записями — "
            "пунктами, коротко, без вводных слов и общих оценок. Не находишь ничего "
            "определённого — отвечай NONE, а не рассказывай, что на фото вообще есть."
        )
    return (
        "К комментарию приложен кадр. Смотри на него, чтобы уточнить или опровергнуть "
        "слова аудитора, но не добавляй из кадра масштаб и характер повреждения."
    )


def question_text(
    note: str,
    picks: Sequence[str],
    zones: Sequence[Zone],
    zone_hint: str | None,
    lang: str,
    *,
    with_photo: bool,
) -> str:
    """Переменная часть запроса: комментарий, подсказка зоны, перечень кандидатов."""
    hint = (
        f"Зона, в которой аудитор сейчас находится: {zone_hint}. Используй её, если "
        "в комментарии места нет."
        if zone_hint
        else "Зона не подсказана: бери её из слов аудитора, иначе " + UNKNOWN_ZONE + "."
    )
    photo_line = _photo_line(with_photo=with_photo, has_note=bool(note.strip()))
    return (
        f"КОММЕНТАРИЙ АУДИТОРА: {note.strip() or '(пусто)'}\n\n"
        f"{hint}\n{photo_line}\n\n"
        f"ЗОНЫ:\n{_zone_lines(zones, lang)}\n\n"
        f"ДОПУСТИМЫЕ ЗНАЧЕНИЯ item (пункт и класс), в порядке вероятности:\n"
        f"{_pick_lines(picks, lang)}\n"
        f"- {NONE_CODE} — ни один пункт перечня не подходит"
    )
