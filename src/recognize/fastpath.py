"""T113 (D063): быстрый путь — пункт без вызова модели, когда слова однозначны.

Владелец: «у нас тут не нужны размышления, а нужна сверка с текущим списком
нарушений». Замер это подтверждает наполовину: ждём мы не картинку, а
рассуждение модели (текст без кадра 4.3 с против 5.3 с с кадром), поэтому
пропуск модели там, где думать не о чем, экономит почти всё время разбора.

**Чем этот модуль отличается от `shortlist.py`.** Там сужение готовит перечень
для модели, и цена ошибки несимметрична в другую сторону: лишний код в перечне
стоит копейки, недостающий — неверную запись. Здесь наоборот. Быстрый путь
показывает готовый пункт кнопкой, и аудитор подтверждает его нажатием: лишнее
срабатывание становится записью в отчёте, которую никто не обдумывал. Поэтому
критерий однозначности строгий, а не «похоже подходит»:

1. **Зона названа человеком.** Правило 6 `docs/03-recording-rules.md`: зону
   определяет аудитор, не догадка по словам.
2. **Слова покрывают строку карты целиком — и утвердительно.** Не «задели
   общим словом», а произнесли подсказку `data/photo-cues.md` полностью.
   Порог сужения (два слова или одно различающее) для решения за человека
   слишком мягкий: комментарий про пол в подсобной зоне задевает
   перечислительную строку карты про полы и стены производственных помещений
   одним словом из пяти, и по такому касанию показывать готовый пункт нельзя.
   **Отрицание сверяется с двух сторон (T195).** Слово, отрицаемое в словах
   аудитора, строку не покрывает: «в одной таре НЕ смешаны разные партии» —
   не про смешение партий. Обратное тоже верно: строка карты, сформулированная
   через отсутствие («Тара без ярлыка»), требует отрицания и в словах, иначе
   «тара с ярлыком» покрывала бы её ровно наоборот. Таких строк в боевой карте
   13 из 75 — правило «в комментарии есть отрицание, значит отказ» отключило бы
   их все, и это была бы не осторожность, а тихая потеря быстрого пути.
   **Противоречие внутри фразы — отказ (T197).** Основа, сказанная и отрицаемая
   разом («в зале урны нет, а в подсобке урна переполнена»), не считается ни
   сказанной, ни отрицаемой: разбирать за человека, какая половина фразы про
   что, быстрый путь не берётся.
3. **Строка даёт ровно один код — в названной зоне.** Карта различает грязь и
   поломку одного объекта колонками («Печь | CLN05 | TEH05») и сама объясняет
   разницу — значит, слова должны сказать, о чём речь. Не сказали или сказали
   и то и другое — не однозначно. Слово при отрицании при этом не считается:
   «печь без нагара» и «нагара нет» — не про нагар. Слова колонок берутся из
   встроенного минимума **и из самой карты**: какими словами говорят аудиторы,
   знает управляющая компания (T143, D066), и дописывать их выпуском кода
   значило бы держать её словарь в чужих руках.
4. **У пункта единственный допустимый класс.** Где классов несколько, разницу
   задаёт то, чего в словах нет: сколько упаковок, как долго, насколько
   массово. «Живые насекомые» — это D1 или D3 по массовости, и решает её
   человек.
5. **Пункт применим к названной зоне и не служебный.** Расхождение слов и
   места — работа для модели, а не повод показать кнопку.

**Зона участвует в решении, а не проверяется в конце (T143).** Названная
человеком зона сужает коды **внутри** покрытой строки — и только те, чьи
перечни зон не пересекаются: тогда строка не предлагает выбор, а перечисляет
один объект по местам («пол на кухне» и «пол в зале» — разные пункты). Строка
вида «PRD09, PRD11» остаётся выбором самой карты и быстрым путём не проходит
никогда — теперь как следствие этого правила, а не отдельным запретом. Сами
покрытые строки зоной **не отбрасываются**: строка, которая в названной зоне
не ведёт никуда, — это громкий отказ, а не повод ответить по соседней.

Формулировку быстрый путь не пишет вообще: на кнопке стоит вопрос чек-листа,
текстом записи остаются слова самого аудитора. Правила 2–4 (масштаб за кадром,
характер повреждения, похвала без основания) нарушить тут нечем.
"""

from __future__ import annotations

