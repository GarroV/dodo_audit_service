"""T113 (D063): быстрый путь — пункт без вызова модели, когда слова однозначны.

Владелец: «у нас тут не нужны размышления, а нужна сверка с текущим списком
нарушений». Замер это подтверждает наполовину: ждём мы не картинку, а
рассуждение модели (текст без кадра 4.3 с против 5.3 с с кадром), поэтому
пропуск модели там, где думать не о чем, экономит почти всё время разбора.

**Чем этот модуль отличается от `shortlist.py`.** Там сужение готовит перечень
для модели, и цена ошибки несимметрична в другую сторону: лишний код в перечне
стоит копейки, недостающий — неверную запись. Здесь наоборот. Быстрый путь
показывает готовый пункт кнопкой, и аудитор подтверждает его нажатием: лишнее
срабатывание становится записью в отчёте, которую никто не обдумывал. Поэтому
критерий однозначности строгий, а не «похоже подходит»:

1. **Зона названа человеком.** Правило 6 `docs/03-recording-rules.md`: зону
   определяет аудитор, не догадка по словам.
2. **Слова покрывают строку карты целиком.** Не «задели общим словом», а
   произнесли подсказку `data/photo-cues.md` полностью. Порог сужения (два
   слова или одно различающее) для решения за человека слишком мягкий:
   «Пол в курьерской зоне» задевает строку «Пол, стены, потолок, двери на
   кухне» одним словом из пяти.
3. **Строка даёт ровно один код.** Карта различает грязь и поломку одного
   объекта колонками («Печь | CLN05 | TEH05») и сама объясняет разницу —
   значит, слова должны сказать, о чём речь. Не сказали или сказали и то и
   другое — не однозначно. Строка вида «PRD09, PRD11» — выбор из двух пунктов,
   предложенный самой картой, и быстрым путём не проходит никогда.
4. **У пункта единственный допустимый класс.** Где классов несколько, разницу
   задаёт то, чего в словах нет: сколько упаковок, как долго, насколько
   массово. «Живые насекомые» — это D1 или D3 по массовости, и решает её
   человек.
5. **Пункт применим к названной зоне и не служебный.** Расхождение слов и
   места — работа для модели, а не повод показать кнопку.

Формулировку быстрый путь не пишет вообще: на кнопке стоит вопрос чек-листа,
текстом записи остаются слова самого аудитора. Правила 2–4 (масштаб за кадром,
характер повреждения, похвала без основания) нарушить тут нечем.
"""

from __future__ import annotations

from dataclasses import dataclass

from src.domain import allowed_levels, get_item, list_items

from .config import DEFAULT_LANG
from .cues import Cue, load_cues, stems
from .shortlist import MANUAL_ONLY

#: Почему быстрый путь не сработал. Строки, а не флаги: их видно в замере
#: (`tools/fastpath_measure.py`) и они объясняют, чего карте не хватило.
NO_ZONE = "зона не названа"
NO_CUE = "ни одна строка карты не произнесена целиком"
SEVERAL_ITEMS = "слова указывают на несколько пунктов"
NO_COLUMN = "по словам не видно, грязь это или поломка"
SEVERAL_LEVELS = "класс выбирает аудитор: у пункта их несколько"
WRONG_ZONE = "пункт не применим к названной зоне"
NOT_OFFERED = "пункт служебный или его ставит только аудитор"

#: Слова, которыми аудитор называет грязь. Взяты из двух источников и ниоткуда
#: больше: заголовок колонки самой карты («Грязь») и формулировки боевых
#: проверок в `examples/` — «нагар», «налёт», «потёки», «крошки», «пыль»,
#: «мусор», «загрязнения». Выдумывать за управляющую компанию, какими словами
#: говорят аудиторы, нельзя, поэтому список короткий и растёт только по факту.
#:
#: Слов, которые переворачиваются отрицанием, здесь нет намеренно: «не убран»,
#: «не протёрт», «не мыли» значат ровно обратное «убран», «протёрт», «мыли», а
#: совпадение идёт по основам и частицу «не» не видит.
DIRT_WORDS = (
    "грязь",
    "грязный",
    "загрязнение",
    "нагар",
    "налёт",
    "копоть",
    "пыль",
    "мусор",
    "крошки",
    "жир",
    "плесень",
    "разводы",
    "потёки",
    "подтёки",
    "пятна",
    "паутина",
    "липкий",
)

#: Слова, которыми аудитор называет поломку. Тот же принцип: заголовок колонки
#: («Поломка») плюс формы, которые не переворачиваются отрицанием — «не
#: работает» и «не закрывается» сюда не годятся по той же причине.
BREAKAGE_WORDS = (
    "сломан",
    "поломка",
    "неисправный",
    "неисправность",
    "трещина",
    "треснул",
    "скол",
    "разбит",
    "оторван",
    "отвалился",
    "деформация",
    "порван",
    "оплавлен",
    "погнут",
)


def _vocabulary(words: tuple[str, ...]) -> frozenset[str]:
    return frozenset(stem for word in words for stem in stems(word))


#: Заголовок колонки → словарь, которым она выбирается. Заголовок, которого
#: здесь нет («Кандидаты»), словами не выбирается никогда: строка с двумя
#: такими колонками останется неоднозначной, и это правильный отказ.
COLUMN_VOCABULARY: dict[str, frozenset[str]] = {
    "грязь": _vocabulary(DIRT_WORDS),
    "поломка": _vocabulary(BREAKAGE_WORDS),
}


@dataclass(frozen=True)
class FastItem:
    """Пункт, показанный кнопкой подтверждения: ни одного придуманного слова."""

    code: str
    level: str
    zone: str
    #: Вопрос чек-листа на языке аудитора — текст кнопки.
    title: str
    #: Строка карты, которая сработала. Аудитору видно, почему предложен пункт.
    cue: str


@dataclass(frozen=True)
class FastPath:
    """Ответ быстрого пути: пункт или причина, по которой его нет."""

    item: FastItem | None
    reason: str


def _covered(words: set[str]) -> list[Cue]:
    """Строки карты, произнесённые целиком: все значимые слова подсказки в словах."""
    return [cue for cue in load_cues() if (phrase := stems(cue.phrase)) and phrase <= words]


def _resolve(cue: Cue, words: set[str]) -> tuple[str, ...]:
    """Коды строки после разбора колонок. Пусто — колонка не выбрана словами."""
    distinct = {column[1] for column in cue.by_column}
    if len(distinct) == 1:
        return next(iter(distinct))
    matched = [
        codes
        for header, codes in cue.by_column
        if COLUMN_VOCABULARY.get(header.strip().lower(), frozenset()) & words
    ]
    return matched[0] if len(matched) == 1 else ()


def fast_path(note: str, zone_hint: str | None, *, lang: str = DEFAULT_LANG) -> FastPath:
    """Однозначен ли комментарий настолько, чтобы показать пункт без модели.

    Возвращает либо пункт (`item`), либо причину отказа (`reason`). Отказ —
    обычный ответ, а не сбой: он означает «дальше как раньше, спрашиваем
    модель», и на боевых данных так заканчивается большинство записей.
    """
    if zone_hint is None:
        return FastPath(None, NO_ZONE)
    words = stems(note)
    covered = _covered(words)
    if not covered:
        return FastPath(None, NO_CUE)

    picked: dict[str, str] = {}
    for cue in covered:
        codes = _resolve(cue, words)
        if not codes:
            return FastPath(None, NO_COLUMN)
        if len(codes) > 1:
            return FastPath(None, SEVERAL_ITEMS)
        picked.setdefault(codes[0], cue.phrase)
    if len(picked) > 1:
        return FastPath(None, SEVERAL_ITEMS)

    code, phrase = next(iter(picked.items()))
    item = get_item(code)
    if item.kind != "violation" or code in MANUAL_ONLY:
        return FastPath(None, NOT_OFFERED)
    levels = allowed_levels(code)
    if len(levels) != 1:
        return FastPath(None, SEVERAL_LEVELS)
    if code not in {i.code for i in list_items(zone=zone_hint)}:
        return FastPath(None, WRONG_ZONE)
    return FastPath(
        FastItem(
            code=code,
            level=levels[0],
            zone=zone_hint,
            title=item.question(lang),
            cue=phrase,
        ),
        "",
    )
