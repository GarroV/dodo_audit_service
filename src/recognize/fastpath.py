#: Почему быстрый путь не сработал. Строки, а не флаги: их видно в замере
#: (`tools/fastpath_measure.py`) и они объясняют, чего карте не хватило.
NO_ZONE = "зона не названа"
NO_CUE = "ни одна строка карты не произнесена целиком"
SEVERAL_ITEMS = "слова указывают на несколько пунктов"
NO_COLUMN = "по словам не видно, грязь это или поломка"
SEVERAL_LEVELS = "класс выбирает аудитор: у пункта их несколько"
WRONG_ZONE = "пункт не применим к названной зоне"
NOT_OFFERED = "пункт служебный или его ставит только аудитор"

#: Частицы, которые переворачивают смысл слова, и куда каждая смотрит. «Печь
#: без нагара» — это не нагар, «нагара нет» — тем более, а совпадение идёт по
#: основам слов и частицу не видит. Поэтому отрицаемое слово не участвует ни в
#: выборе колонки, ни в покрытии строки карты: отказ стоит вызова модели,
#: срабатывание — записи в отчёте партнёру, показанной без подтверждения (D064).
#:
#: Частицы всех языков лежат в `language_rules.json` (T192): по-английски то же
#: правило нужно слово в слово («oven without soot»), и оставить его русским
#: значило бы, что английский комментарий с отрицанием даёт срабатывание.
NEGATIONS = language.negations()


def _vocabulary(words: tuple[str, ...]) -> frozenset[str]:
    return frozenset(stem for word in words for stem in stems(word))


def _denied_words(words: tuple[str, ...], gaps: tuple[str, ...]) -> set[int]:
    """Номера слов, стоящих под отрицанием.

    Частица относится к **ближайшему значимому** слову в свою сторону, а не к
    буквально соседнему: между ними сплошь и рядом стоит предлог, и «не в одной
    таре» — это то же отрицание, что «не смешаны». Служебные слова частица
    перешагивает, другую частицу — тоже («нет ни одного ярлыка»).

    Знак препинания её останавливает. Это не тонкость: без него «жалоб нет, в
    зале урна переполнена» теряет срабатывание, потому что «нет» и «урна» стоят
    рядом. Замер на боевой карте — так теряются 30 строк из 32, то есть быстрый
    путь обнуляется молча и выглядит это как «стало безопаснее».
    """
    denied: set[int] = set()
    for index, word in enumerate(words):
        direction = NEGATIONS.get(word)
        if direction is None:
            continue
        if direction in (language.FORWARD, language.BOTH):
            _reach(words, gaps, index, +1, denied)
        if direction in (language.BACKWARD, language.BOTH):
            _reach(words, gaps, index, -1, denied)
    return denied


def _reach(
    words: tuple[str, ...], gaps: tuple[str, ...], start: int, step: int, denied: set[int]
) -> None:
    """Отметить ближайшее значимое слово в сторону `step`, не пересекая знаков."""
    previous, index = start, start + step
    while 0 <= index < len(words):
        if gaps[min(previous, index)].strip():
            return
        if words[index] not in NEGATIONS and stems(words[index]):
            denied.add(index)
            return
        previous, index = index, index + step


def _said(text: str) -> tuple[frozenset[str], frozenset[str]]:
    """Основы слов текста: сказанные утвердительно и сказанные под отрицанием.

    Считается одинаково и для комментария аудитора, и для строки карты: строки
    вида «Тара без ярлыка» описывают отсутствие, и сверять их с комментарием
    можно только тем же разбором, каким разобран комментарий.

    Сами частицы не попадают ни в тот набор, ни в другой: это служебные слова, и
    по-русски они и так стоп-слова, а по-английски («without», «no») стоп-словами
    объявлены быть не могут — иначе строка карты со словом «without» покрывалась
    бы комментарием, который говорит обратное.

    **Основа, сказанная и отрицаемая разом, не попадает ни в один набор (T197).**
    Наборы теряют число вхождений, и одно слово, встреченное во фразе дважды —
    раз под отрицанием, раз без него, — попадало сразу в оба: «в зале урны нет,
    а в подсобке урна переполнена». Утвердительное вхождение побеждало, строка
    карты считалась покрытой, и записывался пункт про зал — ровно то, чего
    аудитор там не видел. Это остаток, который замер T195 назвал числом: 8
    случаев из 412 на боевой карте.

    Отказ здесь, а не выбор одной из сторон: фраза противоречива по словам, и
    решать такое за человека быстрый путь не берётся — ни в пользу утверждения,
    ни в пользу отрицания. Дороже ошибиться: срабатывание становится записью в
    отчёте партнёру без подтверждения (D064), отказ стоит вызова модели.
    """
    words, gaps = words_and_gaps(text)
    denied_at = _denied_words(words, gaps)
    spoken: set[str] = set()
    denied: set[str] = set()
    for index, word in enumerate(words):
        if word in NEGATIONS:
            continue
        (denied if index in denied_at else spoken).update(stems(word))
    contradictory = spoken & denied
    return frozenset(spoken - contradictory), frozenset(denied - contradictory)


#: Заголовок колонки → **встроенный минимум** слов, которым она выбирается.
#: Заголовок, которого нет ни здесь, ни в карте («Кандидаты»), словами не
#: выбирается никогда: строка с двумя такими колонками останется неоднозначной,
#: и это правильный отказ.
#:
#: Сами слова живут в `language_rules.json` (T192) и взяты из двух источников и
#: ниоткуда больше: заголовок колонки самой карты («Грязь», «Dirt») и
#: формулировки боевых проверок. Выдумывать за управляющую компанию, какими
#: словами говорят аудиторы, нельзя — поэтому список короткий, растёт по факту
#: и **дополняется картой** (D077), а не заменяется ею. Слов, которые
#: переворачиваются отрицанием («не убран», «works»), там нет намеренно.
BUILTIN_COLUMN_VOCABULARY: dict[str, frozenset[str]] = {
    header: _vocabulary(words) for header, words in language.column_words().items()
}


def _vocabulary_now(chat_id: int | None) -> dict[str, frozenset[str]]:
    """Словарь колонок: встроенный минимум плюс слова из карты (T143).

    Сложение, а не замена: раздел, забытый в новой версии карты, не должен
    молча отключать различение грязи и поломки, а владелец про этот механизм
    сказал «дополняем наш список терминов» (D077). Карта читается на каждом
    вызове по той же причине, что и подсказки: методику подкладывают снаружи.
    """
    merged = dict(BUILTIN_COLUMN_VOCABULARY)
    for header, words in map_column_words(chat_id=chat_id).items():
        merged[header] = merged.get(header, frozenset()) | words
    return merged


@dataclass(frozen=True)
class FastItem:
    """Пункт, показанный кнопкой подтверждения: ни одного придуманного слова."""

    code: str
    level: str
    zone: str
    #: Вопрос чек-листа на языке аудитора — текст кнопки.
    title: str
    #: Строка карты, которая сработала. Аудитору видно, почему предложен пункт.
    cue: str


@dataclass(frozen=True)
class FastPath:
    """Ответ быстрого пути: пункт или причина, по которой его нет."""

    item: FastItem | None
    reason: str


def _covered(spoken: frozenset[str], denied: frozenset[str], chat_id: int | None) -> list[Cue]:
    """Строки карты, произнесённые целиком и с тем же отрицанием, что в них самих.

    Двух проверок ровно две, и обе обязательны: утвердительные слова строки
    должны быть сказаны утвердительно, а отрицаемые строкой — отрицаемы и в
    комментарии. Одна половина без другой даёт либо запись того, что аудитор
    отрицал, либо потерю всех строк карты про отсутствие.
    """
    covered: list[Cue] = []
    for cue in load_cues(chat_id=chat_id):
        phrase_spoken, phrase_denied = _said(cue.phrase)
        if not (phrase_spoken or phrase_denied):
            continue
        if phrase_spoken <= spoken and phrase_denied <= denied:
            covered.append(cue)
    return covered


def _resolve(
    cue: Cue, spoken: frozenset[str], vocabulary: dict[str, frozenset[str]]
) -> tuple[str, ...]:
    """Коды строки после разбора колонок. Пусто — колонка не выбрана словами."""
    distinct = {column[1] for column in cue.by_column}
    if len(distinct) == 1:
        return next(iter(distinct))
    matched = [
        codes
        for header, codes in cue.by_column
        if vocabulary.get(header.strip().lower(), frozenset()) & spoken
    ]
    return matched[0] if len(matched) == 1 else ()


def _offered(codes: tuple[str, ...], chat_id: int | None) -> bool:
    """Все ли коды строки вообще предлагаются разбором.

    Смешанная строка (служебный пункт рядом с нарушением) — не повод показать
    нарушение и промолчать про остальное: это ошибка карты, и она должна быть
    видна отказом, а не тихим отбрасыванием половины строки.
    """
    return all(
        get_item(c, chat_id=chat_id).kind == "violation" and c not in MANUAL_ONLY for c in codes
    )


def _separable_by_zone(codes: tuple[str, ...], chat_id: int | None) -> bool:
    """Перечисляет ли строка один объект по местам — или предлагает выбор (T143).

    Зона вправе развести коды строки только тогда, когда их перечни зон **не
    пересекаются**: тогда строка не выбирает между двумя вопросами, а называет,
    как один объект заведён в методике в разных местах («пол на кухне» и «пол в
    зале» — разные пункты про одно и то же).

    Пересеклись — это выбор, предложенный самой картой («PRD09, PRD11»), и зона
    его не решает: там, где применимы оба, строка честно неоднозначна, и
    отвечать однозначно в соседней зоне значило бы дать разный ответ на один
    комментарий по причине, которой человеку не видно.

    Пункт без перечня зон применим везде (`ChecklistItem.applies_to`), поэтому
    развести его зоной нельзя ни с чем.
    """
    zone_sets: list[set[str]] = []
    for code in codes:
        zones = get_item(code, chat_id=chat_id).zones
        if not zones or zones == ["*"]:
            return False
        zone_sets.append(set(zones))
    return all(
        not (first & second)
        for index, first in enumerate(zone_sets)
        for second in zone_sets[index + 1 :]
    )


def fast_path(
    note: str, zone_hint: str | None, *, lang: str = DEFAULT_LANG, chat_id: int | None
) -> FastPath:
    """Однозначен ли комментарий настолько, чтобы показать пункт без модели.

    Возвращает либо пункт (`item`), либо причину отказа (`reason`). Отказ —
    обычный ответ, а не сбой: он означает «дальше как раньше, спрашиваем
    модель», и на боевых данных так заканчивается большинство записей.

    **Зона участвует в решении, а не проверяется последней (T143).** Она
    сужает коды **внутри** покрытой строки — но не отбрасывает саму строку:
    строка, которая в названной зоне не ведёт никуда, остаётся отказом
    `WRONG_ZONE`. Замер объясняет, почему именно так: на боевых записях
    отбрасывание строк по зоне даёт одно лишнее срабатывание из семнадцати, и
    оно неверное.

    **`chat_id` обязателен и умолчания не имеет (T226).** Пункты, классы, зоны
    и сама карта слов берутся из издания ТОЙ проверки (T169): карта входит в
    отпечаток издания (D063/D064), а показанный ею пункт становится записью в
    отчёте партнёру, у которой отдельного подтверждения текста больше нет
    (D064). Карта из действующего каталога означала бы запись по правилам,
    которых в издании проверки нет. Пустой чат (`config.NO_CHAT`) — законное
    «проверки нет»: так зовёт замер по выгрузкам `examples/`.
    """
    if zone_hint is None:
        return FastPath(None, NO_ZONE)
    # Зона проверяется до слов: иначе отказ методики на неизвестную зону
    # зависел бы от того, задел ли комментарий строку карты, и опечатка в коде
    # зоны нашлась бы через месяц на первом же совпавшем слове.
    zone_codes = {i.code for i in list_items(zone=zone_hint, chat_id=chat_id)}
    spoken, denied = _said(note)
    covered = _covered(spoken, denied, chat_id)
    if not covered:
        return FastPath(None, NO_CUE)

    vocabulary = _vocabulary_now(chat_id)
    picked: dict[str, str] = {}
    for cue in covered:
        codes = _resolve(cue, spoken, vocabulary)
        if not codes:
            return FastPath(None, NO_COLUMN)
        # Вид пункта — раньше зоны: сводная строка процесса применима во всех
        # зонах сразу, и зональный отказ подменил бы правило 8 неверной причиной.
        if not _offered(codes, chat_id):
            return FastPath(None, NOT_OFFERED)
        if len(codes) > 1 and not _separable_by_zone(codes, chat_id):
            return FastPath(None, SEVERAL_ITEMS)
        applicable = tuple(code for code in codes if code in zone_codes)
        if not applicable:
            return FastPath(None, WRONG_ZONE)
        if len(applicable) > 1:
            return FastPath(None, SEVERAL_ITEMS)
        picked.setdefault(applicable[0], cue.phrase)
    if len(picked) > 1:
        return FastPath(None, SEVERAL_ITEMS)

    code, phrase = next(iter(picked.items()))
    levels = allowed_levels(code, chat_id=chat_id)
    if len(levels) != 1:
        return FastPath(None, SEVERAL_LEVELS)
    return FastPath(
        FastItem(
            code=code,
            level=levels[0],
            zone=zone_hint,
            title=get_item(code, chat_id=chat_id).question(lang),
            cue=phrase,
        ),
        "",
    )
