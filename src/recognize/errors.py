"""Отказы блока `recognize`.

Тип отказа решает, что делает бот: переспросить аудитора, показать кнопки
ручного выбора или не подниматься вовсе. Поэтому классы разные, а не один
общий: по тексту сообщения такое решение принимать нельзя.
"""

from __future__ import annotations


class RecognizeError(Exception):
    """Базовый отказ разбора."""


class RecognizeConfigError(RecognizeError):
    """Разбирать нечем: нет карты кадров, ключа модели или ffmpeg.

    Отдельный класс нужен, чтобы бот не молчал: без карты кадров сужение
    перечня превращается в догадку, а тихо взятый неполный перечень —
    ровно та ошибка, которую разведка признала самой опасной.
    """


class ModelUnavailable(RecognizeError):
    """Модель не ответила: сеть, ключ, лимит, таймаут, испорченный ответ.

    Проверку это не роняет — бот переходит на ручной выбор пункта кнопками
    (`manual_candidates`).
    """


class TranscriptionFailed(RecognizeError):
    """Голосовое не разобрано: не перекодировалось, не распозналось, пустое.

    Аудитора просят написать текстом; проверка продолжается.
    """
