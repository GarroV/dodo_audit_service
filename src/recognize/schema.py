"""T031: схема ответа модели. Код и класс приходят из перечисления, а не из строки.

Главное решение модуля: **код и класс склеены в одно поле** `item` вида
`CLN05:D1`. Так схема сама гарантирует обе вещи, которых требует контракт блока:
код — строго из переданного перечня, класс — только из разрешённых для этого
пункта. Разделять их на два поля значило бы либо проверять пару постфактум
(запрещено контрактом), либо описывать перечень ветвями `anyOf` — по одной на
каждый из 75 кодов зоны, что раздувает запрос в десяток килобайт ради того же
результата.

Строгий режим OpenAI не поддерживает `maxItems`, `minimum` и `maximum`, поэтому
число кандидатов и границы уверенности проверяются при разборе ответа
(`classify`), а не заявляются в схеме. Заявить их и получить молчаливое
игнорирование было бы хуже: проверка выглядела бы существующей.
"""

from __future__ import annotations

from collections.abc import Sequence
from typing import Any

from src.domain import allowed_levels

from .errors import RecognizeConfigError
from .models import NONE_CODE, UNKNOWN_ZONE

#: Разделитель кода и класса внутри значения перечисления.
PICK_SEP = ":"

#: Значение, которым модель говорит «ничего из перечня не подходит». Обязано
#: быть в перечислении: без варианта отказа модель выбирает ближайший пункт —
#: разведка на боевом кадре (`docs/forge/research/recognize-probe.md`).
NONE_PICK = NONE_CODE


def picks_for(codes: Sequence[str], *, chat_id: int | None) -> tuple[str, ...]:
    """Пары «код:класс» для перечисления — по одной на каждый допустимый класс.

    Порядок кодов сохраняется: перечень уже отсортирован так, что поднятые
    картой кадров стоят первыми. Пункт без единого допустимого класса — отказ,
    а не пропуск: молча выпавший из перечисления код модель не предложит
    никогда, и понять это по ответу будет нельзя.

    `chat_id` обязателен и умолчания не имеет (T226): классы берутся из издания
    ТОЙ проверки (T169). Класс из действующей методики движок у этой проверки
    не примет, и починить это с точки нельзя.
    """
    picks: list[str] = []
    for code in codes:
        levels = allowed_levels(code, chat_id=chat_id)
        if not levels:
            raise RecognizeConfigError(
                f"У пункта {code} в методике нет ни одного допустимого класса. "
                f"Молча выкинуть его из перечисления нельзя: модель просто никогда его "
                f"не предложит, и по ответу это будет неотличимо от «не подходит»"
            )
        picks.extend(f"{code}{PICK_SEP}{level}" for level in levels)
    return (*picks, NONE_PICK)


def split_pick(pick: str) -> tuple[str, str]:
    """Разобрать значение перечисления на код и класс. Отказ — это `(NONE, "")`."""
    if pick == NONE_PICK:
        return NONE_CODE, ""
    code, _, level = pick.partition(PICK_SEP)
    return code, level


def response_schema(picks: Sequence[str], zones: Sequence[str]) -> dict[str, Any]:
    """Строгая схема ответа: список записей плюс уточняющий вопрос.

    `question` — то, что модель спрашивает у аудитора, когда по кадру и
    комментарию непонятно (правило 7). Поле обязательное: в строгом режиме
    необязательных полей не бывает, пустая строка означает «вопросов нет».
    """
    return {
        "type": "object",
        "additionalProperties": False,
        "required": ["records", "question"],
        "properties": {
            "records": {
                "type": "array",
                "description": (
                    "Предложения записей. Один комментарий может содержать несколько "
                    "нарушений — тогда записей несколько. Ни одна не подходит — пустой "
                    "список либо единственная запись с item=NONE."
                ),
                "items": {
                    "type": "object",
                    "additionalProperties": False,
                    "required": ["item", "zone", "wording", "reason", "confidence"],
                    "properties": {
                        "item": {
                            "type": "string",
                            "description": (
                                "Пункт и класс одним значением из перечня. NONE — если "
                                "ни один пункт перечня не подходит."
                            ),
                            "enum": list(picks),
                        },
                        "zone": {
                            "type": "string",
                            "description": (
                                "Зона из слов аудитора или из подсказки. Выводить зону "
                                f"из вида кадра запрещено: не сказано — {UNKNOWN_ZONE}."
                            ),
                            "enum": [*zones, UNKNOWN_ZONE],
                        },
                        "wording": {
                            "type": "string",
                            "description": "Формулировка записи по правилам фиксации.",
                        },
                        "reason": {
                            "type": "string",
                            "description": "Что в комментарии или кадре указывает на этот пункт.",
                        },
                        "confidence": {
                            "type": "number",
                            "description": "Уверенность от 0 до 1.",
                        },
                    },
                },
            },
            "question": {
                "type": "string",
                "description": (
                    "Что спросить у аудитора, если непонятно. Пустая строка — вопросов нет."
                ),
            },
        },
    }
