"""T032: страховка после модели — код-уровневая проверка формулировки.

Промпт запрещает масштаб за кадром, додуманный характер повреждения и похвалу
без основания (`docs/03-recording-rules.md`, правила 2–4), но соблюдение
инструкции моделью не гарантировано никаким механизмом схемы: в отличие от
кода и класса, у текста формулировки нет `enum`, который отсекал бы плохой
ответ структурно. Эта проверка — второй, а не единственный слой: подозрительная
формулировка не блокируется и не переписывается сама — она помечается
(`Candidate.flags`), и аудитор видит пометку вместо того, чтобы прочитать
текст как обычную, уже проверенную запись.

Шаблоны собраны из разбора боевых ошибок, на которые ссылается сам документ
правил, а не придуманы заранее — это защита от конкретных повторяющихся
промахов, а не общий стоп-лист слов.
"""

from __future__ import annotations

import re

#: Слова масштаба за пределами кадра (правило 2). Ошибка из боевого отчёта:
#: «обои и стена над плинтусом в затирках и потёртостях на протяжении
#: нескольких метров» — при одной фотографии одного угла.
_SCALE_PATTERNS = (
    re.compile(r"на протяжении (нескольких|\d+) (метр|м\b)", re.IGNORECASE),
    re.compile(r"в нескольких местах", re.IGNORECASE),
    re.compile(r"по всей (ширине|длине|площади)", re.IGNORECASE),
    re.compile(r"по всему (залу|цеху|помещению|заведению)", re.IGNORECASE),
    re.compile(r"в течение (всей|целой) смены", re.IGNORECASE),
    re.compile(r"\bповсюду\b|\bвезде\b", re.IGNORECASE),
)

#: Додуманный характер повреждения (правило 3): «в плотных загрязнениях с
#: коррозией» на фотографии, где под грязью целый металл — ошибка повторилась
#: дважды в двух отчётах. Слово о повреждении без слова о металле рядом — то
#: же самое додумывание, случай не различает фото и текст.
_DAMAGE_WORDS = (
    re.compile(r"коррози", re.IGNORECASE),
    re.compile(r"трещин", re.IGNORECASE),
    re.compile(r"скол(ы|а|ов)?\b", re.IGNORECASE),
    re.compile(r"плесен", re.IGNORECASE),
)
_METAL_MENTIONED = re.compile(r"металл", re.IGNORECASE)

#: Похвала без основания (правило 4): «Борт равномерный, пропёк без белых
#: участков... Нареканий нет» — про пиццу, у которой при увеличении нашлись
#: неровный борт, воздушный карман и неравномерный пропёк. Похвала помечается,
#: только если модель не оставила основания в `reason`: заполненный `reason` —
#: и есть то основание, которого правило требует.
_PRAISE_PATTERNS = (
    re.compile(r"нарекани[йя]\s+нет", re.IGNORECASE),
    re.compile(r"без\s+замечани", re.IGNORECASE),
    re.compile(r"полностью\s+соответствует", re.IGNORECASE),
    re.compile(r"нет\s+нареканий", re.IGNORECASE),
)

#: Значения `Candidate.flags`. Строки, а не enum: пометки читает только
#: человек (текст рядом с записью), машинного потребителя у них нет.
SCALE_BEYOND_FRAME = "масштаб-за-кадром"
DAMAGE_WITHOUT_BASIS = "характер-повреждения-не-обоснован"
UNWARRANTED_PRAISE = "похвала-без-основания"


def check_wording(wording: str, reason: str) -> tuple[str, ...]:
    """Пометки формулировки. Пустой кортеж — нет оснований для внимания.

    Ни одна пометка не меняет и не отбрасывает запись: `classify` показывает
    её человеку как есть, вместе с пометками. Решение остаётся за ним —
    тот же принцип, что и для кандидатов в целом.
    """
    flags: list[str] = []
    if any(p.search(wording) for p in _SCALE_PATTERNS):
        flags.append(SCALE_BEYOND_FRAME)
    if any(p.search(wording) for p in _DAMAGE_WORDS) and not _METAL_MENTIONED.search(wording):
        flags.append(DAMAGE_WITHOUT_BASIS)
    if any(p.search(wording) for p in _PRAISE_PATTERNS) and not reason.strip():
        flags.append(UNWARRANTED_PRAISE)
    return tuple(flags)
