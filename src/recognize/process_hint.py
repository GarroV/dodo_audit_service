"""Указание аудитора «<описание>, это <процесс>» (T166, D077).

Владелец, дословно: «при несостыковках, или если пользователь добавит что-то в
духе "ГРЯЗЬ НА ПОЛКЕ В ГОРЯЧЕМ ЦЕХЕ, ЭТО ЧИСТОТА" то мы долполняем наш список
терминов». Аудитор в такой фразе не описывает нарушение, а указывает системе
процесс методики — такое указание стоит собирать для управляющей компании
(задача T165, другой блок).

Признак **ненадёжен**: тот же речевой акт бывает и обычным комментарием.
«Просрочка на полке, это пищевая безопасность» — одновременно и похоже на
указание словарю, и обычное описание находки; по одному тексту эти два
прочтения неразличимы. Поэтому функция ничего не решает и никого не зовёт:
она только **распознаёт форму**, в дополнение к разбору, а не вместо него.
Ничего никуда не пополняется (D077) — сбор предложений для управляющей
компании остаётся отдельной задачей (T165) над тем, что вернула эта функция.
Если аудитор на самом деле описывал нарушение, поток не должен его потерять:
`process_hint` — чистая функция без побочных эффектов, обычный разбор
комментария она не подменяет и не блокирует.

Связка-СЛОВО объявлена на каждый язык в `language_rules.json` (T196): «это»
по-русски, «is» по-английски. Русским выражением она быть не могла — аудитор,
ведущий проверку по-английски, не мог указать процесс вовсе, и молчал признак
бесшумно, ничем не отличаясь от «указаний не было». Тире и дефис в связки не
взяты ни на одном языке намеренно: они сплошь и рядом стоят в обычных
комментариях («нагар — жирные потёки»), и на них признак превратился бы в шум.
Это решение, а не недоделка.

**Почему за английскую связку не страшно, хотя «is» частотнее «это».**
Ограничитель здесь не связка, а хвост: после неё должно стоять РОВНО имя
процесса и ничего больше. Проверено на речи управляющей компании о нарушениях
по-английски — 136 вопросов методики, в 31 из них есть «is»: признак не сработал
ни разу. Это тот же корпус-заместитель, на котором меряется русская связка
(`make processhint`), и обещанием он не является: боевых английских проверок
пока не существует, и доля ложных срабатываний на живой английской речи не
посчитана ни по чему.
"""

from __future__ import annotations

import re
from dataclasses import dataclass

from src.domain import list_items

from . import language
from .config import DEFAULT_LANG
from .cues import stems

#: Связки-символы. В правила языков не вынесены намеренно: «=» и «→» словами
#: никакого языка не являются и пишутся одинаково хоть в русском, хоть в
#: сербском комментарии — объявлять их на каждый язык значило бы заводить три
#: копии одного и того же и ждать, что они не разойдутся.
_SYMBOLS = ("=", "→")


def _connective() -> re.Pattern[str]:
    """Выражение связки: слова всех языков плюс символы.

    Слова обрамлены границами слова, чтобы не задеть «этот» или «всё это»;
    регистр роли не играет. Порядок слов задан `language.connectives()` и
    отсортирован там же: чередование, зависящее от порядка языков в файле,
    давало бы разный разбор одного текста после добавления третьего языка.
    """
    words = "|".join(rf"\b{re.escape(word)}\b" for word in language.connectives())
    return re.compile("|".join([words, *map(re.escape, _SYMBOLS)]), re.IGNORECASE)


#: Связки признака на всех объявленных языках. Публичная: тем же выражением
#: замер (`tools/process_hint_measure.py`) считает, в скольких текстах связка
#: вообще стоит. Своя копия правила разошлась бы с этим молча, и замер начал бы
#: мерить не тот признак.
CONNECTIVE = _connective()

#: Пробелы и хвостовая пунктуация, которые обрезаются у `said` по обоим краям.
_EDGE_CHARS = " \t\r\n,.:;—-"


@dataclass(frozen=True)
class ProcessHint:
    """Указание аудитора «<описание>, это <процесс>»."""

    process: str
    said: str
    connective: str


def process_hint(note: str, *, lang: str = DEFAULT_LANG, chat_id: int | None) -> ProcessHint | None:
    """Распознать указание процесса методики в комментарии, если оно есть.

    Признак двухчастный, и обе части обязательны:

    1. в комментарии есть связка («это», «=» или «→»);
    2. хвост после связки — **ровно** имя процесса методики, и ничего больше:
       сравнение идёт по основам слов (`stems`), лишнее слово в хвосте признак
       снимает («это порядок на полке» — не признак).

    Имена процессов читаются из методики при каждом вызове (`list_items` →
    `item.process(lang)`), а не зашиты в код: переименованный управляющей
    компанией процесс обязан начать узнаваться сам, без пересборки — тот же
    принцип, что у карты кадров в `cues.py`.

    Связок в комментарии может быть несколько — берётся последняя, у которой
    хвост совпал с именем процесса; если ни у одной не совпал, ответ `None`.
    У выбранной связки часть до неё («said») не должна быть пустой:
    комментарий из одной связки и процесса («это порядок») не описывает
    ничего, указывать не на что, и попытка взять более раннюю связку здесь не
    делается — правило читает буквально: подошла последняя, а перед ней пусто
    → отказ, а не перебор в поисках связки получше.

    Отказ методики (`src.domain` при сломанной конфигурации) не перехватывается
    и уходит наружу как есть — своих исключений функция не заводит.

    `chat_id` обязателен и умолчания не имеет (T226): имена процессов — такой
    же справочник, как пункты и зоны, и читаются они из издания ТОЙ проверки
    (T169). Признак пока никем в продукте не зовётся — сбор предложений для
    управляющей компании остаётся задачей T165, — но параметр заведён сразу:
    умолчание здесь и есть тот молчаливый откат на действующую методику,
    который T226 снимает во всём блоке, и заводить его, чтобы снять потом,
    значило бы заложить дефект осознанно.
    """
    if not note.strip():
        return None

    vocabulary = _process_vocabulary(lang, chat_id)
    if not vocabulary:
        return None

    for match in reversed(list(CONNECTIVE.finditer(note))):
        tail_stems = stems(note[match.end() :])
        if not tail_stems:
            continue
        process = _match_process(tail_stems, vocabulary)
        if process is None:
            continue
        said = note[: match.start()].strip(_EDGE_CHARS)
        if not said:
            return None
        return ProcessHint(process=process, said=said, connective=match.group().lower())
    return None


def _process_vocabulary(lang: str, chat_id: int | None) -> dict[str, frozenset[str]]:
    """Имена процессов методики → их основы слов. Читается заново на каждый вызов.

    Имена отсортированы намеренно: два процесса с одинаковым набором основ
    («Замеры» и «Замер») давали бы разный ответ от прогона к прогону, потому что
    порядок множества в Python зависит от засева хеша. Совпадение имён — ошибка
    методики, но невоспроизводимое поведение на ней хуже воспроизводимого:
    первое не разбирается вовсе.
    """
    names = sorted({item.process(lang) for item in list_items(chat_id=chat_id)})
    return {name: frozenset(stems(name)) for name in names if name and stems(name)}


def _match_process(tail_stems: set[str], vocabulary: dict[str, frozenset[str]]) -> str | None:
    """Имя процесса, чьи основы слов совпадают с хвостом ровно как множество."""
    for name, name_stems in vocabulary.items():
        if name_stems == tail_stems:
            return name
    return None
