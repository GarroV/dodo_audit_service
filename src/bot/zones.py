"""Зона из слов аудитора (задача T124, решения D047 и D048, правило 6).

Зону определяет человек. Правило 6 `docs/03-recording-rules.md` сформулировано
прямо: «Зону определяет человек или разбор его комментария, но не догадка
модели по внешнему виду кадра» — «стена за кассовой стойкой это зал, а не
мойка, даже если рядом стоит ведро». Спека того же требует словами аудитора:
«я хочу, чтобы зона бралась из моих слов».

Отдельного шага «выберите зону» в разговоре нет и не будет (D047): аудитор идёт
по точке с занятыми руками. Значит, единственный источник — сам комментарий, а
память о прошлой записи (D048) остаётся тем, чем её и назвал владелец: **первой
догадкой**, когда о зоне в этих словах ничего не сказано.

**Названия зон берутся из методики, а не из списка в коде.** Управляющая
компания правит `data/zones.csv`, и переименованная зона обязана начать
узнаваться сама. В коде живёт только то, чего в методике нет и быть не может, —
как эту зону называют вслух («зал» вместо полного названия зоны из методики). Список
короткий намеренно и растёт по факту, а не по фантазии: каждая строка ниже
взята либо из слов владельца, либо из формулировок боевых проверок в
`examples/`. Выдумывать за управляющую компанию, какими словами говорят
аудиторы, здесь нельзя — тем же правилом живёт словарь `recognize.fastpath`.

**Совпадение — по строке целиком, длинная сильнее короткой.** «Морозильный шкаф
в горячем цеху» — это горячий цех: строка «горячий цех» произнесена из двух
слов, а «морозильная камера» не произнесена вовсе. Названы две зоны разом —
разбор не выбирает за человека и молчит: пусть подставится память, которую
видно и меняют одним нажатием.
"""

from __future__ import annotations

import re

from src import domain
from src.recognize.cues import stems

from .texts import UI_LANGS

#: Как зоны называют вслух — то, чего в `data/zones.csv` нет.
#:
#: Источники каждой строки, и других нет:
#: * `dining` — «в зале», «Полы в зале», «за кассовой стойкой» из боевых
#:   проверок `examples/`; «кассовая зона» — слова владельца при решении D064.
#: * `dough` — «Тестомес не накрыт» из боевой проверки Белград-2; «мучной цех» —
#:   слова владельца из ответа 03.09.2026 («мучной цех, на дрожжах нет
#:   маркировки»), пойманные приёмкой: методика называет зону тестомесильным
#:   цехом, а вслух её называют мучным.
#: * `freezer` — «морозилка», обиходная форма названия из методики.
#:
#: Чего здесь намеренно НЕТ: «холодильник» и «морозильный шкаф». Это
#: оборудование, и в боевых проверках оно стоит в горячем цехе, а не в
#: одноимённой камере — короткое слово утащило бы запись в чужую зону.
SPOKEN: dict[str, tuple[str, ...]] = {
    "dining": ("зал", "касса", "кассовая"),
    "dough": ("тестомес", "мучной цех"),
    "freezer": ("морозилка",),
}

#: Чем разрезается название зоны на самостоятельные имена: составное имя зоны —
#: это два имени одного места, и произносят их по отдельности.
_SPLIT = re.compile(r"[/,]|\sи\s|\sand\s")


def _names(code: str, title: str) -> list[str]:
    return [part.strip() for part in _SPLIT.split(title) if part.strip()]


def phrases() -> dict[str, tuple[frozenset[str], ...]]:
    """Основы слов каждого имени зоны: код зоны → набор произносимых строк.

    Методика читается на каждом обращении, а не кешируется: её подкладывают
    томом снаружи, и кеш означал бы работу по старым названиям до перезапуска
    (тем же живёт `recognize.cues.load_cues`).
    """
    out: dict[str, tuple[frozenset[str], ...]] = {}
    for zone in domain.list_zones():
        names = [name for lang in UI_LANGS for name in _names(zone.code, zone.title(lang))]
        names.extend(SPOKEN.get(zone.code, ()))
        found = {frozenset(s) for name in names if (s := stems(name))}
        out[zone.code] = tuple(found)
    return out


def zone_from_words(note: str) -> str | None:
    """Код зоны, названной в этих словах. Не названа или названы две — `None`.

    `None` — обычный ответ, а не отказ: он означает «зону подставит память»
    (D048), и на боевых комментариях так заканчивается большинство записей.
    """
    words = stems(note)
    if not words:
        return None
    # Длина совпавшего имени — мера того, насколько это имя произнесли, а не
    # задели одним словом: имя из двух основ весомее имени из одной.
    best: dict[str, int] = {}
    for code, names in phrases().items():
        for name in names:
            if name <= words:
                best[code] = max(best.get(code, 0), len(name))
    if not best:
        return None
    top = max(best.values())
    winners = [code for code, size in best.items() if size == top]
    return winners[0] if len(winners) == 1 else None
