"""Чтение проверки так, чтобы бот не онемел ни на одной форме порчи (T126).

Состояние проверки ведёт блок `domain`, и читает его бот через `get_state`.
Беда в том, что порча приходит в этот вызов **разными дверями**, а отказом
предметной области оказывается не всякая:

| Форма порчи | Что бросает `domain.get_state` |
|---|---|
| пустой файл, обрезанный JSON, список вместо объекта | `DomainError` |
| двоичный мусор | `UnicodeDecodeError` |
| поле `findings` не список | `TypeError` |
| нет прав на чтение | `PermissionError` |
| чужая структура JSON | ничего: возвращает пустую «проверку» |
| каталог вместо файла | ничего: возвращает `None` — «не начата» |

Первые три бот разбирал, остальные пять — нет. Три средних роняли каждый вход,
включая последний рубеж (`app.on_unexpected_error`), и аудитор не получал
**ничего**. Две нижних не роняли ничего и потому были хуже: `/start` показывал
чужой JSON как незавершённую проверку с пустыми полями, а каталог — как чистый
лист, и следующая «Новая проверка» затирала лежащее рядом молча.

Поэтому весь блок `bot` читает проверку отсюда, а не напрямую. Здесь любая
неудача чтения приводится к одному типу — `DomainError`, — и дальше её ловят
те же `except DomainError`, что и раньше: `/start` показывает выход с кнопкой,
остальные входы доходят до последнего рубежа человеческим текстом.

**Корень при этом не здесь.** `src/domain/state.py::_read_raw` оборачивает
только `json.JSONDecodeError` и пропускает `OSError`, а `_inspection` не
проверяет тип `raw["findings"]` — чинить это надо в блоке `domain`. Пока не
починено, бот обязан отвечать в любом случае, и обёртка ниже — именно об этом,
а не о подмене чужой ответственности.
"""

from __future__ import annotations

from pathlib import Path

from src import domain
from src.domain.config import check_environment
from src.domain.engine import state_file
from src.domain.errors import DomainError


def state_path(chat_id: int) -> Path:
    """Где лежит состояние этого чата.

    Файл бот не открывает — это дело блока `domain` (решение D007). Путь нужен
    ради двух вещей: назвать его в журнале тому, кто будет чинить, и отличить
    «проверка не начата» от «на месте проверки лежит что-то другое».
    """
    return state_file(chat_id, check_environment())


def read_inspection(chat_id: int) -> domain.Inspection | None:
    """Проверка этого чата, `None` — если она не начата, отказ — во всех прочих случаях.

    Отказ всегда `DomainError`, каким бы исключением ни ответило чтение: тип
    отказа — часть контракта для вызывающего, и разбирать в каждом роутере
    `PermissionError` отдельно от `TypeError` означало бы забыть третий.
    """
    path = state_path(chat_id)
    try:
        inspection = domain.get_state(chat_id)
    except DomainError:
        # Уже разобранный отказ с путём внутри — пересказывать его нечем.
        raise
    except Exception as exc:
        raise DomainError(
            f"Состояние проверки не читается: {path} ({type(exc).__name__}: {exc}). "
            f"Файл не тронут — разбирать руками"
        ) from exc

    if inspection is None:
        # `read_state` отвечает `None` и на «файла нет», и на «файл не файл»:
        # он смотрит `path.is_file()`. Первое — обычная жизнь, второе — поломка,
        # и звать её чистым листом нельзя: следующая проверка пишется поверх.
        if path.exists() or path.is_symlink():
            raise DomainError(
                f"На месте состояния проверки лежит не файл проверки: {path}. "
                f"Начать новую поверх значило бы стереть то, что там лежит, — "
                f"разбирать руками"
            )
        return None

    if not inspection.date:
        # Дату ставит движок сам (сегодняшнюю, если не задана), поэтому
        # проверки без даты не бывает. Пустая дата означает, что разобран
        # чужой JSON: полей проверки в нём нет, а пустая «незавершённая
        # проверка» на `/start` — приглашение затереть чужое содержимое.
        raise DomainError(
            f"Состояние проверки не похоже на проверку: {path} — в нём нет даты. "
            f"Файл не тронут — разбирать руками"
        )
    return inspection
