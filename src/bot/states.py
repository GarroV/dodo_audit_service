"""Состояния диалога старта проверки (T050, T051, T052).

Только шаги мастера «Новая проверка» — они не переживают перезапуск бота
(`MemoryStorage`), и это осознанный выбор: пока проверка не начата вызовом
`domain.start_inspection`, ни один факт ещё не сохранён — потерять нечего,
пользователь просто нажимает «Новая проверка» заново.

Приём материала (`routers/material.py`) намеренно НЕ описан состоянием FSM:
после перезапуска бота файл проверки (`inspection.json`) на месте, а значит
хендлеры материала опираются на `domain.get_state(chat_id)`, а не на память
диспетчера — так прерванная проверка продолжается без дополнительного шага
«восстановить прогресс» (контракт блока, пункт про перезапуск контейнера).
"""

from __future__ import annotations

from aiogram.fsm.state import State, StatesGroup


class StartFlow(StatesGroup):
    """Пошаговый мастер начала проверки: пиццерия → вид → язык отчёта."""

    #: Ждём текст с названием пиццерии.
    waiting_unit = State()
    #: Ждём тап по одной из кнопок вида проверки.
    waiting_kind = State()
    #: Ждём тап по одной из кнопок языка отчёта.
    waiting_lang = State()


class EditFlow(StatesGroup):
    """Правка формулировки записи прямо в чате (T056).

    Единственный шаг, которому нужна память диспетчера: бот спросил новую
    формулировку и обязан понять, что следующее текстовое сообщение — ответ на
    вопрос, а не комментарий к кадру. Всё остальное в правках решается кнопками
    и памяти не требует.

    Переживать перезапуск этому состоянию незачем: запись уже зафиксирована и
    лежит в файле, а незаданный вопрос аудитор задаст кнопкой заново.
    """

    #: Ждём текст новой формулировки; номер записи лежит в данных состояния.
    waiting_text = State()
