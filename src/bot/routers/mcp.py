"""Пункт меню «Установка MCP»: готовая команда для терминала (T209, решение D087).

Пункт назван владельцем и устроен как в соседнем продукте: человек берёт из
чата строку и вставляет её в терминал. Отличие ровно одно, и оно по существу.

**Токена в команде нет, и это не осторожность, а единственный честный вариант.**
У соседнего продукта токен в строке стоит потому, что он там ЛИЧНЫЙ по
устройству: бот выпускает его на конкретный Telegram ID, хранит хэшем, старый
при перевыпуске умирает. Здесь всё иначе (`src/mcp/config.py`): токены задаёт
человек в `.env` записями «арендатор=токен», принадлежат они СТОРОНЕ, а не
человеку, и открывают всю её историю проверок. Единственное, что бот знает о
собеседнике, — что его ID стоит в общем списке `ALLOWED_TELEGRAM_IDS`; связи
«этот человек — этот токен» у него нет ни в каком виде. Значит, любой
напечатанный токен был бы выдан наугад: одному он предназначен, всем остальным
— нет, а различить их бот не может. Плюс к тому напечатанный токен остаётся в
переписке навсегда и пересылается одним движением, а отозвать его здесь — это
правка `.env` и перезапуск сервера, то есть отъём доступа у всех, кто им
пользуется.

Поэтому токен в команде — заглушка, и рядом сказано, что он личный и откуда
его берут. Личные токены, выпускаемые ботом на человека (как у соседа), — это
своя задача со своим хранилищем, отзывом и хэшированием; до неё команда честнее
недоговорит, чем отдаст чужой доступ.

**Адрес сервера бот не угадывает.** Он не ходит в MCP-сервер (блоки `bot` и
`mcp` — пиры, друг друга не импортируют, `pyproject.toml`), а тот слушает петлю
и наружу не публикуется — значит, адрес, который человек пишет в команде, это
адрес ЕГО машины или его туннеля, а не то, на чём сервер поднялся. Стенд
называет его переменной, а не называет — на месте адреса стоит такая же
заглушка, как у токена.
"""

from __future__ import annotations

import os

from aiogram import Router
from aiogram.filters import Command
from aiogram.types import Message

from ..lang import chat_ui_lang
from ..texts import t

#: Имя команды. Она же объявляется в меню телеграма (`app.MENU_COMMANDS`):
#: пункт меню владелец и назвал, а команда, о которой нигде не сказано, — то же
#: самое, что её отсутствие.
MCP_COMMAND = "mcp"

#: Адрес MCP-сервера, который бот ПЕЧАТАЕТ в команде установки. Не адрес, куда
#: бот ходит: он туда не ходит вовсе.
#:
#: Своя переменная, а не `MCP_HOST`/`MCP_PORT` соседнего блока, и причин две.
#: Первая — блоки пиры и друг друга не импортируют, а вторая важнее: сервер
#: слушает петлю (`127.0.0.1`), и человеку с другой машины эта строка не
#: подходит — он идёт туннелем, и в команде у него стоит свой адрес. Это разные
#: факты, и копией одного другой не является.
MCP_URL_VAR = "BOT_MCP_URL"


def setup_url(lang: str) -> str:
    """Адрес для команды установки — из окружения стенда или заглушка.

    Пусто — не отказ: пункт меню обязан работать и на стенде, где адрес никто
    не задавал, а заглушка ЗАГЛАВНЫМИ стоит в строке ровно там же, где стоял бы
    адрес, и видна человеку. Подставить сюда петлю по умолчанию значило бы
    выдать догадку за настройку — и человек искал бы, почему «готовая» команда
    не соединяется.
    """
    return (os.environ.get(MCP_URL_VAR) or "").strip() or t("mcp.url_unknown", lang)


def build_mcp_router() -> Router:
    """Роутер установки MCP: одна команда и два сообщения."""
    router = Router(name="mcp")

    @router.message(Command(MCP_COMMAND))
    async def on_mcp(message: Message) -> None:
        """Объяснение и команда — РАЗНЫМИ сообщениями.

        Не для красоты: сообщение в телеграме копируется целиком одним
        движением, и команда, склеенная с объяснением, приезжала бы в терминал
        вместе с ним. Порядок такой же, как у соседнего продукта: сначала о чём
        речь и про личный токен, следом сама строка.
        """
        lang = chat_ui_lang(message.chat.id)
        await message.answer(t("mcp.setup", lang))
        await message.answer(t("mcp.command", lang, url=setup_url(lang)))

    return router
