"""Последний рубеж нажатий: кнопка, которую некому обработать (T134, issue #105).

Сообщения с кнопками висят в чате месяцами. Аудитор пролистал переписку вверх,
нажал на предложение позапрошлой проверки — и до этой задачи не получал
**ничего**: ни сообщения, ни ответа на само нажатие. Второе хуже первого.
Telegram ждёт `answerCallbackQuery` и, не дождавшись, крутит человеку часики до
собственного таймаута — то есть продукт выглядит зависшим, а не отказавшим.

Проверено фактом: `start:kind:0` (вид проверки в старом формате кода) давал
ноль вызовов API. Тот же класс — кнопка снятого обработчика (`rec:fast` жил до
T121) и кнопка шага, который уже пройден.

**Рубеж стоит последним роутером в диспетчере** (`src/bot/app.py`) и фильтра
данных не имеет вовсе. Оба свойства обязательны и связаны: без фильтра он
перехватил бы каждое нажатие, стой он раньше живых обработчиков, — а с фильтром
по списку известных кодов он пропускал бы ровно то, ради чего написан, потому
что список кодов прошлых версий продукта неизвестен по построению.

Отвечать бот обязан **всегда, а канала у ответа два**. Обычный — сообщение в
чат. Но у нажатия старше 48 часов Telegram не кладёт сообщения вовсе (тот же
случай, что стережёт `tests/test_bot_callback_edges.py`), и чата бот не знает.
Тогда единственный канал — текст самого `answerCallbackQuery`, всплывающим
окном: короткого объяснения хватает, чтобы человек не считал продукт зависшим.

Текст не обещает «старая версия» категорично намеренно. Кнопка бывает и своя,
и текущей версии — просто из шага, который уже пройден, — и обещать человеку
причину, которой мы не знаем, значит врать ему в единственной фразе, которую он
здесь прочитает. Поэтому названы обе возможности и один надёжный выход.
"""

from __future__ import annotations

import logging

from aiogram import Router
from aiogram.types import CallbackQuery, Message

from ..lang import chat_ui_lang
from ..texts import default_ui_lang, t

logger = logging.getLogger(__name__)


def build_fallback_router() -> Router:
    """Роутер последнего рубежа. Включается в диспетчер ПОСЛЕДНИМ."""
    router = Router(name="fallback")

    @router.callback_query()
    async def on_stale_button(callback: CallbackQuery) -> None:
        message = callback.message
        # Код кнопки — в журнал: какие именно старые кнопки жмут живые люди,
        # узнать больше неоткуда, а от этого зависит, какие из них стоит
        # оживить, а не объяснять.
        logger.info("нажата кнопка, которую некому обработать: %r", callback.data)
        if not isinstance(message, Message):
            # Чата нет — сообщение отправлять некуда. Ответ на нажатие остаётся
            # единственным каналом, и без окна человек его не увидит.
            await callback.answer(t("error.button_gone", default_ui_lang()), show_alert=True)
            return
        # Часики снимаются ПЕРВЫМ действием: сообщение может и не уйти (чат
        # закрыт, телеграм отказал), а зависший интерфейс — это то, ради чего
        # задача и заведена.
        await callback.answer()
        await message.answer(t("error.button_gone", chat_ui_lang(message.chat.id)))

    return router
