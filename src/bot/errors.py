"""Отказы блока `bot`.

Отдельные от `domain.errors`: у бота свои причины не подниматься или не принять
сообщение, и путать их с отказами предметной области не стоит — читатель кода
должен видеть по типу исключения, чей это контракт.
"""

from __future__ import annotations


class BotError(Exception):
    """Базовый отказ блока `bot`."""


class BotConfigError(BotError):
    """Окружение бота непригодно: нет токена, списка ID или режим неизвестен.

    Поднимается на старте — бот не должен слушать Telegram, отвечая всем подряд
    или падая на первом обновлении вместо явного отказа при запуске.
    """


class BotTextError(BotError):
    """Текст интерфейса не собрался: нет ключа, языка или параметра.

    Ошибка программиста, а не аудитора, поэтому она падает, а не заменяется
    подстановкой по умолчанию: «Записей: {findings}» в чате читается как
    сломанный бот, и заметит это только человек на точке.
    """
