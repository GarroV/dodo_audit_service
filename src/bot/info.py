"""Информационная часть проверки: какие поля спрашиваются и чем они разные (T158).

Решения D069 и D070. Спрашивается она в конце — после подтверждения завершения
и **до** сборки отчёта, иначе ответы в документ уже не попадут.

**Полей семь, и это не весь список `info` в методике.** Из неё выброшены два
вида пунктов, и оба намеренно:

* `INF02` (вид проверки) — его задаёт мастер начала проверки. Спросить второй
  раз значило бы отнять у аудитора то, что он уже сделал.
* `INF09`–`INF11` (настройки печи, показания оборудования, фото продукта) — это
  фотофиксация, и она работает обычным потоком кадров: замеры ложатся записями
  класса `D0` среди находок (T057).

**Способов ввода четыре, а видов поля три.** Свободный текст (`INF01`, `INF06`,
`INF08`) принимается написанным, наговоренным голосом или подписью к кадру; да
и нет (`INF03`, `INF04`) — кнопками; даты (`INF05`, `INF07`) — текстом или
голосом с разбором. Четвёртый способ — не вид поля, а способ ввода: голос
проходит через расшифровку и показывается ДО записи (D069).

**Ни одно поле не обязательно** (допущение D070). Аудитор в конце обхода не
должен упираться в семь обязательных вопросов; пропущенное поле не печатается
вовсе, а срок плана действий при пропуске падает на прежний расчёт движка
(`report.plan_due_date`: дата проверки плюс `plan_due_days`).

**Вопрос берётся из методики, а не из каталога текстов.** Партнёр видит в
отчёте формулировку пункта (`engine/report.py` подписывает поле его вопросом),
и спрашивать аудитора другими словами значило бы развести два текста об одном.
Отсюда же следствие: поля, которого в методике нет, бот не спрашивает — состав
информационной части задаёт управляющая компания своим чек-листом, а не код.
"""

from __future__ import annotations

import re
from dataclasses import dataclass
from datetime import date

from src import domain
from src.domain.errors import DomainError

#: Свободный текст: пишется, наговаривается или приходит подписью к кадру.
KIND_TEXT = "text"
#: Да или нет — кнопками.
KIND_YES_NO = "yes_no"
#: Дата (у `INF05` — с временем): текстом или голосом, с разбором.
KIND_DATE = "date"


@dataclass(frozen=True)
class InfoField:
    """Одно поле информационной части: код пункта и способ ввода."""

    code: str
    kind: str


#: Порядок — порядок чек-листа, и он же порядок в отчёте: движок печатает поля
#: в том порядке, в каком их записали. Спрашивать вразнобой значило бы получить
#: вразнобой и в документе партнёру.
FIELDS: tuple[InfoField, ...] = (
    InfoField("INF01", KIND_TEXT),
    InfoField("INF03", KIND_YES_NO),
    InfoField("INF04", KIND_YES_NO),
    InfoField("INF05", KIND_DATE),
    InfoField("INF06", KIND_TEXT),
    InfoField("INF07", KIND_DATE),
    InfoField("INF08", KIND_TEXT),
)


def question(field: InfoField, lang: str, *, chat_id: int) -> str | None:
    """Вопрос пункта словами — или ничего, если пункта в методике нет.

    Отсутствие пункта не отказ и не молчание: состав информационной части
    задаёт управляющая компания, и методика без `INF08` означает ровно то, что
    отзыв о тестовом заказе в ней не спрашивают. Тот же урок, что D068 и D075
    про необязательные файлы методики: недостающие данные превращают шаг в
    пропущенный, а не в отказ в руках аудитора.
    """
    try:
        return domain.get_item(field.code, chat_id=chat_id).question(lang)
    except DomainError:
        return None


def fields_to_ask(lang: str, *, chat_id: int) -> tuple[tuple[InfoField, str], ...]:
    """Поля, которые есть в этой методике, вместе с их вопросами.

    Методика здесь — издание ТОЙ проверки (T169, T225): состав информационной
    части задаёт управляющая компания, и переиздание посреди выезда меняло бы
    набор вопросов на середине.
    """
    asked = []
    for field in FIELDS:
        text = question(field, lang, chat_id=chat_id)
        if text:
            asked.append((field, text))
    return tuple(asked)


#: Разделители даты, которые встречаются в живой записи: точка, дефис, косая.
_DATE = re.compile(r"^\s*(\d{1,4})\s*[.\-/]\s*(\d{1,2})\s*[.\-/]\s*(\d{2,4})")
#: Время рядом с датой: «18:30», «18 30», «в 18:30».
_TIME = re.compile(r"(?<!\d)([01]?\d|2[0-3])\s*[:.\s]\s*([0-5]\d)(?!\d)")

#: Как дата уезжает в отчёт партнёру. Совпадает с тем, как их печатает движок
#: (`engine/report.py: fmt_date`), и письмо такую строку пропускает как есть —
#: то есть срок плана действий читается человеком, а не машиной.
DATE_FORMAT = "%d.%m.%Y"


def parse_date(text: str, *, today: date | None = None) -> str | None:
    """Разобрать дату в записываемый вид — или ничего, если это не дата.

    Форматы приняты те, которыми люди пишут дату в чате: `14.09.2026`,
    `14-09-2026`, `14/09/2026` и `2026-09-14`. Двузначный год достраивается до
    текущего века: `14.09.26` — это 2026 год, а не 26-й.

    Время, если оно названо, остаётся рядом с датой: `INF05` спрашивает дату **и
    время** созвона, и терять половину ответа нельзя.

    Ничего не возвращается там, где разобрать не удалось. Молча записать
    неразобранное значило бы отправить партнёру в отчёт «завтра после обеда» в
    поле, которое читает письмо как срок.
    """
    hit = _DATE.match(text)
    if hit is None:
        return None
    first, second, third = (int(part) for part in hit.groups())
    if len(hit.group(1)) == 4:
        year, month, day = first, second, third
    else:
        day, month, year = first, second, third
        if year < 100:
            century = (today or date.today()).year // 100 * 100
            year += century
    try:
        parsed = date(year, month, day)
    except ValueError:
        # Разобрали числа, но такой даты нет: 31.02 или 45-й месяц. Это не
        # дата, и записывать её нельзя ровно так же, как неразобранный текст.
        return None
    stamp = parsed.strftime(DATE_FORMAT)
    tail = text[hit.end() :]
    clock = _TIME.search(tail)
    if clock is None:
        return stamp
    return f"{stamp} {int(clock.group(1)):02d}:{clock.group(2)}"
