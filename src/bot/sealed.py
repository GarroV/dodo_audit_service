"""Сданная проверка не правится (задача T201, решение владельца D080).

Владелец, дословно: «отчеты мы не правим. в будущем доабвим функционал, сейчас
мы можем только удалить его, или завести новый».

**Что такое «сдана».** Признака завершённости у движка нет, и бот его не
выдумывает: он опирается на то, что сделал сам, — собрал отчёт и отдал его
аудитору в чат (`sidecar.handed_over`). До T201 сданной звалась проверка, в
которой с тех пор не прибавилось записей, — счёт сверялся с делом. Теперь
дописывать нечего и незачем: сданная проверка запечатана, число записей в ней
меняться не может, и признак вернулся к тому, чем он и был по смыслу.

**Почему запрет, а не удобство.** История точки узнаёт проверку по слепку
содержимого. Дописанная после сдачи запись меняет содержимое, слепок больше не
совпадает — и тот же обход ложится в историю ВТОРОЙ строкой. Разделить их
потом нечем: завершённая проверка в базе не правится и не удаляется.

**Закрыт каждый вход, а не кнопка.** Материал попадает в проверку кадром,
комментарием, нажатием под старой записью, ответом на сообщение бота и
командой `/undo`. Закрытая кнопка при открытом кадре была бы не запретом, а
его видимостью, поэтому проверка стоит там, где проверка МЕНЯЕТСЯ.

**Отказ объясняет и даёт выход.** Аудитор на точке: ему нужно понимать, почему
нельзя и что делать. Поэтому рядом с отказом — обе двери, названные владельцем:
начать новую проверку или убрать сданную из чата.
"""

from __future__ import annotations

from aiogram.types import Message

from . import sidecar
from .keyboards import sealed_keyboard
from .texts import t


def is_sealed(chat_id: int) -> bool:
    """Отдан ли по проверке этого чата отчёт. Проверки нет вовсе — не сдана."""
    return sidecar.handed_over(chat_id)


async def refuse(message: Message, lang: str) -> None:
    """Сказать, что проверка сдана, и показать обе двери.

    Текст один на все входы намеренно: аудитор упирается в запрет то кадром, то
    кнопкой, и разные слова об одном и том же читались бы как разные запреты.
    """
    await message.answer(t("sealed.blocked", lang), reply_markup=sealed_keyboard(lang))
