"""Что в этом чате ждёт нажатия кнопки: вопрос «Разобрать?» и показанные предложения.

Хранится только в памяти, и это осознанный выбор, а не упрощение. Всё, что
переживает перезапуск, уже лежит на диске: сама проверка — в `inspection.json`
(блок `domain`), кадры, источники записей и последняя зона — в заметках бота
(`src/bot/sidecar.py`). Здесь же живёт разговор в моменте: кадр, на который
задан вопрос, и пять кандидатов, показанных кнопками. Переживи они перезапуск,
аудитор нажал бы кнопку под ответом модели, которого больше нет ни у кого в
памяти, и получил бы запись, собранную по устаревшему разбору.

Поэтому нажатие на кнопку, которой бот уже не помнит, — это не ошибка, а
нормальный исход: он отвечает «предложение устарело», и аудитор присылает кадр
заново. Молчание в этом месте читалось бы как «бот завис».

**Предложений в чате бывает несколько разом** (задача T206, решение D081).
Пачка кадров разбирается по кадру, и отбивка приходит списком отдельными
сообщениями — по сообщению на кадр. Нажатие адресует ТО предложение, под
сообщением которого стоит кнопка: `callback_data` кнопки об этом не знает
(в ней едет номер кандидата), зато телеграм присылает само сообщение. Отсюда
карта «сообщение бота → предложение», и нажатие ищется по ней.

Раньше предложение было одно на чат, и новое вытесняло старое. Вытеснение
осталось для одиночного потока — кнопки под позапрошлым кадром не должны
стрелять, — но на пачку не распространяется: её предложения живут все сразу и
до тех пор, пока аудитор не разберёт список. Разница названа полем
`Proposal.batch`, а не догадкой по числу живых предложений.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from itertools import count

from src.recognize.fastpath import FastItem
from src.recognize.manual import ManualCandidate
from src.recognize.models import Candidate


@dataclass(frozen=True)
class Offer:
    """Кадры, на которые задан вопрос «Разобрать?» и ждём нажатия (T067, D046).

    `anchor_id` — первый `message_id` группы кадров: он уходит в `callback_data`
    и по нему же группа снимается с очереди ожидания комментария. Кодом, а не
    формулировкой — принцип проекта.

    `question_id` — сообщение самого бота с кнопкой. Нужен, чтобы снять кнопку,
    когда аудитор вместо нажатия прислал комментарий: слова аудитора сильнее
    догадки по картинке (D046), и висящая кнопка предлагала бы разобрать кадр,
    по которому запись уже сделана.
    """

    anchor_id: int
    file_ids: tuple[str, ...]
    question_id: int | None = None


@dataclass(frozen=True)
class Proposal:
    """Показанные кнопками кандидаты и всё, что нужно для фиксации (T055).

    `source` — откуда взялась запись: со слов аудитора или разбором кадра по
    нажатию (D044). Хранится здесь, потому что в момент нажатия кнопки другого
    места узнать это уже нет.

    `manual` не пуст, когда модель недоступна и перечень собран справочником
    (`recognize.manual_candidates`, T034). Тогда `candidates` пуст: это не
    предложения модели, а полный список для осознанного выбора человеком, и
    показывается он страницами.
    """

    file_ids: tuple[str, ...]
    source: str
    note: str = ""
    candidates: tuple[Candidate, ...] = ()
    manual: tuple[ManualCandidate, ...] = ()
    question: str = ""
    zone_hint: str = ""
    #: Зону назвал человек — в САМИХ этих словах или кнопкой зоны, — а не
    #: подставила память о прошлой записи (T124, D047/D048, T156). Отличать
    #: обязательно: запись по словам ложится без подтверждения, и выдать
    #: догадку за слова аудитора значит спрятать промах ровно там, где его
    #: некому заметить. Кнопка зоны стоит здесь наравне со словами: это тоже
    #: человек, а не прошлая запись, и оговорка о памяти была бы неправдой.
    zone_spoken: bool = False
    #: Кандидат, который аудитор выбрал, но зафиксировать пока нечем: модель не
    #: назвала зону, и её спрашивают кнопкой. Хранится здесь, потому что в
    #: `callback_data` кнопки зоны едет зона, а не выбор.
    picked: int | None = None
    #: Номер записи, которую этот разбор ПРАВИТ, а не заводит (T204, D081).
    #: Пусто — обычный разбор нового материала. Не пусто — аудитор ответил на
    #: сообщение бота с записью, и всё, что найдётся дальше — сверкой ли,
    #: моделью ли, ручным перечнем, — ложится в ту же запись. Адресат назван
    #: здесь, а не в момент нажатия: между показом кандидатов и кнопкой аудитор
    #: успевает прислать ещё кадр, и «последняя запись» к тому времени уже
    #: другая.
    correcting: int | None = None
    #: Пункт, найденный без модели по словам аудитора (T117, D063). Не пуст —
    #: значит, показано быстрое предложение, и модель по этому материалу ещё не
    #: звали: кнопка «Разобрать моделью» разбирает те же слова и тот же кадр.
    fast: FastItem | None = None
    #: Номер этого разговора о материале в хранилище. Кандидаты, вопрос о зоне,
    #: страницы ручного перечня и выбор класса — это один и тот же разговор,
    #: показанный разными сообщениями, и по номеру он опознаётся целиком: взятое
    #: предложение снимает со всех своих сообщений сразу, а не с последнего.
    #: Ноль — предложение, заведённое мимо хранилища (юнит-тесты).
    slot: int = 0
    #: Какой это кадр пачки и сколько их всего (T206, D081) — или ничего, если
    #: материал одиночный. Служит и признаком пачки, и её нумерацией в отбивке:
    #: список из пяти сообщений без номеров аудитор не соотнесёт с кадрами.
    #: Пачка — единственный случай, когда живых предложений в чате несколько, и
    #: неадресованное нажатие по ней отвечает отказом, а не догадкой.
    batch: tuple[int, int] | None = None
    #: Сообщение АУДИТОРА, из которого вырос этот материал (T205). Ответом на
    #: него аудитор присылает кадр, и кадр уходит в получившуюся запись. Хранится
    #: здесь, потому что в момент нажатия кнопки взять его больше неоткуда:
    #: `callback.message` — это сообщение бота, а не человека.
    origin: int | None = None


@dataclass
class ChatPending:
    """Ожидания одного чата."""

    offers: dict[int, Offer] = field(default_factory=dict)
    #: Живые предложения по номеру разговора. Одиночный поток держит здесь одно,
    #: пачка кадров (T206) — по одному на кадр.
    live: dict[int, Proposal] = field(default_factory=dict)
    #: Сообщения бота с кнопками → номер разговора, к которому они относятся.
    at_message: dict[int, int] = field(default_factory=dict)
    #: Последнее показанное предложение: им отвечает нажатие, о сообщении
    #: которого ничего не известно.
    current: int | None = None


class PendingStore:
    """Ожидания по чатам, лениво создаются."""

    def __init__(self) -> None:
        self._chats: dict[int, ChatPending] = {}
        self._slots = count(1)

    def _chat(self, chat_id: int) -> ChatPending:
        if chat_id not in self._chats:
            self._chats[chat_id] = ChatPending()
        return self._chats[chat_id]

    def next_slot(self) -> int:
        """Номер нового разговора о материале. Сквозной, а не по чату: он и не
        обязан быть коротким, а сквозной не даст спутать чаты при отладке."""
        return next(self._slots)

    # --- вопрос «Разобрать?» (T067) ---

    def offer(self, chat_id: int, offer: Offer) -> None:
        self._chat(chat_id).offers[offer.anchor_id] = offer

    def take_offer(self, chat_id: int, anchor_id: int) -> Offer | None:
        """Забрать вопрос по нажатию. Второе нажатие той же кнопки — уже `None`."""
        return self._chat(chat_id).offers.pop(anchor_id, None)

    def take_offer_for(self, chat_id: int, file_ids: tuple[str, ...]) -> Offer | None:
        """Забрать вопрос, заданный по этим кадрам: комментарий их забрал.

        Ищем по кадрам, а не по номеру сообщения, потому что комментарий
        связывается с материалом (`src/bot/material.py`), а тот знает кадры, а
        не сообщения, которыми они пришли.
        """
        chat = self._chat(chat_id)
        wanted = set(file_ids)
        for anchor_id, offer in list(chat.offers.items()):
            if wanted.intersection(offer.file_ids):
                del chat.offers[anchor_id]
                return offer
        return None

    # --- показанные предложения (T055, T206) ---

    def propose(self, chat_id: int, proposal: Proposal, *, at: int | None = None) -> None:
        """Запомнить показанное; `at` — сообщение бота, под которым стоят кнопки.

        Одиночное предложение вытесняет предыдущее одиночное: кнопки под ним уже
        не отвечают ничему живому, и держать их означало бы дать аудитору
        зафиксировать разбор позапрошлого кадра.

        Предложения ПАЧКИ (T206) не вытесняют ничего и не вытесняются: список
        нарушений на то и список, что аудитор разбирает его не по порядку и не
        за один раз, а между двумя нажатиями успевает прислать ещё кадр. Живут
        они до своего нажатия или до начала новой проверки (`forget`).

        `at` не обязателен: сообщение, о номере которого ничего не известно
        (подделка телеграма в тесте, отказ отправки), просто не попадает в карту
        — тогда нажатие ищет предложение по последнему показанному, как раньше.
        """
        chat = self._chat(chat_id)
        if proposal.batch is None:
            for slot, живое in list(chat.live.items()):
                if slot != proposal.slot and живое.batch is None:
                    self._drop(chat, slot)
        chat.live[proposal.slot] = proposal
        chat.current = proposal.slot
        if at is not None:
            chat.at_message[at] = proposal.slot

    def proposal(self, chat_id: int, *, at: int | None = None) -> Proposal | None:
        """Предложение, под сообщением которого нажата кнопка (`at`), — не забирая.

        Не забирая, потому что перелистывание страниц ручного перечня не должно
        съедать предложение.

        **Сообщение опознано — ответ только по нему.** Разговор известен точно, и
        если среди живых его больше нет (запись по нему уже сделана, кнопку
        нажали второй раз), то это «предложение устарело», а не повод ответить
        чужим. Отвечай тут последнее показанное — нажатие на использованную
        кнопку записало бы материал СОСЕДНЕГО кадра, и заметить это было бы
        негде.

        Сообщение неизвестно — отвечает последнее показанное, и это верный
        ответ, пока предложение в чате одно (перезапуск бота, кнопка из старого
        сообщения). Как только их несколько (пачка, T206), догадка запрещена по
        той же причине: она записала бы не тот кадр.
        """
        chat = self._chat(chat_id)
        if at is not None and at in chat.at_message:
            return chat.live.get(chat.at_message[at])
        current = None if chat.current is None else chat.live.get(chat.current)
        if current is not None and current.batch is not None:
            return None
        return current

    def take_proposal(self, chat_id: int, *, at: int | None = None) -> Proposal | None:
        """Забрать предложение: запись по нему уже сделана, второй раз нельзя.

        Забирается весь разговор целиком — со всеми сообщениями, которыми он
        показывался. Сними мы одно последнее, кнопка под первым сообщением того
        же разговора завела бы вторую запись по тому же кадру.
        """
        chat = self._chat(chat_id)
        taken = self.proposal(chat_id, at=at)
        if taken is not None:
            self._drop(chat, taken.slot)
        return taken

    @staticmethod
    def _drop(chat: ChatPending, slot: int) -> None:
        """Убрать разговор из живых.

        Сообщения этого разговора из карты НЕ убираются, и это не забывчивость:
        по ним нажатие узнаёт, к какому именно разговору относится кнопка, — и
        узнав, что разговор окончен, честно отвечает «устарело». Забудь мы их,
        то же нажатие искало бы предложение по последнему показанному и
        записало бы чужой кадр. Карта живёт до начала новой проверки
        (`forget`), а растёт она на одну строку на показанное сообщение.
        """
        chat.live.pop(slot, None)
        if chat.current == slot:
            chat.current = None

    def forget(self, chat_id: int) -> None:
        """Забыть всё: началась новая проверка, старые кнопки не должны стрелять."""
        self._chats.pop(chat_id, None)
