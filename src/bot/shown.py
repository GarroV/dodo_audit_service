"""Карты «сообщение → запись»: чем бот показал запись и из чего она выросла.

Аудитор правит запись ОТВЕТОМ на сообщение бота о ней и присылает к ней кадр
ОТВЕТОМ на свои же слова (решение D081), поэтому связь «сообщение → запись»
нужна в каждом месте, где запись показывается или заводится: при фиксации, при
правке кнопкой, при правке ответом. Мест этих несколько, а правило одно —
отдельный модуль ровно затем, чтобы оно не разъехалось между ними и чтобы
роутер правки не зависел от роутера разбора ради одной строки.

Хранит связи `sidecar`, здесь — только решение о том, что делать с отказом
заметок: он гасится, потому что запись уже сделана, а потеря привязки стоит
аудитору одного удобства, а не материала.
"""

from __future__ import annotations

import logging
from collections.abc import Callable

from aiogram.types import Message

from . import sidecar
from .errors import BotNotesError

logger = logging.getLogger(__name__)


def _quietly(запомнить: Callable[[], None], chat_id: int, n: int, потеря: str) -> None:
    """Записать в заметки, а отказ — в журнал: показ записи он ронять не должен.

    Молчанием это не становится: в журнале остаётся и запись, и то, чего из-за
    неё не будет, — иначе чинящий видел бы только «не работает ответом».
    """
    try:
        запомнить()
    except BotNotesError:
        logger.warning(
            "запись #%s в чате %s не попала в карту сообщений — %s",
            n,
            chat_id,
            потеря,
            exc_info=True,
        )


def remember(chat_id: int, sent: Message | None, n: int) -> None:
    """Запомнить сообщение, которым показана запись #`n`.

    Отказ заметок наружу не пускается: запись уже сделана и показана, а потеря
    привязки стоит аудитору одной возможности — поправить эту запись ответом;
    кнопки правки под ней остаются на месте. Уронить из-за неё показ значило бы
    поменять неудобство на настоящую потерю.

    `None` вместо сообщения приходит от подделок телеграма в тестах и от
    отправки, о которой ничего не известно: запоминать тогда нечего.
    """
    if sent is None:
        return
    _quietly(
        lambda: sidecar.remember_record(chat_id, sent.message_id, n),
        chat_id,
        n,
        "правка ответом на неё работать не будет",
    )


def remember_origin(chat_id: int, message_id: int | None, n: int) -> None:
    """Запомнить сообщение аудитора, из которого выросла запись #`n` (T205).

    Отказ заметок гасится по тому же правилу и по той же причине, что и у
    показа: запись уже сделана, а потеря привязки стоит одной возможности —
    прислать к ней кадр ответом на свои же слова. Кадр при этом не пропадает:
    он придёт обычным путём, с вопросом «Разобрать?».

    `None` вместо номера означает «сообщения аудитора у этой записи нет»: так
    приходит разбор кадра по кнопке, где слов не было вовсе.
    """
    if message_id is None:
        return
    _quietly(
        lambda: sidecar.remember_origin(chat_id, message_id, n),
        chat_id,
        n,
        "кадр ответом на свои слова в неё не попадёт",
    )
