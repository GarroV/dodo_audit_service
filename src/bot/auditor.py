"""Имя проверяющего по Telegram ID (задача T063, решение D032).

Аудитор своё имя не вводит: оно подставляется по ID отправителя и уходит в
шапку отчёта партнёру. Источника два и порядок между ними жёсткий:

1. карта `AUDITOR_NAMES` — имя в том виде, в каком его должен увидеть партнёр;
2. имя профиля Telegram — если ID в карте нет.

Профиль как запасной источник выбран сознательно: карта не обязательна, и
проверка не должна вставать из-за незаполненной переменной окружения. Цена в
том, что в отчёт попадёт имя профиля со всеми его эмодзи, поэтому подставленное
имя бот показывает аудитору сразу при старте проверки — молча оно не уезжает.

Обрезка по байтам (T128, переоткрытая часть, issue #103): имя профиля —
`first_name` + `last_name`, до 64 знаков каждое, и в них бывают эмодзи (4 байта
на знак). Отказать здесь нельзя — имя приходит из профиля, а не от аудитора в
этот момент, — поэтому `auditor_name` уже отдаёт имя, пригодное для имени
файла отчёта: обрезку с этим модулем не разминуть, она в форме кода, а не в
обещании звонящего.
"""

from __future__ import annotations

from collections.abc import Mapping

#: Бюджет имени аудитора В БАЙТАХ — часть общего бюджета имени файла отчёта.
#:
#: Движок собирает имя файла как «Аудит <точка> - <аудитор> - <дата>.pdf», а
#: предел имени файла на ext4 (боевая площадка, контейнер Linux, D053) — 255
#: байт. Замерено фактическим кодированием (python3, UTF-8): постоянная часть
#: формулы — слово «Аудит » (11 байт для кириллицы, худший случай против
#: «Audit » в 6 байт), два разделителя « - » (по 3 байта — 6 байт), дата
#: «дд.мм.гггг» (10 байт, только ASCII) и «.pdf» (4 байта) — итого 31 байт.
#: Остаётся 224 байта на название точки и имя аудитора вместе. Название точки
#: забирает 120 байт (`UNIT_NAME_BYTE_LIMIT` в `routers/start.py`, ровно 60
#: кириллических знаков — старый предел `UNIT_NAME_LIMIT` не тронут), имени
#: аудитора остаётся 100 байт — 50 кириллических знаков, живым именам с
#: запасом. Худший случай целиком: 31 + 120 + 100 = 251 ≤ 255.
AUDITOR_NAME_BYTE_LIMIT = 100

#: Обрезка обязана быть ВИДНА в самом имени — иначе аудитор не узнает, что в
#: шапке отчёта и в имени файла стоит не то имя, что у него в профиле.
_ELLIPSIS = "…"

#: Резать по границе слова, если она рядом, а не обрывать слово посередине.
#: «Рядом» — столько символов перед точкой обрезки по байтам.
_WORD_BOUNDARY_LOOKBACK = 20


def auditor_name(user_id: int, profile_name: str, names: Mapping[int, str]) -> str:
    """Как проверяющий будет назван в отчёте — уже пригодным для имени файла.

    Пустая строка не возвращается никогда: пустое поле в шапке отчёта выглядит
    как потерянные данные, а `Telegram <id>` — как то, что и есть, и по нему
    видно, чей ID добавить в `AUDITOR_NAMES`. Имя длиннее `AUDITOR_NAME_BYTE_LIMIT`
    байт в UTF-8 обрезается здесь же (T128) — оно уходит и в шапку отчёта, и в
    имя файла, и оба места должны получить одно и то же уже безопасное имя.
    """
    return _fit_within_bytes(
        _raw_auditor_name(user_id, profile_name, names), AUDITOR_NAME_BYTE_LIMIT
    )


def auditor_name_was_shortened(user_id: int, profile_name: str, names: Mapping[int, str]) -> bool:
    """Обрезалось ли имя ради бюджета имени файла — сказать об этом аудитору.

    Признака обрезки в самом `auditor_name` нет — он отдаёт готовую строку, а
    не пару (имя, флаг), чтобы существующие вызовы не различали, обрезано имя
    или нет. Этой функции он и нужен: старт проверки зовёт её отдельно, чтобы
    добавить в чат отдельную строку, а не молчать о подмене.
    """
    raw = _raw_auditor_name(user_id, profile_name, names)
    return _fit_within_bytes(raw, AUDITOR_NAME_BYTE_LIMIT) != raw


def _raw_auditor_name(user_id: int, profile_name: str, names: Mapping[int, str]) -> str:
    """Имя проверяющего ДО обрезки по байтам: карта, иначе профиль, иначе ID."""
    mapped = (names.get(user_id) or "").strip()
    if mapped:
        return mapped
    profile = profile_name.strip()
    if profile:
        return profile
    return f"Telegram {user_id}"


def _fit_within_bytes(name: str, limit: int) -> str:
    """Обрезать `name`, чтобы его UTF-8 представление уместилось в `limit` байт.

    Резать по СИМВОЛАМ, не по байтам: Python-строка режется по кодпоинтам, и
    многобайтовый символ (кириллица — 2 байта, эмодзи — обычно 4) разрубить
    пополам этим нельзя даже случайно — в отличие от среза по уже закодированным
    байтам, где такая ошибка тихо портит символ на границе.
    """
    if len(name.encode("utf-8")) <= limit:
        return name
    budget = limit - len(_ELLIPSIS.encode("utf-8"))
    if budget <= 0:
        return _ELLIPSIS
    cut = len(name)
    while cut > 0 and len(name[:cut].encode("utf-8")) > budget:
        cut -= 1
    lookback_from = max(0, cut - _WORD_BOUNDARY_LOOKBACK)
    boundary = name.rfind(" ", lookback_from, cut)
    if boundary > lookback_from:
        cut = boundary
    return name[:cut].rstrip() + _ELLIPSIS
