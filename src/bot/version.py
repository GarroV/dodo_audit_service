"""Версия сборки: чем именно отвечает этот процесс (T246, #201).

Значение кладётся в образ при сборке (`BUILD_SHA`, см. Dockerfile и
docker-compose.yml) и больше нигде не вычисляется: внутри контейнера нет ни
`.git`, ни каталога репозитория, поэтому спросить git о версии некому — это и
есть причина, по которой расхождение кода с образом было невидимым.

Незнание версии называется незнанием. Соблазн подставить что-нибудь
правдоподобное («latest», дату старта) здесь опаснее пустоты: по такому ответу
невозможно отличить собранный по процедуре образ от собранного мимо неё, а
именно это и надо было различить.
"""

from __future__ import annotations

import os

#: Что отвечаем, когда версия в образ не попала. Строка намеренно не выглядит
#: версией — её видно и в чате, и в логе.
UNKNOWN_VERSION = "неизвестна"

#: Имя переменной одно на Dockerfile, compose, смоук и код.
BUILD_SHA_VAR = "BUILD_SHA"


def build_version() -> str:
    """Версия сборки образа или `UNKNOWN_VERSION`, если её не заложили."""
    value = os.environ.get(BUILD_SHA_VAR, "").strip()
    return value or UNKNOWN_VERSION
