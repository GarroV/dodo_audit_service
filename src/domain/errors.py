"""Отказы блока `domain`.

Отдельные классы нужны не для красоты: бот показывает аудитору текст отказа, а
решает по типу — переспросить (`ValidationError`), предложить начать проверку
(`InspectionNotStarted`) или вообще не подниматься (`ConfigError`).
"""

from __future__ import annotations


class DomainError(Exception):
    """Базовый отказ предметной области."""


class ConfigError(DomainError):
    """Окружение непригодно: нет переменной, каталога методики или найден форк.

    Поднимается на старте и при каждом обращении к методике. Пустой чек-лист
    вместо исключения выглядел бы как честный ответ «нарушений не нашлось».
    """


class ValidationError(DomainError):
    """Значение отвергнуто до вызова движка: неизвестная зона, код, язык."""


class InspectionNotStarted(DomainError):
    """В этом чате проверка не начата — записывать нечего и считать нечего."""


class ChecklistVersionMismatch(DomainError):
    """Проверка помечена одной версией методики, а движок читает другую.

    Отметку ставят на старте, а считают потом — и между этими двумя моментами
    методику успевают издать заново: публикация версии (D049) переставляет
    указатель в каталоге, откуда движок берёт данные, а сценарий «прерванная
    проверка продолжается» есть в самой спеке. Посчитать в таком положении
    значит выдать оценку по новой методике под старой отметкой: запись уедет в
    базу выглядящей сравнимой с соседними, не будучи ею.

    Пересчитать по прежней методике блок не может: снимок версии лежит в
    хранилище другого блока, а `AUDIT_DATA_DIR` показывает только действующую.
    Молча переставить отметку тоже нельзя — D033 запрещает менять проверку
    задним числом. Поэтому отказ, а решение остаётся человеку
    (`sync_checklist_version`).
    """

    def __init__(self, message: str, *, recorded: str, current: str) -> None:
        super().__init__(message)
        self.message = message
        self.recorded = recorded
        self.current = current


class EngineError(DomainError):
    """Движок отказал.

    Текст берётся у самого движка: методику и её проверки блок не дублирует,
    но и не глотает — отказ уходит наружу как есть.
    """

    def __init__(self, message: str, *, code: int, command: str) -> None:
        super().__init__(message)
        self.message = message
        self.code = code
        self.command = command
