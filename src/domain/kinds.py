"""Вид проверки: код — сущность, слово — перевод (T152, задача #123).

Плановая, повторная, внеплановая — это перечень предметной области, а не набор
надписей на кнопках. Здесь он и живёт: раньше таблица стояла в клавиатурах
бота, и потому вид проверки существовал в системе только словом.

**Чем это кончалось тихо.** Слово писалось в проверку, уезжало в колонку базы и
переводилось обратно сопоставлением строк (`TYPE_EN` в `engine/report.py`) с
молчаливым возвратом исходника, если строка не совпала. Переименование вида —
хоть в интерфейсе, хоть в данных — ломало перевод без единой ошибки: партнёр
получал письмо со словом на чужом языке. Проверено запуском: мастер с
английским отчётом клал в проверку «Planned», а таблица движка знала это же
значение как «Scheduled», то есть за одним видом было закреплено два разных
английских слова.

Поэтому:

* **связывает код.** `Inspection.kind`, колонка базы, отпечаток проверки — код;
* **слово подставляется при печати, по языку печати.** Отсюда и только отсюда;
* **третий язык — строка в таблице,** а не правка кода. Язык — параметр.

Незнакомый код и незаведённый язык — отказ, а не откат на русский: молчаливый
откат поставил бы русское слово в шапку английского отчёта партнёру, и заметил
бы это партнёр, а не мы.
"""

from __future__ import annotations

from collections.abc import Mapping

from .errors import ValidationError

#: Код вида проверки → слово на каждом языке отчёта.
#:
#: Единственное место в системе, где вид проверки превращается в слово. Языки
#: перечислены здесь, а не выведены из `models.TEXT_LANGS`: набор языков
#: методики и набор языков, на которых мы умеем назвать вид проверки, — разные
#: вещи, и в тот день, когда они разойдутся, дырка обязана быть видна тестом
#: полноты таблицы, а не в шапке уже собранного отчёта.
INSPECTION_KINDS: Mapping[str, Mapping[str, str]] = {
    "planned": {"ru": "Плановая", "en": "Planned"},
    "repeat": {"ru": "Повторная", "en": "Repeat"},
    "unscheduled": {"ru": "Внеплановая", "en": "Unscheduled"},
}


def kind_title(code: str, lang: str) -> str:
    """Вид проверки словами. Язык — параметр, и он не всегда язык интерфейса.

    На кнопке мастера вид стоит на языке ИНТЕРФЕЙСА (аудитор читает его сам), а
    в шапке отчёта — на языке ОТЧЁТА (её читает партнёр). Одна функция на оба
    случая, разные аргументы.
    """
    titles = INSPECTION_KINDS.get(code)
    if titles is None:
        raise ValidationError(
            f"Вид проверки «{code}» неизвестен. Вид связывается кодом, а не формулировкой; "
            f"известные коды: {', '.join(INSPECTION_KINDS)}"
        )
    title = titles.get(lang)
    if title is None:
        raise ValidationError(
            f"Вид проверки «{code}» не заведён на языке «{lang}». Доступны: {', '.join(titles)}"
        )
    return title
