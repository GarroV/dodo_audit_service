#: Сборщик писем и отчётов. Лежит рядом с движком оценки, и путь к нему
#: выводится из уже известного пути: подменили каталог движка — подменились оба
#: скрипта разом.
REPORT_SCRIPT = AUDIT_SCRIPT.with_name("report.py")

#: Откуда взята методика. Словами, потому что это читает человек: снимок
#: версии и «боевая методика сама ею и является» — разные основания доверять
#: собранному письму.
FROM_SNAPSHOT = "stored snapshot of the version this inspection was scored by"
FROM_LIVE = "live methodology, which is that exact version"
FROM_SHELF = "snapshot the bot kept when this inspection was started"

#: Поля шапки письма: движок печатает их над текстом и подписывает ими
#: отправителя. Слой чтения отдаёт все четыре с T176 (`db.InspectionRow`:
#: `auditor`, `city`, `partner`, `contact`), и пустыми они приезжают теперь
#: только там, где пусты в базе.
#:
#: Перечень нужен не как константа-заплатка. Пустое поле шапки движок печатает
#: прочерком и выходит с нулевым кодом — письмо выглядит готовым, поэтому
#: недостающее называется в ответе вслух. Отсюда же `getattr` со значением по
#: умолчанию в `_cover`: перечень сверяется со СТРОКОЙ ЧТЕНИЯ на каждом вызове,
#: и поле, пропавшее из неё, станет недостающим в ответе, а не отказом
#: инструмента.
#:
#: Шапкой невосстановленное не исчерпывается: срок плана действий приходит из
#: информационной части и назван отдельно (`PLAN_DUE_FIELD`, T200). Он не поле
#: `inspections`, и пустым местом в письме он себя не выдаёт — движок
#: подставляет вместо него свой расчёт.
COVER_FIELDS = ("auditor", "city", "partner", "contact")

#: Чего не хватает письму, когда информационной части у записанной проверки нет
#: вовсе (T200). Названо отдельным именем, а не строкой по месту: его читают в
#: ответе инструмента и по нему же спрашивают тесты.
PLAN_DUE_FIELD = "action plan deadline"

#: Чего не хватает письму, собранному не на том языке, на котором записаны
#: находки (T220). Формулировка находки — слова аудитора, и переводить их не
#: полагается никому: машинный перевод отправил бы партнёру чужую формулировку
#: под подписью аудитора. Поэтому шапку и названия зон движок переводит, а
#: находки печатает как записаны — письмо выходит наполовину на другом языке,
#: и это НЕ дефект сборки, а известное свойство.
#:
#: Молчать о нём при этом нельзя, и по той же причине, что и о подставленном
#: сроке: пустое место в шапке видно прочерком, а связный текст на чужом языке
#: выглядит настоящим документом. Отправитель, не читающий язык записи, увидел
#: бы «готово к отправке» и отправил бы партнёру половину письма на языке,
#: которого тот может не знать.
FINDING_TEXT_FIELD = "finding wording in the letter language"

#: Чего не хватает письму, в котором у находки нет формулировки ВООБЩЕ (T237).
#: Слой чтения объявляет `FindingRow.text` как `str | None`, и `None` там
#: означает «строки перевода нет вовсе» — подменять её пустой строкой прямо
#: запрещено: «перевода нет» стало бы неотличимо от «аудитор ничего не написал».
#: Письму оба случая обходятся одинаково, потому что оба доезжают до движка
#: пустым `evidence`.
#:
#: **И пустого места в письме при этом не появляется** — проверено запуском,
#: и это хуже, чем предполагалось при заведении задачи. Движок подставляет
#: вместо недостающих слов ФОРМУЛИРОВКУ ВОПРОСА МЕТОДИКИ по коду пункта
#: (`engine/report.py`: `evidence or clean_q(question)`), причём на языке
#: письма. Строка в перечне выходит связной, переведённой и на вид
#: законченной, а сказано в ней то, чего аудитор не писал: вопросы методики
#: сформулированы как утверждение нормы, то есть у отклонения оказывается
#: текст, читающийся как «всё в порядке». Пустое место хотя бы видно; эта
#: подмена не видна ничем.
#:
#: Не то же самое, что `FINDING_TEXT_FIELD`, и слить их нельзя. Там
#: формулировка ЕСТЬ, но не на языке письма — читающему нужен переводчик.
#: Здесь её нет ни на каком языке, и переводить нечего: нужен сам аудитор, и
#: найти его надо до отправки, а не после.
#:
#: Отдаётся такое письмо всё равно, как отдаётся письмо с подставленным сроком
#: и со смешанными языками: правило блока — «отдаётся, но НЕ молча».
BLANK_TEXT_FIELD = "finding wording, missing in every language"

#: Переменная, из которой берётся боевая методика. Имя названо в отказе:
#: абсолютного пути в ответе быть не должно (T120), а чинить человеку что-то
#: надо.
DATA_DIR_VAR = "AUDIT_DATA_DIR"
STORE_VAR = "MCP_CHECKLIST_STORE"

#: Каталог состояния бота, внутри которого лежит полка снимков изданий
#: (`STATE_DIR/methodology/<издание>/`, задача T169). Читается ТОЛЬКО на чтение
#: и только по имени, выведенному из содержимого, — писать туда этот блок не
#: имеет права ничем: полка принадлежит идущим проверкам.
STATE_DIR_VAR = "STATE_DIR"


@dataclass(frozen=True)
class Papers:
    """Откуда брать методику для пересборки: боевая, хранилище версий, полка бота.

    Все три необязательны, и это не небрежность. Хранилища версий может не быть
    вовсе (до T098 весь MCP был чтением проверок), боевой методики может не быть
    у процесса, поднятого без `AUDIT_DATA_DIR`, а полки — у процесса, поднятого
    без `STATE_DIR`. Пересборка при этом не ломается молча: она отказывает и
    называет переменную.

    Полка (`shelf`) — третье место, где издание может лежать, и добавлена она
    вместе со сверкой отпечатка (T236), а не до неё. Порядок именно такой:
    брать каталог с чужой полки, доверяя его ИМЕНИ, значило бы расширить ровно
    тот дефект, ради которого задача заведена. Со сверкой источник перестаёт
    быть вопросом доверия: годится тот каталог, чьё содержимое и есть это
    издание, кто бы его ни положил.
    """

    live: Path | None
    store: Path | None
    #: `STATE_DIR/methodology/` — снимки изданий, которые бот снимает на старте
    #: каждой проверки (T169). Здесь лежат издания, которых в хранилище версий
    #: MCP нет и не будет: хранилище наполняет правка методики через агента, а
    #: полку — каждая проверка на точке.
    shelf: Path | None = None


def sources(env: Mapping[str, str] | None = None) -> Papers:
    """Каталоги методики из окружения.

    Читается на вызове, а не разбирается на старте вместе с остальными
    настройками: инструменты проверок получают от точки входа только код
    арендатора, и третий вид инструмента (со своим контекстом) открыл бы
    объявленной записи дорогу мимо заслона, который сегодня держится одним
    правилом — «обработчик всего, что не методика, лежит в модуле чтения».
    Так же и по той же причине берёт своё окружение блок `db`.
    """
    src = os.environ if env is None else env

    def _path(name: str) -> Path | None:
        raw = (src.get(name) or "").strip()
        return Path(os.path.abspath(os.path.expanduser(raw))) if raw else None

    состояние = _path(STATE_DIR_VAR)
    return Papers(
        live=_path(DATA_DIR_VAR),
        store=_path(STORE_VAR),
        shelf=None if состояние is None else состояние / SHELF_DIR,
    )


def version_of(data_dir: Path) -> str:
    """Идентификатор версии этого каталога методики.

    Считает его тот же код, что штампует версию в каждую проверку
    (`domain.version.compose`). Второй экземпляр формулы означал бы, что
    «совпало» и «не совпало» здесь решаются не тем же способом, каким версия
    попала в проверку.
    """
    return compose(data_dir, DATA_FILES)


def _run(script: Path, args: list[str], *, data_dir: Path, state: Path) -> tuple[int, str, str]:
    """Запустить скрипт движка над указанной методикой и состоянием.

    Отдельно от `checklist._run` намеренно, и разница ровно одна: там вывод
    склеивается в один текст (нужен весь отказ целиком), а здесь `stdout` —
    это САМО ПИСЬМО, и приклеенный к нему `stderr` уехал бы партнёру внутри
    текста.

    Рабочий каталог — временный и пустой: из каталога с методикой движок
    подобрал бы форк `checklist_data/`, случайно оказавшийся рядом.
    """
    env = dict(os.environ)
    env["CHECKLIST_DIR"] = str(data_dir)
    env["INSPECTION_FILE"] = str(state)
    # Кэш байткода в чужом каталоге движку не нужен, а рядом с методикой он
    # выглядел бы файлом методики.
    env["PYTHONDONTWRITEBYTECODE"] = "1"
    готово = subprocess.run(  # noqa: S603 — список аргументов собран здесь, оболочки нет
        [sys.executable, str(script), *args],
        cwd=str(state.parent),
        env=env,
        capture_output=True,
        text=True,
        timeout=ENGINE_TIMEOUT_SEC,
    )
    return готово.returncode, готово.stdout, готово.stderr


def _lang(detail: InspectionDetail, asked: str | None) -> str:
    """Язык письма: названный или тот, на котором отчёт записан.

    Незнакомый язык — отказ. Движок на такой молча откатывается на русский
    (`if lang not in T: lang = "ru"`), то есть спрашивающий получил бы письмо
    не на том языке и ничем бы об этом не узнал.
    """
    if asked is None:
        return detail.inspection.report_lang
    value = asked.strip().lower()
    if value not in TEXT_LANGS:
        raise ToolError(
            f"Язык письма «{asked}» в методике не заведён. Доступны: {', '.join(TEXT_LANGS)}. "
            f"Движок на незнакомый язык молча собирает письмо по-русски — и отправитель "
            f"узнал бы об этом от партнёра"
        )
    return value


def _cover(detail: InspectionDetail) -> tuple[dict[str, str], list[str]]:
    """Шапка письма и перечень того, чего слой чтения не отдал.

    `getattr` со значением по умолчанию, а не обращение к полю: перечень
    обязан выводиться из строки чтения, а не быть переписанным списком. Как
    только `db.InspectionRow` начнёт отдавать аудитора и город, шапка станет
    полной сама, без правки здесь.
    """
    шапка = {поле: str(getattr(detail.inspection, поле, "") or "") for поле in COVER_FIELDS}
    return шапка, [поле for поле, значение in шапка.items() if not значение]


def _wording_langs(detail: InspectionDetail, *, lang: str) -> list[str]:
    """Языки записанных находок, отличные от языка ПИСЬМА.

    Выводится из самих находок, а не из поля проверки, и это та же причина, по
    которой перечень шапки выводится из строки чтения: слой чтения отдаёт язык
    вместе с каждой находкой (`FindingRow.lang` — язык речи той проверки), и
    письмо печатает ровно то, что в этих строках лежит.

    Сверяется именно с языком письма, а не с языком отчёта: языка у проверки
    три, и они разные поля. Аудитор мог говорить по-английски при отчёте
    по-русски — тогда смешано и письмо, которого никто отдельно не заказывал.

    Находок может не быть вовсе — тогда смешивать в письме нечего, и список
    пуст: сказать о смешении там, где его нет, значит научить читающего
    пропускать это слово мимо глаз.
    """
    письмо = lang.strip().casefold()
    языки = {(находка.lang or "").strip() for находка in detail.findings}
    return sorted(язык for язык in языки if язык and язык.casefold() != письмо)


def _blank_wordings(detail: InspectionDetail) -> list[int]:
    """Номера находок, у которых формулировки нет ВООБЩЕ (T237).

    Меряется и `None`, и пустая строка, и строка из пробелов, хотя означают они
    разное: `None` — строки перевода нет вовсе, пустая — аудитор ничего не
    написал (`db.FindingRow.text`, и склеивать их в слое чтения прямо
    запрещено). Здесь склеивать можно и нужно: письму все три обходятся
    одинаково — движок печатает находку с пустым местом там, где стоят слова, и
    выходит с нулевым кодом. Перечень невосстановленного описывает ПИСЬМО, а не
    происхождение строки.

    Выводится из самих находок, как перечень языков и перечень шапки: находка,
    у которой формулировка появилась, перестаёт быть невосстановленной сама,
    без правки здесь.

    Номера, а не коды: в письме находки перечислены по порядку, и отправитель
    ищет пустое место глазами. Код пункта в письме не печатается вовсе.
    """
    return sorted(находка.n for находка in detail.findings if not (находка.text or "").strip())


def state_json(detail: InspectionDetail, *, lang: str) -> str:
    """Записанная проверка в форме файла состояния, который читает движок.

    Кадров здесь нет: они лежат в хранилище за ссылками, а письму они не
    нужны вовсе — их печатает отчёт. Пустой список честнее подставленного
    пути: движок ничего не ищет на диске сам.

    Формулировка находки уезжает как записана, на языке речи аудитора.
    Переводить её нельзя: это чужие слова в отчёте партнёру.

    **Информационная часть уезжает в том порядке, в каком записана** (T200).
    Из неё письмо читает срок плана действий — ответ аудитора, который партнёру
    уже назван; пустой блок здесь означал ровно то, что движок подставит вместо
    ответа свой расчёт, и партнёр получит от управляющей компании другой срок.
    Ответ уходит дословно и не переводится: движок печатает его как записан на
    любом языке письма, а срок вдобавок читается человеком, а не машиной.
    """
    шапка, _ = _cover(detail)
    строка = detail.inspection
    return json.dumps(
        {
            "meta": {
                "unit": строка.unit_name,
                "city": шапка["city"],
                "partner": шапка["partner"],
                "contact": шапка["contact"],
                "auditor": шапка["auditor"],
                # Вид проверки в базе лежит кодом (T152), а движок печатает
                # шапку словом. Слово подставляется здесь и по языку ПИСЬМА:
                # письмо по одной и той же проверке собирается на разных
                # языках, и слово, записанное однажды, было бы верным ровно на
                # одном из них.
                "type": kind_title(строка.kind, lang),
                "date": строка.inspection_date.isoformat(),
                "lang": lang,
            },
            "findings": [
                {
                    "n": находка.n,
                    "qid": находка.code,
                    "level": находка.level,
                    "zone": находка.zone,
                    "photos": [],
                    "comment": находка.comment or "",
                    "evidence": находка.text or "",
                }
                for находка in detail.findings
            ],
            # Форма поля — пара «текст + кадры», та же, что пишет движок с T172.
            # Кадры пусты по той же причине, что и у находок: письмо их не
            # печатает, а лежат они в хранилище за ссылками.
            "info": {поле.code: {"text": поле.text, "photos": []} for поле in detail.info},
        },
        ensure_ascii=False,
    )


def check_version(version: str) -> str:
    """Идентификатор издания как имя каталога — или отказ ИНСТРУМЕНТА чтения.

    Правило то же самое, что у хранилища версий и у полки снимков домена
    (`domain.version.is_one_segment`), и живёт оно в одном месте: сведено на
    T243, где два правила на одно имя расходились молча. Здесь только тип
    отказа свой. `ChecklistError` означает «движок не принял правку методики», а
    ни правки, ни движка на этом пути нет вовсе: инструменты проверок читают
    базу, и отказ у них — `ToolError`.

    Пробелы по краям обрезаются до правила, а не правилом: это приведение
    аргумента, приехавшего от агента, и делают его одинаково все три сторожа
    хранилища (`_check_name`, `check_code`, `_check_version`).
    """
    try:
        return _check_version(version)
    except ChecklistError as отказ:
        raise ToolError(str(отказ)) from None


def pinned(version: str, papers: Papers) -> tuple[Path, str] | None:
    """Каталог методики ТОЙ версии, которой помечена проверка, и откуда он взят.

    **Годным считается каталог, чьё содержимое И ЕСТЬ это издание** — сверяется
    отпечаток, а не имя (T236). Имя каталога доказательством не является:
    каталоги кладёт не один этот блок, и каталог с правильным именем и чужим
    содержимым подписал бы ответы аудитора формулировками другой методики.
    Письмо такую подмену ловило пересчётом (`_verify`), а карточка проверки
    (`info_part`) не ловила ничем — она читает подписи полей и не считает
    ничего. Поэтому сверка стоит здесь, у общего для обоих потребителя.

    Сверяет её `domain.version.edition_of` — тот же код, которым тот же вопрос
    задаёт полка снимков домена (`domain.edition`). До T236 ответов было два:
    полка сверяла отпечаток, хранилище довольствовалось именем — и расходились
    они молча.

    Мест, где издание может лежать, три, и порядок между ними на правильность
    не влияет: годность каждого решает отпечаток, а не очередь. Порядок задаёт
    только то, ЧЕМ подписан ответ человеку:

    1. хранилище версий MCP — архив управляющей компании (D050, версии не
       удаляются никогда);
    2. боевая методика — годится, только если она и есть это издание;
    3. полка бота (`STATE_DIR/methodology/`) — снимки, снятые на старте
       проверок (T169). Здесь лежат издания, которых в хранилище MCP нет
       вовсе: хранилище наполняет правка методики через агента, полку —
       каждый выезд на точку.

    Ничего — значит, этого издания на машине нет ни в одном из трёх мест. Что с
    этим делать, решает вызывающий, и решает по-разному: письмо без методики не
    собрать (его пишет движок), а карточке проверки нечем подписать поля — она
    читается и без единого файла методики.

    Имя версии приезжает из базы и подставляется в путь каталога, поэтому
    сторож имени стоит здесь, а не у вызывающего: забытый у второго потребителя,
    он открыл бы `..` в идентификаторе версии дорогу к чужому каталогу. Сверка
    отпечатка его не заменяет — она про содержимое, а не про то, куда ходили
    смотреть.

    **Негодное имя — отказ, а не `None`** (T243). Раньше сторож глотался
    молча, и «идентификатор не может быть именем каталога» приезжало к обоим
    потребителям тем же ответом, что «издания на машине нет»: письмо посылало
    человека искать снимок, которого никто не терял, а карточка сообщала, что
    методики нет, стоя на ней ногами. Два разных ответа обязаны выглядеть
    по-разному, а решает, что с ними делать, по-прежнему вызывающий.
    """
    хотим = check_version(version)
    хранилище = None if papers.store is None else papers.store / VERSIONS_DIR / хотим
    полка = None if papers.shelf is None else papers.shelf / хотим

    # Оба каталога, НАЗВАННЫЕ изданием, разбираются до ответа, а не до первого
    # совпадения. Самозванец, оставшийся за спиной удачного ответа, — это
    # по-прежнему сломанное хранилище, и молчать о нём нельзя оттого, что
    # выручила соседняя полка. Стоит это одного лишнего чтения методики и
    # только когда оба каталога на месте: отсутствующий отвечает сразу.
    в_хранилище = None if хранилище is None else edition_of(хранилище, DATA_FILES)
    на_полке = None if полка is None else edition_of(полка, DATA_FILES)

    for каталог, оказалось in ((хранилище, в_хранилище), (полка, на_полке)):
        if каталог is not None and оказалось != хотим and каталог.is_dir():
            # Отказ агенту от этого не меняется — «этого издания на машине
            # нет», и путь с диска в ответ не уходит (T120). Но человек, у
            # которого лежит каталог с правильным именем и чужим содержимым,
            # обязан узнать, КАКОЙ именно: до сверки такой каталог доходил до
            # чтения файла пунктов и оставлял след там, и закрытие дефекта не
            # имеет права заодно спрятать его причину.
            _to_log("каталог назван изданием проверки, но им не является", издание=каталог)

    # Боевая методика в жалобу выше не входит: она изданием проверки не
    # НАЗВАНА, она им просто не является — обычное дело после переиздания.
    if хранилище is not None and в_хранилище == хотим:
        return хранилище, FROM_SNAPSHOT
    if papers.live is not None and edition_of(papers.live, DATA_FILES) == хотим:
        return papers.live, FROM_LIVE
    if полка is not None and на_полке == хотим:
        return полка, FROM_SHELF
    return None


def _methodology(version: str, papers: Papers) -> tuple[Path, str]:
    """Каталог методики для ПИСЬМА — или отказ, объясняющий, чего не хватило.

    Поиск общий с карточкой проверки (`pinned`), а отказ свой: письмо без
    методики собрать нечем, и молчаливая выдача письма «как получилось» здесь
    невозможна по определению.
    """
    хотим = check_version(version)
    найдено = pinned(хотим, papers)
    if найдено is not None:
        return найдено
    if papers.live is None:
        raise ToolError(
            f"Не задан {DATA_DIR_VAR} — каталог методики, по которой считается оценка. "
            f"Без него собрать письмо не из чего"
        )
    if not papers.live.is_dir():
        _to_log("каталога методики нет", методика=papers.live)
        raise ToolError(
            f"Каталог методики из {DATA_DIR_VAR} не открывается. Какой именно — в логе сервера: "
            f"он остаётся на машине"
        )
    живая = version_of(papers.live)
    raise ToolError(
        f"Проверка посчитана по версии методики {хотим}, а её снимка нет: в хранилище "
        f"({STORE_VAR}) такой версии не лежит, боевая методика сейчас {живая}. Собрать письмо "
        f"по сегодняшней методике значило бы пересчитать проверку задним числом и отдать "
        f"партнёру другую букву под прежней датой (D033)"
    )


def _verify(detail: InspectionDetail, data_dir: Path, state: Path) -> None:
    """Убедиться, что движок по этой методике считает ровно записанное.

    Имя каталога версии доказательством не является: каталог кладёт не только
    этот блок, а совпадение отпечатка проверяется лишь у боевой методики.
    Настоящее доказательство — совпадение оценки, и стоит оно один запуск
    движка.
    """
    код, вывод, ошибки = _run(AUDIT_SCRIPT, ["score", "--json"], data_dir=data_dir, state=state)
    if код != 0:
        raise ToolError(
            f"Движок не смог посчитать эту проверку по её же методике, поэтому письмо не "
            f"собрано: {_clean(вывод + ошибки, data_dir, state.parent)}"
        )
    try:
        посчитано: Any = json.loads(вывод)
    except json.JSONDecodeError:
        raise ToolError(
            "Движок ответил на сверку оценки не разбираемым JSON — письмо не собрано"
        ) from None
    записано = detail.inspection
    pct, grade = float(посчитано["pct"]), str(посчитано["grade"])
    if round(pct, 2) != round(записано.pct, 2) or grade != записано.grade:
        raise ToolError(
            f"Оценка, посчитанная по версии {записано.checklist_version}, не сходится с "
            f"записанной в проверке: записано {записано.pct:g}% {записано.grade}, посчитано "
            f"{pct:g}% {grade}. Письмо не собрано: партнёру ушла бы другая оценка под прежней "
            f"датой. Отчёт задним числом не пересчитывается (D033)"
        )


def _status(
    шапки_нет: list[str],
    *,
    срока_нет: bool,
    языки_находок: list[str],
    язык: str,
    пустые: list[int],
) -> str:
    """Прямой ответ на вопрос «это можно отправлять».

    Про срок и про язык находок сказано отдельными предложениями, а не ещё
    двумя именами в общем перечне, и это не оформление. У пустой шапки видно
    пустое место — движок подписывает письмо прочерком, и получатель ответа
    сразу понимает, что чинить. Срок ПОДСТАВЛЯЕТСЯ расчётом: он читается как
    ответ аудитора и ничем себя не выдаёт. Формулировки находок печатаются на
    языке записи среди переведённой шапки и переведённых названий зон: письмо
    связное, выглядит готовым и молчит о том, что половина его на другом
    языке. Одно слово в списке рядом с «engine signed the letter with a blank
    line» описывало бы оба случая неверно.

    Про находку без формулировки — своё предложение и с НОМЕРАМИ находок
    (T237). Соседнее, про язык записи, говорит «переведите», и на находку, у
    которой слов нет ни на каком языке, это указание не годится: переводить
    нечего, нужен сам аудитор.

    Номер здесь обязателен, и это не удобство. Движок не оставляет пустого
    места, а подставляет формулировку вопроса методики на языке письма — то
    есть строка выглядит нормальнее соседних, а не хуже. Найти её в тексте
    иначе как по номеру нечем: кода пункта письмо не печатает вовсе.
    """
    if not шапки_нет and not срока_нет and not языки_находок and not пустые:
        return (
            "letter rebuilt on the methodology version this inspection was scored by; "
            "the score the engine computed matches the one recorded"
        )
    предложения = [
        "letter rebuilt and its score matches the one recorded, but it is NOT ready to send "
        "as it stands."
    ]
    if шапки_нет:
        предложения.append(
            f"The recorded inspection cannot be read back in full, so {', '.join(шапки_нет)} "
            f"are missing and the engine signed the letter with a blank line; fill them in "
            f"before sending."
        )
    if срока_нет:
        предложения.append(
            "No information part is recorded for this inspection, so the action plan deadline "
            "in this letter is the engine's own fallback (inspection date plus the standard "
            "term), not the date the auditor named to the partner; check it against the report "
            "the partner already received before sending."
        )
    if языки_находок:
        предложения.append(
            f"This letter is written in {язык}, but the findings are recorded in "
            f"{', '.join(языки_находок)} and are printed as recorded, while the engine "
            f"translated the header and the zone names: a finding is the auditor's own "
            f"wording and is never machine-translated, so the letter is mixed-language by "
            f"design and the findings need a human translation before it goes to the partner."
        )
    if пустые:
        сколько = "finding" if len(пустые) == 1 else "findings"
        предложения.append(
            f"No wording is recorded in any language for {сколько} "
            f"{', '.join(str(номер) for номер in пустые)}, and the engine did NOT leave a gap: "
            f"it substituted the methodology's own question wording for that item, translated "
            f"into {язык}. Those lines read as finished sentences the auditor never wrote, and "
            f"because a question states the standard rather than the deviation, a deviation "
            f"ends up described as if nothing were wrong. Recover the auditor's wording from "
            f"the inspection before sending — translating is not an option here, there is "
            f"nothing to translate."
        )
    return " ".join(предложения)


def build(detail: InspectionDetail, *, lang: str | None, papers: Papers) -> dict[str, object]:
    """Собрать письмо партнёру по записанной проверке.

    Возвращается записанная оценка, текст письма и прямой ответ на вопрос,
    можно ли это отправлять: письмо с неполной шапкой выглядит готовым, и
    именно поэтому его нельзя отдавать молча.

    **Срок плана действий называет аудитор**, и письмо печатает его ответ
    (T200). Информационной части у записанной проверки может не быть вовсе —
    проверка слита до T200 либо аудитор пропустил все поля (D070), — и тогда
    движок подставляет свой расчёт: дата обхода плюс стандартный срок. Такое
    письмо отдаётся, но НЕ молча: подставленная дата читается как ответ
    аудитора, и партнёр, у которого на руках бумага от аудитора, получил бы от
    управляющей компании другой срок. Проверить по коду, что срок в письме
    настоящий, нечем: поле ищет сам движок и не по коду пункта, а по
    формулировке вопроса методики, — вторая копия этого правила здесь разошлась
    бы с первой молча. Поэтому названо то, что известно точно: информационной
    части нет, значит ответа аудитора в письме нет тоже.

    **Письмо не на языке записи смешивает языки, и это тоже сказано вслух**
    (T220). Шапку и названия зон движок переводит, а формулировки находок
    печатает как записаны: это слова аудитора, и переводить их не полагается
    никому. Правило не меняется — меняется молчание о нём. Такое письмо
    связное, подписанное и с верной оценкой, то есть выглядит готовым, а
    половина его написана на языке, которого получатель может не знать;
    отправителю, который язык записи не читает, заметить это не по чему.
    Поэтому язык находок попадает в тот же перечень невосстановленного, что и
    пустая шапка со сроком, а `status` называет оба языка.

    **Находка без формулировки — третий случай того же рода** (T237), и с T220
    он не сливается. Там формулировка есть, но не на языке письма: нужен
    переводчик. Здесь её нет ни на каком — `db.FindingRow.text` объявлен
    `str | None` намеренно, и `None` там значит «строки перевода нет вовсе».

    Наблюдаемое при этом оказалось хуже ожидаемого, и проверено это запуском.
    Пустого места в письме НЕ появляется: движок подставляет вместо
    недостающих слов формулировку вопроса методики по коду пункта, переведённую
    на язык письма (`engine/report.py`). Строка выходит связной и законченной,
    а говорит она то, чего аудитор не писал; вопросы методики сформулированы
    как утверждение нормы, поэтому у отклонения оказывается текст, читающийся
    как «всё в порядке». Заметить это в тексте нечем — потому `status` и
    называет НОМЕРА таких находок.

    Штатным путём такая находка не получается (слив пишет строку на языке речи
    аудитора), но слой чтения к ней готов, и строка из базы не имеет права
    заставить письмо соврать.
    """
    язык = _lang(detail, lang)
    каталог, откуда = _methodology(detail.inspection.checklist_version, papers)
    _, шапки_нет = _cover(detail)
    срока_нет = not detail.info
    языки_находок = _wording_langs(detail, lang=язык)
    пустые = _blank_wordings(detail)
    не_восстановлено = [
        *шапки_нет,
        *([PLAN_DUE_FIELD] if срока_нет else []),
        *([FINDING_TEXT_FIELD] if языки_находок else []),
        *([BLANK_TEXT_FIELD] if пустые else []),
    ]
    with tempfile.TemporaryDirectory(prefix="mcp-letter-") as рядом:
        состояние = Path(рядом) / "inspection.json"
        состояние.write_text(state_json(detail, lang=язык), encoding="utf-8")
        _verify(detail, каталог, состояние)
        код, письмо, ошибки = _run(
            REPORT_SCRIPT, ["letter", f"--lang={язык}"], data_dir=каталог, state=состояние
        )
        if код != 0:
            raise ToolError(
                f"Движок не собрал письмо: {_clean(письмо + ошибки, каталог, состояние.parent)}"
            )
        текст = письмо.strip()
    if not текст:
        raise ToolError(
            "Сборщик письма отчитался об успехе и вернул пустой текст — отправлять партнёру нечего"
        )
    готово = not не_восстановлено
    return {
        "lang": язык,
        "report_lang": detail.inspection.report_lang,
        "checklist_version": detail.inspection.checklist_version,
        "methodology": откуда,
        "score_verified": True,
        "pct": detail.inspection.pct,
        "grade": detail.inspection.grade,
        "letter": текст,
        "not_restored": не_восстановлено,
        "ready_to_send": готово,
        "status": _status(
            шапки_нет,
            срока_нет=срока_нет,
            языки_находок=языки_находок,
            язык=язык,
            пустые=пустые,
        ),
    }
