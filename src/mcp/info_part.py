"""Информационная часть записанной проверки в карточке чтения (T207).

Семь полей, которые аудитор заполняет в конце обхода, доезжают до базы и до
письма с T200. В карточке одной проверки (`tools.get_inspection`) их не было:
агент получал находки, оценку и разбивку по зонам — и ни одного ответа конца
проверки.

**Чем это кончалось.** Срок плана действий называет аудитор, и пересобранное
письмо несёт именно его ответ (`src/mcp/letters.py`). Человек, читающий ту же
проверку карточкой, срока не видел вовсе — и заключал, что срока нет: в
карточке не было ни поля, ни слова о том, что часть проверки не показана.

**Поле связано КОДОМ, а подписано формулировкой методики.** Сущности продукта
связывают коды (`INF01`, `INF07`, …), а подпись человеку берётся по этому коду
из методики и на языке, который назвали. Языка у самой записи нет одного:
свободный текст записан на языке речи аудитора, «да/нет» — на языке отчёта,
дата не на языке вовсе (`src/db/models.py: InfoRow`). Поэтому переводится
только подпись, а ответ уходит дословно, как записан.

**Подпись берётся из ТОЙ версии методики, которой помечена проверка.**
Формулировку вопроса правит управляющая компания, и сегодняшняя подпись под
прошлогодним ответом — другой вопрос под прежней датой (D033, D049). Версии
нет на машине — подписи нет вовсе (`None`), и это сказано словами: подпись из
соседней версии выглядела бы настоящей, а `None` виден.

**Почему подписи нет — тоже сказано, и по-разному** (T243). «Издание не
опознано» и «идентификатор версии не может быть именем каталога» — разные
беды: первую чинят на диске, вторую в записи проверки. Слитые в одно
предложение, они посылали читающего искать снимок, которого никто не терял.

**Отсутствие методики отказом здесь НЕ становится**, в отличие от письма.
Письмо без методики не собрать вовсе — его пишет движок; карточка же это
записанные ответы, и они читаются без единого файла методики. Отказ вместо них
означал бы, что переставленный `AUDIT_DATA_DIR` прячет от человека то, что
лежит в базе.

**Пустая информационная часть — это ответ, а не молчание.** Пустота значит две
разные вещи, и различить их нечем: аудитор пропустил все поля (D070) либо
проверка слита до T200. Тот, кто читает карточку, обязан узнать об этом из
ответа, иначе повторит ровно ту ошибку, ради которой задача заведена.
"""

from __future__ import annotations

from dataclasses import dataclass

from ..db.models import InspectionDetail
from ..domain.models import TEXT_LANGS, pick_text
from .checklist import _rows, _to_log
from .errors import ToolError
from .letters import Papers, pinned

#: Колонка методики с кодом пункта. Та же, что читает движок и хранилище
#: версий (`checklist._rows` отбирает строки по ней же).
CODE_COLUMN = "id"

#: Файл методики, в котором лежат формулировки пунктов.
ITEMS_FILE = "checklist.csv"

#: Почему подписи есть — или почему их нет. Три случая, и слить их в «нет» и
#: есть дефект T243: до него негодный идентификатор версии приезжал читающему
#: теми же словами, что отсутствующее издание, и человек шёл искать снимок,
#: которого никто не терял.
#:
#: * `FOUND` — методика той версии на машине есть, подписи взяты из неё;
#: * `NOT_AT_HAND` — издание не опознано: каталога нет, он неполон или его
#:   содержимое этим изданием не является (сверку ведёт `pinned`, T236);
#: * `NOT_A_NAME` — идентификатор версии в самой проверке именем каталога быть
#:   не может, то есть искать нечего и негде: чинить надо запись, а не диск.
FOUND = "found"
NOT_AT_HAND = "not-at-hand"
NOT_A_NAME = "not-a-name"


@dataclass(frozen=True)
class Section:
    """Информационная часть для ответа инструмента.

    `lang` отдаётся наружу намеренно: подпись поля переводится, и по какому
    языку её выбрали — часть ответа, а не догадка читающего.
    """

    lang: str
    fields: list[dict[str, object]]
    note: str


def check_lang(asked: str | None) -> str | None:
    """Язык, названный аргументом, — или отказ. Не названный — не подменяется.

    Незнакомый язык обязан быть отказом по той же причине, по какой им стал
    незнакомый язык письма (T171): подпись поля есть только на языках, которые
    заведены в методике, а молча подставленный русский выглядел бы переводом,
    которого никто не делал.
    """
    if asked is None:
        return None
    значение = asked.strip().lower()
    if значение not in TEXT_LANGS:
        raise ToolError(
            f"Язык «{asked}» в методике не заведён. Доступны: {', '.join(TEXT_LANGS)}. "
            f"Подписи полей берутся из методики, и на незаведённом языке их нет — "
            f"подставленный вместо них русский читался бы как перевод"
        )
    return значение


def _titles(version: str, *, lang: str, papers: Papers) -> tuple[dict[str, str], str]:
    """Подписи пунктов по кодам из методики этой версии и что с самой методикой.

    Второе значение отделено от пустого словаря намеренно: «методики этой
    версии на машине нет» и «методика есть, а такого пункта в ней нет» — разные
    ответы человеку, и по пустому словарю их не различить. Значений у него три,
    а не два (`FOUND`, `NOT_AT_HAND`, `NOT_A_NAME`): третье добавлено на T243 —
    негодный идентификатор версии до него был неотличим от потерянного снимка.

    Язык проверяется ещё раз, хотя язык отчёта проверен при заведении проверки
    (`domain.state`): значение приходит из базы, а инструмент чтения не имеет
    права падать на строке, которую туда положили не мы.

    По той же причине здесь ловится отказ `pinned` на негодном идентификаторе:
    карточка читается и без единого файла методики, и отказ вместо записанных
    ответов означал бы, что испорченная строка в базе прячет от человека
    документ, который уже ушёл партнёру.
    """
    if lang not in TEXT_LANGS:
        return {}, NOT_AT_HAND
    try:
        найдено = pinned(version, papers)
    except ToolError:
        return {}, NOT_A_NAME
    if найдено is None:
        return {}, NOT_AT_HAND
    каталог, _ = найдено
    try:
        строки = _rows(каталог / ITEMS_FILE)
    except OSError:
        # Путь остаётся в логе процесса, а не в ответе агента (T120). Молча
        # это глотать нельзя: снимок версии без файла пунктов — поломка
        # хранилища, и починить её можно только зная, где смотреть.
        _to_log("методику версии проверки не прочитать", методика=каталог)
        return {}, NOT_AT_HAND
    подписи: dict[str, str] = {}
    for строка in строки:
        код = (строка.get(CODE_COLUMN) or "").strip().upper()
        подпись = pick_text(
            строка.get("question_ru", ""), строка.get("question_en", ""), lang
        ).strip()
        # Первое вхождение кода, а не последнее: движок читает дубль так же —
        # берёт первый и предупреждает. Строка-комментарий пропускается там же.
        if код and not код.startswith("#") and подпись:
            подписи.setdefault(код, подпись)
    return подписи, FOUND


def _note(поля: list[dict[str, object]], *, методика: str) -> str:
    """Приписка к статусу инструмента — прямая, а не перечень имён.

    Про пустую часть сказано отдельным предложением, потому что молчание здесь
    и есть тот самый дефект: ответ без раздела читается как «аудитор ничего не
    отвечал», а на деле означает ещё и «проверка слита до того, как эти ответы
    начали храниться».

    Подписей нет по двум разным причинам, и предложения у них разные (T243).
    «Издания нет на машине» отправляет искать снимок и разбираться с
    хранилищем; «идентификатор версии не может быть именем каталога» означает,
    что искать нечего, и чинить надо строку проверки. Одно слово на оба случая
    посылало человека не туда — молча и убедительно.
    """
    if not поля:
        return (
            "no information part recorded for this inspection: either the auditor skipped "
            "every field or the inspection was recorded before these answers were stored, "
            "and the two are not told apart here"
        )
    голова = f"{len(поля)} information fields recorded"
    без_подписи = [str(поле["code"]) for поле in поля if поле["title"] is None]
    if not без_подписи:
        return голова
    if методика == NOT_A_NAME:
        return (
            f"{голова}, shown by code alone: the checklist version recorded for this "
            f"inspection cannot be the name of a stored edition at all, so there is no "
            f"methodology to look the wording up in — it is the recorded identifier that "
            f"needs fixing, not a missing snapshot"
        )
    if методика == NOT_AT_HAND:
        return (
            f"{голова}, shown by code alone: the methodology version this inspection was "
            f"scored by is not at hand, and wording from another version would be a "
            f"different question under the same date"
        )
    # Сказано «нет формулировки», а не «нет пункта», и это не смягчение. Пункт
    # бывает на месте, а формулировки на нужном языке у него нет: английский
    # текст пункта необязателен при заведении (`add_checklist_item`,
    # `question_en` можно не называть). «Такого пункта нет» было бы там прямым
    # враньём про методику управляющей компании.
    return (
        f"{голова}, of which {', '.join(без_подписи)} are shown by code alone: that version "
        f"of the methodology has no wording for them in this language"
    )


def read(detail: InspectionDetail, *, lang: str | None, papers: Papers) -> Section:
    """Информационная часть проверки: код, подпись из методики и ответ дословно.

    Порядок — записанный, а не алфавитный по коду: его задаёт бот, и это
    порядок разделов документа, ушедшего партнёру (`InspectionDetail.info`).

    Язык — параметр: названный аргументом или тот, на котором выпущен отчёт.
    Константы здесь быть не может, поэтому язык уезжает в ответ вместе с
    полями.
    """
    язык = lang or detail.inspection.report_lang
    подписи, методика = _titles(detail.inspection.checklist_version, lang=язык, papers=papers)
    поля: list[dict[str, object]] = [
        {
            "code": строка.code,
            "title": подписи.get(строка.code.strip().upper()),
            "text": строка.text,
        }
        for строка in detail.info
    ]
    return Section(lang=язык, fields=поля, note=_note(поля, методика=методика))
