"""Инструмент «снять проверку из истории» (T211, решения D086 и D089).

Это ЕДИНСТВЕННОЕ место блока, где через агента меняется проверка. Читающая
половина (`tools.py`) отвечает на вопросы о том, что случилось, правящая
(`checklist_tools.py`) — о том, по чему будут считаться будущие проверки;
здесь снимается уже выданный документ.

Три правила, которые здесь важнее удобства.

**Снять — не значит поправить.** Неверный отчёт не правится: заводится новый,
а старый снимается (D086). Поэтому у инструмента нет и не будет ни одного
аргумента, меняющего содержимое проверки: он ставит пометку и называет
причину, всё остальное — новая проверка, которую проводит аудитор.

**Причина обязательна, и это не аккуратность** (D089). Снятая проверка — это
отозванный у партнёра документ; без причины отзыв неотличим от подчистки
истории. Обязательность держат ограничения схемы и `db.retract`, здесь она не
переписывается.

**Снять вслепую нельзя.** Идентификатор — это тридцать шесть знаков, которые
человек глазами не читает, а снятие для партнёра необратимо: письмо и отчёт у
него на руках, а кадры уезжают из хранилища насовсем. Поэтому вызов обязан
назвать ещё и точку с датой обхода — то, что человек видит на самом документе.
Не сошлось — снятия не происходит, а в отказе написано, чем эта проверка
является на самом деле. Подтверждением тут работает не обещание агента, что он
спросил человека, а невозможность попасть в чужую строку с первого раза.

Арендатор приходит сверху, из токена, как и у остальных инструментов. Право на
сам вызов — отдельное и ЛИЧНОЕ: оно даётся токену, а не стороне
(`config.MCP_RETRACTION_TOKENS`), и спрашивается на входе, до обработчика
(`rpc._call_tool`), а не здесь.

Запросов к базе в этом модуле нет: снятие целиком живёт в `src/db/retract.py`,
чтение — в `src/db/queries.py`. Здесь граница инструмента: подтверждение,
перевод отказов на человеческие слова и заслон от чужого текста в ответе.
"""

from __future__ import annotations

from datetime import date

from ..db.models import InspectionRow
from .errors import ToolError
from .tools import _parse_date, _require_inspection_id

#: Отказ на стенде, где снятие не настроено. Своим текстом, а не общим отказом
#: чтения: без этой переменной не работает ни один шаг снятия, включая чтение
#: проверки для подтверждения, — и человек, увидевший «не удалось прочитать»,
#: пошёл бы чинить базу, которая в порядке.
NOT_CONNECTED = (
    "Снятие проверок на этом стенде не настроено: не задана переменная окружения "
    "DATABASE_RETRACTION_URL. Снятые проверки видны только администратору истории "
    "(роль dodo_audit_admin), и приходит он отдельным подключением — обычной ролью "
    "приложения снятую проверку не увидеть и не снять. Это отказ настройки, а не "
    "отсутствие проверки"
)

#: Отказ на проверку, которой у этого арендатора нет. Один текст на «нет такой»
#: и «есть, но чужая» — намеренно, ровно как в чтении (`db.queries`): разные
#: ответы подтверждали бы существование чужого документа тому, кто перебирает
#: идентификаторы. Про снятые сказано отдельно, потому что здесь это третий
#: случай: снятую проверку не видно и тому, кому снятие не открыто.
UNKNOWN_INSPECTION = (
    "Проверки {ident} у этого доступа нет: её не существует, она принадлежит другому "
    "арендатору либо снята кем-то раньше. Что именно из трёх — не говорится намеренно: "
    "иначе перебором идентификаторов читался бы состав чужой истории"
)

#: Чем отказ хранилища или базы приходит наружу. Текст чужого отказа в ответ не
#: попадает никогда: в сообщении драйвера базы бывает адрес и имя базы, а ответ
#: инструмента уходит в модель, то есть за пределы машины (T120).
FOREIGN_FAILURE = (
    "Снятие проверки {ident} не довершено ({вид}). Это отказ базы или хранилища, а не "
    "отказ в снятии: подробности остались в логе сервера, он не уезжает с машины. "
    "Пометка снятия ставится одной транзакцией — наполовину снятой проверка не "
    "остаётся, и повторный вызов доделает начатое"
)


def _same_unit(записано: str, названо: str) -> bool:
    """Та же ли это точка. Сравнение — ключом сопоставления продукта, а не своим.

    Нормализацию имён точек продукт уже имеет (`db.units.normalize_unit_name`):
    обрезанные края, схлопнутые пробелы, casefold. Второе правило сравнения
    здесь означало бы, что подтверждение принимает не то же имя, под которым
    проверка лежит в базе, — и человек, скопировавший название из карточки,
    получал бы отказ.
    """
    from ..db.units import normalize_unit_name

    return normalize_unit_name(записано) == normalize_unit_name(названо)


def _describe(строка: InspectionRow) -> str:
    """Чем проверка является на самом деле — одной строкой для человека.

    Оценка сюда попадает ЗАПИСАННОЙ и ничего не пересчитывает: это то же
    число, что стоит в документе у партнёра, и по нему человек узнаёт бумагу,
    которую собирается отозвать.
    """
    return (
        f"«{строка.unit_name}» от {строка.inspection_date.isoformat()}, "
        f"{строка.pct:g}% {строка.grade}, находок — {строка.findings_count}"
    )


def _detail(ident: str, *, tenant: str) -> InspectionRow | None:
    """Шапка проверки глазами администратора истории. `None` — такой у него нет.

    Читается ПОД ТОЙ ЖЕ ролью, под которой пойдёт снятие
    (`include_retracted=True`), и это не удобство. Обычная роль снятой проверки
    не видит вовсе, и подтверждение, прочитанное ею, отвечало бы «такой нет» на
    проверку, которая есть и снята, — то есть на единственный случай, ради
    которого повторный вызов и делают.

    Импорт внутри функции: `src.db.queries` тянет `psycopg`, а жадный импорт
    ронял бы сбор всего `tests/` там, где зависимость блока не поставлена (тот
    же приём и та же причина, что в `tools._read`).
    """
    from ..db.errors import ConfigError as DbConfigError
    from ..db.queries import get_inspection

    try:
        подробно = get_inspection(ident, tenant=tenant, include_retracted=True)
    except DbConfigError:
        raise ToolError(NOT_CONNECTED) from None
    return None if подробно is None else подробно.inspection


def _confirmed(строка: InspectionRow, *, unit: str, day: date) -> None:
    """Та ли это проверка, которую называет вызывающий. Не та — отказ и описание.

    Отказ показывает, чем проверка является, и это не утечка: за токеном уже
    открыта вся история ЭТОГО арендатора, а чужая проверка сюда не доходит —
    её отсекает чтение выше. Зато промах по идентификатору перестаёт быть
    молчаливым: человек видит, какую бумагу он чуть не отозвал.
    """
    сошлось = _same_unit(строка.unit_name, unit) and строка.inspection_date == day
    if сошлось:
        return
    raise ToolError(
        f"Подтверждение не сошлось, проверка не снята. Названы точка «{unit}» и дата "
        f"{day.isoformat()}, а проверка {строка.id} — это {_describe(строка)}. Снятие "
        f"необратимо для партнёра: письмо и отчёт у него на руках, кадры уезжают из "
        f"хранилища насовсем. Если снимать нужно именно эту — назвать её точку и дату "
        f"обхода так, как они записаны"
    )


def _retract(ident: str, *, tenant: str, reason: str) -> tuple[str, str, int]:
    """Позвать снятие и вернуть записанную причину, время и число убранных кадров.

    **Отказ переводится по происхождению его текста, а не по разбору строки.**
    `db.retract` отвечает одним типом (`RetractionError`) и на отказ по существу
    («причина не названа», «проверка не запечатана», «на неё уже сослались»), и
    на беду окружения — а в тексте второго он приводит сообщение драйвера
    целиком. В сообщении psycopg о неудачном подключении стоят адрес, порт и имя
    базы; уехать это должно в лог, а не в ответ агенту (T120).

    Различает их `__cause__`: он есть ровно там, где чужое исключение обёрнуто
    (`raise ... from exc`), то есть ровно там, где в текст подставлен чужой
    текст. Отказы по существу написаны блоком `db` целиком и приходят человеку
    его словами — пересказывать их здесь нельзя, второй экземпляр разошёлся бы
    с первым при первой же правке.
    """
    from ..db.errors import ConfigError as DbConfigError
    from ..db.errors import RetractionError
    from ..db.retract import retract_inspection

    try:
        снятие = retract_inspection(ident, tenant=tenant, reason=reason)
    except DbConfigError:
        raise ToolError(NOT_CONNECTED) from None
    except RetractionError as отказ:
        if отказ.__cause__ is not None:
            raise ToolError(
                FOREIGN_FAILURE.format(ident=ident, вид=type(отказ.__cause__).__name__)
            ) from None
        raise ToolError(str(отказ)) from None
    return снятие.reason, снятие.retracted_at, снятие.photos_purged


def _cleanup_note(убрано: int) -> str:
    """Что стало с кадрами — словами, а не числом в отдельном поле.

    Ноль означает и «кадров не было», и «их убрал предыдущий вызов»: отметка
    `purged_at` у кадра одна, различить исходы нечем, и выдумывать разницу
    здесь нельзя.
    """
    if убрано == 0:
        return "no photos left storage on this call (there were none, or an earlier call took them)"
    return f"{убрано} photo objects were removed from storage and cannot be restored"


def _already_retracted(строка: InspectionRow, *, tenant: str) -> ToolError:
    """Отказ на проверку, снятую раньше, — и доделанная за ним уборка кадров.

    Отказ, а не «готово»: вызывающий просил записать СВОЮ причину, а она не
    записывается — причина снятия не переписывается никогда, иначе снятие
    стало бы способом править основание задним числом. Ответ «сделано» он
    однажды перескажет человеку как «причина принята» (то же соображение, что
    у `checklist_tools._accepted`).

    Уборка кадров при этом доделывается, и об этом сказано в самом отказе.
    Снятие и уборка идут разными транзакциями: обрыв между ними оставляет кадры
    отозванного документа лежать в хранилище, а повторный вызов — единственное,
    что их оттуда убирает. Отказ, молча сделавший работу, хуже отказа; поэтому
    работа названа.
    """
    try:
        # Причина берётся ЗАПИСАННАЯ, а не названная вызовом, и это не мелочь.
        # Здесь не записывают новую причину, а доделывают уборку по уже
        # состоявшемуся снятию: названная вызовом причина всё равно не легла бы,
        # а пустая увела бы ответ в «не названа причина» — то есть в разговор о
        # том, чего этот вызов уже не делает.
        _, _, убрано = _retract(строка.id, tenant=tenant, reason=строка.retraction_reason)
    except ToolError as беда:
        уборка = f"остаток кадров убрать не удалось: {беда}"
    else:
        уборка = (
            "кадров в хранилище не осталось"
            if убрано == 0
            else f"остаток кадров убран этим вызовом: {убрано}"
        )
    return ToolError(
        f"Проверка {строка.id} ({_describe(строка)}) снята раньше, причина записана тогда "
        f"же и здесь не переписывается: снятие — не способ править основание задним "
        f"числом. Записанная причина: «{строка.retraction_reason}». Сейчас ничего не "
        f"снято, {уборка}. Если нужна другая причина — это отдельный разговор с тем, кто "
        f"держит историю, а не повторный вызов"
    )


def retract_inspection(
    *, tenant: str, id: str, reason: str, confirm_unit: str, confirm_date: str
) -> dict[str, object]:
    """Снять сданную проверку из истории этого арендатора (T211, D086/D089).

    Порядок шагов задан тем, что снятие необратимо, а не удобством:

    1. Аргументы разбираются до похода в базу — идентификатор, дата, точка.
    2. Проверка читается глазами администратора истории: снятую иначе не
       увидеть, а именно она и есть частый повторный случай.
    3. Названные точка и дата сверяются с записанными. Не сошлись — отказ с
       описанием того, чем проверка является: попасть в чужую строку с первого
       раза становится нельзя, и это и есть подтверждение.
    4. Снимает `db.retract` — одной транзакцией, с обязательной причиной, с
       уборкой кадров и со всеми отказами по существу (незапечатанная
       проверка, проверка, на которую уже сослались).

    Оценка в ответе — ЗАПИСАННАЯ, из базы: инструмент ничего не считает.
    """
    ident = _require_inspection_id(id)
    точка = (confirm_unit or "").strip()
    if not точка:
        raise ToolError(
            "Не названа точка в confirm_unit. Подтверждение — это то, что человек видит "
            "на самом документе: снятие необратимо, и попасть в него одним "
            "идентификатором из тридцати шести знаков нельзя"
        )
    день = _parse_date(confirm_date, field="confirm_date")
    if день is None:
        raise ToolError(
            "Не названа дата обхода в confirm_date. Подтверждение — это то, что человек "
            "видит на самом документе: снятие необратимо, и попасть в него одним "
            "идентификатором из тридцати шести знаков нельзя"
        )

    строка = _detail(ident, tenant=tenant)
    if строка is None:
        raise ToolError(UNKNOWN_INSPECTION.format(ident=ident))
    _confirmed(строка, unit=точка, day=день)
    if строка.retracted:
        raise _already_retracted(строка, tenant=tenant)

    причина, снята, убрано = _retract(ident, tenant=tenant, reason=reason)
    return {
        "id": строка.id,
        "unit": строка.unit_name,
        "inspection_date": строка.inspection_date.isoformat(),
        "pct": строка.pct,
        "grade": строка.grade,
        "retracted_at": снята,
        "reason": причина,
        "photos_purged": убрано,
        "status": (
            "inspection retracted from the history and no longer appears in any ordinary "
            "read of it: list_inspections, get_inspection, unit_history, findings_by_unit, "
            f"network_summary and inspection_letter all answer as if it were not there. "
            f"{_cleanup_note(убрано)}. The row itself stays, marked and with the reason, so "
            "the history still shows that the inspection happened. This is not reversible "
            "for the partner: the report and the letter are already in their hands, and a "
            "corrected inspection is recorded as a new one, not as an edit of this"
        ),
    }
