"""Отказы блока `mcp`.

Один базовый класс, чтобы точка входа перехватывала любой отказ этого блока
одним `except McpError` и отвечала клиенту внятной ошибкой, а не трейсбеком:
трейсбек ушёл бы агенту партнёра вместе с путями и строкой подключения.

Тексты отказов безопасны для лога и для ответа наружу: ни токена, ни данных
проверок в них нет (конституция, раздел «Правила безопасности»).
"""

from __future__ import annotations


class McpError(Exception):
    """Базовый отказ блока `mcp`."""


class McpConfigError(McpError):
    """Окружение непригодно: нет карты токенов, кривой адрес или порт.

    Отдельный тип от `AuthError` намеренно: это отказ на старте, до первого
    запроса. Слитые в один тип, они однажды дали бы «сервер поднялся, но не
    пускает никого» вместо «сервер не поднялся, потому что настроен неверно».
    """


class AuthError(McpError):
    """Запрос пришёл без токена или с незнакомым токеном.

    Ни имени арендатора, ни самого токена в тексте нет: отказ уходит клиенту
    и в лог, а перечислять по нему живых арендаторов не должен никто.
    """


class ToolError(McpError):
    """Инструмент вызван с негодными аргументами.

    Пустая выдача на кривой аргумент — худший исход: спросивший читает её как
    «ничего не найдено» и не узнаёт, что спросил не то.
    """


class ChecklistError(McpError):
    """Правка методики не принята — хранилищем версий или самим движком.

    Отдельный тип от `ToolError` намеренно: `ToolError` означает «спросили не
    то», а здесь аргументы могут быть безупречны, и всё равно после правки
    получится методика, которую движок считать откажется (несходящиеся доли
    зон, пункт без критериев, дубль кода). Слитые в один тип, они однажды дали
    бы совет «поправьте аргументы» на отказ, к аргументам отношения не имеющий.

    Текст отказа безопасен для лога и для ответа наружу: пути временных
    каталогов из него убраны, данных проверок в нём нет.
    """
