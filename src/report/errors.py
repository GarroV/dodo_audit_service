"""Отказы блока `report`.

Отдельные классы нужны боту: по типу он решает, что показать аудитору —
«отчёт не собрался, попробуйте ещё раз» (`PdfNotBuilt`) или «кадр к записи №3
не найден, приложите заново» (`PhotoMissing`). Общий текст исключения уходит
аудитору как есть, поэтому в нём нет ни путей вне проверки, ни внутренностей
рендерера.
"""

from __future__ import annotations


class ReportError(Exception):
    """Базовый отказ сборки отчёта."""


class PdfNotBuilt(ReportError):
    """Отчёт не собран.

    Поднимается всегда, когда файла нет или он не является PDF, — даже если
    рендерер отчитался об успехе. Путь к несуществующему файлу бот отдал бы
    аудитору за готовый отчёт, а тот отправил бы его партнёру.
    """


class PhotoMissing(ReportError):
    """Кадр, приложенный к записи, не удалось получить.

    Молчаливая пустота на месте фотографии — худший из исходов: партнёр видит
    нарушение без доказательства и справедливо его оспаривает.
    """

    def __init__(self, message: str, *, misses: list[tuple[int | str, str]]) -> None:
        super().__init__(message)
        self.message = message
        #: Пары «номер записи, ссылка на кадр» — бот называет аудитору записи.
        self.misses = misses
