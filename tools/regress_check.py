#!/usr/bin/env python3
"""Регрессионный якорь: цифры на боевых данных не должны меняться.

Раньше цель `make regress` просто печатала вывод движка и **всегда возвращала
ноль** — `| head -2` съедал код возврата, а сравнивать было не с чем. То есть
команда, названная в документации регрессионным контролем, покраснеть не могла
никогда. Найдено сверкой со спекой 03.09.

Пути к движку и питону абсолютные не для красоты: `examples/` подкладывается в
рабочие копии блоков, и относительный `../../engine/audit.py` из папки проверки
уводил в движок ОСНОВНОЙ копии — гейт был зелёным, не проверяя изменённого.
"""

from __future__ import annotations

import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ДВИЖОК = ROOT / "engine" / "audit.py"
ПИТОН = ROOT / ".venv" / "bin" / "python"

#: Что обязан выдать движок на каждой боевой проверке. Числа взяты не из кода,
#: а из отчётов, которые уже ушли партнёрам: их расхождение и есть регрессия.
ЯКОРЬ = (
    ("belgrade-1", "97.5%", "A", "D1 = 5"),
    ("belgrade-2", "97%", "A", "D1 = 6"),
)


def main() -> int:
    беды: list[str] = []
    for папка, процент, буква, класс in ЯКОРЬ:
        рабочая = ROOT / "examples" / папка
        if not рабочая.is_dir():
            беды.append(f"{папка}: папки проверки нет — регресс проверять не на чем")
            continue
        готово = subprocess.run(  # noqa: S603 — аргументы собраны здесь, оболочки нет
            [str(ПИТОН), str(ДВИЖОК), "score"],
            cwd=рабочая,
            capture_output=True,
            text=True,
            check=False,
        )
        вывод = готово.stdout
        print(f"{папка}: " + " ".join(вывод.splitlines()[:2]))
        if готово.returncode != 0:
            беды.append(
                f"{папка}: движок вернул код {готово.returncode}: {готово.stderr.strip()[:200]}"
            )
            continue
        for ожидалось in (процент, буква, класс):
            if ожидалось not in вывод:
                беды.append(f"{папка}: в выводе нет «{ожидалось}» — цифры разошлись с эталоном")
    if беды:
        print("\nРЕГРЕССИЯ:", file=sys.stderr)
        for б in беды:
            print(f"  {б}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
